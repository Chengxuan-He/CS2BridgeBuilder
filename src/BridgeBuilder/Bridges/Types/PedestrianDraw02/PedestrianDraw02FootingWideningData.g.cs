    internal static MovableStructureModel.Plan CreatePlan(int lod, Vector3[] sourcePositions,
        float halfWidthDelta, int[][] sourceIndices)
    {
        var measured = lod switch
        {
            0 => Near,
            1 => Far,
            _ => throw new ArgumentOutOfRangeException(nameof(lod))
        };
        var triangles = lod == 0 ? 112 : 100;
        if (!float.IsFinite(halfWidthDelta) || sourcePositions.Length != measured.Length ||
            sourceIndices.Length != 1 || sourceIndices[0].Length != triangles * 3)
            throw new ArgumentException("PedestrianDraw02 footing requires its measured native layout and a finite width change.");
        var positions = (Vector3[])sourcePositions.Clone();
        for (var i = 0; i < measured.Length; i++)
        {
            var actual = sourcePositions[i];
            var expected = measured[i].Position;
            if (actual.x != expected.x || actual.y != expected.y || actual.z != expected.z)
                throw new InvalidOperationException($"PedestrianDraw02 footing LOD {lod} vertex {i} differs from its recorded source.");
            positions[i].x += measured[i].Weight * halfWidthDelta;
        }
        return new MovableStructureModel.Plan(sourcePositions, positions, sourceIndices,
            new[] { new bool[triangles] });
    }

