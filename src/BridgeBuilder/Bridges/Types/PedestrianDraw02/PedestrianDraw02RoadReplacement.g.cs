    // Compose with a complete structural plan without discarding its added vertices or fragments.
    // Caller checks source provenance before loading geometry. This method only validates mesh 0.
    internal static MovableStructureModel.Plan WithTopRemoved(int lod, MovableStructureModel.Plan structure)
    {
        var vertexCount = lod switch
        {
            0 => 40168,
            1 => 32137,
            _ => throw new ArgumentOutOfRangeException(nameof(lod))
        };
        var triangleCount = lod == 0 ? 30064 : 18025;
        if (structure.SourcePositions.Length != vertexCount || structure.SourceIndices.Length != 1 ||
            structure.SourceIndices[0].Length != triangleCount * 3 || structure.RemoveTriangles.Length != 1 ||
            structure.RemoveTriangles[0].Length != triangleCount)
            throw new InvalidOperationException($"PedestrianDraw02 LOD {lod} main mesh does not match its measured layout.");
        var indices = structure.SourceIndices[0];
        var removed = (bool[])structure.RemoveTriangles[0].Clone();
        var topFaces = Faces(lod);
        foreach (var face in topFaces)
        {
            var offset = face.Triangle * 3;
            if (indices[offset] != face.A || indices[offset + 1] != face.B || indices[offset + 2] != face.C)
                throw new InvalidOperationException($"PedestrianDraw02 LOD {lod} road triangle {face.Triangle} has changed topology.");
            removed[face.Triangle] = true;
        }
        foreach (var vertex in Vertices(lod))
        {
            var actual = structure.SourcePositions[vertex.Index];
            if (actual.x != vertex.Position.x || actual.y != vertex.Position.y || actual.z != vertex.Position.z)
                throw new InvalidOperationException($"PedestrianDraw02 LOD {lod} road vertex {vertex.Index} has changed position.");
        }
        foreach (var fragment in structure.Fragments)
            if (fragment.Slot == 0 && Array.Exists(topFaces, face => face.Triangle == fragment.Triangle))
                throw new InvalidOperationException($"PedestrianDraw02 LOD {lod} structure fragment would restore removed road triangle {fragment.Triangle}.");
        var positions = new Vector3[vertexCount];
        Array.Copy(structure.Positions, positions, vertexCount);
        // Subdivided coarse faces can have explicitly widened boundaries whose X
        // differs from interpolation of the original corners. Preserve that result.
        var constructedX = new float[structure.ConstructedCount];
        for (var i = 0; i < constructedX.Length; i++)
            constructedX[i] = structure.Positions[vertexCount + i].x;
        return new MovableStructureModel.Plan(structure.SourcePositions, positions, structure.SourceIndices,
            new[] { removed }, structure.AddedVertices, structure.Fragments, structure.InteriorVertices,
            constructedX);
    }

