    internal static MovableStructureModel.Plan CreatePlan(int lod, Vector3[] source,
        int[] indices, float halfWidthDelta)
    {
        var weights = Weights(lod);
        var count = lod switch { 0 => 116, 1 => 81, 2 => 100, _ => throw new ArgumentOutOfRangeException(nameof(lod)) };
        if (source.Length != weights.Length || indices.Length != count * 3)
            throw new InvalidOperationException("Draw01 ordinary cap differs from its recorded topology.");
        var positions = (Vector3[])source.Clone();
        for (var i = 0; i < positions.Length; i++) positions[i].x += weights[i] * halfWidthDelta;
        return new MovableStructureModel.Plan(source, positions, new[] { indices }, new[] { new bool[count] });
    }

