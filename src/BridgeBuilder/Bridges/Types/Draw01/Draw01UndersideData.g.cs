    internal static void Apply(int lod, Draw01UndersideLayout layout, Vector3[] positions, bool[] removed)
    {
        // Far LOD retains its authored merged structural envelope; it was never removed.
        if (lod == 2) return;
        var groups = lod == 0 ? Near : Middle;
        foreach (var group in groups)
        {
            var span = layout.Spans[group.Role];
            if (!(span.y > span.x)) continue;
            foreach (var face in group.Faces) removed[face] = false;
            foreach (var vertex in group.Vertices)
                positions[vertex.Index].x = Mathf.LerpUnclamped(span.x, span.y, vertex.Fraction);
        }
    }

