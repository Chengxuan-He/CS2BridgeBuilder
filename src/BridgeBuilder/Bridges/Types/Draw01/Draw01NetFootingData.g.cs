    internal static MovableStructureModel.Plan CreatePlan(int lod, Vector3[] source,
        int[] indices, float halfWidthDelta)
    {
        var weights = Weights(lod);
        var expectedTriangles = lod switch { 0 => 192, 1 => 115, 2 => 100, _ => throw new ArgumentOutOfRangeException(nameof(lod)) };
        if (source.Length != weights.Length || indices.Length != expectedTriangles * 3)
            throw new InvalidOperationException("Draw01 ordinary footing differs from its recorded topology.");
        var positions = (Vector3[])source.Clone();
        for (var i = 0; i < positions.Length; i++) positions[i].x += weights[i] * halfWidthDelta;
        return new MovableStructureModel.Plan(source, positions, new[] { indices },
            new[] { new bool[expectedTriangles] });
    }

