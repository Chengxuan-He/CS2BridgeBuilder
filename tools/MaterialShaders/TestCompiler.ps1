[CmdletBinding()]
param([string]$AssemblyPath,[string]$SeedPath,[string]$BundleOutput,[int]$SourceTemplate=17)
$ErrorActionPreference='Stop'
if (!$AssemblyPath) { $AssemblyPath=Join-Path $PSScriptRoot '../../src/BridgeBuilder/bin/Release/BridgeBuilder.dll' }
$assembly=[Reflection.Assembly]::Load([IO.File]::ReadAllBytes([IO.Path]::GetFullPath($AssemblyPath)))
$type=$assembly.GetType('BridgeBuilder.Bridges.MovableCustomShaderProgram',$true)
$flags=[Reflection.BindingFlags]'Static,NonPublic'
$kind=$type.GetNestedType('Kind',[Reflection.BindingFlags]'NonPublic')
foreach($name in @('SkeletonDecal','WorldLayeredPbr')) {
 $source=$type.GetMethod('MaterialFunction',$flags).Invoke($null,@([Enum]::Parse($kind,$name)))
 $evaluation=if($name -eq 'SkeletonDecal'){'BBEvaluateDecal(uv.xy,float4(1,1,1,1))'}else{'BBEvaluateLayered(uv.xy,uv.zw,float4(1,1,1,1))'}
 $function="`nfloat4 main(float4 p:SV_POSITION,float4 uv:TEXCOORD0):SV_Target { BBMaterialSample m=$evaluation; return float4(m.albedo,m.alpha); }"
 $compileArgs=[object[]]@(($source+$function),'main','ps_5_0',$null,$null)
 $ok=$type.GetMethod('TryCompile',$flags).Invoke($null,$compileArgs)
 if(!$ok -or $compileArgs[3].Length -eq 0){throw "Compilation failed: $($compileArgs[4])"}
 "PASS current assembly $name generated bytes=$($compileArgs[3].Length)"
}
$badArgs=[object[]]@('invalid material source','main','ps_5_0',$null,$null)
$badOk=$type.GetMethod('TryCompile',$flags).Invoke($null,$badArgs)
if($badOk -or $badArgs[3].Length -ne 0 -or [string]::IsNullOrEmpty($badArgs[4])){throw 'Compiler failure result lost diagnostic or retained output.'}
'PASS invalid source returns diagnosed failure without propagating compiler exception'
if($SeedPath) {
 $packageBytes=[IO.File]::ReadAllBytes([IO.Path]::GetFullPath($SeedPath))
 $envelopeType=$assembly.GetType('BridgeBuilder.Runtime.BridgeCustomShaderPackage',$true)
 $textStream=[IO.MemoryStream]::new()
 try {
  $writeArgs=[object[]]@($textStream,$SourceTemplate,$packageBytes,$null)
  if(!$envelopeType.GetMethod('TryWrite',$flags).Invoke($null,$writeArgs)){throw $writeArgs[3]}
  $textStream.Position=0
  $readArgs=[object[]]@($textStream,$null,$null,$null)
  if(!$envelopeType.GetMethod('TryRead',$flags).Invoke($null,$readArgs)){throw $readArgs[3]}
  $sha=[Security.Cryptography.SHA256]::Create()
  try {if($readArgs[1] -ne $SourceTemplate -or [Convert]::ToBase64String($sha.ComputeHash($readArgs[2])) -ne [Convert]::ToBase64String($sha.ComputeHash($packageBytes))){throw 'Program envelope changed source identity or payload.'}}finally{$sha.Dispose()}
  "PASS owner program envelope exact roundtrip binaryBytes=$($packageBytes.Length); textBytes=$($textStream.Length)"
 } finally {$textStream.Dispose()}
 $badStream=[IO.MemoryStream]::new([Text.Encoding]::UTF8.GetBytes("BridgeBuilder.MaterialProgram/1`n17`nnot-base64`n"))
 try {
  $readArgs=[object[]]@($badStream,$null,$null,$null)
  if($envelopeType.GetMethod('TryRead',$flags).Invoke($null,$readArgs) -or $readArgs[1] -ne -1 -or $readArgs[2].Length -ne 0 -or [string]::IsNullOrEmpty($readArgs[3])){throw 'Invalid envelope retained partial output.'}
  'PASS malformed owner program envelope returns no partial output and explicit diagnostic'
 }finally{$badStream.Dispose()}
 $stream=[IO.File]::OpenRead([IO.Path]::GetFullPath($SeedPath))
 try {
  $clock=[Diagnostics.Stopwatch]::StartNew()
  $packageArgs=[object[]]@($stream,$null,$null)
  $ok=$type.GetMethod('TryCompilePackage',$flags).Invoke($null,$packageArgs)
  $clock.Stop()
  if(!$ok){throw "Package compilation failed: $($packageArgs[2])"}
  if($BundleOutput){[IO.File]::WriteAllBytes([IO.Path]::GetFullPath($BundleOutput),$packageArgs[1])}
  "PASS current assembly complete runtime package bytes=$($packageArgs[1].Length); compileAndPatchMs=$($clock.Elapsed.TotalMilliseconds)"
 } finally {$stream.Dispose()}
 $stream=[IO.MemoryStream]::new([byte[]](66,66,83,49,1,0,0,0))
 try {
  $packageArgs=[object[]]@($stream,$null,$null)
  $ok=$type.GetMethod('TryCompilePackage',$flags).Invoke($null,$packageArgs)
  if($ok -or $packageArgs[1].Length -ne 0 -or [string]::IsNullOrEmpty($packageArgs[2])){throw 'Truncated package retained output or lost error.'}
  'PASS truncated package returns failure with no partial container'
 } finally {$stream.Dispose()}
}
