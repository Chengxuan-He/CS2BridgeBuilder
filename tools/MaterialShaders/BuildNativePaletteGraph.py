"""Offline complete native library graph for the network palette program.

The existing movable program graphs and their producer are intentionally unchanged.
"""
import argparse
import copy
import hashlib
import json
from pathlib import Path
import re
import sys

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--game-resources', type=Path, required=True)
parser.add_argument('--program-dir', type=Path, required=True)
parser.add_argument('--output', type=Path, required=True)
parser.add_argument('--unitypy', type=Path)
args = parser.parse_args()
if args.unitypy:
    sys.path.insert(0, str(args.unitypy))
import UnityPy

root = Path(__file__).resolve().parents[2]
out = args.output.resolve()
out.mkdir(parents=True, exist_ok=True)
name = 'NetworkPalette'
seed = Path(__file__).with_name('NativeGraphSeed.bundle')
env = UnityPy.load(str(seed))
objects = list(env.objects)
def first(kind):
    return next(o for o in objects if o.type.name == kind)
material_obj, graph_obj, shader_obj = first('Material'), first('MonoBehaviour'), first('Shader')
bundle_obj, script_obj = first('AssetBundle'), first('MonoScript')
program = UnityPy.load(str(args.program_dir / (name + '.bundle')))
program_shader = next(o for o in program.objects if o.type.name == 'Shader')
shader_obj.serialized_type.node = program_shader.serialized_type.node
shader_obj.set_raw_data(program_shader.get_raw_data())

game = UnityPy.load(str(args.game_resources))
# Native resources graph supplies the complete template, texture stacks and defaults.
native_graph = next(o for o in game.objects if o.path_id == 124190).read_typetree(graph_obj.serialized_type.node)
description = copy.deepcopy(next(d for d in native_graph['m_MaterialLibrary']['m_Materials'] if d['m_Hash'] == 17))
native_material = next(o for o in game.objects if o.path_id == description['m_Material']['m_PathID'])
material = native_material.read_typetree(material_obj.serialized_type.node)
assert material['m_Name'] == 'NetCompositionMeshLit'
assert all(v['m_Texture']['m_PathID'] == 0 for _, v in material['m_SavedProperties']['m_TexEnvs'])
material['m_Name'] = name
material['m_Shader'] = {'m_FileID': 0, 'm_PathID': shader_obj.path_id}
for i in range(3):
    material['m_SavedProperties']['m_Colors'].append(('_BridgeBuilderPalette' + str(i), dict(r=1., g=1., b=1., a=1.)))
material_obj.save_typetree(material)
description['m_Material'] = {'m_FileID': 0, 'm_PathID': material_obj.path_id}
graph = graph_obj.read_typetree()
graph['m_MaterialLibrary']['m_Materials'] = [description]
graph_obj.save_typetree(graph)
for obj in objects:
    if obj.type.name == 'Material' and obj.path_id != material_obj.path_id:
        del obj.assets_file.objects[obj.path_id]
identity = hashlib.sha256(name.encode()).hexdigest()[:32]
bundle_data = bundle_obj.read_typetree()
bundle_data['m_Name'] = identity
bundle_data['m_AssetBundleName'] = identity
bundle_data['m_PreloadTable'] = [{'m_FileID': 0, 'm_PathID': o.path_id} for o in (shader_obj, script_obj, material_obj, graph_obj)]
bundle_data['m_Container'] = [('assets/nativegraph.asset', dict(preloadIndex=0, preloadSize=4,
    asset={'m_FileID': 0, 'm_PathID': graph_obj.path_id}))]
bundle_obj.save_typetree(bundle_data)
bundle = next(iter(env.files.values()))
old_key = next(k for k, value in bundle.files.items() if hasattr(value, 'objects'))
bundle.files['CAB-' + identity] = bundle.files.pop(old_key)
data = bundle.save(packer='none')
(out / (name + '.bundle')).write_bytes(data)

def offset(obj, tree, change):
    changed_tree = copy.deepcopy(tree)
    change(changed_tree)
    obj.save_typetree(changed_tree)
    changed = bundle.save(packer='none')
    obj.save_typetree(tree)
    assert len(changed) == len(data)
    return min(i for i, (a, b) in enumerate(zip(data, changed)) if a != b)

queue_offset = offset(material_obj, material, lambda tree: tree.update(m_CustomRenderQueue=0x12345678))
hash_offset = offset(graph_obj, graph, lambda tree: tree['m_MaterialLibrary']['m_Materials'][0].update(m_Hash=0x12345678))
identity_offsets = [m.start() for m in re.finditer(identity.encode(), data)]
assert len(identity_offsets) >= 3
cold = UnityPy.load(data)
assert next(o for o in cold.objects if o.type.name == 'Shader').get_raw_data() == program_shader.get_raw_data()
layout = dict(program=name, hashOffset=hash_offset, queueOffset=queue_offset,
              defaultQueue=material['m_CustomRenderQueue'], identityOffsets=identity_offsets,
              bytes=len(data), sha256=hashlib.sha256(data).hexdigest())
(out / 'layout.json').write_text(json.dumps(layout, indent=2) + '\n', encoding='utf-8')
lines = ['// Generated by BuildNativePaletteGraph.py; native UnityFS scalar/string fields.',
         'namespace BridgeBuilder.Runtime;', 'internal static class BridgeNativePaletteLayout', '{']
for field, key in [('HashOffset', 'hashOffset'), ('QueueOffset', 'queueOffset'), ('DefaultQueue', 'defaultQueue')]:
    lines.append(f'    internal const int {field} = {layout[key]};')
lines.append('    internal static readonly int[] IdentityOffsets = { ' + ', '.join(map(str, identity_offsets)) + ' };')
lines.append('}')
(out / 'BridgeNativePaletteLayout.g.cs').write_text('\n'.join(lines) + '\n', encoding='utf-8')
upstream = json.loads((args.program_dir / (name + '.manifest.json')).read_text(encoding='utf-8'))
sources = dict(upstream['sources'])
for file in (Path(__file__), seed):
    sources[file.relative_to(root).as_posix()] = hashlib.sha256(file.read_bytes()).hexdigest()
manifest = dict(schema=2, program=name, producer=Path(__file__).name,
    producerSha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
    packageBytes=len(data), packageSha256=layout['sha256'], format='UnityFS', sources=sources,
    nativeInputs=dict(upstreamShaderBundle=hashlib.sha256((args.program_dir / (name + '.bundle')).read_bytes()).hexdigest(),
                     gameResources=hashlib.sha256(args.game_resources.read_bytes()).hexdigest(),
                     upstream=upstream.get('nativeInputs', {})), sourceTemplate=17, programFamily=0)
(out / (name + '.manifest.json')).write_text(json.dumps(manifest, indent=2) + '\n', encoding='utf-8')
print(json.dumps(layout))
