"""Inspect measured PedestrianDraw02 column parts before emitting all-LOD maps.

Usage: python PedestrianDraw02ColumnParts.py RESEARCH_DIRECTORY OUTPUT_JSON [OUTPUT_CS]
NPZ inputs are decoded native positions/indices, never runtime inputs. This records
the reviewed near/middle assemblies; PedestrianDraw02FarColumn.py handles the far proxy.
"""
import hashlib
import json
from pathlib import Path
import sys
import numpy as np

research, output = map(Path, sys.argv[1:3])
levels = []
for lod in range(3):
    data = np.load(research / f'pedestrian02-column-{lod}.npz')
    vertices, faces = data['positions'], data['indices']
    assert (len(vertices), len(faces)) == ((3332, 1696), (3076, 1526), (121, 92))[lod]
    name = 'PedestrianDrawBridge02Pillar' + (f'_LOD{lod}' if lod else '') + ' Mesh.Geometry'
    level = dict(lod=lod, source=name,
                 sha256=hashlib.sha256((research / 'movable-skin' / name).read_bytes()).hexdigest(),
                 vertices=len(vertices), triangles=len(faces))
    if lod == 2:
        level['status'] = 'Merged shell: separate PedestrianDraw02FarColumn.py subdivision; not a whole-column scale.'
        levels.append(level)
        continue
    parents = list(range(len(vertices)))

    def root(i):
        while parents[i] != i:
            parents[i] = parents[parents[i]]
            i = parents[i]
        return i

    def join(a, b):
        parents[root(int(a))] = root(int(b))

    # The native mesh repeats hard-edge vertices. Rounded welding is only an
    # offline identification aid; no vertices are welded in output geometry.
    seen = {}
    for i, point in enumerate(vertices):
        key = tuple(point.round(3))
        if key in seen:
            join(i, seen[key])
        else:
            seen[key] = i
    for a, b, c in faces:
        join(a, b)
        join(a, c)
    groups = {}
    for i in range(len(vertices)):
        groups.setdefault(root(i), []).append(i)
    assert len(groups) == 88
    parts = []
    for ids in groups.values():
        points = vertices[ids]
        lo, hi = points.min(0), points.max(0)
        assert lo[2] > 0 or hi[2] < 0
        crossing = lo[0] <= 0 <= hi[0]
        if crossing:
            role = 'central connection plate' if hi[0] < 1 else (
                'diagonal brace' if hi[1] - lo[1] > 8 else 'horizontal beam')
        else:
            role = 'pier column' if hi[1] - lo[1] > 9 else 'side bracket'
        parts.append(dict(role=role, end=1 if lo[2] > 0 else -1,
                          transform='own-span stretch' if crossing else 'rigid translation',
                          minimum=lo.tolist(), maximum=hi.tolist(), vertices=ids))
    counts = {role: sum(p['role'] == role for p in parts) for role in sorted({p['role'] for p in parts})}
    assert counts == {'central connection plate': 8, 'diagonal brace': 16,
                      'horizontal beam': 8, 'pier column': 8, 'side bracket': 48}, counts
    assert all(sum(p['end'] == end for p in parts) == 44 for end in (-1, 1))
    level['parts'] = parts
    level['counts'] = counts
    levels.append(level)
    print(f'LOD{lod}: {counts}; all {len(vertices)} vertices assigned once')

# Every mid-distance part must match the near part's role, end and authored bounds.
# Its vertex count may differ; its identity and transform may not.
def key(part):
    return part['role'], part['end'], tuple(part['minimum']), tuple(part['maximum'])

near = {key(p) for p in levels[0]['parts']}
middle = {key(p) for p in levels[1]['parts']}
assert len(near) == len(middle) == 88
assert near == middle, (near - middle, middle - near)
output.write_text(json.dumps(levels, indent=2) + '\n', encoding='utf-8')
print('Near/middle role, end and exact bounds correspondence passed; far map is emitted separately')

if len(sys.argv) > 3:
    # The reviewed detailed parts are emitted independently of the merged far
    # shell. Do not emit a fallback for LOD2 or silently reuse a different LOD.
    lines = ['// Measured PedestrianDrawBridge02Pillar detailed part displacements.',
             '// Generated by PedestrianDraw02ColumnParts.py; far shell is a separate plan.',
             'using System;', 'using UnityEngine;', '', 'namespace BridgeBuilder.Bridges;', '',
             'internal static class PedestrianDraw02ColumnWideningData', '{',
             '    internal static MovableStructureModel.Plan CreateDetailedPlan(int lod,',
             '        Vector3[] source, int[] indices, float delta)', '    {',
             '        var data = lod switch', '        {',
             '            0 => (Weights: Near, IndexCount: 5088),',
             '            1 => (Weights: Middle, IndexCount: 4578),',
             '            _ => throw new ArgumentOutOfRangeException(nameof(lod))',
             '        };',
             '        if (!float.IsFinite(delta) || source.Length != data.Weights.Length ||',
             '            indices.Length != data.IndexCount)',
             '            throw new InvalidOperationException("PedestrianDraw02 column requires its recorded detailed mesh layout.");',
             '        var positions = (Vector3[])source.Clone();',
             '        for (var i = 0; i < positions.Length; i++) positions[i].x += data.Weights[i] * delta;',
             '        return new MovableStructureModel.Plan(source, positions, new[] { indices },',
             '            new[] { new bool[indices.Length / 3] });', '    }', '']
    for level, field in zip(levels[:2], ('Near', 'Middle')):
        v = np.load(research / f"pedestrian02-column-{level['lod']}.npz")['positions']
        weights = np.full(len(v), np.nan, dtype=np.float32)
        for part in level['parts']:
            ids = part['vertices']
            lo, hi = part['minimum'][0], part['maximum'][0]
            if part['transform'] == 'rigid translation':
                weights[ids] = -1 if hi < 0 else 1
            else:
                weights[ids] = (2 * v[ids, 0].astype(float) - lo - hi) / (hi - lo)
        assert np.isfinite(weights).all()
        for delta in (-.5, 0., 2., 8.):
            moved = v.copy()
            moved[:, 0] += weights * np.float32(delta)
            assert np.array_equal(moved[:, 1:], v[:, 1:])
            for part in level['parts']:
                ids = part['vertices']
                old_span = np.ptp(v[ids, 0])
                expected = old_span + (2 * delta if part['transform'] == 'own-span stretch' else 0)
                assert expected > 0
                assert abs(float(np.ptp(moved[ids, 0])) - expected) < 5e-6
                if part['transform'] == 'rigid translation':
                    assert np.unique(weights[ids]).size == 1
            if delta == 0:
                assert np.array_equal(moved, v)
        lines += ['    // Geometry SHA-256: ' + level['sha256'],
                  f'    private static readonly float[] {field} =', '    {']
        for start in range(0, len(weights), 12):
            lines.append('        ' + ', '.join(format(float(w), '.9g') + 'f'
                         for w in weights[start:start+12]) + ',')
        lines += ['    };', '']
        print(f"LOD{level['lod']}: all 88 parts preserve Y/Z and their measured stretch/translation at four widths")
    lines += ['}', '']
    Path(sys.argv[3]).write_text('\n'.join(lines), encoding='utf-8')
