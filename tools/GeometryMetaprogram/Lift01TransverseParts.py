"""Emit reviewed transverse members, excluding road/base and joined support shells.
Usage: python Lift01TransverseParts.py RESEARCH_DIRECTORY OUTPUT_CS
Native detailed component identities correspond one-to-one across the two LODs.
"""
from pathlib import Path
import hashlib
import json
import sys
import numpy as np

r, output = map(Path, sys.argv[1:])
levels = [json.loads((r / f'lift01-crossing-{lod}.json').read_text()) for lod in range(2)]
assert len(levels[0]) == len(levels[1]) == 645
# Reviewed lower web plates, upper transverse beams and transverse tie plates.
# Joined U frames, road bases, deck end lips and tower platforms are excluded.
selected = [1, 5, 6, 9, 11, 15, 16, 19, 347, 350, 351, 354, 355, 358, 359,
            362, 363, 366, 367, 370, 371, 374, 375, 378, 379, 382, 383, 386,
            495, 498, 499, 502, 503, 506, 507, 510, 511, 514, 515, 518, 519,
            522, 523, 526, 527, 530, 531, 534, 492, 639,
            90, 91, 100, 101, 110, 111, 121, 122, 126, 127, 136, 137, 150, 151,
            160, 161, 186, 187, 196, 197, 206, 207, 217, 218, 222, 223, 232, 233,
            246, 247,
            94, 95, 104, 105, 113, 124, 130, 131, 139, 148, 154, 155, 163,
            172, 173, 174, 175, 176, 177, 178, 179, 180, 181, 182, 183, 184,
            185, 190, 191, 200, 201, 209, 220, 226, 227, 235, 244, 250, 251,
            257, 266, 267, 268, 269, 270, 271, 272, 273, 274, 275, 276, 277]
assert [sum(len(levels[lod][i]['vertices']) for i in selected) for lod in range(2)] == [16778, 15696]
for i in selected:
    assert levels[0][i]['minimum'] == levels[1][i]['minimum']
    assert levels[0][i]['maximum'] == levels[1][i]['maximum']
    lo, hi = levels[0][i]['minimum'], levels[0][i]['maximum']
    assert lo[0] == -hi[0]
    assert hi[0] in (3.62957763671875, 5.593505859375, 6.1463623046875, 5.9893798828125)
assert len(selected) == len(set(selected)) == 132

lines = ['// Native LiftBridge01 transverse members, game 1.6.2f1.',
         '// Generated by Lift01TransverseParts.py; excludes road/base/joined shells.',
         'using System;', 'using UnityEngine;', '', 'namespace BridgeBuilder.Bridges;', '',
         'internal static class Lift01TransverseParts', '{',
         '    internal static void Apply(int lod, Vector3[] source, Vector3[] positions, float delta)',
         '    {', '        var data = lod switch', '        {',
         '            0 => (Count: 472209, Parts: Near),',
         '            1 => (Count: 351968, Parts: Middle),',
         '            _ => throw new ArgumentOutOfRangeException(nameof(lod))', '        };',
         '        if (!float.IsFinite(delta) || source.Length != data.Count || positions.Length != data.Count)',
         '            throw new InvalidOperationException("Lift01 transverse parts require their recorded main mesh.");',
         '        foreach (var part in data.Parts)', '        {',
         '            var span = part.Max - part.Min;',
         '            foreach (var i in part.Vertices)',
         '                positions[i].x = source[i].x + (2f * source[i].x - part.Min - part.Max) / span * delta;',
         '        }', '    }', '']
def literal(x):
    return format(float(np.float32(x)), '.9g') + 'f'
for lod, field in enumerate(('Near', 'Middle')):
    d = np.load(r / f'lift01-main-{lod}.npz')
    v = d['positions']
    name = 'LiftBridge01' + ('_LOD1' if lod else '') + ' Mesh.Geometry'
    lines += ['    // Geometry SHA-256: ' + hashlib.sha256((r / 'movable-skin' / name).read_bytes()).hexdigest(),
              f'    private static readonly (float Min, float Max, int[] Vertices)[] {field} =', '    {']
    excluded = {i for part in (3, 13, 487, 30, 31, 32, 33, 493, 640) for i in levels[lod][part]['vertices']}
    excluded.update(i for part in json.loads((r / f'lift01-side-{lod}.json').read_text()) for i in part['vertices'])
    assert v.shape == ((472209, 3) if lod == 0 else (351968, 3))
    assert d['indices'].shape == ((380478, 3) if lod == 0 else (228254, 3))
    used = set()
    for index in selected:
        p = levels[lod][index]
        ids = p['vertices']
        assert not used.intersection(ids)
        assert not excluded.intersection(ids)
        used.update(ids)
        lo, hi = p['minimum'][0], p['maximum'][0]
        assert np.array_equal(v[ids].min(0), p['minimum'])
        assert np.array_equal(v[ids].max(0), p['maximum'])
        member = np.isin(d['indices'], ids)
        assert not np.any(member.any(1) & ~member.all(1))
        faces = d['indices'][member.all(1)]
        before = v[faces].astype(float)
        n0 = np.cross(before[:,1] - before[:,0], before[:,2] - before[:,0])
        weights = (2 * v[ids, 0].astype(float) - lo - hi) / (hi - lo)
        for delta in (-4., -2.75, -(hi-lo)/2, max(-.5, -(hi-lo)*.25), 0., 2., 8.):
            moved = v[ids].astype(float)
            moved[:, 0] += weights * delta
            assert np.array_equal(moved[:, 1:], v[ids, 1:])
            assert abs(np.ptp(moved[:, 0]) - abs(hi - lo + 2 * delta)) < 1e-10
            assert hi - lo > 0
            transformed = v.astype(float)
            transformed[ids] = moved
            after = transformed[faces]
            n1 = np.cross(after[:,1] - after[:,0], after[:,2] - after[:,0])
            valid = np.linalg.norm(n0, axis=1) > 1e-8
            assert np.isfinite(moved).all()
            if hi-lo+2*delta > 0: assert np.all(np.sum(n0[valid] * n1[valid], axis=1) > 0)
        lines += [f'        ({literal(lo)}, {literal(hi)}, new[]', '        {']
        for start in range(0, len(ids), 20):
            lines.append('            ' + ', '.join(map(str, ids[start:start+20])) + ',')
        lines += ['        }),']
    lines += ['    };', '']
    print(f'LOD{lod}: {len(selected)} corresponding members / {len(used)} vertices; seven signed own-span checks passed')
lines += ['}', '']
output.write_text('\n'.join(lines), encoding='utf-8')
