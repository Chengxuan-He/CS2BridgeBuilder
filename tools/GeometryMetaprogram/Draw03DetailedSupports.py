"""Record Draw03 detailed column/footing side bodies and central panel seams.

Usage: python Draw03DetailedSupports.py RESEARCH_DIRECTORY OUTPUT_CS
Far LOD needs a separate measured panel-boundary reconstruction; this emitter
deliberately accepts only the two original detailed levels.
"""
from pathlib import Path
import hashlib
import sys
import numpy as np

r, output = map(Path, sys.argv[1:])
hashes = (
    ('77ebf81e11324571d8e552f53aa32a258866ddb67376d41d06bdc397bf5a4a5b',
     '5b10921bd36c6c587c42e8b6d76c90bdc61e7ad23de4e155e07a295d4df3db3e'),
    ('e0deea7435d42761f8ac5bf8274617587c0c55f5568ba913c7be053908b8eaba',
     'b69766bacb96f51545bf0dccd1928a5d6e0d4ec0de931bd1c1ea006f68e38b42'))
tables = []
for part in range(2):
    for lod in range(2):
        name = 'DrawBridge03Pillar' + ('Base' if part else '') + (f'_LOD{lod}' if lod else '') + ' Mesh.Geometry'
        digest = hashlib.sha256((r / 'movable-skin' / name).read_bytes()).hexdigest()
        assert digest == hashes[part][lod]
        d = np.load(r / f'draw03-support-{part}-{lod}.npz')
        v, faces = d['positions'], d['indices'].reshape(-1, 3)
        assert (len(v), len(faces)) == (((3856, 4056), (4105, 2433)), ((1152, 1408), (1768, 844)))[part][lod]
        # Detailed column centre seams contain the native float residues below;
        # footing seams are exactly zero. Never classify these residues as a side.
        centres = (0.,) if part else (-9.5367431640625e-7, -1.9073486328125e-6)
        centre = np.isin(v[:, 0], centres)
        signs = np.sign(v[:, 0]).astype(int)
        signs[centre] = 0
        minimum = float(np.min(abs(v[~centre, 0])))
        assert minimum == (10.161376953125 if part else 11.728759765625)
        assert not np.any((signs[faces].min(1) < 0) & (signs[faces].max(1) > 0))
        panels = centre[faces].any(1)
        rigid = ~panels
        # Every non-panel face belongs entirely to one side body. Every central
        # panel retains its native centre-to-edge span; no full-object scaling.
        assert np.all(signs[faces[rigid]] == signs[faces[rigid, :1]])
        p = v[faces].astype(float)
        before = np.cross(p[:, 1]-p[:, 0], p[:, 2]-p[:, 0])
        valid = np.linalg.norm(before, axis=1) > 1e-8
        for delta in (-16., -8., -.1, 0., 2., 8.):
            moved = v.astype(float).copy()
            moved[:, 0] += signs * delta
            assert np.array_equal(moved[:, 1:], v[:, 1:])
            assert np.array_equal(moved[centre], v[centre])
            q = moved[faces]
            assert np.allclose(q[rigid, 1:]-q[rigid, :1], p[rigid, 1:]-p[rigid, :1], rtol=0, atol=1e-12)
            after = np.cross(q[:, 1]-q[:, 0], q[:, 2]-q[:, 0])
            if delta >= -.1: assert np.all(np.sum(before[valid]*after[valid], axis=1) > 0)
        ranges = []
        for i, sign in enumerate(signs):
            if ranges and ranges[-1][1] == i-1 and ranges[-1][2] == sign:
                ranges[-1][1] = i
            else:
                ranges.append([i, i, int(sign)])
        tables.append((part, lod, len(v), faces.size, digest, ranges, minimum))
        np.savez(r / f'draw03-support-plan-{part}-{lod}.npz', positions=v,
                 indices=faces, weights=signs)
        print(f'Part {part} LOD{lod}: {len(v)} vertices, {len(faces)} unchanged triangles, '
              f'{centre.sum()} centre vertices; rigid-edge and six signed widths and positive-span winding checks passed')

lines = ['// Measured DrawBridge03 detailed support panels and side bodies, game 1.6.2f1.',
         '// Generated by Draw03DetailedSupports.py; far LOD uses a separate plan.',
         'using System;', 'using UnityEngine;', '', 'namespace BridgeBuilder.Bridges;', '',
         'internal static class Draw03DetailedSupports', '{',
         '    internal static MovableStructureModel.Plan Create(bool footing, int lod, Vector3[] source, int[] indices, float delta)',
         '    {', '        var data = (footing, lod) switch', '        {']
for part, lod, count, indices, digest, ranges, minimum in tables:
    lines.append(f'            ({str(bool(part)).lower()}, {lod}) => (Count: {count}, Indices: {indices}, Minimum: {minimum:.9g}f, Parts: Parts{part}{lod}),')
lines += ['            _ => throw new ArgumentOutOfRangeException(nameof(lod))', '        };',
          '        if (!float.IsFinite(delta) || source.Length != data.Count || indices.Length != data.Indices)',
          '            throw new InvalidOperationException("Draw03 detailed supports require their measured layout.");',
          '        var positions = (Vector3[])source.Clone();',
          '        foreach (var part in data.Parts)',
          '            for (var i = part.First; i <= part.Last; i++) positions[i].x += part.Sign * delta;',
          '        return new MovableStructureModel.Plan(source, positions, new[] { indices }, new[] { new bool[indices.Length / 3] });',
          '    }', '']
for part, lod, count, indices, digest, ranges, minimum in tables:
    lines += ['    // Geometry SHA-256: ' + digest,
              f'    private static readonly (int First, int Last, int Sign)[] Parts{part}{lod} =', '    {']
    lines += [f'        ({a}, {b}, {sign}),' for a, b, sign in ranges]
    lines += ['    };', '']
lines += ['}', '']
output.write_text('\n'.join(lines), encoding='utf-8')
