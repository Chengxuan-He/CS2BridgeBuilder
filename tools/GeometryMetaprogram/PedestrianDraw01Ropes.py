"""Recover detailed left/right rope ownership in the native middle LOD.

Native simplification reuses the two almost-coincident inner X planes across
the opposite ropes, joining their position-welded components. Actual face
vertices remain independent, so no subdivision or attribute editing is needed.
"""
from pathlib import Path
import hashlib, json, sys
import numpy as np

r, output = map(Path, sys.argv[1:])
audit = json.loads((r/'all-movable-audit.json').read_text())
sources = []
for lod in (0,1):
    name = 'PedestrianDrawBridge01'+('_LOD1' if lod else '')+' Mesh'
    digest = hashlib.sha256((r/'movable-skin'/(name+'.Geometry')).read_bytes()).hexdigest()
    assert any(a.get('sha256') == digest for a in audit['assets'].values())
    sources.append((np.load(r/f'pedestrian01-main-{lod}-0.npz'),digest))
near, _ = sources[0]; mid, digest = sources[1]
v, f, components = mid['positions'], mid['indices'], mid['component']
weights = np.zeros(len(v),dtype=np.int8)
selected = np.isin(components,(404,413))
assert selected.sum() == 777 and np.all(selected[f].any(1)==selected[f].all(1))
# Exact inner planes are measured from the four detailed rope components.
inner = []
for group,side in ((421,-1),(422,1),(431,-1),(432,1)):
    p = near['positions'][near['component']==group]
    assert len(p)==164 and np.all(np.sign(p[:,0])==side)
    inner.append(float(p[:,0].max() if side<0 else p[:,0].min()))
assert inner[0]==inner[2] and inner[1]==inner[3]
sf = f[selected[f].all(1)]
for face in sf:
    x = v[face,0]
    exterior = x[(x<inner[0]) | (x>inner[1])]
    assert len(exterior)>0 and np.all(np.sign(exterior)==np.sign(exterior[0]))
    side = int(np.sign(exterior[0]))
    for i in face:
        assert weights[i] in (0,side), 'A shared vertex needs explicit reconstruction'
        weights[i] = side
assert np.array_equal(weights!=0,selected)
bones = np.load(r/'pedestrian01-bones-1.npy')
assert set(bones[selected[f].all(1)]) == {'bone_0','bone_1','bone_2','mixed_bones'}
for delta in (-.25,0,2,8):
    q = v.copy(); q[:,0] += weights*delta
    assert np.array_equal(q[~selected],v[~selected])
    assert np.array_equal(q[:,1:],v[:,1:])
    for corner in (1,2):
        assert np.allclose(q[sf[:,corner]]-q[sf[:,0]],
                           v[sf[:,corner]]-v[sf[:,0]],atol=1e-12,rtol=0)
np.savez(r/'pedestrian01-rope-motion.npz',positions=v,indices=f,
         selected=selected,weights=weights)
ranges = []
for i in np.flatnonzero(selected):
    side = int(weights[i]); i=int(i)
    if ranges and ranges[-1][1]==i-1 and ranges[-1][2]==side:ranges[-1][1]=i
    else:ranges.append([i,i,side])
lines = ['// Generated by PedestrianDraw01Ropes.py; original mixed skinning is retained.',
         'using System;','using UnityEngine;','','namespace BridgeBuilder.Bridges;','',
         'internal static class PedestrianDraw01Ropes','{',
         '    internal static void Apply(int lod, Vector3[] source, Vector3[] positions, float delta)',
         '    {',
         '        var count = lod switch { 0 => 34931, 1 => 33598, 2 => 1702, _ => throw new ArgumentOutOfRangeException(nameof(lod)) };',
         '        if (source.Length != count || positions.Length != count || !float.IsFinite(delta))',
         '            throw new InvalidOperationException("PedestrianDraw01 rope source layout changed.");',
         '        // Detailed ropes are covered by RigidParts. The far mesh omits ropes.',
         '        if (lod != 1) return;',
         '        foreach (var part in Parts)',
         '            for (var i = part.First; i <= part.Last; i++)',
         '                positions[i].x = source[i].x + part.Side * delta;',
         '    }','', '    // Geometry SHA-256: '+digest,
         '    private static readonly (int First, int Last, int Side)[] Parts =','    {']
lines += [f'        ({a}, {b}, {side}),' for a,b,side in ranges]
lines += ['    };','}','']
output.write_text('\n'.join(lines),encoding='utf-8')
print(f'PASS: {selected.sum()} vertices, {len(sf)} triangles; exclusive detailed-side ownership, '
      'mixed bones retained, four-width rigid-edge and exclusion checks')
