"""Emit measured native root unlock inputs, independently of bridge network Prefabs.
Usage: python MovableUnlockInputs.py RESEARCH_DIRECTORY TYPES_DIRECTORY
Inputs follow game 1.6.2f1 PrefabInitializeSystem component dependency filtering.
"""
from pathlib import Path
import hashlib
import json
import sys

research, destination = map(Path, sys.argv[1:])
raw = (research / 'movable-unlock-inputs.json').read_bytes()
assert hashlib.sha256(raw).hexdigest() == 'eab5f44e4840aadaa4b81d2cac85482580c5b7a98885fca955a6067cc216eef0'
inputs = json.loads(raw)
audit_raw = (research / 'all-movable-audit.json').read_bytes()
assert hashlib.sha256(audit_raw).hexdigest() == '47ef0f1723e8643e74a17751aa480f97260bf6e549aa60ec9f14f8e003b12070'
audit = json.loads(audit_raw)
roots = {audit['selected'][str(i)]['data']['m_Name']: audit['selected'][str(i)]['data'] for i in audit['roots']}
assert inputs.keys() == roots.keys()
for name, entry in inputs.items():
    root = roots[name]
    implicit = [p['m_Section']['m_PathID'] for p in root['m_Sections']]
    for key in ('m_AggregateType', 'm_StyleType', 'm_ZoneBlock'):
        if root.get(key, {}).get('m_PathID'): implicit.append(root[key]['m_PathID'])
    for ref in root['components']:
        component = audit['selected'][str(ref['m_PathID'])]
        kind, data = component['class'], component['data']
        assert data['active'] == 1
        if kind in ('NetSubObjects', 'AuxiliaryNets', 'Bridge', 'ElectricityConnection', 'NetPollution', 'Unlockable'):
            continue
        if kind in ('OverheadNetSections', 'UndergroundNetSections'):
            implicit += [p['m_Section']['m_PathID'] for p in data['m_Sections']]
        elif kind == 'EffectSource': implicit += [p['m_Effect']['m_PathID'] for p in data['m_Effects']]
        elif kind == 'AssetPackItem': implicit += [p['m_PathID'] for p in data['m_Packs'] if p['m_PathID']]
        else:
            key = {'PlaceableNet': 'm_UndergroundPrefab', 'ServiceObject': 'm_Service',
                   'ContentPrerequisite': 'm_ContentPrerequisite', 'UIObject': 'm_Group'}[kind]
            if data[key]['m_PathID']: implicit.append(data[key]['m_PathID'])
    assert implicit == [p['path_id'] for p in entry['implicit']]
    gates = [audit['selected'][str(c['m_PathID'])]['data'] for c in root['components'] if c['name'] == 'Unlockable']
    assert len(gates) <= 1
    gate = gates[0] if gates else {'m_RequireAll': [], 'm_RequireAny': [], 'm_IgnoreDependencies': False}
    for field, original in (('all', 'm_RequireAll'), ('any', 'm_RequireAny')):
        assert [p['path_id'] for p in entry[field]] == [p['m_PathID'] for p in gate[original]]
    assert entry['ignore'] == bool(gate['m_IgnoreDependencies'])
    style = name.replace('PedestrianDrawBridge', 'PedestrianDraw').replace('DrawBridge', 'Draw').replace('LiftBridge', 'Lift')
    folder = 'Lift03' if name.endswith(' Train Track') else style
    identifier = 'Lift03Track' if name.endswith(' Train Track') else style
    lines = ['// Native game 1.6.2f1 root dependency inputs: ' + name,
             '// Input SHA-256: ' + hashlib.sha256(raw).hexdigest(),
             '// Generated by MovableUnlockInputs.py. Native sub-object/auxiliary unlock dependencies are ignored.',
             'using System.Collections.Generic;', 'using CS2Mods.Shared.Infrastructure;', 'using Game.Prefabs;',
             '', 'namespace BridgeBuilder.Bridges;', '', f'internal static class {identifier}UnlockData', '{',
             '    internal static bool Apply(NetGeometryPrefab target, ExportReport report, List<PrefabBase> created) =>',
             '        MovableUnlockInputs.Apply(target, report, created, Dependencies, RequireAll, RequireAny,',
             '            ' + str(entry['ignore']).lower() + ');', '']
    for field, member in (('implicit', 'Dependencies'), ('all', 'RequireAll'), ('any', 'RequireAny')):
        lines += [f'    private static readonly PrefabID[] {member} =', '    {']
        for p in entry[field]:
            assert p['name'] and p['type'].endswith('Prefab')
            assert p['name'] == audit['names'][str(p['path_id'])]
            lines.append(f'        new({json.dumps(p["type"])}, {json.dumps(p["name"])}),')
        lines += ['    };', '']
    lines += ['}', '']
    (destination / folder / (identifier + 'UnlockData.g.cs')).write_text('\n'.join(lines), encoding='utf-8')
    print(identifier, len(entry['implicit']), len(entry['all']), len(entry['any']))
