"""Emit measured PedestrianDraw01 supports; side columns translate, foundations stretch."""
from pathlib import Path
import sys,json,hashlib
import numpy as np
r,output=map(Path,sys.argv[1:]);audit=json.loads((r/'all-movable-audit.json').read_text())
records=json.loads((r/'pedestrian01-support-parts.json').read_text());tables=[]
lines=['// Measured native PedestrianDrawBridge01 supports; generated by PedestrianDraw01Supports.py.','using System;','using UnityEngine;','','namespace BridgeBuilder.Bridges;','','internal static class PedestrianDraw01SupportGeometry','{','    internal static MovableStructureModel.Plan Create(bool footing, int lod, Vector3[] source, int[] indices, float delta)','    {','        var data = (footing, lod) switch','        {']
for row in records:
 part,lod=row['part'],row['lod'];d=np.load(r/f'pedestrian01-support-{part}-{lod}.npz');v,f,c=d['positions'],d['indices'],d['component']
 digest=hashlib.sha256((r/'movable-skin'/row['source']).read_bytes()).hexdigest()
 assert digest==row['sha256'] and any(a.get('sha256')==digest for a in audit['assets'].values())
 assert len(row['parts'])==(2 if part else 8)
 weights=np.zeros(len(v))
 for p in row['parts']:
  ids=np.flatnonzero(c==p['id']);lo,hi=v[ids].min(0),v[ids].max(0)
  assert np.array_equal(lo,p['minimum']) and np.array_equal(hi,p['maximum'])
  if part:
   assert lo[0]==-4.0821533203125 and hi[0]==4.0821533203125
   weights[ids]=v[ids,0]/4.0821533203125
  else:
   assert lo[0]>0 or hi[0]<0
   weights[ids]=1 if lo[0]>0 else -1
 for delta in (-1,0,2,8):
  q=v.astype(float).copy();q[:,0]+=weights*delta
  assert np.array_equal(q[:,1:],v[:,1:])
  a,b=v[f].astype(float),q[f];na=np.cross(a[:,1]-a[:,0],a[:,2]-a[:,0]);nb=np.cross(b[:,1]-b[:,0],b[:,2]-b[:,0])
  active=np.linalg.norm(na,axis=1)>1e-9
  assert np.all(np.sum(na[active]*nb[active],axis=1)>0)
  if not part:assert np.allclose(b[:,1:]-b[:,:1],a[:,1:]-a[:,:1],atol=1e-12,rtol=0)
 ranges=[]
 for i,w in enumerate(weights if not part else np.zeros(len(v))):
  if ranges and ranges[-1][1]==i-1 and ranges[-1][2]==w:ranges[-1][1]=i
  else:ranges.append([i,i,float(w)])
 key=f'Parts{part}{lod}'
 lines.append(f'            ({str(bool(part)).lower()}, {lod}) => (Count: {len(v)}, IndexCount: {f.size}, Parts: {key}),')
 tables.append((key,digest,ranges))
 print('PASS',part,lod,len(v),len(f),'four widths, winding and shape rules')
lines+=['            _ => throw new ArgumentOutOfRangeException(nameof(lod))','        };','        if (source.Length != data.Count || indices.Length != data.IndexCount || !float.IsFinite(delta) || delta <= (footing ? -4.0821533203125f : -2.16925048828125f))','            throw new InvalidOperationException("PedestrianDraw01 support requires its native topology and positive span.");','        var positions = (Vector3[])source.Clone();','        foreach (var part in data.Parts)','            for (var i = part.First; i <= part.Last; i++)','                positions[i].x += (footing ? source[i].x / 4.0821533203125f : part.Sign) * delta;','        return new MovableStructureModel.Plan(source, positions, new[] { indices }, new[] { new bool[indices.Length / 3] });','    }','']
for key,digest,ranges in tables:
 lines+=['    // Geometry SHA-256: '+digest,f'    private static readonly (int First, int Last, float Sign)[] {key} =','    {']
 lines += [f'        ({a}, {b}, {w:g}f),' for a,b,w in ranges]
 lines+=['    };','']
lines+=['}',''];output.write_text('\n'.join(lines))
