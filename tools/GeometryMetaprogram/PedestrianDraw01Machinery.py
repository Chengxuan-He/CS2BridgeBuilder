"""Emit measured central wheel assemblies, cap plates and fixed pulleys.

The far shell is the authored envelope of the detailed wheel/housing, with
the same X boundary as the detailed housing. Mixed-bone ropes are excluded.
"""
from pathlib import Path
import ctypes as c
import hashlib, json, struct, sys
import numpy as np

r, output = map(Path, sys.argv[1:])
audit = json.loads((r/'all-movable-audit.json').read_text())
decoder = Path(__file__).with_name('Lift05Counterweights.py').read_text()
exec(decoder[decoder.index('dll = c.CDLL'):decoder.index('tables=[]')])
components = (
    (26,27,29,31,97,188,189,423,424,426,428,297,429,430),
    (26,27,29,31,101,181,182,405,406,408,410,291,411,412),
    (2,32),
)
levels = []
for lod, groups in enumerate(components):
    name = 'PedestrianDrawBridge01'+(f'_LOD{lod}' if lod else '')+' Mesh'
    raw = (r/'movable-skin'/(name+'.Geometry')).read_bytes()
    digest = hashlib.sha256(raw).hexdigest()
    assert any(a.get('sha256') == digest for a in audit['assets'].values())
    version, meshes, flags = struct.unpack_from('<HII', raw)
    assert version == 1 and meshes == (1 if lod == 2 else 2)
    headers = [struct.unpack_from('<QI14i5I',raw,10+i*88) for i in range(meshes)]
    h = headers[0]
    section = decoder[decoder.index('    def decode('):decoder.index('    cached=np.load')]
    exec('\n'.join(line[4:] if line.startswith('    ') else line for line in section.splitlines()))
    cached = np.load(r/f'pedestrian01-main-{lod}-0.npz')
    assert np.array_equal(f, cached['indices'])
    assert np.allclose(v, cached['positions'], rtol=1e-7, atol=1e-6)
    bones = np.load(r/f'pedestrian01-bones-{lod}.npy')
    weights = np.zeros(len(v)); selected = np.isin(cached['component'], groups)
    ranges = []; spans = []
    for ordinal, group in enumerate(groups):
        mask = cached['component'] == group; ids = np.flatnonzero(mask)
        touched = mask[f].any(1)
        assert np.all(mask[f[touched]])
        expected = (1+ordinal if lod == 2 else (0 if ordinal%7 >= 5 else 1+ordinal//7))
        assert set(bones[touched]) == {f'bone_{expected}'}
        x = v[ids,0].astype(float); span = float(np.abs(x).max())
        assert x.min() < 0 < x.max()
        if lod == 2:
            assert span == levels[0][3][0] and np.all(np.abs(x) == span)
        spans.append(span); weights[ids] = x/span
        runs = []
        for i in ids:
            if runs and runs[-1][1] == i-1: runs[-1][1] = int(i)
            else: runs.append([int(i),int(i)])
        ranges.extend((a,b,span) for a,b in runs)
    for delta in (-.03,0,2,8):
        q = v.astype(float).copy(); q[:,0] += weights*delta
        assert np.array_equal(q[~selected],v[~selected])
        assert np.array_equal(q[:,1:],v[:,1:])
        a,b = v[f].astype(float),q[f]
        na = np.cross(a[:,1]-a[:,0],a[:,2]-a[:,0])
        nb = np.cross(b[:,1]-b[:,0],b[:,2]-b[:,0])
        active = np.linalg.norm(na,axis=1)>1e-9
        assert np.all((na[active]*nb[active]).sum(1)>0)
    np.savez(r/f'pedestrian01-machinery-{lod}.npz',positions=v,indices=f,
             selected=selected,weights=weights)
    levels.append((len(v),digest,ranges,spans))
    print(f'PASS LOD{lod}: {len(groups)} parts, {selected.sum()} vertices, '
          f'{selected[f].all(1).sum()} triangles; bones, exclusions and four widths checked')

minimum = min(s for _,_,_,spans in levels for s in spans)
lines = ['// Generated by PedestrianDraw01Machinery.py from decoded native Geometry.',
         'using System;','using UnityEngine;','','namespace BridgeBuilder.Bridges;',
         '', 'internal static class PedestrianDraw01MachineryGeometry','{',
         '    internal static void Apply(int lod, Vector3[] source, Vector3[] positions, float delta)',
         '    {','        var data = lod switch','        {']
for lod,(count,_,_,_) in enumerate(levels):
    lines.append(f'            {lod} => (Count: {count}, Parts: Parts{lod}),')
lines += ['            _ => throw new ArgumentOutOfRangeException(nameof(lod))','        };',
          f'        if (source.Length != data.Count || positions.Length != data.Count || !float.IsFinite(delta) || delta <= -{minimum:.17g}f)',
          '            throw new InvalidOperationException("PedestrianDraw01 machinery requires its recorded layout and positive member spans.");',
          '        foreach (var part in data.Parts)',
          '            for (var i = part.First; i <= part.Last; i++)',
          '                positions[i].x = source[i].x + source[i].x / part.HalfSpan * delta;',
          '    }','']
for lod,(_,digest,ranges,_) in enumerate(levels):
    lines += ['    // Geometry SHA-256: '+digest,
              f'    private static readonly (int First, int Last, float HalfSpan)[] Parts{lod} =','    {']
    lines += [f'        ({a}, {b}, {span:.17g}f),' for a,b,span in ranges]
    lines += ['    };','']
lines += ['}','']
output.write_text('\n'.join(lines),encoding='utf-8')
