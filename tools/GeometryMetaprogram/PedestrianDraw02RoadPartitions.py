"""Emit a non-overlapping motion partition from reviewed native road boundaries.

Usage: python PedestrianDraw02RoadPartitions.py RESEARCH_DIRECTORY OUTPUT_CS
The offline vertical decomposition retains both notched hinges and the authored
centre gap. Runtime consumes cells, never prototype polygons or geometry tests.
"""
from pathlib import Path
import hashlib
import json
import sys
import numpy as np

research, output = map(Path, sys.argv[1:])
records = json.loads((research / 'pedestrian02-complete-road-membership.json').read_text())['levels']
for record in records:
    assert hashlib.sha256((research / 'movable-skin' / record['geometry']).read_bytes()).hexdigest() == record['sha256']
assert [r['loops'] for r in records[0]['regions']] == [r['loops'] for r in records[1]['regions']]
loops = [(region['bone'], np.array(loop, dtype=float))
         for region in records[0]['regions'] for loop in region['loops']]
stations = sorted({float(x) for _, loop in loops for x in loop[:, 0]})
# These near-zero authored stations are recorded centre vertices, not side parts.
# Their weight is emitted explicitly; there is no runtime coordinate threshold.
weights = [0 if abs(x) < .0001 else (-1 if x < 0 else 1) for x in stations]
cells = []
for left, right in zip(stations, stations[1:]):
    x = (left + right) / 2
    intervals = []
    for bone, loop in loops:
        crossings = []
        for a, b in zip(loop, loop[1:]):
            if min(a[0], b[0]) < x < max(a[0], b[0]):
                slope = (b[1] - a[1]) / (b[0] - a[0])
                z = lambda at: float(a[1] + (at - a[0]) * slope)
                crossings.append((z(x), z(left), z(right)))
        crossings.sort()
        assert len(crossings) % 2 == 0
        for low, high in zip(crossings[::2], crossings[1::2]):
            intervals.append((low[0], high[0], bone, low[1], low[2], high[1], high[2]))
    intervals.sort()
    assert all(a[1] <= b[0] for a, b in zip(intervals, intervals[1:]))
    cells.append(intervals)

def classify(x, z, delta):
    shifted = np.array(stations) + np.array(weights) * delta
    slab = np.searchsorted(shifted, x, side='right') - 1
    if slab < 0 or slab >= len(cells):
        return -1
    t = (x - shifted[slab]) / (shifted[slab + 1] - shifted[slab])
    for _, _, bone, ll, lr, ul, ur in cells[slab]:
        if ll + (lr - ll) * t <= z <= ul + (ur - ul) * t:
            return bone
    return -1

def polygon_bone(x, z, delta):
    result = -1
    for bone, original in loops:
        loop = original.copy()
        loop[:, 0] += np.array([weights[stations.index(float(p))] for p in loop[:, 0]]) * delta
        inside = False
        for a, b in zip(loop, loop[1:]):
            if (a[1] > z) != (b[1] > z):
                at = a[0] + (b[0] - a[0]) * ((z - a[1]) / (b[1] - a[1]))
                if x < at:
                    inside = not inside
        if inside:
            assert result == -1
            result = bone
    return result

random = np.random.default_rng(20261019)
for delta in (-.5, 0., 2., 8.):
    assert np.all(np.diff(np.array(stations) + np.array(weights) * delta) > 0)
    for x, z in random.uniform([-5 - max(delta, 0), -78], [5 + max(delta, 0), 78], (2000, 2)):
        assert classify(x, z, delta) == polygon_bone(x, z, delta), (delta, x, z)
for lod, record in enumerate(records):
    data = np.load(research / f'pedestrian02-main-{lod}.npz')
    v, faces = data['positions'], data['indices']
    for region in record['regions']:
        for face in region['triangles']:
            p = v[faces[face]].astype(float).mean(0)
            assert classify(p[0], p[2], 0) == region['bone'], (lod, face)

def f(x):
    return format(float(np.float32(x)), '.9g') + 'f'

lines = ['// Native PedestrianDrawBridge02 mesh-0 motion footprints, game 1.6.2f1.',
         '// LOD0 Geometry SHA-256: ' + records[0]['sha256'],
         '// LOD1 Geometry SHA-256: ' + records[1]['sha256'],
         '// Generated by PedestrianDraw02RoadPartitions.py from matching LOD0/LOD1 loops.',
         '// Half-width displacement moves measured side stations; recorded centre stations stay fixed.',
         'using System;', 'using UnityEngine;',
         'using Partition = BridgeBuilder.Bridges.MovableRoadGeometry.Partition;', '',
         'namespace BridgeBuilder.Bridges;', '', 'internal static class PedestrianDraw02RoadPartitions', '{',
         '    internal static Partition Create(float halfWidthDelta)', '    {',
         '        if (!float.IsFinite(halfWidthDelta)) throw new ArgumentOutOfRangeException(nameof(halfWidthDelta));',
         '        var x = new float[Stations.Length];',
         '        for (var i = 0; i < x.Length; i++)', '        {',
         '            x[i] = Stations[i].X + Stations[i].Weight * halfWidthDelta;',
         '            if (i > 0 && x[i] <= x[i - 1])',
         '                throw new ArgumentOutOfRangeException(nameof(halfWidthDelta), "PedestrianDraw02 hinge stations overlap at this width.");',
         '        }',
         '        Partition Slab(int index)', '        {',
         '            var result = Partition.Gap;',
         '            var entries = Cells[index];',
         '            for (var i = entries.Length - 1; i >= 0; i--)', '            {',
         '                var cell = entries[i];',
         '                var upper = Line(x[index], x[index + 1], cell.UpperLeft, cell.UpperRight,',
         '                    new Partition(cell.Bone), result);',
         '                result = Line(x[index], x[index + 1], cell.LowerLeft, cell.LowerRight, Partition.Gap, upper);',
         '            }', '            return result;', '        }',
         '        Partition Range(int first, int last)', '        {',
         '            if (first == last) return Slab(first);',
         '            var middle = (first + last) / 2;',
         '            return X(x[middle + 1], Range(first, middle), Range(middle + 1, last));', '        }',
         '        return X(x[0], Partition.Gap, X(x[x.Length - 1], Range(0, Cells.Length - 1), Partition.Gap));',
         '    }', '',
         '    private static Partition X(float station, Partition negative, Partition positive)', '    {',
         '        var frame = Matrix4x4.identity;',
         '        frame.m00 = 0f; frame.m02 = -1f;',
         '        frame.m20 = 1f; frame.m22 = 0f; frame.m23 = -station;',
         '        return new Partition(frame, negative, positive);', '    }', '',
         '    private static Partition Line(float left, float right, float zLeft, float zRight,',
         '        Partition negative, Partition positive)', '    {',
         '        var slope = (zRight - zLeft) / (right - left);',
         '        var frame = Matrix4x4.identity;',
         '        frame.m20 = -slope; frame.m23 = slope * left - zLeft;',
         '        return new Partition(frame, negative, positive);', '    }', '',
         '    private static readonly (float X, float Weight)[] Stations =', '    {']
lines += [f'        ({f(x)}, {f(w)}),' for x, w in zip(stations, weights)]
lines += ['    };', '',
          '    private static readonly (int Bone, float LowerLeft, float LowerRight, float UpperLeft, float UpperRight)[][] Cells =',
          '    {']
for intervals in cells:
    lines += ['        new (int, float, float, float, float)[]', '        {']
    lines += [f'            ({bone}, {f(ll)}, {f(lr)}, {f(ul)}, {f(ur)}),'
              for _, _, bone, ll, lr, ul, ur in intervals]
    lines += ['        },']
lines += ['    };', '}', '']
output.write_text('\n'.join(lines), encoding='utf-8')
print(f'{len(cells)} slabs; both LODs: 552 triangle-centroid ownership checks; '
      '8000 independent polygon comparisons across four widths passed.')
