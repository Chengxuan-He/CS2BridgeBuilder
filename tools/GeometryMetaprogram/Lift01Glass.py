"""Verify and emit the immutable Lift01 mesh-1 glass transform.
Usage: python Lift01Glass.py RESEARCH_DIRECTORY OUTPUT_CS
"""
from pathlib import Path
import hashlib
import sys
import numpy as np

research, output = map(Path, sys.argv[1:])
levels = []
for lod in range(2):
    name = 'LiftBridge01' + ('_LOD1' if lod else '') + ' Mesh'
    vertices, faces, bones = [], [], []
    bone = None
    for line in (research / 'movable-skin' / (name + '.mesh-1.obj')).read_text().splitlines():
        fields = line.split()
        if not fields:
            continue
        if fields[0] == 'v':
            vertices.append(list(map(float, fields[1:4])))
        elif fields[0] == 'g':
            bone = fields[1]
        elif fields[0] == 'f':
            faces.append([int(x.split('/')[0]) - 1 for x in fields[1:]])
            bones.append(bone)
    v, f = np.array(vertices), np.array(faces)
    assert v.shape == (160, 3) and f.shape == (80, 3)
    assert set(bones) == {'bone_0'}
    assert np.all(v[:80, 0] < 0) and np.all(v[80:, 0] > 0)
    for quad in range(40):
        assert set(f[quad*2:quad*2+2].flat) == set(range(quad*4, quad*4+4))
    if levels:
        assert np.array_equal(v, levels[0][0])
        assert np.array_equal(f, levels[0][1])
    for delta in (-.5, 0, 2, 8):
        moved = v.copy()
        moved[:80, 0] -= delta
        moved[80:, 0] += delta
        assert np.array_equal(moved[:, 1:], v[:, 1:])
        # Translation preserves every triangle edge, including winding and shape.
        for a, b in ((0, 1), (0, 2)):
            assert np.allclose(moved[f[:, a]] - moved[f[:, b]],
                               v[f[:, a]] - v[f[:, b]], atol=1e-12, rtol=0)
    digest = hashlib.sha256((research / 'movable-skin' / (name + '.Geometry')).read_bytes()).hexdigest()
    levels.append((v, f, digest))
    print(f'LOD{lod}: 40 glass quads, 160 vertices, bone 0; rigid displacement verified')

code = """// Native LiftBridge01 mesh-1 glass, game 1.6.2f1.
// Generated by Lift01Glass.py; both detailed LODs have identical vertex ordering.
using System;
using UnityEngine;

namespace BridgeBuilder.Bridges;

internal static class Lift01Glass
{
    internal static MovableStructureModel.Plan Create(int lod, Vector3[] source,
        int[] indices, float delta)
    {
        if ((lod != 0 && lod != 1) || source.Length != 160 || indices.Length != 240 || !float.IsFinite(delta))
            throw new InvalidOperationException("Lift01 glass requires its recorded mesh-1 layout.");
        var positions = (Vector3[])source.Clone();
        for (var i = 0; i < 80; i++) positions[i].x -= delta;
        for (var i = 80; i < 160; i++) positions[i].x += delta;
        return new MovableStructureModel.Plan(source, positions,
            new[] { indices }, new[] { new bool[80] });
    }
}
"""
header = ''.join(f'// LOD{lod} Geometry SHA-256: {level[2]}\n' for lod, level in enumerate(levels))
output.write_text(header + code, encoding='utf-8')
