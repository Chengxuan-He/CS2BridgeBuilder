"""Emit measured Lift05 window memberships; the far LOD uses its tower atlas.
Usage: python Lift05Glass.py RESEARCH_DIRECTORY OUTPUT_CS
"""
from pathlib import Path
import hashlib
import sys
import numpy as np

r, output = map(Path, sys.argv[1:])
levels=[]
hashes=('10a9c40e522c91debff4bc0251dbe93980cac6b92ff6b176c216e27ba52c05fb',
        'dc4b8d4ae9688952992b03d724d8549cdb79f52eb0877c7f6fe62d1246ce286e')
for lod in range(2):
    stem='LiftBridge05'+('_LOD1' if lod else '')+' Mesh'
    assert hashlib.sha256((r/'movable-skin'/f'{stem}.Geometry').read_bytes()).hexdigest()==hashes[lod]
    vertices,faces,bones=[],[],[]
    bone=None
    for line in (r/'movable-skin'/f'{stem}.mesh-1.obj').read_text().splitlines():
        words=line.split()
        if not words:continue
        if words[0]=='v':vertices.append(list(map(float,words[1:4])))
        elif words[0]=='g':bone=words[1]
        elif words[0]=='f':
            faces.append([int(x.split('/')[0])-1 for x in words[1:]])
            bones.append(bone)
    v,f=np.array(vertices,dtype=np.float32),np.array(faces)
    assert v.shape==(272,3) and f.shape==(136,3) and set(bones)=={'bone_0'}
    # Position-welded inventory supplies pane IDs, but validate each pane against
    # the actual exported native face and position order before emission.
    data=np.load(r/f'lift05-main-{lod}-1.npz')
    assert np.array_equal(v,data['positions'].astype(np.float32)) and np.array_equal(f,data['indices'])
    panes=[]
    for group in range(68):
        ids=np.flatnonzero(data['component']==group)
        assert len(ids)==4
        touched=np.isin(f,ids).any(axis=1)
        assert touched.sum()==2 and np.all(np.isin(f[touched],ids))
        lo,hi=float(v[ids,0].min()),float(v[ids,0].max())
        if lo<=0<=hi:
            assert lo==-0.47966766357421875 and hi==0.47966766357421875
            mode=0
        else:mode=1 if lo>0 else -1
        panes.append((ids,mode))
    assert sum(mode==0 for ids,mode in panes)==4
    for delta in (-8,-1,-.47966766357421875,-.25,0,2,8):
        for ids,mode in panes:
            points=v[ids].astype(float)
            moved=points.copy()
            moved[:,0]+=(mode if mode else points[:,0]/0.47966766357421875)*delta
            assert np.array_equal(points[:,1:],moved[:,1:])
            if mode:assert np.allclose(np.diff(points,axis=0),np.diff(moved,axis=0),rtol=0,atol=1e-12)
            else:assert np.allclose(moved[:,0],points[:,0]*(1+delta/0.47966766357421875))
    modes=np.empty(272,dtype=int)
    for ids,mode in panes:modes[ids]=mode
    ranges=[]
    for i,mode in enumerate(modes):
        if ranges and ranges[-1][2]==mode:ranges[-1][1]=i
        else:ranges.append([i,i,int(mode)])
    levels.append(ranges)
    print(f'LOD{lod}: 64 rigid side panes and 4 centre-crossing panes; 272 vertices, 136 unchanged triangles')

lines=['// Native LiftBridge05 mesh-1 windows, game 1.6.2f1.',
       '// Generated by Lift05Glass.py. LOD2 has no independent glass mesh.',
       'using System;','using UnityEngine;','','namespace BridgeBuilder.Bridges;','',
       'internal static class Lift05Glass','{',
       '    internal static MovableStructureModel.Plan Create(int lod, Vector3[] source, int[] indices, float delta)',
       '    {',
       '        if ((lod != 0 && lod != 1) || source.Length != 272 || indices.Length != 408 || !float.IsFinite(delta))',
       '            throw new InvalidOperationException("Lift05 glass requires its native layout.");',
       '        var positions = (Vector3[])source.Clone();',
       '        foreach (var part in lod == 0 ? Parts0 : Parts1)',
       '            for (var i = part.First; i <= part.Last; i++)',
       '                positions[i].x += (part.Side == 0 ? source[i].x / 0.47966766357421875f : part.Side) * delta;',
       '        return new MovableStructureModel.Plan(source, positions, new[] { indices }, new[] { new bool[136] });',
       '    }','']
for lod,ranges in enumerate(levels):
    lines+=['    // Geometry SHA-256: '+hashes[lod],
            f'    private static readonly (int First, int Last, int Side)[] Parts{lod} =','    {']
    lines += [f'        ({a}, {b}, {mode}),' for a,b,mode in ranges]
    lines+=['    };','']
lines+=['}','']
output.write_text('\n'.join(lines),encoding='utf-8')
