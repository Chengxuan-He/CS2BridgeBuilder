"""Emit Lift04 carriageway top faces, retaining shoulders and underside.
Usage: python Lift04RoadTops.py RESEARCH_DIRECTORY OUTPUT_CS
Far fixed ends are composite shells and require a separate reconstruction plan.
"""
from pathlib import Path
import ctypes as c
import hashlib, json, struct, sys
import numpy as np
r,output=map(Path,sys.argv[1:])
records=json.loads((r/'lift-native-road-plane-candidates.json').read_text())
dll=c.CDLL(r'D:\Program Files (x86)\Steam\steamapps\common\Cities Skylines II\Cities2_Data\Plugins\x86_64\PipelinePlugin.dll')
for name,args,result in (
 ('decompress_calc_bound',[c.c_void_p,c.c_int64,c.c_int],c.c_int64),
 ('decompress_data',[c.c_void_p,c.c_int64,c.c_void_p,c.c_int64,c.c_int],c.c_int64),
 ('decompress_meshopt_index_buffer',[c.c_void_p,c.c_int64,c.c_int,c.c_int,c.c_void_p],c.c_int),
 ('decompress_meshopt_vertex_attribute',[c.c_void_p,c.c_int64,c.c_int,c.c_int,c.c_void_p],c.c_int)):
 method=getattr(dll,name);method.argtypes=args;method.restype=result
levels=[]
for lod in range(2):
 record=next(x for x in records if x['style']==4 and x['lod']==lod)
 path=r/'movable-skin'/record['geometry'];raw=path.read_bytes()
 assert hashlib.sha256(raw).hexdigest()==record['sha256']
 version,meshes,flags=struct.unpack_from('<HII',raw)
 assert version==1 and meshes==(1 if lod==2 else 2)
 headers=[struct.unpack_from('<QI14i5I',raw,10+i*88) for i in range(meshes)];h=headers[0]
 def decode(block,count,stride,index=False):
  if flags&2:
   size=dll.decompress_calc_bound(block,len(block),0);assert size>0
   buf=c.create_string_buffer(size);assert dll.decompress_data(block,len(block),buf,size,0)==size;block=buf.raw
  if flags&1:
   buf=c.create_string_buffer(count*stride)
   method=dll.decompress_meshopt_index_buffer if index else dll.decompress_meshopt_vertex_attribute
   assert method(block,len(block),count,stride,buf)==0;block=buf.raw
  assert len(block)==count*stride
  return block
 offset=10+meshes*88+sum(x[-1]*40 for x in headers)
 stride=4 if h[17]&1 else 2
 f=np.frombuffer(decode(raw[offset:offset+h[16]],h[19],stride,True),dtype='<u4' if stride==4 else '<u2').reshape(-1,3)
 offset+=sum(x[16] for x in headers)
 assert h[0]&15==0 and h[1]&3==2
 v=np.frombuffer(decode(raw[offset:offset+h[2]],h[18],12),dtype='<f4').reshape(-1,3)
 faces=[];bones=[];bone=-1
 for line in path.with_suffix('.mesh-0.obj').read_text().splitlines():
  fields=line.split()
  if not fields:continue
  if fields[0]=='g':bone=int(fields[1][5:]) if fields[1].startswith('bone_') else -1
  elif fields[0]=='f':faces.append([int(x.split('/')[0])-1 for x in fields[1:]]);bones.append(bone)
 assert np.array_equal(f,faces)
 bones=np.array(bones);p=v[f].astype(float)
 normal=np.cross(p[:,1]-p[:,0],p[:,2]-p[:,0])
 moving=np.flatnonzero((bones==2)&np.all(p[:,:,1]==9.71875,axis=1)&(normal[:,1]>0)).tolist()
 fixed=np.flatnonzero((bones==0)&np.all(p[:,:,1]==9.71875,axis=1)&(normal[:,1]>0)).tolist()
 if lod==1:
  slopes=[17291,17292,17294]
  assert set(moving).isdisjoint(slopes) and np.all(bones[slopes]==2)
  assert p[slopes,:,1].min()==9.71875 and p[slopes,:,1].max()==9.75927734375
  moving+=slopes
 assert len(moving)==168 and len(fixed)==32
 assert np.max(np.abs(p[moving+fixed,:,0]))==4
 assert np.all(normal[moving+fixed,1]>0)
 assert abs(normal[moving,1].sum()/2 - 8*2*79.849609375)<1e-6
 assert abs(normal[fixed,1].sum()/2 - 256)<1e-6
 assert np.min(np.abs(p[fixed,:,2]))==80 and np.max(np.abs(p[fixed,:,2]))==96
 levels.append((record,f,sorted(moving+fixed)))
 print(f'PASS LOD{lod}: 168 moving + 32 fixed top faces; bones 2/0, area and boundaries checked')
lines=['// Native LiftBridge04 detailed road-bed tops; generated by Lift04RoadTops.py.', '// Retains shoulders, sidewalls and undersides. Far shell requires separate handling.', 'using System;', '', 'namespace BridgeBuilder.Bridges;', '', 'internal static class Lift04RoadTops', '{', '    internal static void RemoveDetailed(int lod, int[] indices, bool[] removed)', '    {', '        var data = lod switch', '        {']
for lod,(rec,f,ids) in enumerate(levels):lines.append(f'            {lod} => (Count: {len(f)}, Faces: Level{lod}),')
lines+=['            _ => throw new ArgumentOutOfRangeException(nameof(lod))','        };','        if (indices.Length != data.Count * 3 || removed.Length != data.Count)','            throw new InvalidOperationException("Lift04 detailed road-top layout changed.");','        foreach (var face in data.Faces)','        {','            var offset = face.Triangle * 3;','            if (indices[offset] != face.A || indices[offset + 1] != face.B || indices[offset + 2] != face.C)','                throw new InvalidOperationException("Lift04 detailed road-top topology changed.");','            removed[face.Triangle] = true;','        }','    }','']
for lod,(rec,f,ids) in enumerate(levels):
 lines+=['    // Geometry SHA-256: '+rec['sha256'],f'    private static readonly (int Triangle, int A, int B, int C)[] Level{lod} =','    {']
 lines += [f'        ({i}, {f[i,0]}, {f[i,1]}, {f[i,2]}),' for i in ids];lines+=['    };','']
lines+=['}',''];output.write_text('\n'.join(lines),encoding='utf-8')
