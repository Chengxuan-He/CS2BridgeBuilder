"""Emit measured Draw02 ordinary-pillar width transforms at all native LODs.
Usage: python Draw02NetPillarGeometry.py RESEARCH_DIRECTORY OUTPUT_CS
The two caps/columns translate; the continuous foundation uses its own 20 m span.
"""
from pathlib import Path
import hashlib
import sys
import numpy as np

research, output = map(Path, sys.argv[1:])
counts = (((368,184),(344,164),(192,150)),((320,160),(298,144),(329,150)),((224,112),(212,100),(98,100)))
tables=[]
for part,stem in enumerate(('DrawBridge02NetPillarTop','DrawBridge02NetPillar','DrawBridge02NetPillarBase')):
    for lod in range(3):
        d=np.load(research/f'draw02-netpillar-{part}-{lod}.npz')
        v,f=d['positions'].astype(np.float32),d['indices'].reshape(-1,3)
        assert (len(v),len(f))==counts[part][lod]
        if part<2:
            assert np.all(v[:,0]!=0)
            assert np.all(np.sign(v[f,0])==np.sign(v[f[:,0],0])[:,None])
            weights=np.sign(v[:,0])
        else:
            if lod==0: assert v[:,0].min()==-10 and v[:,0].max()==10
            weights=v[:,0]/np.float32(10)
        groups={}
        for i,w in enumerate(weights): groups.setdefault(float(w),[]).append(i)
        for delta in (-.5,0,2,8):
            moved=v.copy();moved[:,0]+=weights*np.float32(delta)
            assert np.array_equal(moved[:,1:],v[:,1:]) and np.isfinite(moved).all()
            if delta==0: assert np.array_equal(moved,v)
            if part<2:
                for sign in (-1,1):
                    side=np.sign(v[:,0])==sign
                    assert np.allclose(moved[side,0]-v[side,0],sign*delta,atol=2e-6)
                    assert np.allclose(np.ptp(moved[side],axis=0),np.ptp(v[side],axis=0),atol=2e-6)
            else: assert np.allclose(moved[:,0],v[:,0]*(1+delta/10),atol=2e-6)
            a,b=v[f].astype(float),moved[f].astype(float)
            n0=np.cross(a[:,1]-a[:,0],a[:,2]-a[:,0]);n1=np.cross(b[:,1]-b[:,0],b[:,2]-b[:,0])
            valid=np.linalg.norm(n0,axis=1)>1e-8
            assert np.all(np.sum(n0[valid]*n1[valid],axis=1)>0)
        suffix=f'_LOD{lod}' if lod else ''
        sha=hashlib.sha256((research/'draw02-network-pillar'/f'{stem}{suffix} Mesh.Geometry').read_bytes()).hexdigest()
        tables.append((part,lod,len(v),len(f),groups,sha))
        print(f'Part {part} LOD{lod}: {len(v)} vertices/{len(f)} triangles; rigid/own-span and winding checks passed')

lines=['// Native DrawBridge02 ordinary pillar width maps, game 1.6.2f1.',
       '// Generated by tools/GeometryMetaprogram/Draw02NetPillarGeometry.py.',
       'using System;', 'using UnityEngine;', '', 'namespace BridgeBuilder.Bridges;', '',
       'internal static class Draw02NetPillarGeometry', '{',
       '    internal static MovableStructureModel.Plan Create(int part, int lod, Vector3[] source, int[] indices, float delta)',
       '    {', '        var data = (part, lod) switch', '        {']
for part,lod,nv,nf,_,_ in tables:
    lines += [f'            ({part}, {lod}) => (Vertices: {nv}, Triangles: {nf}, Groups: Part{part}Lod{lod}),']
lines += ['            _ => throw new ArgumentOutOfRangeException(nameof(part))', '        };',
          '        if (source.Length != data.Vertices || indices.Length != data.Triangles * 3)',
          '            throw new InvalidOperationException("Draw02 ordinary pillar geometry differs from the measured source.");',
          '        var moved = (Vector3[])source.Clone();',
          '        foreach (var group in data.Groups)', '            foreach (var index in group.Vertices)',
          '                moved[index].x = source[index].x + group.Weight * delta;',
          '        return new MovableStructureModel.Plan(source, moved, new[] { indices }, new[] { new bool[data.Triangles] });',
          '    }', '']
for part,lod,nv,nf,groups,sha in tables:
    lines += ['    // Geometry SHA-256: '+sha,
              f'    private static readonly (float Weight, int[] Vertices)[] Part{part}Lod{lod} =', '    {']
    for weight,ids in sorted(groups.items()):
        lines += [f'        ({weight:.9g}f, new[]', '        {']
        for i in range(0,len(ids),20): lines += ['            '+', '.join(map(str,ids[i:i+20]))+',']
        lines += ['        }),']
    lines += ['    };','']
lines += ['}','']
output.write_text('\n'.join(lines),encoding='utf-8')
