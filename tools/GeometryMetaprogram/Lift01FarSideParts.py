"""Emit rigid fixed-side membership for Lift01's native far mechanism.
Usage: python Lift01FarSideParts.py RESEARCH_DIRECTORY OUTPUT_CS
Includes the rigid lateral tower proxy panels; excludes transverse tower panels,
rounded platforms and fixed road shells.
"""
from pathlib import Path
import hashlib
import json
import sys
import numpy as np

r, output = map(Path, sys.argv[1:])
d = np.load(r / 'lift01-main-2.npz')
v, faces = d['positions'], d['indices']
groups = json.loads((r / 'lift01-far-fixed-parts.json').read_text())
assert v.shape == (1110, 3) and faces.shape == (776, 3) and len(groups) == 25
selected = [2, 3, 4, 5, 6, 7, 9, 10, 11, 12, 14, 15, 16, 17, 18, 19, 21, 22, 23, 24]
bone_by_vertex = {}
native_faces = []
active = None
for line in (r / 'movable-skin/LiftBridge01_LOD2 Mesh.mesh-0.obj').read_text().splitlines():
    fields = line.split()
    if not fields:
        continue
    if fields[0] == 'g':
        active = fields[1]
    elif fields[0] == 'f':
        native_faces.append([int(token.split('/')[0]) - 1 for token in fields[1:]])
        for token in fields[1:]:
            bone_by_vertex.setdefault(int(token.split('/')[0]) - 1, set()).add(active)
assert np.array_equal(faces, native_faces)
weights = {}
for ordinal in selected:
    p = groups[ordinal]
    ids = p['vertices']
    assert p['maximum'][0] < 0 or p['minimum'][0] > 0
    assert np.array_equal(v[ids].min(0), p['minimum'])
    assert np.array_equal(v[ids].max(0), p['maximum'])
    assert all(bone_by_vertex[i] == {'bone_0'} for i in ids)
    member = np.isin(faces, ids)
    assert not np.any(member.any(1) & ~member.all(1))
    direction = -1 if p['maximum'][0] < 0 else 1
    for i in ids:
        assert i not in weights
        weights[i] = direction
    for delta in (-.5, 0, 2, 8):
        moved = v[ids].astype(float).copy()
        moved[:, 0] += direction * delta
        assert np.array_equal(moved - moved[0], v[ids].astype(float) - v[ids[0]])
assert len(weights) == 424
assert not set(weights).intersection(i for k in (0, 1, 8, 13, 20) for i in groups[k]['vertices'])
# Native far tower component 0 combines lateral and transverse proxy panels.
# Only the lateral panels represent rigid side structures. Their vertices are
# separate from the end/roof panels, so no subdivision or channel changes are
# necessary here. Keep the 20 crossing faces for their separate mapping stage.
tower_sides = [0, 1, 2, 3, 10, 11, 12, 13,
               388, 389, 390, 391, 398, 399, 400, 401]
tower_vertices = set(groups[0]['vertices'])
side_vertices = set(int(i) for i in faces[tower_sides].flat)
assert len(side_vertices) == 32 and side_vertices <= tower_vertices
assert not side_vertices.intersection(weights)
membership = np.isin(faces, list(side_vertices))
assert np.array_equal(np.flatnonzero(membership.all(1)), tower_sides)
assert not np.any(membership.any(1) & ~membership.all(1))
assert all(bone_by_vertex[i] == {'bone_0'} for i in side_vertices)
for fid in tower_sides:
    points = v[faces[fid]].astype(float)
    assert np.all(points[:, 0] > 0) or np.all(points[:, 0] < 0)
    direction = int(np.sign(points[0, 0]))
    for delta in (-.5, 0, 2, 8):
        moved = points.copy()
        moved[:, 0] += direction * delta
        assert np.array_equal(moved - moved[0], points - points[0])
for i in side_vertices:
    weights[i] = int(np.sign(v[i, 0]))
assert len(weights) == 456
assert len(tower_vertices - side_vertices) == 40
ranges = []
for i, w in sorted(weights.items()):
    if ranges and ranges[-1][1] + 1 == i and ranges[-1][2] == w:
        ranges[-1][1] = i
    else:
        ranges.append([i, i, w])
digest = hashlib.sha256((r / 'movable-skin/LiftBridge01_LOD2 Mesh.Geometry').read_bytes()).hexdigest()
assert digest == 'a634d30d56089487f0a4fbd1d6f7dfbe3644c99f5b447b4a6658e4db282fd925'
lines = ['// Native LiftBridge01_LOD2 fixed stairs, rooms, attachments and lateral tower panels.',
         '// Geometry SHA-256: ' + digest,
         '// Generated by Lift01FarSideParts.py; excludes merged crossing shells.',
         'using System;', 'using UnityEngine;', '', 'namespace BridgeBuilder.Bridges;', '',
         'internal static class Lift01FarSideParts', '{',
         '    internal static void Apply(Vector3[] source, Vector3[] positions, float delta)', '    {',
         '        if (source.Length != 1110 || positions.Length != 1110 || !float.IsFinite(delta))',
         '            throw new InvalidOperationException("Lift01 far side parts require their measured source layout.");',
         '        foreach (var part in Parts)',
         '            for (var i = part.First; i <= part.Last; i++) positions[i].x = source[i].x + part.Direction * delta;',
         '    }', '', '    private static readonly (int First, int Last, int Direction)[] Parts =', '    {']
lines += [f'        ({a}, {b}, {w}),' for a, b, w in ranges]
lines += ['    };', '}']
output.write_text('\n'.join(lines) + '\n', encoding='utf-8')
print(f'20 fixed side parts plus 16 lateral tower faces / 456 vertices / {len(ranges)} ranges; '
      'native topology, whole-face and four-width rigidity checks passed; 40 transverse tower vertices remain separate.')
