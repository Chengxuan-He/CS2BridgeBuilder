"""Emit own-span transforms for Draw03's four fixed rollers and two leaf axles.
Usage: python Draw03Shafts.py RESEARCH_DIRECTORY OUTPUT_CS
Run Draw03RigidParts.py first to regenerate the hash-checked source inventory.
"""
from pathlib import Path
import hashlib
import json
import sys
import numpy as np

r, output = map(Path, sys.argv[1:])
levels = []
for lod in range(2):
    name = 'DrawBridge03' + ('_LOD1' if lod else '') + ' Mesh.Geometry'
    digest = hashlib.sha256((r / 'movable-skin' / name).read_bytes()).hexdigest()
    assert digest == ('f7ecc824ad55745e791e40b18fd12f5def20657ed8ea56d373429d5a1337588f',
                      '15b8419da13d6e99e1dc0591f12f4019f0be09c3b220a481d24720daf7b57e12')[lod]
    all_parts = json.loads((r / f'draw03-parts-{lod}.json').read_text())
    crossing = [p for p in all_parts if not p['side']]
    d = np.load(r / f'draw03-main-{lod}.npz')
    v, faces, bones = d['positions'].astype(float), d['indices'], d['bones']
    parts = [crossing[i]['vertices'] for i in (4, 5, 92, 93, 91)]
    # Same physical positive axle, authored as two halves separated by 49.6 micrometres.
    halves = ((268, 270), (272, 274))[lod]
    parts.append(sorted(all_parts[halves[0]]['vertices'] + all_parts[halves[1]]['vertices']))
    expected_bones = (0, 0, 0, 0, 2, 1)
    used = set()
    spans = []
    for index, (ids, bone) in enumerate(zip(parts, expected_bones)):
        assert not used.intersection(ids)
        used.update(ids)
        member = np.isin(faces, ids)
        assert not np.any(member.any(1) & ~member.all(1))
        triangles = faces[member.all(1)]
        assert set(bones[member.all(1)]) == {bone}
        lo, hi = v[ids].min(0), v[ids].max(0)
        assert lo[0] < 0 < hi[0]
        if index < 4:
            assert hi[0] - lo[0] == 24.5615234375
        else:
            assert lo[0] == -13.215576171875 and hi[0] == 13.215576171875
        spans.append((lo[0], hi[0], ids))
        for delta in (-16, -8, -(hi[0]-lo[0])/2, -.5, 0, 2, 8):
            moved = v.copy()
            moved[ids, 0] += (2 * v[ids, 0] - lo[0] - hi[0]) / (hi[0] - lo[0]) * delta
            assert np.array_equal(moved[ids, 1:], v[ids, 1:])
            assert np.isclose(moved[ids, 0].min(), min(lo[0] - delta, hi[0] + delta))
            assert np.isclose(moved[ids, 0].max(), max(lo[0] - delta, hi[0] + delta))
            before = np.cross(v[triangles[:, 1]] - v[triangles[:, 0]], v[triangles[:, 2]] - v[triangles[:, 0]])
            after = np.cross(moved[triangles[:, 1]] - moved[triangles[:, 0]], moved[triangles[:, 2]] - moved[triangles[:, 0]])
            nonzero = np.linalg.norm(before, axis=1) > 0
            assert np.isfinite(moved).all()
            if hi[0]-lo[0]+2*delta > 0:
                assert np.all(np.sum(before[nonzero] * after[nonzero], axis=1) > 0)
    levels.append((len(v), spans, digest))
    print(f'LOD{lod}: six shafts, {len(used)} vertices; original bones, complete-face ownership and seven signed widths (including exact contact) and positive-span winding verified.')

def literal(x):
    return format(float(np.float32(x)), '.9g') + 'f'

lines = ['// Native DrawBridge03 rollers and leaf axles; generated by Draw03Shafts.py.',
         'using System;', 'using UnityEngine;', '', 'namespace BridgeBuilder.Bridges;', '',
         'internal static class Draw03Shafts', '{',
         '    internal static void Apply(int lod, Vector3[] source, Vector3[] positions, float delta)',
         '    {', '        var data = lod switch', '        {',
         '            0 => (Count: 186078, Parts: Near),',
         '            1 => (Count: 146988, Parts: Middle),',
         '            _ => throw new ArgumentOutOfRangeException(nameof(lod))', '        };',
         '        if (source.Length != data.Count || positions.Length != data.Count || !float.IsFinite(delta))',
         '            throw new InvalidOperationException("Draw03 shafts require their recorded main mesh.");',
         '        foreach (var part in data.Parts)', '        {',
         '            var span = part.Max - part.Min;',
         '            foreach (var range in part.Ranges)',
         '                for (var i = range.First; i <= range.Last; i++)',
         '                    positions[i].x = source[i].x + (2f * source[i].x - part.Min - part.Max) / span * delta;',
         '        }', '    }', '']
for label, (_, parts, digest) in zip(('Near', 'Middle'), levels):
    lines += ['    // Geometry SHA-256: ' + digest,
              f'    private static readonly (float Min, float Max, (int First, int Last)[] Ranges)[] {label} =', '    {']
    for lo, hi, ids in parts:
        ranges = []
        for i in sorted(ids):
            if ranges and ranges[-1][1] + 1 == i:
                ranges[-1][1] = i
            else:
                ranges.append([i, i])
        lines += [f'        ({literal(lo)}, {literal(hi)}, new (int, int)[] {{ ' +
                  ', '.join(f'({a}, {b})' for a, b in ranges) + ' }),']
    lines += ['    };', '']
lines += ['}']
output.write_text('\n'.join(lines) + '\n', encoding='utf-8')
