"""Emit the two reviewed solid Lift03 footing slabs at every native LOD.
Usage: python Lift03Footings.py RESEARCH_DIRECTORY OUTPUT_CS
"""
from pathlib import Path
import hashlib, json, sys
import numpy as np

r, output = map(Path, sys.argv[1:])
hashes = (
    '3ebea1b5996139c7c0830f2ec4814f83b392d89c8040f43fbd2e9da307f2d3e4',
    'a10bfa33e05223b9e61ff47bc4a951046653f476e1bb613aaf7f2d31574c50c0',
    'cf49402959aeab30071f2b3b06bfb1b7d54022d02246bc57f904d0807132946d')
rows = [row for row in json.loads((r/'lift03-support-parts.json').read_text()) if row['part'] == 1]
assert [row['lod'] for row in rows] == [0, 1, 2]
tables = []
for row in rows:
    lod = row['lod']
    assert hashlib.sha256((r/'movable-skin'/row['source']).read_bytes()).hexdigest() == row['sha256'] == hashes[lod]
    data = np.load(r/f'lift03-support-1-{lod}.npz')
    v, f, component = data['positions'], data['indices'], data['component']
    assert len(v) == (2152, 2256, 424)[lod] and len(f) == (2608, 2086, 400)[lod]
    assert len(row['parts']) == 2
    weights = np.empty(len(v), dtype=float)
    ranges = []
    stations = []
    for part in row['parts']:
        ids = np.flatnonzero(component == part['id'])
        points = v[ids]
        lo, hi = float(points[:, 0].min()), float(points[:, 0].max())
        assert lo < 0 < hi
        assert np.array_equal(points.min(0), part['minimum']) and np.array_equal(points.max(0), part['maximum'])
        # Both source solids sit at separate end stations in every LOD.
        assert np.all(points[:, 2] > 0) or np.all(points[:, 2] < 0)
        stations.append(int(np.sign(points[0, 2])))
        weights[ids] = 2 * (points[:, 0].astype(float) - lo) / (hi - lo) - 1
        chunks = np.split(ids, np.flatnonzero(np.diff(ids) != 1) + 1)
        ranges.extend((int(chunk[0]), int(chunk[-1]), lo, hi) for chunk in chunks)
    assert sorted(stations) == [-1, 1] and np.all(np.isfinite(weights))
    for delta in (-1, 0, 2, 8):
        q = v.astype(float).copy()
        q[:, 0] += weights * delta
        assert np.array_equal(q[:, 1:], v[:, 1:])
        a, b = v[f].astype(float), q[f]
        na = np.cross(a[:, 1]-a[:, 0], a[:, 2]-a[:, 0])
        nb = np.cross(b[:, 1]-b[:, 0], b[:, 2]-b[:, 0])
        valid = np.linalg.norm(na, axis=1) > 1e-9
        assert np.all(np.sum(na[valid]*nb[valid], axis=1) > 0)
        if delta == 0: assert np.array_equal(q, v)
    tables.append((len(v), f.size, ranges))
    np.savez(r/f'lift03-footing-{lod}-wide.npz', positions=v+np.column_stack((weights*8,np.zeros((len(v),2)))), indices=f)
    print(f'PASS footing LOD{lod}: {len(v)} vertices, {len(f)} original faces; two measured spans, four widths')

def number(x): return format(x, '.17g')+'f'
lines = ['// Native Lift03 solid footings. Generated by Lift03Footings.py.',
         'using System;', 'using UnityEngine;', '', 'namespace BridgeBuilder.Bridges;', '',
         'internal static class Lift03FootingGeometry', '{',
         '    internal static MovableStructureModel.Plan Create(int lod, Vector3[] source, int[] indices, float delta)',
         '    {', '        var data = lod switch', '        {']
for lod, (count, index_count, _) in enumerate(tables):
    lines.append(f'            {lod} => (Count: {count}, Indices: {index_count}, Parts: Parts{lod}),')
lines += ['            _ => throw new ArgumentOutOfRangeException(nameof(lod))', '        };',
          '        if (source.Length != data.Count || indices.Length != data.Indices || !float.IsFinite(delta))',
          '            throw new InvalidOperationException("Lift03 footing requires its recorded native topology.");',
          '        var positions = (Vector3[])source.Clone();',
          '        foreach (var part in data.Parts)', '        {',
          '            var span = part.Maximum - part.Minimum;',
          '            for (var i = part.First; i <= part.Last; i++)',
          '                positions[i].x += (2f * (source[i].x - part.Minimum) / span - 1f) * delta;',
          '        }',
          '        return new MovableStructureModel.Plan(source, positions, new[] { indices },',
          '            new[] { new bool[indices.Length / 3] });', '    }']
for lod, (_, _, ranges) in enumerate(tables):
    lines += ['    // Geometry SHA-256: '+hashes[lod],
              f'    private static readonly (int First, int Last, float Minimum, float Maximum)[] Parts{lod} =',
              '    {']
    lines += [f'        ({a}, {b}, {number(lo)}, {number(hi)}),' for a,b,lo,hi in ranges]
    lines += ['    };']
lines += ['}', '']
output.write_text('\n'.join(lines), encoding='utf-8')
