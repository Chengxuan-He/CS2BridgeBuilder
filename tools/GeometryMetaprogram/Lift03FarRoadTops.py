points = v[f].astype(float)
normal = np.cross(points[:, 1] - points[:, 0], points[:, 2] - points[:, 0])
top = np.flatnonzero(np.all(points[:, :, 1] == 20.02392578125, axis=1) & (normal[:, 1] > 0))
assert len(top) == 16 and abs(points[top, :, 0]).max() == 9.935546875
native_faces, bones = [], []
bone = -1
for line in path.with_suffix('.mesh-0.obj').read_text().splitlines():
    if line.startswith('g bone_'):
        bone = int(line[7:])
    elif line.startswith('f '):
        native_faces.append([int(token.split('/')[0]) - 1 for token in line.split()[1:]])
        bones.append(bone)
assert np.array_equal(f, native_faces)
assert set(np.array(bones)[top]) == {0, 3}
assert np.count_nonzero(np.array(bones)[top] == 3) == 8
np.savez(r / 'lift03-far-road-tops.npz', positions=v, indices=f, faces=top)
lines = [
    '// Native far upper road tops; generated by Lift03FarRoadTops.py.',
    '// Geometry SHA-256: ' + digest,
    'using System;', '', 'namespace BridgeBuilder.Bridges;', '',
    'internal static class Lift03FarRoadTops', '{',
    '    internal static void Remove(int[] indices, bool[] removed)', '    {',
    '        if (indices.Length != 852 * 3 || removed.Length != 852)',
    '            throw new InvalidOperationException("Lift03 far road-top layout changed.");',
    '        foreach (var face in Faces)', '        {',
    '            var offset = face.Triangle * 3;',
    '            if (indices[offset] != face.A || indices[offset + 1] != face.B || indices[offset + 2] != face.C)',
    '                throw new InvalidOperationException("Lift03 far road-top topology changed.");',
    '            removed[face.Triangle] = true;', '        }', '    }',
    '    private static readonly (int Triangle, int A, int B, int C)[] Faces =', '    {',
]
lines += [f'        ({i}, {f[i, 0]}, {f[i, 1]}, {f[i, 2]}),' for i in top]
lines += ['    };', '}', '']
output.write_text('\n'.join(lines), encoding='utf-8')
print('PASS 16 far upper road faces; original bones 0/3; original structural faces excluded')
