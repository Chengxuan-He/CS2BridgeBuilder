"""Record Lift03's native far upper road top without removing its structural shell.
Usage: python Lift03FarRoadTops.py RESEARCH_DIRECTORY OUTPUT_CS
The lower carriageway has no independent native far road-top plane.
"""
from pathlib import Path
import ctypes as c
import hashlib, struct, sys
import numpy as np

r, output = map(Path, sys.argv[1:3])
path = r / 'movable-skin/LiftBridge03_LOD2 Mesh.Geometry'
raw = path.read_bytes()
digest = '4dd846ac20f020fb45de94549d66e0bbafda4c575554a5b235a93e7d5a6008e4'
assert hashlib.sha256(raw).hexdigest() == digest
decoder = Path(__file__).with_name('Lift05Counterweights.py').read_text()
exec(decoder[decoder.index('dll = c.CDLL'):decoder.index('tables=[]')])
version, meshes, flags = struct.unpack_from('<HII', raw)
assert version == 1 and meshes == 1
headers = [struct.unpack_from('<QI14i5I', raw, 10)]
h = headers[0]
section = decoder[decoder.index('    def decode('):decoder.index('    cached=np.load')]
exec('\n'.join(line[4:] if line.startswith('    ') else line for line in section.splitlines()))
