"""Emit the Draw03 road-adjacent base displacement, excluding support cradles.
Usage: python Draw03Bases.py RESEARCH_DIRECTORY OUTPUT_CS
Original centre residues are recorded as stationary centre vertices offline.
"""
from pathlib import Path
import hashlib
import json
import sys
import numpy as np

r, output = map(Path, sys.argv[1:])
parts = [[p for p in json.loads((r / f'draw03-parts-{lod}.json').read_text()) if not p['side']] for lod in range(2)]
# Reviewed road-adjacent moving bases (two positive halves, one negative body) and fixed end bases.
selected = [0, 1, 3, 88, 90]
assert [len(parts[0][i]['vertices']) for i in selected] == [3984, 3982, 1752, 7966, 1752]
for i in selected:
    assert parts[0][i]['minimum'] == parts[1][i]['minimum']
    assert parts[0][i]['maximum'] == parts[1][i]['maximum']
tables = []
for lod in range(2):
    name = 'DrawBridge03' + ('_LOD1' if lod else '') + ' Mesh.Geometry'
    digest = hashlib.sha256((r / 'movable-skin' / name).read_bytes()).hexdigest()
    assert digest == ('f7ecc824ad55745e791e40b18fd12f5def20657ed8ea56d373429d5a1337588f',
                      '15b8419da13d6e99e1dc0591f12f4019f0be09c3b220a481d24720daf7b57e12')[lod]
    v = np.load(r / f'draw03-main-{lod}.npz')['positions']
    ids = sorted(i for p in selected for i in parts[lod][p]['vertices'])
    assert len(set(ids)) == len(ids)
    for i in selected:
        assert parts[0][i]['minimum'][0] == parts[1][i]['minimum'][0]
        assert parts[0][i]['maximum'][0] == parts[1][i]['maximum'][0]
    weights = np.sign(v[ids, 0]).astype(np.int8)
    # Authored centre seam residues span +/-49.591 micrometres in both LODs.
    weights[abs(v[ids, 0]) <= .000049591064453125] = 0
    groups = {side: [i for i, w in zip(ids, weights) if w == side] for side in (-1, 0, 1)}
    data = np.load(r / f'draw03-main-{lod}.npz')
    for part, expected_bone in zip(selected, (1, 1, 0, 2, 0)):
        membership = np.isin(data['indices'], parts[lod][part]['vertices'])
        assert not np.any(membership.any(1) & ~membership.all(1))
        assert set(data['bones'][membership.all(1)]) == {expected_bone}
    assert len(ids) == (19436, 19858)[lod]
    for delta in (-8., -4., -2., -.24432373, -.1, 0., 2., 8.):
        moved = v[ids].copy()
        moved[:, 0] += weights * delta
        assert np.array_equal(moved[:, 1:], v[ids, 1:])
        assert np.array_equal(moved[weights == 0], v[ids][weights == 0])
        data = np.load(r / f'draw03-main-{lod}.npz')
        all_positions = v.copy()
        all_positions[ids] = moved
        faces = data['indices']
        member = np.isin(faces, ids)
        assert not np.any(member.any(1) & ~member.all(1))
        faces = faces[member.all(1)]
        before, after = v[faces].astype(float), all_positions[faces].astype(float)
        n0 = np.cross(before[:,1]-before[:,0], before[:,2]-before[:,0])
        n1 = np.cross(after[:,1]-after[:,0], after[:,2]-after[:,0])
        valid = np.linalg.norm(n0, axis=1) > 1e-8
        assert np.isfinite(moved).all()
        if delta >= -.1: assert np.all(np.sum(n0[valid]*n1[valid], axis=1) > 0)
        for side in (-1, 1):
            assert np.allclose(moved[weights == side] - v[ids][weights == side], [side * delta, 0, 0], atol=2e-6)
    name = 'DrawBridge03' + ('_LOD1' if lod else '') + ' Mesh.Geometry'
    tables.append((groups, hashlib.sha256((r / 'movable-skin' / name).read_bytes()).hexdigest()))
    print(f'LOD{lod}: 5 base components, {len(ids)} vertices; centre and side displacement checks passed')

def ranges(ids):
    result = []
    for i in ids:
        if result and result[-1][1] + 1 == i:
            result[-1][1] = i
        else:
            result.append([i, i])
    return result

lines = ['// Native DrawBridge03 road-adjacent bases and road bodies.',
         '// Generated by Draw03Bases.py; centre residues are explicitly assigned.',
         'using System;', 'using UnityEngine;', '', 'namespace BridgeBuilder.Bridges;', '',
         'internal static class Draw03Bases', '{',
         '    internal static void Apply(int lod, Vector3[] source, Vector3[] positions, float delta)',
         '    {', '        var data = lod switch', '        {',
         '            0 => (Count: 186078, Left: Left0, Centre: Centre0, Right: Right0),',
         '            1 => (Count: 146988, Left: Left1, Centre: Centre1, Right: Right1),',
         '            _ => throw new ArgumentOutOfRangeException(nameof(lod))', '        };',
         '        if (!float.IsFinite(delta) || source.Length != data.Count || positions.Length != data.Count)',
         '            throw new InvalidOperationException("Draw03 bases require their recorded main mesh.");',
         '        foreach (var range in data.Left)',
         '            for (var i = range.First; i <= range.Last; i++) positions[i].x = source[i].x - delta;',
         '        foreach (var range in data.Centre)',
         '            for (var i = range.First; i <= range.Last; i++) positions[i].x = source[i].x;',
         '        foreach (var range in data.Right)',
         '            for (var i = range.First; i <= range.Last; i++) positions[i].x = source[i].x + delta;',
         '    }', '']
for lod, (groups, digest) in enumerate(tables):
    lines.append('    // Geometry SHA-256: ' + digest)
    for side, name in ((-1, 'Left'), (0, 'Centre'), (1, 'Right')):
        lines += [f'    private static readonly (int First, int Last)[] {name}{lod} =', '    {']
        lines += [f'        ({a}, {b}),' for a, b in ranges(groups[side])]
        lines += ['    };', '']
lines += ['}', '']
output.write_text('\n'.join(lines), encoding='utf-8')
