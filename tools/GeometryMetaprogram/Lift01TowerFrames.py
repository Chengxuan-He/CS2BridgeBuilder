"""Emit Lift01 joined tower crossbars with stationary centre columns.
Usage: python Lift01TowerFrames.py RESEARCH_DIRECTORY OUTPUT_CS
"""
from pathlib import Path
import hashlib
import json
import sys
import numpy as np

r, output = map(Path, sys.argv[1:])
selected = [280, 308]
tables = []
near = json.loads((r / 'lift01-crossing-0.json').read_text())
for lod in range(2):
    parts = json.loads((r / f'lift01-crossing-{lod}.json').read_text())
    d = np.load(r / f'lift01-main-{lod}.npz')
    v, faces = d['positions'], d['indices']
    weights = {}
    for ordinal in selected:
        part = parts[ordinal]
        assert part['minimum'] == near[ordinal]['minimum']
        assert part['maximum'] == near[ordinal]['maximum']
        ids = part['vertices']
        member = np.isin(faces, ids)
        assert not np.any(member.any(1) & ~member.all(1))
        fs = faces[member.all(1)]
        # Offline inspection: complete crossbars have endpoints at +/-7.6124.. m.
        # The centre column's outer faces are at +/-0.3396 m. Original index
        # ownership is separate despite coincident attachment positions.
        bars = fs[np.max(abs(v[fs][:, :, 0]), axis=1) > 7]
        bar_ids = set(map(int, bars.flat))
        column_ids = set(ids) - bar_ids
        assert len(bar_ids) == 576 and len(column_ids) == 336
        assert all(not (set(f) & bar_ids and set(f) & column_ids) for f in fs)
        assert np.max(abs(v[list(column_ids), 0])) == .339599609375
        assert set(v[list(bar_ids), 0]).issubset({0., -7.6126708984375,
            7.6126708984375, -7.612548828125, 7.612548828125,
            -7.6124267578125, 7.6124267578125})
        assert not set(weights).intersection(ids)
        for i in ids:
            weights[i] = int(np.sign(v[i, 0])) if i in bar_ids else 0
        for delta in (-2.99, -2.75, -2., -.5, 0., 2., 8.):
            moved = v.copy()
            for i in ids:
                moved[i, 0] += weights[i] * delta
            assert np.array_equal(moved[list(column_ids)], v[list(column_ids)])
            assert np.array_equal(moved[ids, 1:], v[ids, 1:])
            a, b = v[fs].astype(float), moved[fs].astype(float)
            n0 = np.cross(a[:,1]-a[:,0], a[:,2]-a[:,0])
            n1 = np.cross(b[:,1]-b[:,0], b[:,2]-b[:,0])
            valid = np.linalg.norm(n0, axis=1) > 1e-8
            assert np.all(np.sum(n0[valid]*n1[valid], axis=1) > 0)
    digest = hashlib.sha256((r/'movable-skin'/('LiftBridge01'+('_LOD1' if lod else '')+' Mesh.Geometry')).read_bytes()).hexdigest()
    tables.append((weights, digest))
    print(f'LOD{lod}: 1152 crossbar vertices and 672 stationary column vertices; seven widths passed')

def ranges(ids):
    result = []
    for i in sorted(ids):
        if result and result[-1][1]+1 == i:
            result[-1][1] = i
        else:
            result.append([i,i])
    return result

lines = ['// Native LiftBridge01 tower crossbars and centre columns.',
         '// Generated by Lift01TowerFrames.py; no runtime part classification.',
         'using System;', 'using UnityEngine;', '', 'namespace BridgeBuilder.Bridges;', '',
         'internal static class Lift01TowerFrames', '{',
         '    internal static void Apply(int lod, Vector3[] source, Vector3[] positions, float delta)',
         '    {', '        var data = lod switch', '        {',
         '            0 => (Count: 472209, Parts: Near),',
         '            1 => (Count: 351968, Parts: Middle),',
         '            _ => throw new ArgumentOutOfRangeException(nameof(lod))', '        };',
         '        if (!float.IsFinite(delta) ||',
         '            source.Length != data.Count || positions.Length != data.Count)',
         '            throw new InvalidOperationException("Lift01 tower frames require their recorded layout.");',
         '        foreach (var range in data.Parts)',
         '            for (var i = range.First; i <= range.Last; i++)',
         '                positions[i].x = source[i].x + range.Weight * delta;',
         '    }', '']
for lod,(weights,digest) in enumerate(tables):
    lines += ['    // Geometry SHA-256: '+digest,
        '    private static readonly (int First, int Last, int Weight)[] '+('Near' if lod==0 else 'Middle')+' =', '    {']
    for w in (-1,0,1):
        lines += [f'        ({a}, {b}, {w}),' for a,b in ranges(i for i,x in weights.items() if x==w)]
    lines += ['    };','']
lines += ['}','']
output.write_text('\n'.join(lines), encoding='utf-8')
