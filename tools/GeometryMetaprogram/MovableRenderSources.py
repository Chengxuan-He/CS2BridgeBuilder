"""Emit prototype-independent movable render inputs from the native 1.6.2f1 audit.
Usage: python MovableRenderSources.py AUDIT_JSON REPOSITORY
The audit is an offline input, not a runtime dependency.
"""
import hashlib
import json
from pathlib import Path
import struct
import sys
import re

audit = Path(sys.argv[1])
repo = Path(sys.argv[2])
digest = hashlib.sha256(audit.read_bytes()).hexdigest()
assert digest == '47ef0f1723e8643e74a17751aa480f97260bf6e549aa60ec9f14f8e003b12070'
records = json.loads(audit.read_text(encoding='utf-8'))['selected']
styles = [('Draw02', 'DrawBridge02'), ('Draw03', 'DrawBridge03')]
styles += [(f'Lift{i:02}', f'LiftBridge{i:02}') for i in range(1, 6)]
styles += [(f'PedestrianDraw{i:02}', f'PedestrianDrawBridge{i:02}') for i in range(1, 3)]

def cid(value):
    words = [value[f'm_GuidPart{i}'] for i in range(1, 5)]
    raw = struct.pack('<4i', *words)
    text = ''.join(f'{b & 15:x}{b >> 4:x}' for b in raw)
    # Independent reverse conversion catches word ordering and nibble inversion.
    decoded = bytes(int(text[i + 1] + text[i], 16) for i in range(0, 32, 2))
    assert struct.unpack('<4i', decoded) == tuple(words)
    return json.dumps(text)

def f(value):
    return format(float(value), '.17g') + 'f'

def vector(value):
    return 'new float3(' + ', '.join(f(value[k]) for k in 'xyz') + ')'

total = 0
for style, native in styles:
    owners = [v['data'] for v in records.values()
              if v['data'].get('m_Name') == native and 'm_Meshes' in v['data']]
    assert len(owners) == 1 and len(owners[0]['m_Meshes']) == 3
    lines = [f'// Recorded {native} render inputs, game 1.6.2f1.',
             '// Audit SHA-256: ' + digest,
             '// Generated by tools/GeometryMetaprogram/MovableRenderSources.py.',
             'using Colossal.Mathematics;', 'using Game.Prefabs;', 'using Unity.Mathematics;',
             '', 'namespace BridgeBuilder.Bridges;', '',
             f'internal sealed class {style}SourceRenders : MovableSourceRenders', '{',
             f'    internal {style}SourceRenders(RenderPrefab nativeDefaultBase, ContentPrefab content)',
             '    {', '        try', '        {']
    for part, item in zip(('Mechanism', 'Column', 'Footing'), owners[0]['m_Meshes']):
        root = records[str(item['m_Mesh']['m_PathID'])]['data']
        lod_component = next(c for c in root['components'] if c['name'] == 'LodProperties')
        lods = records[str(lod_component['m_PathID'])]['data']['m_LodMeshes']
        levels = [root] + [records[str(lod['m_PathID'])]['data'] for lod in lods]
        configuration = (repo / 'src/BridgeBuilder/Bridges/Types' / style /
                         f'{style}RenderData.g.cs').read_text(encoding='utf-8')
        expected = re.search(r'case Part\.' + part + r':.*?levels.Length != (\d+)',
                             configuration, re.S)
        assert expected and len(levels) == int(expected.group(1)), (style, part, len(levels))
        lines += [f'            var {part.lower()} = new[]', '            {']
        for d in levels:
            assert d['m_IsImpostor'] == 0 and d['m_ManualVTRequired'] == 0
            surfaces = ', '.join(cid(v) for v in d['m_SurfaceAssets'])
            lines += [f'                Create({json.dumps(d["m_Name"])}, {cid(d["m_GeometryAsset"])},',
                      f'                    new[] {{ {surfaces} }},',
                      f'                    new Bounds3({vector(d["m_Bounds"]["min"])}, {vector(d["m_Bounds"]["max"])}),',
                      f'                    {d["m_VertexCount"]}, {d["m_IndexCount"]}, {d["m_MeshCount"]}, {f(d["m_SurfaceArea"])}),']
            total += 1
        lines += ['            };',
                  f'            {style}RenderData.Configure({style}RenderData.Part.{part}, {part.lower()}, nativeDefaultBase, content);']
        if part == 'Mechanism':
            lines += ['            for (var lod = 0; lod < mechanism.Length; lod++)',
                      f'                {style}MechanismData.ApplySkeleton(mechanism[lod], lod);']
    lines += ['            Roots = new[] { mechanism[0], column[0], footing[0] };',
              '        }', '        catch { Dispose(); throw; }', '    }', '}', '']
    path = repo / 'src/BridgeBuilder/Bridges/Types' / style / f'{style}SourceRenders.cs'
    path.write_text('\n'.join(lines), encoding='utf-8')
    print(style, 'recorded input graph emitted')
print(total, 'render descriptors; CID reverse conversion passed')
