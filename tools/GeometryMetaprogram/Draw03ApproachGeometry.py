"""Emit native Draw03 approach base seam maps, preserving all fifteen meshes.
Usage: python Draw03ApproachGeometry.py RESEARCH_DIRECTORY OUTPUT_CS
Run Draw03ApproachBraces.py first. The connected road-bottom shell uses the base
sign mapping, not a uniform scale of its attached longitudinal members.
"""
from pathlib import Path
import hashlib
import json
import sys
import numpy as np

r, output = map(Path, sys.argv[1:])
audit = json.loads((r/'all-movable-audit.json').read_text())
inventory = json.loads((r/'draw03-approach-inventory.json').read_text())
counts = [[None]*3 for _ in range(5)]
centres = []
for item in inventory:
    part, lod = item['part'], item['lod']
    digest = hashlib.sha256((r/'draw03-approach'/item['source']).read_bytes()).hexdigest()
    assert digest == item['sha256']
    assert any(a.get('sha256') == digest for a in audit['assets'].values())
    data = np.load(r/f'draw03-approach-{part}-{lod}.npz')
    v, faces = data['positions'].astype(float), data['indices'].reshape(-1, 3)
    assert len(v) == item['vertices'] and len(faces) == item['triangles']
    counts[part][lod] = (len(v), len(faces))
    weights = np.zeros(len(v))
    if part == 0:
        parts = json.loads((r/f'draw03-approach-parts-0-{lod}.json').read_text())
        shell = np.array(parts[0]['vertices'])
        assert len(shell) == (605, 410, 120)[lod]
        centre = shell[v[shell, 0] == -1.5]
        assert len(centre) == (164, 100, 22)[lod]
        assert np.min(v[shell[v[shell, 0] > -1.5], 0]+1.5) >= 2
        # Native strip cursor contributes +delta/2 for this first strip.
        weights[:] = .5
        weights[centre] = -.5
        braces = np.load(r/f'draw03-approach-braces-{lod}.npz')['vertices']
        assert not np.intersect1d(shell, braces).size
        weights[braces] = (v[braces, 0]+1.5)/(2.62939453125 if lod == 2 else 2.626800537109375)-.5
        assert len(np.union1d(shell, braces)) == ((1373, 922, 248)[lod])
        centres.append((lod, digest, centre.tolist()))
    for delta in (-8., -4., -2., -.24432373, -.1, 0., 2., 8.):
        moved = v.copy(); moved[:, 0] += weights*delta
        assert np.array_equal(moved[:, 1:], v[:, 1:])
        p, q = v[faces], moved[faces]
        n = np.cross(p[:, 1]-p[:, 0], p[:, 2]-p[:, 0])
        m = np.cross(q[:, 1]-q[:, 0], q[:, 2]-q[:, 0])
        valid = np.linalg.norm(n, axis=1) > 1e-8
        assert np.isfinite(moved).all()
        if delta >= -.1: assert np.all(np.sum(n[valid]*m[valid], axis=1) > 0)
        if part == 0:
            assert np.allclose(moved[centre, 0]+1.5+delta/2, 0, atol=1e-12)
            side = np.ones(len(v), bool); side[centre] = False; side[braces] = False
            assert np.allclose(moved[side, 0]-v[side, 0]+delta/2, delta, atol=1e-12)
        else:
            assert np.array_equal(moved, v)
    np.savez(r/f'draw03-approach-plan-{part}-{lod}.npz', positions=v, indices=faces, weights=weights)
    print(f'Family {part} LOD{lod}: {len(v)} vertices, {len(faces)} original triangles; eight-width centre/rigid-side and positive-span winding checks pass.')

lines = ['// Native DrawBridge03 road-bottom base and side pieces, game 1.6.2f1.',
         '// Generated by tools/GeometryMetaprogram/Draw03ApproachGeometry.py.',
         'using System;', 'using UnityEngine;', '', 'namespace BridgeBuilder.Bridges;', '',
         'internal static class Draw03ApproachGeometry', '{',
         '    internal static MovableStructureModel.Plan Create(int family, int lod, Vector3[] source, int[] indices, float delta)',
         '    {',
         '        var expected = Counts[family][lod];',
         '        if (source.Length != expected.Vertices || indices.Length != expected.Triangles * 3 ||',
         '            !float.IsFinite(delta))',
         '            throw new InvalidOperationException("Draw03 approach requires its recorded meshes.");',
         '        var positions = (Vector3[])source.Clone();',
         '        if (family == 0)', '        {',
         '            // Layout widens only this strip by delta. Its origin moves delta/2;',
         '            // outer strip origins move delta and their local vertices stay unchanged.',
         '            for (var i = 0; i < positions.Length; i++) positions[i].x += delta * 0.5f;',
         '            foreach (var i in CentreVertices[lod]) positions[i].x = source[i].x - delta * 0.5f;',
         '            Draw03ApproachBraces.Apply(lod, source, positions, delta);',
         '        }',
         '        return new MovableStructureModel.Plan(source, positions, new[] { indices },',
         '            new[] { new bool[expected.Triangles] });', '    }', '',
         '    private static readonly (int Vertices, int Triangles)[][] Counts =', '    {']
for family in counts:
    assert all(family)
    lines.append('        new[] { '+', '.join(f'({v}, {t})' for v,t in family)+' },')
lines += ['    };', '', '    private static readonly int[][] CentreVertices =', '    {']
for lod, digest, ids in sorted(centres):
    lines += ['        // Geometry SHA-256: '+digest, '        new[]', '        {']
    for start in range(0,len(ids),16): lines.append('            '+', '.join(map(str,ids[start:start+16]))+',')
    lines += ['        },']
lines += ['    };', '}', '']
output.write_text('\n'.join(lines),encoding='utf-8')
