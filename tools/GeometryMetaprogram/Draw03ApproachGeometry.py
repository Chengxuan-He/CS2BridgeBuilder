"""Emit uniformly stretched Draw03 approach structure at all native LODs.
Usage: python Draw03ApproachGeometry.py RESEARCH_DIRECTORY OUTPUT_CS
"""
from pathlib import Path
import hashlib,json,sys
import numpy as np
r,output=map(Path,sys.argv[1:])
inventory=json.loads((r/'draw03-approach-inventory.json').read_text())
counts=[[None]*3 for _ in range(5)]
for item in inventory:
 part,lod=item['part'],item['lod']
 assert hashlib.sha256((r/'draw03-approach'/item['source']).read_bytes()).hexdigest()==item['sha256']
 d=np.load(r/f'draw03-approach-{part}-{lod}.npz');v=d['positions'];f=d['indices'].reshape(-1,3)
 counts[part][lod]=(len(v),len(f))
 assert (len(v),len(f))==(item['vertices'],item['triangles'])
 for delta in (-8.,-4.,0.,2.,8.):
  q=v.copy()
  if part<4:q[:,0]*=1+delta/12.5
  assert np.array_equal(q[:,1:],v[:,1:])
  if part==4:assert np.array_equal(q,v)
  a=v[f].astype(float);b=q[f].astype(float)
  n=np.cross(a[:,1]-a[:,0],a[:,2]-a[:,0]);m=np.cross(b[:,1]-b[:,0],b[:,2]-b[:,0]);valid=np.linalg.norm(n,axis=1)>1e-8
  assert np.all(np.sum(n[valid]*m[valid],axis=1)>0)
 print(f'PASS approach family{part} LOD{lod}: original topology and Y/Z; five widths.')
# Native positive-side strip centres and widths. All structural strips share one scale;
# the outer 0.5 m railing strip translates with the structural envelope.
for delta in (-8.,-4.,0.,2.,8.):
 scale=1+delta/12.5
 widths=np.array([3.,3.,3.,3.5])*scale
 centers=np.cumsum(widths)-widths/2
 assert np.allclose(centers,np.array([1.5,4.5,7.5,10.75])*scale)
 assert np.isclose(sum(widths),12.5+delta)
lines=['// Generated by Draw03ApproachGeometry.py. Whole fixed truss stretch.',
 'using System;','using UnityEngine;','namespace BridgeBuilder.Bridges;',
 'internal static class Draw03ApproachGeometry {',
 'internal static MovableStructureModel.Plan Create(int family,int lod,Vector3[] source,int[] indices,float delta) {',
 'var expected=Counts[family][lod];',
 'if(source.Length!=expected.Vertices || indices.Length!=expected.Triangles*3 || !float.IsFinite(delta)) throw new InvalidOperationException("Draw03 approach requires its measured meshes.");',
 'var positions=(Vector3[])source.Clone();',
 'if(family<4) { var scale=Draw03Truss.Scale(delta); AffineGeometry.For(0,positions.Length,i=>positions[i].x=AffineGeometry.Scale(source[i].x,scale)); }',
 'return new MovableStructureModel.Plan(source,positions,new[]{indices},new[]{new bool[expected.Triangles]});',
 '}', 'private static readonly (int Vertices,int Triangles)[][] Counts = {']
for family in counts:lines.append('new[]{'+','.join(f'({v},{f})' for v,f in family)+'},')
lines+=['};','}'];output.write_text('\n'.join(lines)+'\n',encoding='utf-8')
