"""Emit Lift01 fixed-span side parts and complete transverse plates.
Usage: python Lift01ApproachParts.py RESEARCH_DIRECTORY OUTPUT_CS
Joined frames/base remain a separate stage; this does not classify at runtime.
"""
from pathlib import Path
import hashlib
import json
import sys
import numpy as np

r, output = map(Path, sys.argv[1:])
hashes = (
    '13872e5563f59223f541d1d2146d9cec7bfe7fac937c9d829c4a7474313621f3',
    '7d859975ab9190b8881d6b93b38ada4a70db112f9a6b9eecc4c11880e7047992',
    '4c393e78ac9580d7a2ceda0f7417ebfdd1b2908af5f61347278ddc064ac567d6')
plate_parts = (
    (5, 13, 19, 26, 32, 39, 45, 52, 793, 801, 807, 814, 820, 827, 833, 840),
    (5, 13, 19, 26, 32, 39, 45, 52, 281, 289, 295, 302, 308, 315, 321, 328),
    ())
counts = (80210, 38399, 1484)
tables = []
for lod in range(3):
    name = 'LiftBridge01Net' + (f'_LOD{lod}' if lod else '') + ' Mesh.Geometry'
    assert hashlib.sha256((r / 'lift01-approaches' / name).read_bytes()).hexdigest() == hashes[lod]
    data = np.load(r / f'lift01-approach-{lod}.npz')
    v, faces = data['positions'], data['indices']
    assert len(v) == counts[lod]
    groups = json.loads((r / f'lift01-approach-{lod}-parts.json').read_text())
    assert len(groups) == (1575, 775, 31)[lod]
    assert sorted(i for g in groups for i in g['vertices']) == list(range(len(v)))
    weights = np.full(len(v), np.nan)
    rigid, transverse = [], []
    side_count = 0
    for ordinal, group in enumerate(groups):
        ids = group['vertices']; p = v[ids]
        if p[:, 0].min() > 0 or p[:, 0].max() < 0:
            side_count += 1
            sign = int(np.sign(p[0, 0])); weights[ids] = sign
            rigid.extend((i, sign) for i in ids)
        elif ordinal in plate_parts[lod]:
            assert p[:, 0].min() == -3.62957763671875 and p[:, 0].max() == 3.62957763671875
            assert len(ids) == (262, 248)[lod]
            weights[ids] = p[:, 0] / np.float32(3.62957763671875)
            transverse.extend(ids)
    assert side_count == (1542, 742, 30)[lod]
    assert len(transverse) == (4192, 3968, 0)[lod]
    selected = np.isfinite(weights)
    membership = selected[faces]
    assert not np.any(membership.any(1) & ~membership.all(1))
    triangles = faces[membership.all(1)]
    before = v[triangles].astype(float)
    normal = np.cross(before[:, 1] - before[:, 0], before[:, 2] - before[:, 0])
    valid = np.linalg.norm(normal, axis=1) > 1e-8
    for delta in (-4, -2.75, -2, -1, 0, 2, 8):
        moved = v.copy(); moved[selected, 0] += weights[selected] * delta
        assert np.array_equal(moved[~selected], v[~selected])
        assert np.array_equal(moved[:, 1:], v[:, 1:])
        for group in groups:
            ids = group['vertices']
            if np.all(weights[ids] == 1) or np.all(weights[ids] == -1):
                assert np.allclose(moved[ids, 0] - v[ids, 0], weights[ids] * delta, atol=1e-6)
        after = moved[triangles].astype(float)
        n = np.cross(after[:, 1] - after[:, 0], after[:, 2] - after[:, 0])
        if delta >= -1: assert np.all((normal[valid] * n[valid]).sum(1) > 0)
    def ranges(pairs):
        result = []
        for i, value in sorted(pairs):
            if result and result[-1][1] + 1 == i and result[-1][2] == value:
                result[-1][1] = i
            else: result.append([i, i, value])
        return result
    tables.append((ranges(rigid), ranges((i, 0) for i in transverse)))
    print(f'LOD{lod}: {side_count} rigid parts, {len(plate_parts[lod])} transverse plates; '
          f'{selected.sum()}/{len(v)} vertices and {len(triangles)}/{len(faces)} whole triangles; seven signed widths and positive-span winding passed')

lines = ['// Native LiftBridge01Net fixed-span part transforms, game 1.6.2f1.',
         '// Generated by tools/GeometryMetaprogram/Lift01ApproachParts.py.',
         'using System;', 'using UnityEngine;', '', 'namespace BridgeBuilder.Bridges;', '',
         'internal static class Lift01ApproachParts', '{',
         '    // Joined frames and the road-adjacent base are handled separately.',
         '    internal static void Apply(int lod, Vector3[] source, Vector3[] positions, float delta)',
         '    {', '        var count = lod switch', '        {',
         '            0 => 80210, 1 => 38399, 2 => 1484,',
         '            _ => throw new ArgumentOutOfRangeException(nameof(lod))', '        };',
         '        if (source.Length != count || positions.Length != count || !float.IsFinite(delta))',
         '            throw new InvalidOperationException("Lift01 fixed-span parts require the recorded layout.");',
         '        foreach (var part in Rigid[lod])',
         '            for (var i = part.First; i <= part.Last; i++)',
         '                positions[i].x = source[i].x + part.Direction * delta;',
         '        foreach (var part in Plates[lod])',
         '            for (var i = part.First; i <= part.Last; i++)',
         '                positions[i].x = source[i].x + source[i].x / 3.62957763671875f * delta;',
         '    }', '']
for table_name, index in (('Rigid', 0), ('Plates', 1)):
    lines += [f'    private static readonly (int First, int Last, int Direction)[][] {table_name} =', '    {']
    for lod, table in enumerate(tables):
        lines += [f'        // Geometry SHA-256: {hashes[lod]}', '        new (int, int, int)[]', '        {']
        lines += [f'            ({a}, {b}, {w}),' for a, b, w in table[index]]
        lines += ['        },']
    lines += ['    };', '']
lines += ['}', '']
output.write_text('\n'.join(lines), encoding='utf-8')
