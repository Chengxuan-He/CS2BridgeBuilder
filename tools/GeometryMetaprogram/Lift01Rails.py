"""Emit whole native Lift01 rail/fastener faces for selected-road replacement.
Usage: python Lift01Rails.py RESEARCH_DIRECTORY OUTPUT_CS
Requires the side/crossing group records emitted by Lift01RigidParts.py.
Native track sleepers are removed by the separate Lift01SleeperRemoval stage.
"""
from pathlib import Path
import hashlib
import json
import sys
import numpy as np

r, output = map(Path, sys.argv[1:])
groups = [json.loads((r / f'lift01-side-{lod}.json').read_text()) for lod in (0, 1)]
# Reviewed authored group ranges: fixed rails/fasteners, moving positive half,
# moving negative half. Intervening groups include unrelated machinery.
chosen = list(range(1814, 2138)) + list(range(6270, 7072)) + list(range(8966, 9766))
rails = {1814, 1815, 1976, 1977, 6270, 6271}
crossing = json.loads((r / 'lift01-crossing-0.json').read_text())
sleepers = [p for p in crossing if p['minimum'][0] == -1.350006103515625
            and p['maximum'][0] == 1.350006103515625
            and p['minimum'][1] == 9.800048828125 and p['maximum'][1] == 9.86962890625]
assert len(sleepers) == 240 and len(chosen) == 1926
hits = np.zeros(240, dtype=int)
for i in chosen:
    if i in rails:
        continue
    p = groups[0][i]
    matches = [j for j, q in enumerate(sleepers)
               if q['minimum'][2] <= p['minimum'][2] and p['maximum'][2] <= q['maximum'][2]]
    assert len(matches) == 1
    hits[matches[0]] += 1
assert np.all(hits == 8)
audit = json.loads((r / 'lift-native-road-plane-candidates.json').read_text())
tables = []
for lod in (0, 1):
    data = np.load(r / f'lift01-main-{lod}.npz')
    v, f = data['positions'], data['indices']
    selected = np.zeros(len(v), dtype=bool)
    for i in chosen:
        group = groups[lod][i]
        assert np.max(abs(np.array(group['minimum']) - groups[0][i]['minimum'])) <= .05078125
        assert np.max(abs(np.array(group['maximum']) - groups[0][i]['maximum'])) <= .05078125
        ids = group['vertices']
        assert not selected[ids].any()
        selected[ids] = True
        assert np.array_equal(v[ids].min(0), group['minimum'])
        assert np.array_equal(v[ids].max(0), group['maximum'])
    membership = selected[f].sum(1)
    assert not np.any((membership != 0) & (membership != 3))
    faces = np.flatnonzero(membership == 3).tolist()
    record = next(x for x in audit if x['style'] == 1 and x['lod'] == lod)
    digest = hashlib.sha256((r / 'movable-skin' / record['geometry']).read_bytes()).hexdigest()
    assert digest.lower() == record['sha256'].lower()
    tops = {i for c in record['candidates'] if c['bone'] in (0, 4)
            and c['y'] == 9.800048828125 for i in c['faces']}
    assert tops.isdisjoint(faces)
    ranges = []
    for i in faces:
        if ranges and ranges[-1][1] + 1 == i:
            ranges[-1][1] = i
        else:
            ranges.append([i, i])
    assert [i for a, b in ranges for i in range(a, b+1)] == faces
    tables.append((len(f), ranges, digest))
    print(f'LOD{lod}: 6 rails / 1920 fasteners, {len(faces)} faces, no shared structural/top faces.')

lines = ['// Generated by Lift01Rails.py from reviewed native rail and fastener groups.',
         '// Only whole original triangles are removed; no runtime spatial selection.',
         'using System;', '', 'namespace BridgeBuilder.Bridges;', '',
         'internal static class Lift01RailRemoval', '{',
         '    internal static void Remove(int lod, bool[] removed)', '    {',
         '        var data = lod switch', '        {']
for lod, (count, _, _) in enumerate(tables):
    lines.append(f'            {lod} => (Count: {count}, Ranges: Lod{lod}),')
lines += ['            _ => throw new ArgumentOutOfRangeException(nameof(lod))', '        };',
          '        if (removed.Length != data.Count)',
          '            throw new InvalidOperationException("Lift01 rail source layout changed.");',
          '        foreach (var range in data.Ranges)',
          '            for (var i = range.First; i <= range.Last; i++) removed[i] = true;',
          '    }', '']
for lod, (_, ranges, digest) in enumerate(tables):
    lines += [f'    // Geometry SHA-256: {digest}',
              f'    private static readonly (int First, int Last)[] Lod{lod} =', '    {']
    lines += [f'        ({a}, {b}),' for a, b in ranges]
    lines += ['    };', '']
lines += ['}']
output.write_text('\n'.join(lines)+'\n', encoding='utf-8')
