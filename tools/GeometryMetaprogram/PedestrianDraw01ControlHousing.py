"""Emit the fixed centre-crossing control enclosure at each native LOD."""
from pathlib import Path
import ctypes as c
import hashlib,json,struct,sys
import numpy as np

r,output=map(Path,sys.argv[1:])
audit=json.loads((r/'all-movable-audit.json').read_text())
decoder=Path(__file__).with_name('Lift05Counterweights.py').read_text()
exec(decoder[decoder.index('dll = c.CDLL'):decoder.index('tables=[]')])
levels=[]
for lod in range(3):
    name='PedestrianDrawBridge01'+(f'_LOD{lod}' if lod else '')+' Mesh'
    raw=(r/'movable-skin'/(name+'.Geometry')).read_bytes()
    digest=hashlib.sha256(raw).hexdigest()
    assert any(a.get('sha256')==digest for a in audit['assets'].values())
    version,meshes,flags=struct.unpack_from('<HII',raw)
    assert version==1 and meshes==(1 if lod==2 else 2)
    headers=[struct.unpack_from('<QI14i5I',raw,10+i*88) for i in range(meshes)]
    h=headers[0]
    section=decoder[decoder.index('    def decode('):decoder.index('    cached=np.load')]
    exec('\n'.join(line[4:] if line.startswith('    ') else line for line in section.splitlines()))
    cached=np.load(r/f'pedestrian01-main-{lod}-0.npz')
    assert np.array_equal(f,cached['indices'])
    assert np.allclose(v,cached['positions'],atol=1e-6,rtol=1e-7)
    comp=cached['component'];selected=np.zeros(len(v),dtype=bool)
    if lod<2:
        fixed=np.isin(comp,(0,204) if lod==0 else (0,197))
        mask=fixed[f].all(1)&(v[f,1]>=10).all(1)&(np.abs(v[f,0])<=.25726318359375).all(1)
        selected[np.unique(f[mask])]=True
    else:selected=np.isin(comp,(0,30))
    spans=[]
    for sign in (-1,1):
        p=v[selected & (np.sign(v[:,2])==sign)]
        assert p[:,0].max()==-p[:,0].min()==.25726318359375
        spans.append(float(p[:,0].max()))
    touched=selected[f].any(1)
    # The enclosure foot shares vertices with native walking faces that the
    # separate road replacement removes. No retained structure may straddle it.
    road=np.load(r/f'pedestrian01-road-removal-{lod}.npy')
    crossing=touched & ~selected[f].all(1)
    assert np.all(np.isin(np.flatnonzero(crossing),road))
    touched=selected[f].all(1)
    bones=np.load(r/f'pedestrian01-bones-{lod}.npy')
    assert set(bones[touched])=={'bone_0'}
    base=np.load(r/f'pedestrian01-deck-base-{lod}.npz')['selected']
    assert not np.any(base & selected)
    for delta in (-.03,0,2,8):
        q=v.astype(float).copy();q[selected,0]+=v[selected,0].astype(float)/spans[0]*delta
        assert np.array_equal(q[~selected],v[~selected]) and np.array_equal(q[:,1:],v[:,1:])
        a,b=v[f[touched]].astype(float),q[f[touched]]
        n=np.cross(a[:,1]-a[:,0],a[:,2]-a[:,0]);m=np.cross(b[:,1]-b[:,0],b[:,2]-b[:,0])
        active=np.linalg.norm(n,axis=1)>1e-9
        assert np.all((n[active]*m[active]).sum(1)>0)
    ranges=[]
    for i in np.flatnonzero(selected):
        i=int(i)
        if ranges and ranges[-1][1]==i-1:ranges[-1][1]=i
        else:ranges.append([i,i])
    np.savez(r/f'pedestrian01-control-{lod}.npz',positions=v,indices=f,selected=selected)
    levels.append((len(v),digest,ranges))
    print('PASS',lod,'control vertices',selected.sum(),'triangles',touched.sum(),'native bone 0; disjoint from bases')
lines=['// Generated by PedestrianDraw01ControlHousing.py from the native fixed enclosure.',
       'using System;','using UnityEngine;','','namespace BridgeBuilder.Bridges;','',
       'internal static class PedestrianDraw01ControlHousing','{',
       '    internal static void Apply(int lod, Vector3[] source, Vector3[] positions, float delta)',
       '    {','        var data = lod switch','        {']
for lod,(count,_,_) in enumerate(levels):lines.append(f'            {lod} => (Count: {count}, Parts: Parts{lod}),')
lines+=['            _ => throw new ArgumentOutOfRangeException(nameof(lod))','        };',
        '        const float halfSpan = 0.25726318359375f;',
        '        if (source.Length != data.Count || positions.Length != data.Count || !float.IsFinite(delta) || delta <= -halfSpan)',
        '            throw new InvalidOperationException("PedestrianDraw01 control enclosure requires its native layout and positive span.");',
        '        foreach (var part in data.Parts)',
        '            for (var i = part.First; i <= part.Last; i++)',
        '                positions[i].x = source[i].x + source[i].x / halfSpan * delta;',
        '    }','']
for lod,(_,digest,ranges) in enumerate(levels):
    lines+=['    // Geometry SHA-256: '+digest,
            f'    private static readonly (int First, int Last)[] Parts{lod} =','    {']
    lines += [f'        ({a}, {b}),' for a,b in ranges];lines+=['    };','']
lines+=['}',''];output.write_text('\n'.join(lines),encoding='utf-8')
