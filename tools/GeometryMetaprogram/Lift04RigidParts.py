"""Emit Lift04 disconnected side-part translations from reviewed native inventories.
Usage: python Lift04RigidParts.py RESEARCH_DIRECTORY OUTPUT_CS
This is a transform map, not a sidewalk-presence or road-replacement mask.
"""
from pathlib import Path
import hashlib,json,sys
import numpy as np
r,output=map(Path,sys.argv[1:])
records=json.loads((r/'lift04-main-parts.json').read_text())
hashes=('869158c6d06c9a9717851460adf922838d45c294c4b1e692b7b96e4585422980',
 '4d57e1fe16365bf8702d310191fefbbbbbece9fcafb413b980052640e26d1b6f',
 next(x['sha256'] for x in records if x['lod']==2 and x['mesh']==0))
levels=[]
for lod in range(3):
 record=next(x for x in records if x['lod']==lod and x['mesh']==0)
 path=r/'movable-skin'/(record['source']+'.Geometry')
 assert hashlib.sha256(path.read_bytes()).hexdigest()==record['sha256']==hashes[lod]
 data=np.load(r/f'lift04-main-{lod}-0.npz')
 v,f,component=data['positions'],data['indices'],data['component']
 vertices=[];faces=[];bones=[];bone=-1
 for line in path.with_suffix('.mesh-0.obj').read_text().splitlines():
  fields=line.split()
  if not fields:continue
  if fields[0]=='v':vertices.append(list(map(float,fields[1:4])))
  elif fields[0]=='g':bone=int(fields[1][5:]) if fields[1].startswith('bone_') else -1
  elif fields[0]=='f':faces.append([int(x.split('/')[0])-1 for x in fields[1:]]);bones.append(bone)
 assert np.array_equal(v,vertices) and np.array_equal(f,faces)
 signs=np.zeros(len(v),dtype=np.int8);parts=[]
 for part in record['parts']:
  ids=np.flatnonzero(component==part['id']);p=v[ids]
  assert len(ids)==part['vertices']
  assert np.array_equal(p.min(0),part['minimum']) and np.array_equal(p.max(0),part['maximum'])
  crossing=p[:,0].min()<=0<=p[:,0].max()
  assert crossing==part['crosses']
  if crossing:continue
  side=-1 if p[:,0].max()<0 else 1
  mask=component==part['id'];touched=mask[f].any(1)
  assert np.all(mask[f[touched]]) and touched.sum()==part['triangles']
  signs[ids]=side
  parts.append(dict(id=part['id'],side=side,minimum=part['minimum'],maximum=part['maximum'],bones=sorted(set(np.array(bones)[touched].tolist()))))
 selected=signs!=0
 assert len(parts)==(922,851,130)[lod] and selected.sum()==(36732,26051,1576)[lod]
 assert np.all(selected[f].any(1)==selected[f].all(1))
 sf=f[selected[f].all(1)]
 for delta in (-.25,0,2,8):
  moved=v.copy();moved[:,0]+=signs*delta
  assert np.array_equal(moved[:,1:],v[:,1:])
  for i in (1,2):assert np.allclose(moved[sf[:,i]]-moved[sf[:,0]],v[sf[:,i]]-v[sf[:,0]],rtol=0,atol=1e-12)
  assert np.array_equal(moved[~selected],v[~selected])
  np.savez(r/f'lift04-rigid-{lod}-{delta:g}.npz',positions=moved,indices=f,selected=selected)
 levels.append((v,signs,record['sha256'],parts))
 print(f'LOD{lod}: {len(parts)} side components, {selected.sum()} vertices, {len(sf)} triangles; rigid edges and four widths passed')
# Every reduced side envelope must remain on its source side. Detailed/far merging
# does not authorize moving any component which reaches the centre into this map.
# Joined fixed/moving bodies, machinery and crossing members remain excluded.
(r/'lift04-rigid-parts.json').write_text(json.dumps([x[3] for x in levels],indent=2)+'\n')
lines=['// Native LiftBridge04 disconnected side components; game 1.6.2f1.',
 '// Generated by Lift04RigidParts.py. Crossing/merged parts require separate plans.',
 '// This table assigns width transforms only; sidewalk-dependent inclusion is separate.',
 'using System;','using UnityEngine;','','namespace BridgeBuilder.Bridges;','',
 'internal static class Lift04RigidParts','{',
 '    internal static void Apply(int lod, Vector3[] source, Vector3[] positions, float delta)','    {',
 '        var data = lod switch','        {']
for lod,(v,signs,digest,parts) in enumerate(levels):lines.append(f'            {lod} => (Count: {len(v)}, Parts: Parts{lod}),')
lines+=['            _ => throw new ArgumentOutOfRangeException(nameof(lod))','        };',
 '        if (source.Length != data.Count || positions.Length != data.Count || !float.IsFinite(delta))',
 '            throw new InvalidOperationException("Lift04 side-part source layout changed.");',
 '        foreach (var part in data.Parts)',
 '            for (var i = part.First; i <= part.Last; i++)',
 '                positions[i].x = source[i].x + part.Side * delta;','    }','']
for lod,(v,signs,digest,parts) in enumerate(levels):
 lines+=['    // Geometry SHA-256: '+digest,
 f'    private static readonly (int First, int Last, int Side)[] Parts{lod} =','    {']
 ranges=[]
 for i in np.flatnonzero(signs):
  side=int(signs[i]);i=int(i)
  if ranges and ranges[-1][1]==i-1 and ranges[-1][2]==side:ranges[-1][1]=i
  else:ranges.append([i,i,side])
 lines += [f'        ({a}, {b}, {side}),' for a,b,side in ranges]
 lines += ['    };','']
lines+=['}',''];output.write_text('\n'.join(lines),encoding='utf-8')


