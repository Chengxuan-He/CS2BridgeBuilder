"""Emit native Lift01 far moving-part membership, retaining its original bones.
Usage: python Lift01FarMovingParts.py RESEARCH_DIRECTORY OUTPUT_CS
"""
from pathlib import Path
import hashlib
import sys
import numpy as np

r, output = map(Path, sys.argv[1:])
d = np.load(r / 'lift01-main-2.npz')
v, f = d['positions'], d['indices']
assert v.shape == (1110, 3) and f.shape == (776, 3)
owner, ordered, active = {}, [], None
for line in (r / 'movable-skin/LiftBridge01_LOD2 Mesh.mesh-0.obj').read_text().splitlines():
    fields = line.split()
    if not fields:
        continue
    if fields[0] == 'g':
        active = int(fields[1].removeprefix('bone_'))
    elif fields[0] == 'f':
        face = [int(x.split('/')[0]) - 1 for x in fields[1:]]
        assert np.array_equal(f[len(ordered)], face)
        ordered.append(active)
        for i in face:
            assert i not in owner or owner[i] == active
            owner[i] = active
assert len(ordered) == len(f) and len(owner) == len(v)
assert [sum(b == k for b in owner.values()) for k in range(5)] == [710, 136, 136, 48, 80]
ordered = np.array(ordered)
for bone in (1, 2):
    x = v[f[ordered == bone], 0]
    # Each wheel is a side part; no native wheel triangle joins left and right.
    assert np.all(np.sign(x).min(1) == np.sign(x).max(1))
    assert set(np.sign(x.ravel())) == {-1, 1}
counter = [i for i, bone in owner.items() if bone == 3]
assert set(v[counter, 0]) == {-6.4205322265625, 6.4205322265625}
# Counterweight boxes have only their own span endpoints; their affine weights
# are exactly +/-1. Bone 4 is handled with the fixed road bases by Lift01FarBases.
weights = {i: int(np.sign(v[i, 0])) for i, bone in owner.items() if bone in (1, 2, 3)}
assert len(weights) == 320 and all(abs(w) == 1 for w in weights.values())
subset = f[np.isin(ordered, (1, 2, 3))]
p = v[subset].astype(float)
normal = np.cross(p[:, 1] - p[:, 0], p[:, 2] - p[:, 0])
for delta in (-2.99, -2.75, -2, -.5, 0, 2, 8):
    moved = v.astype(float).copy()
    for i, w in weights.items():
        moved[i, 0] += w * delta
    assert np.array_equal(moved[:, 1:], v[:, 1:])
    q = moved[subset]
    after = np.cross(q[:, 1] - q[:, 0], q[:, 2] - q[:, 0])
    assert np.all((normal * after).sum(1) > 0)
    for bone in (1, 2):
        for sign in (-1, 1):
            ids = [i for i, b in owner.items() if b == bone and weights[i] == sign]
            assert np.allclose(moved[ids] - v[ids], [sign * delta, 0, 0], rtol=0, atol=1e-12)
ranges = []
for i, w in sorted(weights.items()):
    if ranges and ranges[-1][1] + 1 == i and ranges[-1][2] == w:
        ranges[-1][1] = i
    else:
        ranges.append([i, i, w])
digest = hashlib.sha256((r / 'movable-skin/LiftBridge01_LOD2 Mesh.Geometry').read_bytes()).hexdigest()
lines = ['// Native LiftBridge01_LOD2 moving parts; original procedural bones unchanged.',
         '// Geometry SHA-256: ' + digest,
         '// Generated by Lift01FarMovingParts.py; fixed parts and road bases are handled separately.',
         'using System;', 'using UnityEngine;', '', 'namespace BridgeBuilder.Bridges;', '',
         'internal static class Lift01FarMovingParts', '{',
         '    internal static void Apply(Vector3[] source, Vector3[] positions, float delta)', '    {',
         '        if (source.Length != 1110 || positions.Length != 1110 || !float.IsFinite(delta))',
         '            throw new InvalidOperationException("Lift01 far moving parts require their measured layout.");',
         '        foreach (var part in Parts)',
         '            for (var i = part.First; i <= part.Last; i++) positions[i].x = source[i].x + part.Direction * delta;',
         '    }', '', '    private static readonly (int First, int Last, int Direction)[] Parts =', '    {']
lines += [f'        ({a}, {b}, {w}),' for a, b, w in ranges]
lines += ['    };', '}']
output.write_text('\n'.join(lines) + '\n', encoding='utf-8')
print(f'320 wheel/counterweight vertices, 280 faces, {len(ranges)} ranges; original bone ownership and seven widths verified.')
