"""Emit native Lift05 side-column and foundation translations at every LOD.
Usage: python Lift05Supports.py RESEARCH_DIRECTORY OUTPUT_CS
"""
from pathlib import Path
import hashlib
import json
import sys
import numpy as np

r, output = map(Path, sys.argv[1:])
audit = json.loads((r / 'all-movable-audit.json').read_text())
tables = []
for part in range(2):
    for lod in range(3):
        name = 'LiftBridge05Pillar' + ('Base' if part else '') + (f'_LOD{lod}' if lod else '') + ' Mesh.Geometry'
        raw = (r / 'movable-skin' / name).read_bytes()
        digest = hashlib.sha256(raw).hexdigest()
        assert any(a.get('sha256') == digest for a in audit['assets'].values())
        data = np.load(r / f'lift05-support-{part}-{lod}.npz')
        v, faces = data['positions'], data['indices']
        counts = ((896, 1097, 256), (1792, 1638, 448))
        triangles = ((768, 690, 192), (1536, 1382, 384))
        assert len(v) == counts[part][lod] and len(faces) == triangles[part][lod]
        signs = np.sign(v[:, 0]).astype(int)
        assert np.all(signs != 0) and np.all(signs[faces] == signs[faces[:, :1]])
        # Weld position seams only for offline ownership checks. Runtime keeps
        # all original vertices and attributes, including UV/normal seams.
        parent = list(range(len(v)))
        def find(i):
            while parent[i] != i:
                parent[i] = parent[parent[i]]
                i = parent[i]
            return i
        def join(a, b):
            parent[find(a)] = find(b)
        same = {}
        for i, point in enumerate(v):
            key = tuple(point)
            if key in same: join(i, same[key])
            else: same[key] = i
        for a, b, c in faces:
            join(a, b); join(a, c)
        groups = {}
        for i in range(len(v)): groups.setdefault(find(i), []).append(i)
        assert len(groups) == 8
        for ids in groups.values(): assert np.all(signs[ids] == signs[ids[0]])
        for delta in (-16, -8, -.5, 0, 2, 8):
            moved = v.astype(float).copy()
            moved[:, 0] += signs * delta
            p, q = v[faces].astype(float), moved[faces]
            assert np.array_equal(q[:, 1:] - q[:, :1], p[:, 1:] - p[:, :1])
            assert np.array_equal(moved[:, 1:], v[:, 1:])
        ranges = []
        for i, sign in enumerate(signs):
            if ranges and ranges[-1][1] == i - 1 and ranges[-1][2] == sign:
                ranges[-1][1] = i
            else:
                ranges.append([i, i, int(sign)])
        tables.append((part, lod, len(v), faces.size, digest, ranges, float(abs(v[:, 0]).min())))
        print(f'Part {part} LOD{lod}: {len(v)} vertices, {len(faces)} unchanged triangles; rigid translation checks passed')

lines = ['// Native LiftBridge05 side supports, game 1.6.2f1.',
         '// Generated by Lift05Supports.py; no runtime geometric classification.',
         'using System;', 'using UnityEngine;', '', 'namespace BridgeBuilder.Bridges;', '',
         'internal static class Lift05SupportGeometry', '{',
         '    internal static MovableStructureModel.Plan Create(bool footing, int lod, Vector3[] source, int[] indices, float delta)',
         '    {', '        var data = (footing, lod) switch', '        {']
for part, lod, count, indices, digest, ranges, minimum in tables:
    lines.append(f'            ({str(bool(part)).lower()}, {lod}) => (Count: {count}, Indices: {indices}, Parts: Parts{part}{lod}),')
lines += ['            _ => throw new ArgumentOutOfRangeException(nameof(lod))', '        };',
          '        if (!float.IsFinite(delta) || source.Length != data.Count || indices.Length != data.Indices)',
          '            throw new InvalidOperationException("Lift05 support requires its measured layout.");',
          '        var positions = (Vector3[])source.Clone();',
          '        foreach (var part in data.Parts)',
          '            for (var i = part.First; i <= part.Last; i++) positions[i].x += part.Sign * delta;',
          '        return new MovableStructureModel.Plan(source, positions, new[] { indices }, new[] { new bool[indices.Length / 3] });',
          '    }', '']
for part, lod, count, indices, digest, ranges, minimum in tables:
    lines += ['    // Geometry SHA-256: ' + digest,
              f'    private static readonly (int First, int Last, int Sign)[] Parts{part}{lod} =', '    {']
    lines += [f'        ({a}, {b}, {sign}),' for a, b, sign in ranges]
    lines += ['    };', '']
lines += ['}', '']
output.write_text('\n'.join(lines), encoding='utf-8')
