"""Emit Lift01 ordinary-pillar inputs and object behavior from the native audit.
Usage: python Lift01PillarSources.py AUDIT_JSON OUTPUT_CS
This is distinct from the mechanism's stacked column and foundation.
"""
from pathlib import Path
import hashlib
import json
import struct
import sys

audit, output = map(Path, sys.argv[1:])
digest = hashlib.sha256(audit.read_bytes()).hexdigest()
assert digest == '47ef0f1723e8643e74a17751aa480f97260bf6e549aa60ec9f14f8e003b12070'
records = json.loads(audit.read_text(encoding='utf-8'))['selected']
owners = [r['data'] for r in records.values() if r['data'].get('m_Name') == 'LiftBridge01NetPillar']
assert len(owners) == 1
owner = owners[0]
assert len(owner['m_Meshes']) == 3 and owner['m_Circular'] == 0

def resolve(ref):
    return records[str(ref['m_PathID'])]['data']

def components(data):
    return {c['name']:resolve(c) for c in data['components']}

def number(value):
    return format(float(value), '.17g') + 'f'

def vector(value):
    return 'new float3(' + ', '.join(number(value[k]) for k in 'xyz') + ')'

def cid(value):
    words = tuple(value[f'm_GuidPart{i}'] for i in range(1,5))
    raw = struct.pack('<4i',*words)
    text = ''.join(f'{b&15:x}{b>>4:x}' for b in raw)
    assert struct.unpack('<4i',bytes(int(text[i+1]+text[i],16) for i in range(0,32,2))) == words
    return json.dumps(text)

lines = ['// Native LiftBridge01NetPillar, game 1.6.2f1.', '// Audit SHA-256: ' + digest,
         '// Generated by tools/GeometryMetaprogram/Lift01PillarSources.py.',
         'using System;', 'using Colossal.Mathematics;', 'using Game.Prefabs;', 'using Unity.Mathematics;',
         '', 'namespace BridgeBuilder.Bridges;', '',
         'internal sealed class Lift01PillarSources : MovableSourceRenders', '{',
         '    internal Lift01PillarSources(RenderPrefab nativeDefaultBase, ContentPrefab content)',
         '    {', '        try', '        {']
for part, entry in enumerate(owner['m_Meshes']):
    assert entry['m_Position'] == dict(x=0.,y=0.,z=0.)
    assert entry['m_Rotation']['value'] == dict(x=0.,y=0.,z=0.,w=1.) and entry['m_RequireState'] == 0
    root = resolve(entry['m_Mesh'])
    cs = components(root)
    assert set(cs) == ({'LodProperties','StackProperties','ContentPrerequisite','BaseProperties'} if part == 2 else
                       {'LodProperties','StackProperties','ContentPrerequisite'})
    lod = cs['LodProperties']
    levels = [root] + [resolve(r) for r in lod['m_LodMeshes']]
    assert len(levels) == 3
    lines += [f'            var part{part} = new[]', '            {']
    for d in levels:
        assert d['m_MeshCount'] == 1 and d['m_IsImpostor'] == 0 and d['m_ManualVTRequired'] == 0
        assert len(d['m_SurfaceAssets']) == 1
        lines += [f'                Create({json.dumps(d["m_Name"])}, {cid(d["m_GeometryAsset"])},',
                  f'                    new[] {{ {cid(d["m_SurfaceAssets"][0])} }},',
                  f'                    new Bounds3({vector(d["m_Bounds"]["min"])}, {vector(d["m_Bounds"]["max"])}),',
                  f'                    {d["m_VertexCount"]}, {d["m_IndexCount"]}, 1, {number(d["m_SurfaceArea"])}),']
    lines += ['            };', f'            var lod{part} = part{part}[0].AddComponent<LodProperties>();',
              f'            lod{part}.m_Bias = {number(lod["m_Bias"])};',
              f'            lod{part}.m_ShadowBias = {number(lod["m_ShadowBias"])};',
              f'            lod{part}.m_LodMeshes = new[] {{ part{part}[1], part{part}[2] }};',
              f'            var stack{part} = part{part}[0].AddComponent<StackProperties>();']
    stack=cs['StackProperties']
    for field, cast in (('m_Direction','StackDirection'),('m_Order','StackOrder')):
        lines += [f'            stack{part}.{field} = ({cast}){stack[field]};']
    for field in ('m_StartOverlap','m_EndOverlap'):
        lines += [f'            stack{part}.{field} = {number(stack[field])};']
    lines += [f'            stack{part}.m_ForbidScaling = {str(bool(stack["m_ForbidScaling"])).lower()};']
    if part == 2:
        base=cs['BaseProperties']
        assert base['m_BaseType']['name']=='Default_Base Mesh'
        lines += [f'            var foundation = part{part}[0].AddComponent<BaseProperties>();',
                  '            foundation.m_BaseType = nativeDefaultBase;',
                  f'            foundation.m_UseMinBounds = {str(bool(base["m_UseMinBounds"])).lower()};']
    for level,d in enumerate(levels):
        c=components(d)
        if level: assert set(c)=={'ContentPrerequisite'}
        assert c['ContentPrerequisite']['m_ContentPrerequisite']['name']=='BridgesAndPorts'
        assert all(x['active']==1 for x in c.values())
        lines += [f'            part{part}[{level}].AddComponent<ContentPrerequisite>().m_ContentPrerequisite = content;']
lines += ['            Roots = new[] { part0[0], part1[0], part2[0] };',
          '        }', '        catch { Dispose(); throw; }', '    }', '']
cs=components(owner)
assert set(cs)=={'PillarObject','StandingObject','ContentPrerequisite'}
standing=cs['StandingObject']
assert cs['ContentPrerequisite']['m_ContentPrerequisite']['name']=='BridgesAndPorts'
p=cs['PillarObject']
assert all(c['active']==1 for c in cs.values())
lines += ['    // Inputs here are generated, factory-owned render graphs, not the temporary source roots.',
          '    internal static StaticObjectPrefab CreateObject(TowerFactory factory, string name,',
          '        RenderPrefab top, RenderPrefab column, RenderPrefab footing, ContentPrefab content)',
          '        => factory.CreateMovableObject(name, false, new[]', '        {']
for name in ('top','column','footing'):
    lines += [f'            new ObjectMeshInfo {{ m_Mesh = {name}, m_Position = float3.zero,',
              '                m_Rotation = quaternion.identity, m_RequireState = 0 },']
lines += ['        }, Array.Empty<ObjectSubObjectInfo>(), target =>', '        {',
          '            var pillar = target.AddComponent<PillarObject>();',
          f'            pillar.m_Type = (PillarType){p["m_Type"]};',
          f'            pillar.m_AnchorOffset = {number(p["m_AnchorOffset"])};',
          f'            pillar.m_VerticalPillarOffsetRange = new Bounds1({number(p["m_VerticalPillarOffsetRange"]["min"])}, {number(p["m_VerticalPillarOffsetRange"]["max"])});',
          '            var standing = target.AddComponent<StandingObject>();',
          f'            standing.m_LegSize = {vector(standing["m_LegSize"])};',
          f'            standing.m_LegGap = new float2({number(standing["m_LegGap"]["x"])}, {number(standing["m_LegGap"]["y"])});',
          f'            standing.m_CircularLeg = {str(bool(standing["m_CircularLeg"])).lower()};',
          '            target.AddComponent<ContentPrerequisite>().m_ContentPrerequisite = content;',
          '        });', '}', '']
output.write_text('\n'.join(lines),encoding='utf-8')
print('Lift01 ordinary pillar: 9 native renders, all stack/LOD/base/content components and pillar/standing behavior recorded')
