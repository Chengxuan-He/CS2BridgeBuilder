"""Emit measured end cross-connectors, excluding joined main bodies and machinery."""
from pathlib import Path
import sys,json,hashlib
import numpy as np
r,out=map(Path,sys.argv[1:]);audit=json.loads((r/'all-movable-audit.json').read_text())
components=((2,3,136,137,141,203,206,207,336,337,341,401),(2,3,131,132,136,196,199,200,321,322,326,385),())
levels=[]
for lod,ids in enumerate(components):
 name='PedestrianDrawBridge01'+(f'_LOD{lod}' if lod else '')+' Mesh'
 digest=hashlib.sha256((r/'movable-skin'/(name+'.Geometry')).read_bytes()).hexdigest();assert any(a.get('sha256')==digest for a in audit['assets'].values())
 d=np.load(r/f'pedestrian01-main-{lod}-0.npz');v=d['positions'].astype(np.float32).astype(float);f,c=d['indices'],d['component'];weights=np.zeros(len(v));ranges=[]
 bones=np.load(r/f'pedestrian01-bones-{lod}.npy');boneSets=[]
 for comp in ids:
  selected=c==comp;ii=np.flatnonzero(selected);p=v[ii];span=float(p[:,0].max());assert -p[:,0].min()==span and span>2.46
  touched=selected[f].any(1);assert np.all(selected[f[touched]])
  boneSets.append(sorted(set(bones[touched].tolist())))
  weights[ii]=p[:,0]/span
  runs=[]
  for i in ii:
   if runs and runs[-1][1]==i-1:runs[-1][1]=int(i)
   else:runs.append([int(i),int(i)])
  ranges.extend((a,b,span) for a,b in runs)
 selected=weights!=0
 for delta in (-.5,0,2,8):
  q=v.copy();q[:,0]+=weights*delta
  assert np.array_equal(q[:,1:],v[:,1:]) and np.array_equal(q[~selected],v[~selected])
  a,b=v[f],q[f];na=np.cross(a[:,1]-a[:,0],a[:,2]-a[:,0]);nb=np.cross(b[:,1]-b[:,0],b[:,2]-b[:,0]);active=np.linalg.norm(na,axis=1)>1e-9
  assert np.all(np.sum(na[active]*nb[active],axis=1)>0)
 print('PASS',lod,'parts',len(ids),'vertices',int(np.isin(c,ids).sum()),'triangles',int(np.isin(c[f[:,0]],ids).sum()),'bones',boneSets)
 levels.append((len(v),digest,ranges))
lines=['// Generated by PedestrianDraw01EndConnectors.py; native skeletal channels remain unchanged.','using System;','using UnityEngine;','','namespace BridgeBuilder.Bridges;','','internal static class PedestrianDraw01EndConnectorGeometry','{','    internal static void Apply(int lod, Vector3[] source, Vector3[] positions, float delta)','    {','        var data = lod switch','        {']
for lod,(count,digest,ranges) in enumerate(levels):lines.append(f'            {lod} => (Count: {count}, Parts: Parts{lod}),')
lines+=['            _ => throw new ArgumentOutOfRangeException(nameof(lod))','        };','        if (source.Length != data.Count || positions.Length != data.Count || !float.IsFinite(delta) || delta <= -2.46075439453125f)','            throw new InvalidOperationException("PedestrianDraw01 end connectors require their recorded layout and positive span.");','        foreach (var part in data.Parts)','            for (var i = part.First; i <= part.Last; i++)','                positions[i].x = source[i].x + source[i].x / part.HalfSpan * delta;','    }','']
for lod,(count,digest,ranges) in enumerate(levels):
 lines+=['    // Geometry SHA-256: '+digest,f'    private static readonly (int First, int Last, float HalfSpan)[] Parts{lod} =','    {']
 lines += [f'        ({a}, {b}, {span:.17g}f),' for a,b,span in ranges];lines+=['    };','']
lines+=['}',''];out.write_text('\n'.join(lines))
