"""Emit Lift03 ordinary-column width plans from three hash-verified native meshes.
Usage: python Lift03NetColumnGeometry.py RESEARCH_DIRECTORY OUTPUT_CS
"""
from pathlib import Path
import hashlib,json,sys
import numpy as np
r,output=map(Path,sys.argv[1:])
inventory=json.loads((r/'lift03-netpillar-inventory.json').read_text())
half=3.3563232421875
# Native column side-arc joins; the middle connector spans -half..half.
inventory=[record for record in inventory if record["part"] == 1]
# Reuse polygon clipping arithmetic only, never another style's part membership.
helper=(Path(__file__).with_name('Lift05MovingShell.py')).read_text()
exec(helper[helper.index('def clip('):helper.index('levels=[]')])
levels=[]
for record in inventory:
 part,lod=record['part'],record['lod']
 stem=('LiftBridge03NetPillarTop','LiftBridge03NetPillar','LiftBridge03NetPillarBase')[part]
 name=stem+(f'_LOD{lod}' if lod else '')+' Mesh.Geometry'
 assert hashlib.sha256((r/'lift03-network-pillar'/name).read_bytes()).hexdigest()==record['sha256']
 d=np.load(r/f'lift03-netpillar-{part}-{lod}.npz');v=d['positions'].astype(float);f=d['indices']
 assert (len(v),len(f))==(record['vertices'],record['triangles'])
 split=True
 weights=np.clip(v[:,0]/half,-1,1) if split else np.sign(v[:,0])

 edges=[];extra=[];fragments=[]
 if split:
  for fid,face in enumerate(f):
   points=v[face]
   if not any(points[:,0].min()<cut<points[:,0].max() for cut in (-half,half)):continue
   polys=[list(np.eye(3))]
   for cut in (-half,half):
    result=[]
    for poly in polys:
     xs=[b@points[:,0] for b in poly]
     if min(xs)<cut<max(xs):result.extend((clip(poly,points,cut,True),clip(poly,points,cut,False)))
     else:result.append(poly)
    polys=result
   indices=[];local={}
   for poly in polys:
    polygon=[]
    for bary in poly:
     nz=np.flatnonzero(abs(bary)>1e-10)
     if len(nz)==1:polygon.append(int(face[nz[0]]));continue
     assert len(nz)==2
     a,b=map(int,nz);fraction=float(np.float32(bary[b]));key=(int(face[a]),int(face[b]),fraction)
     if key not in local:
      point=points[a]+(points[b]-points[a])*fraction
      local[key]=len(v)+len(edges);edges.append((*key,float(np.clip(point[0]/half,-1,1))));extra.append(point)
     polygon.append(local[key])
    for j in range(1,len(polygon)-1):indices.extend((polygon[0],polygon[j],polygon[j+1]))
   fragments.append((fid,indices))
 replaced={fid for fid,_ in fragments}
 final=np.array([face.tolist() for i,face in enumerate(f) if i not in replaced]+[ids[j:j+3] for _,ids in fragments for j in range(0,len(ids),3)])
 expanded=np.concatenate((v,np.array(extra).reshape(-1,3)))
 allweights=np.concatenate((weights,[e[3] for e in edges]))
 p=expanded[final];n=np.cross(p[:,1]-p[:,0],p[:,2]-p[:,0]);active=np.linalg.norm(n,axis=1)>1e-9
 src=v[f];area=np.linalg.norm(np.cross(src[:,1]-src[:,0],src[:,2]-src[:,0]),axis=1).sum()
 assert np.isclose(np.linalg.norm(n,axis=1).sum(),area,rtol=1e-6)
 for delta in (-1,0,2,8):
  moved=expanded.copy();moved[:,0]+=allweights*delta
  assert np.array_equal(moved[:,1:],expanded[:,1:])
  q=moved[final];after=np.cross(q[:,1]-q[:,0],q[:,2]-q[:,0]);assert np.all((n[active]*after[active]).sum(1)>0)
  for side in (-1,1):
   rigid=np.all(side*p[:,:,0]>=(half-1e-6 if split else 0),axis=1)
   assert np.allclose(q[rigid]-p[rigid],(side*delta,0,0),atol=2e-6)
  if delta==8:np.savez(r/f'lift03-netpillar-{part}-{lod}-wide.npz',positions=moved,source=expanded,indices=final)
 ranges=[]
 for i,w in enumerate(weights):
  if ranges and ranges[-1][1]+1==i and ranges[-1][2]==w:ranges[-1][1]=i
  else:ranges.append([i,i,float(w)])
 levels.append((record,ranges,edges,fragments))
 print(f'Part {part} LOD{lod}: {len(f)} -> {len(final)} faces, {len(edges)} edge vertices; area, side rigidity and four widths passed')
lines=['// Native Lift03 ordinary-column width plans; generated by Lift03NetColumnGeometry.py.', 'using System;','using UnityEngine;','','namespace BridgeBuilder.Bridges;','','internal static class Lift03NetColumnGeometry','{','    internal static MovableStructureModel.Plan Create(int lod, Vector3[] source, int[] indices, float delta)','    {','        var data = lod switch','        {']
for rec,_,_,_ in levels:
 p,l=rec['part'],rec['lod'];lines.append(f'            {l} => (Count: {rec["vertices"]}, Faces: {rec["triangles"]}, Motion: Motion{p}{l}, Edges: Edges{p}{l}, Fragments: Fragments{p}{l}),')
lines+=['            _ => throw new ArgumentOutOfRangeException(nameof(lod))','        };','        if (source.Length != data.Count || indices.Length != data.Faces * 3 || !float.IsFinite(delta))','            throw new InvalidOperationException("Lift03 ordinary pillar requires its measured native layout.");','        var positions = (Vector3[])source.Clone();','        foreach (var range in data.Motion)','            for (var i = range.First; i <= range.Last; i++)','                positions[i].x = source[i].x + range.Weight * delta;','        var edges = new MovableStructureModel.EdgeVertex[data.Edges.Length];','        var x = new float[edges.Length];','        for (var i = 0; i < edges.Length; i++)','        {','            var edge = data.Edges[i];','            edges[i] = new MovableStructureModel.EdgeVertex(edge.A, edge.B, edge.Fraction);','            x[i] = Mathf.LerpUnclamped(source[edge.A].x, source[edge.B].x, edge.Fraction) + edge.Weight * delta;','        }','        return new MovableStructureModel.Plan(source, positions, new[] { indices }, new[] { new bool[data.Faces] },','            addedVertices: edges, fragments: data.Fragments, constructedX: x);','    }','']
for rec,ranges,edges,fragments in levels:
 key=f'{rec["part"]}{rec["lod"]}';lines+=['    // Geometry SHA-256: '+rec['sha256'],f'    private static readonly (int First, int Last, float Weight)[] Motion{key} =','    {']
 lines += [f'        ({a}, {b}, {w:.9g}f),' for a,b,w in ranges]
 lines+=['    };',f'    private static readonly (int A, int B, float Fraction, float Weight)[] Edges{key} =','    {']
 lines += [f'        ({a}, {b}, {t:.9g}f, {w:.9g}f),' for a,b,t,w in edges]
 lines+=['    };',f'    private static readonly MovableStructureModel.Fragment[] Fragments{key} =','    {']
 lines += [f'        new(0, {fid}, '+', '.join(map(str,ids))+'),' for fid,ids in fragments]
 lines+=['    };','']
lines+=['}',''];output.write_text('\n'.join(lines),encoding='utf-8')

