"""Emit the eighteen measured moving deck crossbeams in detailed PedestrianDraw01."""
from pathlib import Path
import sys,json,hashlib
import numpy as np
r,out=map(Path,sys.argv[1:]);audit=json.loads((r/'all-movable-audit.json').read_text())
components=((21,89,90,91,92,93,94,95,96,225,289,290,291,292,293,294,295,296),(21,93,94,95,96,97,98,99,100,218,283,284,285,286,287,288,289,290),())
levels=[];bounds=[]
for lod,ids in enumerate(components):
 name='PedestrianDrawBridge01'+(f'_LOD{lod}' if lod else '')+' Mesh'
 digest=hashlib.sha256((r/'movable-skin'/(name+'.Geometry')).read_bytes()).hexdigest()
 assert any(x.get('sha256')==digest for x in audit['assets'].values())
 d=np.load(r/f'pedestrian01-main-{lod}-0.npz');v,f,c=d['positions'],d['indices'],d['component'];selected=np.isin(c,ids)
 bones=[];bone=''
 for line in (r/'movable-skin'/(name+'.mesh-0.obj')).read_text().splitlines():
  if line.startswith('g '):bone=line[2:]
  if line.startswith('f '):bones.append(bone)
 levelbounds=[]
 for comp in ids:
  mask=c==comp;p=v[mask];faces=mask[f].all(1)
  assert mask.sum()==24 and faces.sum()==12 and np.all(mask[f].any(1)==faces)
  assert abs(p[:,0].max()-3.886474609375)<1e-6 and abs(p[:,0].min()+3.886474609375)<1e-6
  assert set(np.array(bones)[faces])=={'bone_1' if p[:,2].min()>0 else 'bone_2'}
  levelbounds.append((tuple(p.min(0)),tuple(p.max(0))))
 if lod==1:assert sorted(levelbounds)==sorted(bounds[0])
 bounds.append(levelbounds)
 for delta in (-1,0,2,8):
  q=v.copy();q[selected,0]+=v[selected,0]/3.886474609375*delta
  assert np.array_equal(q[~selected],v[~selected]) and np.array_equal(q[:,1:],v[:,1:])
  a,b=v[f],q[f];na=np.cross(a[:,1]-a[:,0],a[:,2]-a[:,0]);nb=np.cross(b[:,1]-b[:,0],b[:,2]-b[:,0]);active=np.linalg.norm(na,axis=1)>1e-8
  assert np.all(np.sum(na[active]*nb[active],axis=1)>0)
 ranges=[]
 for i in np.flatnonzero(selected):
  if ranges and ranges[-1][1]==i-1:ranges[-1][1]=int(i)
  else:ranges.append([int(i),int(i)])
 levels.append((len(v),digest,ranges))
 print('PASS LOD',lod,'beams',len(ids),'vertices',int(selected.sum()),'triangles',int(selected[f].all(1).sum()))
lines=['// Generated by PedestrianDraw01Crossbeams.py; original bones 1/2 are retained.','using System;','using UnityEngine;','','namespace BridgeBuilder.Bridges;','','internal static class PedestrianDraw01CrossbeamGeometry','{','    internal static void Apply(int lod, Vector3[] source, Vector3[] positions, float delta)','    {','        var data = lod switch','        {']
for lod,(count,digest,ranges) in enumerate(levels):lines.append(f'            {lod} => (Count: {count}, Parts: Parts{lod}),')
lines+=['            _ => throw new ArgumentOutOfRangeException(nameof(lod))','        };','        if (source.Length != data.Count || positions.Length != data.Count || !float.IsFinite(delta) || delta <= -3.886474609375f)','            throw new InvalidOperationException("PedestrianDraw01 crossbeams require their recorded layout and positive span.");','        foreach (var part in data.Parts)','            for (var i = part.First; i <= part.Last; i++)','                positions[i].x = source[i].x + source[i].x / 3.886474609375f * delta;','    }','']
for lod,(count,digest,ranges) in enumerate(levels):
 lines+=['    // Geometry SHA-256: '+digest,f'    private static readonly (int First, int Last)[] Parts{lod} =','    {']
 lines +=[f'        ({a}, {b}),' for a,b in ranges];lines+=['    };','']
lines+=['}',''];out.write_text('\n'.join(lines))
