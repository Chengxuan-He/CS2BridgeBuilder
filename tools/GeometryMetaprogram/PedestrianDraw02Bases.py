"""Emit the PedestrianDraw02 road-adjacent base displacement, excluding support cradles.
Usage: python PedestrianDraw02Bases.py RESEARCH_DIRECTORY OUTPUT_CS
Original centre residues are recorded as stationary centre vertices offline.
"""
from pathlib import Path
import hashlib
import json
import sys
import numpy as np

r, output = map(Path, sys.argv[1:])
parts = [[p for p in json.loads((r / f'pedestrian02-main-{lod}-parts.json').read_text()) if p['crossing']]
         for lod in range(2)]
selected = []
for i, p in enumerate(parts[0]):
    lo, hi = p['minimum'], p['maximum']
    body = len(p['vertices']) in (455, 678, 680)
    adjacent = hi[1] == 9.699951171875 and lo[1] in (9.39990234375, 9.49658203125)
    if body or adjacent:
        selected.append(i)
assert len(selected) == 24
tables = []
for lod in range(2):
    v = np.load(r / f'pedestrian02-main-{lod}.npz')['positions']
    ids = sorted(i for p in selected for i in parts[lod][p]['vertices'])
    assert len(set(ids)) == len(ids)
    for i in selected:
        assert parts[0][i]['minimum'][0] == parts[1][i]['minimum'][0]
        assert parts[0][i]['maximum'][0] == parts[1][i]['maximum'][0]
    weights = np.sign(v[ids, 0]).astype(np.int8)
    weights[abs(v[ids, 0]) < .00001] = 0
    groups = {side: [i for i, w in zip(ids, weights) if w == side] for side in (-1, 0, 1)}
    for delta in (-4., -2., -.25, -.0318012238, -.01, 0., 2., 8.):
        moved = v[ids].copy()
        moved[:, 0] += weights * delta
        assert np.array_equal(moved[:, 1:], v[ids, 1:])
        assert np.array_equal(moved[weights == 0], v[ids][weights == 0])
        for side in (-1, 1):
            assert np.allclose(moved[weights == side] - v[ids][weights == side], [side * delta, 0, 0], atol=2e-6)
    name = 'PedestrianDrawBridge02' + ('_LOD1' if lod else '') + ' Mesh.Geometry'
    tables.append((groups, hashlib.sha256((r / 'movable-skin' / name).read_bytes()).hexdigest()))
    print(f'LOD{lod}: 24 base/road bodies, {len(ids)} vertices; centre and side displacement checks passed')

def ranges(ids):
    result = []
    for i in ids:
        if result and result[-1][1] + 1 == i:
            result[-1][1] = i
        else:
            result.append([i, i])
    return result

lines = ['// Native PedestrianDrawBridge02 road-adjacent bases and road bodies.',
         '// Generated by PedestrianDraw02Bases.py; centre residues are explicitly assigned.',
         'using System;', 'using UnityEngine;', '', 'namespace BridgeBuilder.Bridges;', '',
         'internal static class PedestrianDraw02Bases', '{',
         '    internal static void Apply(int lod, Vector3[] source, Vector3[] positions, float delta)',
         '    {', '        var data = lod switch', '        {',
         '            0 => (Count: 40168, Left: Left0, Centre: Centre0, Right: Right0),',
         '            1 => (Count: 32137, Left: Left1, Centre: Centre1, Right: Right1),',
         '            _ => throw new ArgumentOutOfRangeException(nameof(lod))', '        };',
         '        if (!float.IsFinite(delta) || source.Length != data.Count || positions.Length != data.Count)',
         '            throw new InvalidOperationException("PedestrianDraw02 bases require their recorded main mesh.");',
         '        foreach (var range in data.Left)',
         '            for (var i = range.First; i <= range.Last; i++) positions[i].x = source[i].x - delta;',
         '        foreach (var range in data.Centre)',
         '            for (var i = range.First; i <= range.Last; i++) positions[i].x = source[i].x;',
         '        foreach (var range in data.Right)',
         '            for (var i = range.First; i <= range.Last; i++) positions[i].x = source[i].x + delta;',
         '    }', '',
         '']
for lod, (groups, digest) in enumerate(tables):
    lines.append('    // Geometry SHA-256: ' + digest)
    for side, name in ((-1, 'Left'), (0, 'Centre'), (1, 'Right')):
        lines += [f'    private static readonly (int First, int Last)[] {name}{lod} =', '    {']
        lines += [f'        ({a}, {b}),' for a, b in ranges(groups[side])]
        lines += ['    };', '']
lines += ['}', '']
output.write_text('\n'.join(lines), encoding='utf-8')
