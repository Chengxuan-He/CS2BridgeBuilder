"""Emit Draw03 first-strip central V braces at all three native LODs.
Usage: python Draw03ApproachBraces.py RESEARCH_DIRECTORY OUTPUT_CS
The complete brace includes both mirrored first-strip occurrences. Identification
is offline; runtime receives only measured vertex ranges and the native half-span.
"""
from pathlib import Path
import hashlib
import json
import sys
import numpy as np

r, output = map(Path, sys.argv[1:])
audit = json.loads((r/'all-movable-audit.json').read_text())
tables = []
for lod in range(3):
    name = 'DrawBridge03BottomFirst300cm'+(f'_LOD{lod}' if lod else '')+' Mesh.Geometry'
    digest = hashlib.sha256((r/'draw03-approach'/name).read_bytes()).hexdigest()
    assert any(a.get('sha256') == digest for a in audit['assets'].values())
    data = np.load(r/f'draw03-approach-0-{lod}.npz')
    vertices, faces = data['positions'], data['indices'].reshape(-1, 3)
    _, inverse = np.unique(vertices, axis=0, return_inverse=True)
    parent = np.arange(inverse.max()+1)

    def root(x):
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x

    for triangle in inverse[faces]:
        for other in triangle[1:]:
            parent[root(other)] = root(triangle[0])
    labels = np.array([root(i) for i in inverse])
    parts = []
    for label in np.unique(labels):
        ids = np.flatnonzero(labels == label)
        p = vertices[ids]
        # Measured central V profiles; excludes the connected end/longitudinal shell.
        if p[:, 0].min() == -1.5 and p[:, 1].min() == -5.617431640625:
            parts.append(ids)
    assert len(parts) == (32 if lod == 2 else 16)
    expected_size = (48, 32, 4)[lod]
    assert all(len(p) == expected_size for p in parts)
    stations = {}
    for ids in parts:
        z = float(vertices[ids, 2].mean())
        station = int(round((z+30)/4))
        assert 0 <= station < 16 and abs(z-(-30+station*4)) < .4
        stations.setdefault(station, []).append(ids)
    assert len(stations) == 16
    assert all(len(p) == (2 if lod == 2 else 1) for p in stations.values())
    ids = np.sort(np.concatenate(parts))
    half_span = (2.626800537109375, 2.626800537109375, 2.62939453125)[lod]
    assert vertices[ids, 0].max()+1.5 == half_span
    membership = np.isin(faces, ids)
    assert not np.any(membership.any(1) & ~membership.all(1))
    selected_faces = faces[membership.all(1)]
    for delta in (-8., -4., -2., -.24432373, -.1, 0., 2., 8.):
        # The first strip gains delta width; its positive-side origin moves delta/2.
        moved = vertices.astype(float).copy()
        moved[ids, 0] += ((vertices[ids, 0].astype(float)+1.5)/half_span-.5)*delta
        global_x = moved[ids, 0]+1.5+delta/2
        expected = (vertices[ids, 0].astype(float)+1.5)*(1+delta/half_span)
        assert np.allclose(global_x, expected, rtol=0, atol=1e-12)
        assert np.array_equal(moved[:, 1:], vertices[:, 1:])
        untouched = np.ones(len(vertices), bool); untouched[ids] = False
        assert np.array_equal(moved[untouched], vertices[untouched])
        p, q = vertices[selected_faces].astype(float), moved[selected_faces]
        before = np.cross(p[:, 1]-p[:, 0], p[:, 2]-p[:, 0])
        after = np.cross(q[:, 1]-q[:, 0], q[:, 2]-q[:, 0])
        valid = np.linalg.norm(before, axis=1) > 1e-8
        assert np.isfinite(moved).all()
        if delta >= -.1: assert np.all(np.sum(before[valid]*after[valid], axis=1) > 0)
    ranges = []
    for i in ids.tolist():
        if ranges and i == ranges[-1][1]+1: ranges[-1][1] = i
        else: ranges.append([i, i])
    tables.append((len(vertices), half_span, digest, ranges))
    np.savez(r/f'draw03-approach-braces-{lod}.npz', vertices=ids, faces=selected_faces)
    print(f'LOD{lod}: 16 braces, {len(ids)} vertices, {len(selected_faces)} unchanged triangles; eight-width placement and positive-span winding checks pass.')

def f(value): return format(float(np.float32(value)), '.9g')+'f'
lines = ['// DrawBridge03 central approach braces, game 1.6.2f1.',
         '// Generated by tools/GeometryMetaprogram/Draw03ApproachBraces.py.',
         'using System;', 'using UnityEngine;', '', 'namespace BridgeBuilder.Bridges;', '',
         'internal static class Draw03ApproachBraces', '{',
         '    // First-strip local coordinates. Layout must increase its width by delta,',
         '    // shifting the positive-side strip origin from 1.5 to 1.5 + delta / 2.',
         '    // The native inverted occurrence supplies the opposite half of each brace.',
         '    internal static void Apply(int lod, Vector3[] source, Vector3[] positions, float delta)',
         '    {', '        var data = lod switch', '        {']
for lod, (count, span, _, _) in enumerate(tables):
    lines.append(f'            {lod} => (Count: {count}, HalfSpan: {f(span)}, Ranges: Level{lod}),')
lines += ['            _ => throw new ArgumentOutOfRangeException(nameof(lod))', '        };',
          '        if (source.Length != data.Count || positions.Length != data.Count ||',
          '            !float.IsFinite(delta))',
          '            throw new InvalidOperationException("Draw03 approach braces require their measured first strip.");',
          '        foreach (var range in data.Ranges)',
          '            for (var i = range.First; i <= range.Last; i++)',
          '                positions[i].x = source[i].x + ((source[i].x + 1.5f) / data.HalfSpan - 0.5f) * delta;',
          '    }', '']
for lod, (_, _, digest, ranges) in enumerate(tables):
    lines += ['    // Geometry SHA-256: '+digest,
              f'    private static readonly (int First, int Last)[] Level{lod} =', '    {']
    lines += [f'        ({first}, {last}),' for first, last in ranges]
    lines += ['    };', '']
lines += ['}', '']
output.write_text('\n'.join(lines), encoding='utf-8')
