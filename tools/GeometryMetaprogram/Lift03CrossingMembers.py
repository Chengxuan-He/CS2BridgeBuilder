"""Emit measured Lift03 detailed continuous deck-support members, preserving native bones.
Usage: python Lift03CrossingMembers.py RESEARCH_DIRECTORY OUTPUT_CS
"""
from pathlib import Path
import hashlib,json,sys
import numpy as np
r,output=map(Path,sys.argv[1:]);rows=json.loads((r/'lift03-main-parts.json').read_text())
hashes=('f8bc2882fcba043d1d57a17fd27a43631b492ab4292f8fc6b9c3beeb00af53cd','455d25f8ec83f91ea097551fb09a9f41abc79e9f15e836b19c0a527ad50ff9fa')
lines=['// Measured LiftBridge03 continuous deck supports and end strips; generated by Lift03CrossingMembers.py.','using System;','using UnityEngine;','','namespace BridgeBuilder.Bridges;','','internal static class Lift03CrossingMembers','{','    internal static void Apply(int lod, Vector3[] source, Vector3[] positions, float upperDelta, float lowerDelta)','    {','        var data = lod switch','        {']
tables=[];near={}
for lod in range(2):
 row=next(x for x in rows if x['lod']==lod and x['mesh']==0)
 assert hashlib.sha256((r/'movable-skin'/(row['source']+'.Geometry')).read_bytes()).hexdigest()==hashes[lod]
 d=np.load(r/f'lift03-main-{lod}-0.npz');v,f,c=d['positions'],d['indices'],d['component']
 bones=[];bone=None;obj_vertices=[];obj_faces=[]
 for line in (r/'movable-skin'/(row['source']+'.mesh-0.obj')).read_text().splitlines():
  if line.startswith('g '):bone=line.split()[1]
  elif line.startswith('v '):obj_vertices.append(list(map(float,line.split()[1:4])))
  elif line.startswith('f '):
   bones.append(bone);obj_faces.append([int(x.split('/')[0])-1 for x in line.split()[1:]])
 assert len(bones)==len(f) and np.array_equal(v,obj_vertices) and np.array_equal(f,obj_faces)
 entries=[];selected=np.zeros(len(v),bool);weights=np.zeros(len(v));domains=np.full(len(v),-1)
 # U frames and arched end beams contain side arms. They require separate
 # authored-part maps and must not be scaled as whole connected components.
 for family,(half,domain,count) in enumerate(((9.429199,1,3),(5.140503,2,3),(5.0264893,2,6))):
  parts=[p for p in row['parts'] if p['minimum'][0]==-half and p['maximum'][0]==half]
  assert len(parts)==count
  for p in parts:
   ids=np.flatnonzero(c==p['id']);mask=c==p['id'];faces=mask[f].any(1)
   assert np.all(mask[f[faces]]) and faces.sum()==p['triangles']
   assert np.array_equal(v[ids].min(0),p['minimum']) and np.array_equal(v[ids].max(0),p['maximum'])
   bone_set=set(np.array(bones)[faces]);assert len(bone_set)==1 and 'mixed_bones' not in bone_set
   key=(family,round((p['minimum'][2]+p['maximum'][2])/2,2))
   if lod==0:
    assert key not in near
    near[key]=(p['minimum'],p['maximum'],bone_set)
   else:
    original=near[key]
    assert bone_set==original[2]
    assert p['minimum'][1]==original[0][1] and p['maximum'][1]==original[1][1]
    assert np.allclose(p['minimum'][2:],original[0][2:],atol=.002,rtol=0) and np.allclose(p['maximum'][2:],original[1][2:],atol=.002,rtol=0)
   assert not selected[ids].any();selected[ids]=True;weights[ids]=v[ids,0]/float(np.float32(half));domains[ids]=domain
   for i in ids:
    if entries and entries[-1][1]==i-1 and entries[-1][2:]==[half,domain]:entries[-1][1]=int(i)
    else:entries.append([int(i),int(i),half,domain])
 for deltas in ((0,0,0),(-.25,-.25,-.25),(2,2,2),(8,8,2),(8,2,8)):
  q=v.copy();q[selected,0]+=weights[selected]*np.array(deltas)[domains[selected]]
  assert np.array_equal(q[:,1:],v[:,1:]) and np.array_equal(q[~selected],v[~selected])
  sf=f[selected[f].all(1)];a,b=v[sf],q[sf];na=np.cross(a[:,1]-a[:,0],a[:,2]-a[:,0]);nb=np.cross(b[:,1]-b[:,0],b[:,2]-b[:,0]);valid=np.linalg.norm(na,axis=1)>1e-10
  assert np.all(np.sum(na[valid]*nb[valid],axis=1)>0)
 lines.append(f'            {lod} => (Count: {len(v)}, Parts: Level{lod}),');tables.append(entries)
 np.savez(r/f'lift03-crossing-members-{lod}.npz',selected=selected,weights=weights,domains=domains)
 print(f'PASS LOD{lod}: {selected.sum()} vertices; original bone ownership, LOD correspondence, winding and five width combinations')
lines+=['            _ => throw new ArgumentOutOfRangeException(nameof(lod))','        };','        if (source.Length != data.Count || positions.Length != data.Count || !float.IsFinite(upperDelta) || !float.IsFinite(lowerDelta))','            throw new InvalidOperationException("Lift03 crossing-members require their recorded topology.");','        foreach (var part in data.Parts)','            for (var i = part.First; i <= part.Last; i++)','                positions[i].x = source[i].x + source[i].x / part.HalfSpan * (part.Domain == 1 ? upperDelta : lowerDelta);','    }','']
for lod,entries in enumerate(tables):
 lines+=['    // Geometry SHA-256: '+hashes[lod],f'    private static readonly (int First, int Last, float HalfSpan, int Domain)[] Level{lod} =','    {']
 lines += [f'        ({a}, {b}, {float(np.float32(w)):.12g}f, {domain}),' for a,b,w,domain in entries]
 lines+=['    };','']
lines+=['}',''];output.write_text('\n'.join(lines),encoding='utf-8')
