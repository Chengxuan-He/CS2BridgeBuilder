"""Verify and emit the immutable Lift03 mesh-1 glass transform.
Usage: python Lift03Glass.py RESEARCH_DIRECTORY OUTPUT_CS
"""
from pathlib import Path
import hashlib
import sys
import numpy as np

research, output = map(Path, sys.argv[1:])
levels = []
for lod in range(2):
    name = 'LiftBridge03' + ('_LOD1' if lod else '') + ' Mesh'
    vertices, faces, bones = [], [], []
    bone = None
    for line in (research / 'movable-skin' / (name + '.mesh-1.obj')).read_text().splitlines():
        fields = line.split()
        if not fields:
            continue
        if fields[0] == 'v':
            vertices.append(list(map(float, fields[1:4])))
        elif fields[0] == 'g':
            bone = fields[1]
        elif fields[0] == 'f':
            faces.append([int(x.split('/')[0]) - 1 for x in fields[1:]])
            bones.append(bone)
    v, f = np.array(vertices), np.array(faces)
    assert v.shape == (1200, 3) and f.shape == (600, 3)
    assert set(bones) == {'bone_0'}
    signs = np.sign(v[:, 0]).astype(int)
    assert np.count_nonzero(signs == 1) == 600 and np.count_nonzero(signs == -1) == 600
    assert np.all(signs[f] == signs[f[:, :1]])
    # Compare all native pane triangles across detailed levels.
    if levels:
        canonical = lambda points: sorted(tuple(sorted(tuple(p) for p in tri)) for tri in points)
        assert canonical(v[f]) == canonical(levels[0][0][levels[0][1]])
    for delta in (-.5, 0, 2, 8):
        moved = v.copy()
        moved[:, 0] += signs * delta

        assert np.array_equal(moved[:, 1:], v[:, 1:])
        # Translation preserves every triangle edge, including winding and shape.
        for a, b in ((0, 1), (0, 2)):
            assert np.allclose(moved[f[:, a]] - moved[f[:, b]],
                               v[f[:, a]] - v[f[:, b]], atol=1e-12, rtol=0)
    digest = hashlib.sha256((research / 'movable-skin' / (name + '.Geometry')).read_bytes()).hexdigest()
    assert digest == (
        'f8bc2882fcba043d1d57a17fd27a43631b492ab4292f8fc6b9c3beeb00af53cd',
        '455d25f8ec83f91ea097551fb09a9f41abc79e9f15e836b19c0a527ad50ff9fa')[lod]
    expected = [-1]*300 + [1]*300 + [-1]*300 + [1]*300
    assert signs.tolist() == expected
    levels.append((v, f, digest))
    print(f'LOD{lod}: 300 glass quads, 1200 vertices, bone 0; rigid displacement verified')

code = """// Native LiftBridge03 mesh-1 glass, game 1.6.2f1.
// Generated by Lift03Glass.py; native LOD index ordering and fixed bone 0 remain unchanged.
using System;
using UnityEngine;

namespace BridgeBuilder.Bridges;

internal static class Lift03Glass
{
    private static readonly (int First, int Last, int Side)[] Sides =
    { (0, 299, -1), (300, 599, 1), (600, 899, -1), (900, 1199, 1) };
    internal static MovableStructureModel.Plan Create(int lod, Vector3[] source,
        int[] indices, float delta)
    {
        if ((lod != 0 && lod != 1) || source.Length != 1200 || indices.Length != 1800 || !float.IsFinite(delta))
            throw new InvalidOperationException("Lift03 glass requires its recorded mesh-1 layout.");
        var positions = (Vector3[])source.Clone();
        foreach (var range in Sides)
            for (var i = range.First; i <= range.Last; i++) positions[i].x += range.Side * delta;

        return new MovableStructureModel.Plan(source, positions,
            new[] { indices }, new[] { new bool[600] });
    }
}
"""
header = ''.join(f'// LOD{lod} Geometry SHA-256: {level[2]}\n' for lod, level in enumerate(levels))
output.write_text(header + code, encoding='utf-8')



