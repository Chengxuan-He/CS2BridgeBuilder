"""Emit measured Lift03 column-side translations, preserving the central web.
Usage: python Lift03Columns.py RESEARCH_DIRECTORY OUTPUT_CS
"""
from pathlib import Path
import hashlib,json,sys
import numpy as np
r,output=map(Path,sys.argv[1:])
audit=json.loads((r/'all-movable-audit.json').read_text())
lines=['// Native LiftBridge03 columns, game 1.6.2f1.', '// Generated by Lift03Columns.py; measured memberships, no runtime classification.', 'using System;', 'using UnityEngine;', '', 'namespace BridgeBuilder.Bridges;', '', 'internal static class Lift03ColumnGeometry', '{', '    internal static MovableStructureModel.Plan Create(int lod, Vector3[] source, int[] indices, float delta)', '    {', '        var data = lod switch', '        {']
pins = [('9b7bd06b4b0cb3fde25d376504d798e62447b4c42bac137290751866a1cc1976', 'd247658e1de7021d36eb4c208d0ef0d99ebb61afb12a32561606cc753df1b74e', '317bb4bae5bfe6cd186fcf67b7df4af521f9eb95aad31a584a432599d31c1f70'), ('910e1f71683f0ed479fde02b894498fd31c191ffb243819898295eaa3da8bc91', 'b4c70e43c0140446856342978c4af8fc8d9ffdf8e8e43812d110c95a1ce3f59e', '6b2c9404f96f130df8c84011b5bd22bd3e94a8f4484e2e87c62893a8d49b7cab'), ('c4f8c29fbda4a2a51f8ae3b6c6f6eec0befc6a99eb99a17420685d2a85dc2e34', '083b9e1c41bacd4f77175aa5d0b2de97cb551c8cad482b9d022958e5d269f3da', '7e5458c23eb0026479bf5ed672d4f3285a421c46c9164fc1c7734731b8e48cbd')]
levels=[]
for lod in range(3):
 name='LiftBridge03Pillar'+(f'_LOD{lod}' if lod else '')+' Mesh.Geometry'
 digest=hashlib.sha256((r/'movable-skin'/name).read_bytes()).hexdigest()
 assert digest == pins[lod][0]
 assert any(a.get('sha256')==digest for a in audit['assets'].values())
 d=np.load(r/f'lift03-support-0-{lod}.npz');v=d['positions'].astype(float);f=d['indices'];signs=np.where(np.abs(v[:,0]) < 1e-5, 0, np.sign(v[:,0])).astype(int)
 assert hashlib.sha256(v.astype('<f4').tobytes()).hexdigest() == pins[lod][1]
 assert hashlib.sha256(f.astype('<u4').tobytes()).hexdigest() == pins[lod][2]
 assert v.shape==((1816,1302,708)[lod],3) and f.shape==((1288,772,500)[lod],3)
 # Only the recorded near/middle transverse walls contain centre-seam vertices.
 assert np.count_nonzero(signs == 0) == (80 if lod < 2 else 0)
 crossing=np.ptp(signs[f],axis=1)>0
 assert int(crossing.sum()) == (80 if lod < 2 else 48)
 # Cross-centre faces are thin front/back walls, not longitudinal side columns.
 wall=v[f[crossing]]
 assert np.ptp(wall[:,:,2],axis=1).max() < .6
 z=np.abs(wall[:,:,2])
 assert np.all(((z>=70.2)&(z<=70.9))|((z>=112.1)&(z<=112.7)))
 assert np.all(np.abs(v[signs!=0,0]) >= 7.1646728515625)
 if lod==2: assert np.min(np.abs(v[:,0])) == 7.1646728515625
 same=np.all(signs[f]==signs[f[:,:1]],axis=1)
 for delta in (-1,0,2,8):
  moved=v.copy();moved[:,0]+=signs*delta
  p,q=v[f],moved[f];n=np.cross(p[:,1]-p[:,0],p[:,2]-p[:,0]);m=np.cross(q[:,1]-q[:,0],q[:,2]-q[:,0])
  assert np.array_equal(moved[:,1:],v[:,1:])
  assert np.allclose(q[same,1:]-q[same,:1],p[same,1:]-p[same,:1],atol=1e-12,rtol=0)
  active=np.linalg.norm(n,axis=1)>1e-9
  assert np.all(np.sum(n[active]*m[active],axis=1)>0)
 ranges=[]
 for i,s in enumerate(signs):
  if ranges and ranges[-1][1]==i-1 and ranges[-1][2]==s:ranges[-1][1]=i
  else:ranges.append([i,i,int(s)])
 levels.append((digest,ranges))
 lines.append(f'            {lod} => (Count: {len(v)}, Indices: {f.size}, Parts: Parts{lod}),')
 print(f'LOD{lod}: {len(v)} vertices / {len(f)} unchanged triangles; side shape and four-width winding passed')
lines+=['            _ => throw new ArgumentOutOfRangeException(nameof(lod))', '        };', '        if (!float.IsFinite(delta) || source.Length != data.Count || indices.Length != data.Indices)', '            throw new InvalidOperationException("Lift03 column requires its recorded layout.");', '        var positions = (Vector3[])source.Clone();', '        foreach (var part in data.Parts)', '            for (var i = part.First; i <= part.Last; i++) positions[i].x += part.Sign * delta;', '        return new MovableStructureModel.Plan(source, positions, new[] { indices }, new[] { new bool[indices.Length / 3] });', '    }', '']
for lod,(digest,ranges) in enumerate(levels):
 lines+=['    // Geometry SHA-256: '+digest,f'    private static readonly (int First, int Last, int Sign)[] Parts{lod} =', '    {']
 lines +=[f'        ({a}, {b}, {s}),' for a,b,s in ranges]
 lines+=['    };','']
lines+=['}',''];output.write_text('\n'.join(lines),encoding='utf-8')
