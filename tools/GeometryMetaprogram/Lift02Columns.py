"""Emit measured Lift02 column-side translations, preserving the central web.
Usage: python Lift02Columns.py RESEARCH_DIRECTORY OUTPUT_CS
"""
from pathlib import Path
import hashlib,json,sys
import numpy as np
r,output=map(Path,sys.argv[1:])
audit=json.loads((r/'all-movable-audit.json').read_text())
lines=['// Native LiftBridge02 columns, game 1.6.2f1.', '// Generated by Lift02Columns.py; measured memberships, no runtime classification.', 'using System;', 'using UnityEngine;', '', 'namespace BridgeBuilder.Bridges;', '', 'internal static class Lift02ColumnGeometry', '{', '    internal static MovableStructureModel.Plan Create(int lod, Vector3[] source, int[] indices, float delta)', '    {', '        var data = lod switch', '        {']
levels=[]
for lod in range(3):
 name='LiftBridge02Pillar'+(f'_LOD{lod}' if lod else '')+' Mesh.Geometry'
 digest=hashlib.sha256((r/'movable-skin'/name).read_bytes()).hexdigest()
 assert any(a.get('sha256')==digest for a in audit['assets'].values())
 d=np.load(r/f'lift02-support-0-{lod}.npz');v=d['positions'].astype(float);f=d['indices'];signs=np.sign(v[:,0]).astype(int)
 assert v.shape==((298,296,303)[lod],3) and f.shape==((264,237,150)[lod],3)
 assert np.all(abs(v[:,0])>= (2.60003662109375 if lod<2 else 2.4110107421875))
 same=np.all(signs[f]==signs[f[:,:1]],axis=1)
 for delta in (-4.99,-4,-3,-1,0,2,8):
  moved=v.copy();moved[:,0]+=signs*delta
  p,q=v[f],moved[f];n=np.cross(p[:,1]-p[:,0],p[:,2]-p[:,0]);m=np.cross(q[:,1]-q[:,0],q[:,2]-q[:,0])
  assert np.array_equal(moved[:,1:],v[:,1:])
  assert np.allclose(q[same,1:]-q[same,:1],p[same,1:]-p[same,:1],atol=1e-12,rtol=0)
  active=np.linalg.norm(n,axis=1)>1e-9
  assert np.isfinite(moved).all()
  if delta >= -1: assert np.all(np.sum(n[active]*m[active],axis=1)>0)
  else: print(f"Column LOD{lod} delta={delta}: {np.count_nonzero(np.sum(n[active]*m[active],axis=1)<=0)} collapsed/reversed faces")
 ranges=[]
 for i,s in enumerate(signs):
  if ranges and ranges[-1][1]==i-1 and ranges[-1][2]==s:ranges[-1][1]=i
  else:ranges.append([i,i,int(s)])
 levels.append((digest,ranges))
 lines.append(f'            {lod} => (Count: {len(v)}, Indices: {f.size}, Parts: Parts{lod}),')
 print(f'LOD{lod}: {len(v)} vertices / {len(f)} unchanged triangles; side shape and seven-width signed mapping passed')
lines+=['            _ => throw new ArgumentOutOfRangeException(nameof(lod))', '        };', '        if (!float.IsFinite(delta) || source.Length != data.Count || indices.Length != data.Indices)', '            throw new InvalidOperationException("Lift02 column requires its recorded layout.");', '        var positions = (Vector3[])source.Clone();', '        foreach (var part in data.Parts)', '            for (var i = part.First; i <= part.Last; i++) positions[i].x += part.Sign * delta;', '        return new MovableStructureModel.Plan(source, positions, new[] { indices }, new[] { new bool[indices.Length / 3] });', '    }', '']
for lod,(digest,ranges) in enumerate(levels):
 lines+=['    // Geometry SHA-256: '+digest,f'    private static readonly (int First, int Last, int Sign)[] Parts{lod} =', '    {']
 lines +=[f'        ({a}, {b}, {s}),' for a,b,s in ranges]
 lines+=['    };','']
lines+=['}',''];output.write_text('\n'.join(lines),encoding='utf-8')
