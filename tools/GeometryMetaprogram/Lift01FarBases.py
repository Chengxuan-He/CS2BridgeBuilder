"""Emit Lift01 far fixed/moving road-base displacement from measured membership.
Usage: python Lift01FarBases.py RESEARCH_DIRECTORY OUTPUT_CS
Corresponds to the detailed road shells handled by Lift01Bases.
"""
from pathlib import Path
import hashlib
import json
import sys
import numpy as np

r, output = map(Path, sys.argv[1:])
d = np.load(r / 'lift01-main-2.npz')
v, faces = d['positions'], d['indices']
groups = json.loads((r / 'lift01-far-fixed-parts.json').read_text())
assert v.shape == (1110, 3) and faces.shape == (776, 3)
owners, ordered, bone = {}, [], None
for line in (r / 'movable-skin/LiftBridge01_LOD2 Mesh.mesh-0.obj').read_text().splitlines():
    fields = line.split()
    if not fields:
        continue
    if fields[0] == 'g':
        bone = int(fields[1].removeprefix('bone_'))
    elif fields[0] == 'f':
        ids = [int(x.split('/')[0]) - 1 for x in fields[1:]]
        assert np.array_equal(faces[len(ordered)], ids)
        ordered.append(bone)
        for i in ids:
            assert i not in owners or owners[i] == bone
            owners[i] = bone
assert len(ordered) == len(faces)
fixed = [i for k in (8, 20) for i in groups[k]['vertices']]
moving = [i for i, bone in owners.items() if bone == 4]
assert len(fixed) == 96 and len(moving) == 80
assert all(owners[i] == 0 for i in fixed)
assert not set(fixed).intersection(moving)
ids = sorted(fixed + moving)
weights = {i: int(np.sign(v[i, 0])) for i in ids}
assert all(abs(w) == 1 for w in weights.values())
assert set(v[ids, 0]) == {
    -4.0416259765625, -3.28533935546875, -3.245361328125,
    3.245361328125, 3.28533935546875, 4.0416259765625,
}
member = np.isin(faces, ids)
assert not np.any(member.any(1) & ~member.all(1))
subset = faces[member.all(1)]
assert len(subset) == 100
p = v[subset].astype(float)
normal = np.cross(p[:, 1] - p[:, 0], p[:, 2] - p[:, 0])
for delta in (-2.99, -2.75, -2., -.5, 0., 2., 8.):
    moved = v.astype(float).copy()
    for i, w in weights.items():
        moved[i, 0] += w * delta
    assert np.array_equal(moved[:, 1:], v[:, 1:])
    untouched = sorted(set(range(len(v))) - set(ids))
    assert np.array_equal(moved[untouched], v[untouched])
    q = moved[subset]
    after = np.cross(q[:, 1] - q[:, 0], q[:, 2] - q[:, 0])
    assert np.all((normal * after).sum(1) > 0)
    for part in (fixed[:48], fixed[48:], moving):
        before_width = float(np.ptp(v[part, 0]))
        assert np.isclose(np.ptp(moved[part, 0]), before_width + 2 * delta, rtol=0, atol=1e-12)
        for side in (-1, 1):
            side_ids = [i for i in part if weights[i] == side]
            assert np.allclose(moved[side_ids] - v[side_ids], [side * delta, 0, 0], rtol=0, atol=1e-12)
ranges = []
for i, w in sorted(weights.items()):
    if ranges and ranges[-1][1] + 1 == i and ranges[-1][2] == w:
        ranges[-1][1] = i
    else:
        ranges.append([i, i, w])
digest = hashlib.sha256((r / 'movable-skin/LiftBridge01_LOD2 Mesh.Geometry').read_bytes()).hexdigest()
lines = ['// Native LiftBridge01_LOD2 fixed and moving road-adjacent bases.',
         '// Geometry SHA-256: ' + digest,
         '// Generated by Lift01FarBases.py; original bones 0 and 4 remain unchanged.',
         'using System;', 'using UnityEngine;', '', 'namespace BridgeBuilder.Bridges;', '',
         'internal static class Lift01FarBases', '{',
         '    internal static void Apply(Vector3[] source, Vector3[] positions, float delta)', '    {',
         '        if (source.Length != 1110 || positions.Length != 1110 || !float.IsFinite(delta))',
         '            throw new InvalidOperationException("Lift01 far bases require their measured layout.");',
         '        foreach (var part in Parts)',
         '            for (var i = part.First; i <= part.Last; i++) positions[i].x = source[i].x + part.Direction * delta;',
         '    }', '', '    private static readonly (int First, int Last, int Direction)[] Parts =', '    {']
lines += [f'        ({a}, {b}, {w}),' for a, b, w in ranges]
lines += ['    };', '}']
output.write_text('\n'.join(lines) + '\n', encoding='utf-8')
print(f'176 road-base vertices / 100 faces / {len(ranges)} ranges; bone ownership and seven widths verified.')
