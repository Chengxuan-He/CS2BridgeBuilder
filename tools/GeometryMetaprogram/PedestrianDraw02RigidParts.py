"""Emit measured side-part vertex ranges for both PedestrianDraw02 main LODs.
Usage: python PedestrianDraw02RigidParts.py RESEARCH_DIRECTORY OUTPUT_CS
Connected-part identification and LOD correspondence are offline only. Crossing
members, including joined road/base shells, require separate deformation plans.
"""
from pathlib import Path
import hashlib
import sys
import numpy as np

r, output = map(Path, sys.argv[1:])
levels = []
for lod in range(2):
    data = np.load(r / f'pedestrian02-main-{lod}.npz')
    v, faces = data['positions'], data['indices']
    assert (len(v), len(faces)) == ((40168, 30064), (32137, 18025))[lod]
    parent = list(range(len(v)))
    def root(i):
        while parent[i] != i:
            parent[i] = parent[parent[i]]
            i = parent[i]
        return i
    def join(a, b):
        parent[root(int(a))] = root(int(b))
    for a, b, c in faces:
        join(a, b)
        join(a, c)
    seen = {}
    for i, p in enumerate(v):
        key = tuple(p.round(4))
        if key in seen:
            join(i, seen[key])
        else:
            seen[key] = i
    groups = {}
    for i in range(len(v)):
        groups.setdefault(root(i), []).append(i)
    sides = []
    signs = np.zeros(len(v), dtype=np.int8)
    for ids in groups.values():
        p = v[ids]
        lo, hi = p.min(0), p.max(0)
        if lo[0] <= 0 <= hi[0]:
            continue
        sign = -1 if hi[0] < 0 else 1
        signs[ids] = sign
        sides.append((ids, lo, hi, sign))
    assert len(sides) == (534, 550)[lod]
    assert np.count_nonzero(signs) == (25488, 19155)[lod]
    levels.append((v, sides, signs))

# LOD1 merges some rail segments and omits details, so group counts differ.
# Every surviving side vertex lies inside at least one LOD0 authored side part
# on the SAME side, with no tolerance expansion. Do not remap crossing parts.
near = levels[0][1]
for side in (-1, 1):
    lo = np.array([p[1] for p in near if p[3] == side])
    hi = np.array([p[2] for p in near if p[3] == side])
    v, _, signs = levels[1]
    points = v[signs == side]
    for start in range(0, len(points), 512):
        q = points[start:start+512, None, :]
        assert np.all(np.any(np.all((q >= lo) & (q <= hi), axis=2), axis=1))

def ranges(ids):
    result = []
    for i in ids:
        i = int(i)
        if result and result[-1][1] + 1 == i:
            result[-1][1] = i
        else:
            result.append([i, i])
    return result

lines = ['// Native PedestrianDrawBridge02 mesh-0 authored side parts, game 1.6.2f1.',
         '// Generated by PedestrianDraw02RigidParts.py; no runtime spatial classification.',
         'using System;', 'using UnityEngine;', '', 'namespace BridgeBuilder.Bridges;', '',
         'internal static class PedestrianDraw02RigidParts', '{',
         '    internal static void Apply(int lod, Vector3[] source, Vector3[] positions, float delta)',
         '    {', '        var data = lod switch', '        {',
         '            0 => (Count: 40168, Left: Left0, Right: Right0),',
         '            1 => (Count: 32137, Left: Left1, Right: Right1),',
         '            _ => throw new ArgumentOutOfRangeException(nameof(lod))', '        };',
         '        if (!float.IsFinite(delta) || source.Length != data.Count || positions.Length != data.Count)',
         '            throw new InvalidOperationException("PedestrianDraw02 rigid parts require their recorded main mesh.");',
         '        foreach (var range in data.Left)',
         '            for (var i = range.First; i <= range.Last; i++) positions[i].x = source[i].x - delta;',
         '        foreach (var range in data.Right)',
         '            for (var i = range.First; i <= range.Last; i++) positions[i].x = source[i].x + delta;',
         '    }', '']
for lod, (v, parts, signs) in enumerate(levels):
    name = 'PedestrianDrawBridge02' + ('_LOD1' if lod else '') + ' Mesh.Geometry'
    lines += ['    // Geometry SHA-256: ' + hashlib.sha256((r / 'movable-skin' / name).read_bytes()).hexdigest()]
    for side, label in ((-1, 'Left'), (1, 'Right')):
        ids = np.flatnonzero(signs == side)
        intervals = ranges(ids)
        assert [i for a, b in intervals for i in range(a, b + 1)] == ids.tolist()
        lines += [f'    private static readonly (int First, int Last)[] {label}{lod} =', '    {']
        lines += [f'        ({a}, {b}),' for a, b in intervals]
        lines += ['    };', '']
    for delta in (-.5, 0., 2., 8.):
        moved = v.copy()
        moved[:, 0] += signs * delta
        assert np.array_equal(moved[:, 1:], v[:, 1:])
        assert np.array_equal(moved[signs == 0], v[signs == 0])
        for ids, lo, hi, side in parts:
            assert np.allclose(moved[ids] - v[ids], [side * delta, 0, 0], atol=2e-6)
    print(f'LOD{lod}: {len(parts)} side parts / {np.count_nonzero(signs)} vertices; '
          'rigid displacement and untouched crossing vertices passed at four widths')
lines += ['}', '']
output.write_text('\n'.join(lines), encoding='utf-8')
print('All 19155 LOD1 side vertices have same-side LOD0 part-envelope coverage.')
