"""Emit Draw03 motion seams from its original near road faces, never from bone bounds.
Usage: python Draw03RoadPartitions.py RESEARCH_DIRECTORY OUTPUT_CS
"""
from pathlib import Path
import hashlib
import sys
import numpy as np

research, output = map(Path, sys.argv[1:])
geometry = research / 'movable-skin/DrawBridge03 Mesh.Geometry'
digest = hashlib.sha256(geometry.read_bytes()).hexdigest()
assert digest == 'f7ecc824ad55745e791e40b18fd12f5def20657ed8ea56d373429d5a1337588f'
vertices, faces, bones = [], [], []
bone = None
for line in geometry.with_suffix('.mesh-0.obj').read_text().splitlines():
    fields = line.split()
    if not fields:
        continue
    if fields[0] == 'v':
        vertices.append(list(map(float, fields[1:4])))
    elif fields[0] == 'g':
        bone = int(fields[1].split('_')[1])
    elif fields[0] == 'f':
        faces.append([int(item.split('/')[0]) - 1 for item in fields[1:]])
        bones.append(bone)
v = np.asarray(vertices, dtype=np.float32).astype(float)
f, bones = np.asarray(faces), np.asarray(bones)
assert v.shape == (186078, 3) and f.shape == (127148, 3)
p = v[f]
normal = np.cross(p[:, 1] - p[:, 0], p[:, 2] - p[:, 0])

# These reviewed top faces belong to the same authored road strips at both ends.
# Horizontal exterior platforms are intentionally irrelevant to the motion boundary.
def tops(height, bone):
    ids = np.flatnonzero((np.max(abs(p[:, :, 1] - height), axis=1) == 0)
                        & (normal[:, 1] > 0) & (bones == bone))
    return p[ids]

seams = []
for height, centre, expected_count in ((10., .02740478515625, 40),
                                      (10.199951171875, .02741241455078125, 40)):
    positive, negative = tops(height, 1), tops(height, 2)
    assert len(positive) == len(negative) == expected_count
    assert positive[:, :, 2].min() == centre
    assert negative[:, :, 2].max() == -centre
    assert positive[:, :, 2].max() == -negative[:, :, 2].min() == 80.015625
    fixed = tops(height, 0)
    assert np.abs(fixed[:, :, 2]).min() == 80.041015625
    seams.append(centre)

# The existing three-LOD skeleton uses array index 1/connection 101 for positive Z,
# index 2/connection 100 for negative Z; index 0 remains fixed.
text = '''using UnityEngine;
using Partition = BridgeBuilder.Bridges.MovableRoadGeometry.Partition;

namespace BridgeBuilder.Bridges;

// Generated by Draw03RoadPartitions.py from the original near road surfaces.
// Geometry SHA-256: @HASH@
// Physical seams are shared by every generated LOD; native bones are unchanged.
internal static class Draw03RoadPartitions
{
    private const float FixedStart = 80.041015625f;
    private const float LeafEnd = 80.015625f;
    internal static readonly Partition Carriageway = Create(@ROAD@f);
    internal static readonly Partition Sidewalk = Create(@WALK@f);

    private static Partition Create(float centreHalfGap)
    {
        var fixedRoad = new Partition(0);
        return Cut(-FixedStart, fixedRoad,
            Cut(-LeafEnd, Partition.Gap,
                Cut(-centreHalfGap, new Partition(2),
                    Cut(centreHalfGap, Partition.Gap,
                        Cut(LeafEnd, new Partition(1),
                            Cut(FixedStart, Partition.Gap, fixedRoad))))));
    }

    private static Partition Cut(float seam, Partition negative, Partition positive)
    {
        var frame = Matrix4x4.identity;
        frame.m23 = -seam;
        return new Partition(frame, negative, positive);
    }
}
'''
output.write_text(text.replace('@HASH@', digest).replace('@ROAD@', str(seams[0]))
                  .replace('@WALK@', str(seams[1])), encoding='utf-8')
print('Verified native road/sidewalk seams, 40 faces per leaf per domain; emitted original-bone partitions.')
