"""Record complete Draw03 moving and fixed under-deck truss assemblies; no runtime classification.
Usage: python Draw03Truss.py RESEARCH_DIRECTORY OUTPUT_CS
"""
from pathlib import Path
import hashlib, json, sys
import numpy as np
r, output = map(Path, sys.argv[1:])
tables = []
for lod in range(2):
    data = np.load(r/f'draw03-main-{lod}.npz')
    v, faces = data['positions'], data['indices']
    name = 'DrawBridge03'+('_LOD1' if lod else '')+' Mesh.Geometry'
    digest = hashlib.sha256((r/'movable-skin'/name).read_bytes()).hexdigest()
    assert digest == ('f7ecc824ad55745e791e40b18fd12f5def20657ed8ea56d373429d5a1337588f',
                      '15b8419da13d6e99e1dc0591f12f4019f0be09c3b220a481d24720daf7b57e12')[lod]
    parts = json.loads((r/f'draw03-parts-{lod}.json').read_text())
    # Offline measured five longitudinal frames, diagonal members and their connectors.
    # Excludes road/base plates, perimeter rails, masonry housings and full-width axle.
    selected = [p for p in parts if p['bone'] in (1,2)
                and p['minimum'][0] >= -12.5 and p['maximum'][0] <= 12.5
                and p['minimum'][1] >= .4751129150390625 and p['maximum'][1] <= 7.6292724609375]
    assert len(selected) == 1498
    # Bone-zero end trusses are inside the mechanism asset, not the approach pieces.
    # Explicit component ranges identified from both native inventories: bearing
    # brackets, longitudinal end beams, transverse braces and centre connectors.
    fixed_ranges = (((707,722),(1481,1510),(2178,2193),(2950,2979)),
                    ((747,762),(1521,1550),(2266,2281),(3038,3067)))[lod]
    fixed = [parts[i] for a,b in fixed_ranges for i in range(a,b+1)]
    assert len(fixed) == 92 and all(p['bone'] == 0 for p in fixed)
    assert sum(len(p['vertices']) for p in fixed) == (4680,4239)[lod]
    selected += fixed
    ids = sorted(i for p in selected for i in p['vertices'])
    assert len(ids) == len(set(ids)) == (68192,59247)[lod]
    mask = np.isin(faces,ids)
    assert not np.any(mask.any(1) & ~mask.all(1))
    assert set(data['bones'][mask.all(1)]) == {0,1,2}
    for delta in (-8.,-4.,0.,2.,8.):
        moved=v.copy(); moved[ids,0] += v[ids,0]/12.5*delta
        assert np.array_equal(moved[:,1:],v[:,1:])
        assert np.allclose(moved[ids,0],v[ids,0]*(1+delta/12.5),atol=3e-6)
        for p in selected:
            a=np.array(p['vertices']); before=v[a,0]; after=moved[a,0]
            assert np.isclose(np.ptp(after),np.ptp(before)*(1+delta/12.5),atol=4e-6)
        f=faces[mask.all(1)]; a=v[f].astype(float); b=moved[f].astype(float)
        n=np.cross(a[:,1]-a[:,0],a[:,2]-a[:,0]); m=np.cross(b[:,1]-b[:,0],b[:,2]-b[:,0])
        valid=np.linalg.norm(n,axis=1)>1e-8
        assert np.all(np.sum(n[valid]*m[valid],axis=1)>0)
    ranges=[]
    for i in ids:
        if ranges and ranges[-1][1]+1==i:ranges[-1][1]=i
        else:ranges.append([i,i])
    tables.append((len(v),ranges,digest))
    print(f'PASS LOD{lod}: {len(selected)} complete truss components, {len(ids)} vertices; common scale, bones, winding and Y/Z.')
lines=['// Generated by Draw03Truss.py. Moving and bone-zero fixed trusses use the shared deck span.',
       'using System;','using UnityEngine;','namespace BridgeBuilder.Bridges;',
       'internal static class Draw03Truss {',
       'internal static void Apply(int lod, Vector3[] source, Vector3[] positions, float delta) {',
       'var data = lod switch {']
for lod,(count,_,_) in enumerate(tables):lines.append(f'{lod} => (Count: {count}, Ranges: Level{lod}),')
lines += ['_ => throw new ArgumentOutOfRangeException(nameof(lod)) };',
          'if(source.Length != data.Count || positions.Length != data.Count || !float.IsFinite(delta)) throw new InvalidOperationException("Draw03 truss requires its measured mesh.");',
          'foreach(var range in data.Ranges) AffineGeometry.For(range.First, range.Last + 1, i => positions[i].x = AffineGeometry.AddScaled(source[i].x, source[i].x / 12.5f, delta));',
          '}', 'internal static float Scale(float delta) => 1f + delta / 12.5f;',
          'internal static bool IsApproachStructure(int family) => family < 4;']
for lod,(_,ranges,digest) in enumerate(tables):
    lines += ['// SHA256: '+digest,f'private static readonly (int First,int Last)[] Level{lod} = {{']
    lines += [f'({a},{b}),' for a,b in ranges]; lines += ['};']
lines += ['}']
output.write_text('\n'.join(lines)+'\n',encoding='utf-8')
