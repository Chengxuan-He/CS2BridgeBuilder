"""Emit measured Draw02 road-top triangle records, without runtime spatial inference.
Usage: python Draw02RoadTops.py RESEARCH_DIRECTORY OUTPUT_CS
Road side closures and structural widening are separate plans, not inferred here.
"""
from pathlib import Path
import hashlib
import json
import sys
import numpy as np

research, output = map(Path, sys.argv[1:])
candidates = json.loads((research / 'draw02-road-plane-candidates.json').read_text())
# Audited planes: near/middle carriageway and sidewalk; far authored flattened proxies.
planes = ((9.800049, 10.0), (9.800049, 10.0), (10.52832, 10.005615))
expected = ((44370, 24664, 1696), (31007, 14766, 1521), (893, 548, 44))
records = []
platforms = []
for lod in range(3):
    data = np.load(research / f'draw02-main-lod{lod}-uv.npz')
    positions = data['positions'].astype(np.float32)
    triangles = data['indices'].reshape(-1, 3)
    faces = sorted(face for c in candidates[lod]['candidates'] if c['y'] in planes[lod]
                   for face in c['triangle_ordinals'])
    assert (len(positions), len(triangles), len(faces)) == expected[lod]
    assert len(set(faces)) == len(faces)
    points = positions[triangles[faces]]
    normals = np.cross(points[:, 1] - points[:, 0], points[:, 2] - points[:, 0])
    assert np.all(normals[:, 1] > 0), 'Only upward road tops may be removed'
    assert np.all(np.ptp(points[:, :, 1], axis=1) == 0)
    # Fixed service platforms lie OUTSIDE the measured 19 m road corridor.
    # Their tops share the sidewalk's Y plane, but are not selected-road surfaces.
    # Near/middle have separate faces; the far proxy welds road and platform tops.
    # Clip those far faces offline and emit their native-attribute construction data.
    preserved, edges, fragments, weights = [], [], [], []
    lookup = {}
    def edge_vertex(a, b, fraction, side):
        if a > b:
            a, b, fraction = b, a, 1 - fraction
        fraction = float(np.float32(fraction))
        key = (a, b, fraction)
        if key not in lookup:
            lookup[key] = len(edges)
            edges.append(key)
            weights.append(side)
        return len(positions) + lookup[key]
    for face in faces:
        tri = triangles[face]
        p = positions[tri]
        if not (p[:, 2].min() > 69 or p[:, 2].max() < -69):
            continue
        if p[:, 0].min() >= 9.5 or p[:, 0].max() <= -9.5:
            preserved.append(face)
            continue
        for side in (-1, 1):
            distance = side * p[:, 0] - np.float32(9.5)
            if distance.max() <= 0:
                continue
            assert lod == 2, ('Unexpected merged near platform', lod, face)
            polygon = []
            for corner in range(3):
                next_corner = (corner + 1) % 3
                a, b = int(tri[corner]), int(tri[next_corner])
                da, db = float(distance[corner]), float(distance[next_corner])
                if da >= 0:
                    polygon.append(a)
                if da < 0 < db or db < 0 < da:
                    polygon.append(edge_vertex(a, b, da / (da - db), side))
            indices = [i for j in range(1, len(polygon) - 1)
                       for i in (polygon[0], polygon[j], polygon[j+1])]
            assert indices
            fragments.append((face, indices))
    assert len(preserved) == (48, 40, 8)[lod]
    assert len(fragments) == (0, 0, 12)[lod]
    faces = [face for face in faces if face not in set(preserved)]
    name = 'DrawBridge02' + (f'_LOD{lod}' if lod else '') + ' Mesh.Geometry'
    digest = hashlib.sha256((research / 'movable-skin' / name).read_bytes()).hexdigest()
    records.append((faces, triangles, digest))
    platforms.append((preserved, edges, fragments, weights))

lines = ['// Measured DrawBridge02 road tops, game 1.6.2f1.',
         '// Generated by tools/GeometryMetaprogram/Draw02RoadTops.py.',
         'using System;', 'using System.Collections.Generic;', 'using UnityEngine;', '', 'namespace BridgeBuilder.Bridges;', '',
         'internal static class Draw02RoadTops', '{',
         '    internal static MovableStructureModel.Plan Remove(int lod, MovableStructureModel.Plan structure, float delta)',
         '    {', '        var data = lod switch', '        {']
for lod, (vertices, faces, _) in enumerate(expected):
    lines += [f'            {lod} => (Vertices: {vertices}, Faces: {faces}, Records: Lod{lod}, Edges: Edges{lod}, Fragments: Fragments{lod}, Weights: Weights{lod}),']
lines += ['            _ => throw new ArgumentOutOfRangeException(nameof(lod))', '        };',
          '        if (structure.SourcePositions.Length != data.Vertices || structure.SourceIndices.Length != 1 ||',
          '            structure.SourceIndices[0].Length != data.Faces * 3 || structure.RemoveTriangles.Length != 1 ||',
          '            structure.RemoveTriangles[0].Length != data.Faces)',
          '            throw new InvalidOperationException("Draw02 road-top removal requires its recorded main mesh.");',
          '        var mask = (bool[])structure.RemoveTriangles[0].Clone();',
          '        var top = new bool[data.Faces];',
          '        for (var i = 0; i < data.Records.Length; i += 4)',
          '        {', '            var face = data.Records[i];',
          '            for (var corner = 0; corner < 3; corner++)',
          '                if (structure.SourceIndices[0][face * 3 + corner] != data.Records[i + 1 + corner])',
          '                    throw new InvalidOperationException("Draw02 recorded road-top topology changed.");',
          '            mask[face] = top[face] = true;', '        }',
          '        foreach (var fragment in structure.Fragments)',
          '            if (fragment.Slot == 0 && top[fragment.Triangle])',
          '                throw new InvalidOperationException("Draw02 structural fragment restores a removed road top.");',
          '        // Recorded Draw02 shell fragments use edge vertices only. Appending edges',
          '        // therefore leaves every existing fragment index unchanged.',
          '        if (structure.InteriorVertices.Length != 0)',
          '            throw new InvalidOperationException("Draw02 platform construction requires its recorded edge-only shell plan.");',
          '        var edges = new MovableStructureModel.EdgeVertex[structure.AddedVertices.Length + data.Edges.Length];',
          '        Array.Copy(structure.AddedVertices, edges, structure.AddedVertices.Length);',
          '        Array.Copy(data.Edges, 0, edges, structure.AddedVertices.Length, data.Edges.Length);',
          '        var fragments = new List<MovableStructureModel.Fragment>(structure.Fragments);',
          '        foreach (var fragment in data.Fragments)',
          '        {',
          '            var indices = (int[])fragment.Indices.Clone();',
          '            for (var i = 0; i < indices.Length; i++)',
          '                if (indices[i] >= data.Vertices) indices[i] += structure.AddedVertices.Length;',
          '            fragments.Add(new MovableStructureModel.Fragment(0, fragment.Triangle, indices));',
          '        }',
          '        var originalPositions = new Vector3[data.Vertices];',
          '        Array.Copy(structure.Positions, originalPositions, originalPositions.Length);',
          '        var constructedX = new float[edges.Length];',
          '        for (var i = 0; i < structure.ConstructedCount; i++) constructedX[i] = structure.Positions[data.Vertices + i].x;',
          '        // Measured platform/road boundary: +/-9.5 m. It follows the same rigid',
          '        // displacement as the exterior platform, not interpolation from x=0.',
          '        for (var i = 0; i < data.Edges.Length; i++)',
          '            constructedX[structure.ConstructedCount + i] = data.Weights[i] * (9.5f + delta);',
          '        return new MovableStructureModel.Plan(structure.SourcePositions, originalPositions, structure.SourceIndices,',
          '            new[] { mask }, edges, fragments.ToArray(), constructedX: constructedX);',
          '    }', '']
for lod, (faces, triangles, digest) in enumerate(records):
    lines += ['    // Geometry SHA-256: ' + digest, f'    private static readonly int[] Lod{lod} =', '    {']
    for i in range(0, len(faces), 4):
        values = [value for face in faces[i:i+4] for value in (face, *triangles[face])]
        lines += ['        ' + ', '.join(map(str, values)) + ',']
    lines += ['    };', '']
    preserved, edges, fragments, weights = platforms[lod]
    lines += [f'    private static readonly MovableStructureModel.EdgeVertex[] Edges{lod} =', '    {']
    for a, b, fraction in edges:
        lines += [f'        new({a}, {b}, {fraction:.17g}f),']
    lines += ['    };', f'    private static readonly int[] Weights{lod} = {{ ' + ', '.join(map(str, weights)) + ' };',
              f'    private static readonly MovableStructureModel.Fragment[] Fragments{lod} =', '    {']
    for face, indices in fragments:
        lines += [f'        new(0, {face}, ' + ', '.join(map(str, indices)) + '),']
    lines += ['    };', '']
    print(f'LOD{lod}: {len(faces)} replaced tops; retained {len(preserved)} exterior platform faces and {sum(len(ids)//3 for _,ids in fragments)} platform fragments')
lines += ['}', '']
output.write_text('\n'.join(lines), encoding='utf-8')
