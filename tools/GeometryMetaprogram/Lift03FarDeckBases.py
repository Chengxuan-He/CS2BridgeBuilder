"""Emit Lift03 middle deck-base faces for the far supplement; preserves native skinning.
Usage: python Lift03FarDeckBases.py RESEARCH_DIRECTORY OUTPUT_CS
"""
from pathlib import Path
import sys, hashlib
import numpy as np
r,out=map(Path,sys.argv[1:])
sha='455d25f8ec83f91ea097551fb09a9f41abc79e9f15e836b19c0a527ad50ff9fa'
assert hashlib.sha256((r/'movable-skin/LiftBridge03_LOD1 Mesh.Geometry').read_bytes()).hexdigest()==sha
d=np.load(r/'lift03-main-1-0.npz');v,f,c=d['positions'],d['indices'],d['component']
parts=(65,66,778,779,2826,2827)
faces=np.flatnonzero(np.isin(c[f],parts).all(1))
assert len(faces)==1868
assert np.all(c[f[faces]]==c[f[faces]][:,0,None])
lines=['// Measured middle-source road bases for Lift03 far LOD; generated by Lift03FarDeckBases.py.',
 '// Geometry SHA-256: '+sha,'using System;','','namespace BridgeBuilder.Bridges;','',
 'internal static class Lift03FarDeckBases','{',
 '    internal static void Include(int[] indices, bool[] removed)','    {',
 '        if (indices.Length != 229516 * 3 || removed.Length != 229516)',
 '            throw new InvalidOperationException("Lift03 far deck supplement requires its recorded middle layout.");',
 '        foreach (var face in Faces)','        {','            var offset = face.Triangle * 3;',
 '            if (indices[offset] != face.A || indices[offset + 1] != face.B || indices[offset + 2] != face.C)',
 '                throw new InvalidOperationException("Lift03 far deck supplement topology changed.");',
 '            removed[face.Triangle] = false;','        }',
 '        Lift03RoadTops.RemoveDetailed(1, indices, removed);','    }',
 '    private static readonly (int Triangle, int A, int B, int C)[] Faces =','    {']
lines += [f'        ({i}, {f[i,0]}, {f[i,1]}, {f[i,2]}),' for i in faces]
lines += ['    };','}',''];out.write_text('\n'.join(lines),encoding='utf-8')
for ud,ld in ((0,0),(2,2),(8,2),(2,8),(-.25,-.25)):
 q=v.copy();sel=np.isin(c,parts);upper=np.isin(c,(65,778,2826));q[sel,0]+=np.sign(v[sel,0])*np.where(upper[sel],ud,ld)
 a,b=v[f[faces]],q[f[faces]];na=np.cross(a[:,1]-a[:,0],a[:,2]-a[:,0]);nb=np.cross(b[:,1]-b[:,0],b[:,2]-b[:,0]);valid=np.linalg.norm(na,axis=1)>1e-10
 assert np.all((na[valid]*nb[valid]).sum(1)>0)
 assert np.array_equal(q[:,1:],v[:,1:])
print('PASS five independent deck-width pairs; 1868 measured source faces before road-top exclusion')
