"""Emit measured detailed Lift01 footing transforms without runtime classification.
Usage: python Lift01Footing.py RESEARCH_DIRECTORY OUTPUT_CS
Two capsule collars, eight curved fenders and sixty side posts/brackets.
"""
from pathlib import Path
import hashlib
import json
import sys
import numpy as np

r, output = map(Path, sys.argv[1:])
tables = []
for lod in (0, 1):
    d = np.load(r / f'lift01-footing-{lod}.npz')
    v, f = d['positions'], d['indices']
    groups = json.loads((r / f'lift01-footing-parts-{lod}.json').read_text())
    assert v.shape == ((10836, 3) if lod == 0 else (11530, 3))
    assert f.shape == ((8960, 3) if lod == 0 else (5376, 3))
    assert len(groups) == 70
    covered = np.zeros(len(v), dtype=bool)
    weight = np.zeros(len(v))
    for ordinal, p in enumerate(groups):
        ids = p['vertices']
        assert not covered[ids].any()
        covered[ids] = True
        assert np.array_equal(v[ids].min(0), p['minimum'])
        assert np.array_equal(v[ids].max(0), p['maximum'])
        member = np.isin(f, ids)
        assert not np.any(member.any(1) & ~member.all(1))
        x = v[f[member.all(1)], 0]
        if ordinal < 10:
            # The original straight portions have only centre and tangent-end
            # vertices. Curved portions contain exclusively same-side vertices.
            tangent = 9.111328125 if ordinal < 2 else 8.0263671875
            inner = 9.08837890625 if ordinal < 2 else 8.011962890625
            assert p['minimum'][0] < 0 < p['maximum'][0]
            assert np.min(abs(v[ids, 0][v[ids, 0] != 0])) >= inner
            mixed = np.sign(x).min(1) != np.sign(x).max(1)
            assert abs(x[mixed]).max() == tangent
        else:
            assert p['maximum'][0] < 0 or p['minimum'][0] > 0
        weight[ids] = np.sign(v[ids, 0])
    assert covered.all()
    before = v[f].astype(float)
    normal = np.cross(before[:, 1] - before[:, 0], before[:, 2] - before[:, 0])
    valid = np.linalg.norm(normal, axis=1) > 1e-8
    for delta in (-2.99, -2.75, -2, -.5, 0, 2, 8):
        moved = v.astype(float).copy()
        moved[:, 0] += weight * delta
        assert np.array_equal(moved[:, 1:], v[:, 1:])
        q = moved[f]
        after = np.cross(q[:, 1] - q[:, 0], q[:, 2] - q[:, 0])
        assert np.all(np.sum(normal[valid] * after[valid], axis=1) > 0)
        for p in groups[10:]:
            ids = p['vertices']
            assert np.allclose(moved[ids] - moved[ids[0]], v[ids] - v[ids[0]], atol=1e-6)
    ranges = []
    for i, w in enumerate(weight):
        if ranges and ranges[-1][2] == w:
            ranges[-1][1] = i
        else:
            ranges.append([i, i, int(w)])
    name = 'LiftBridge01PillarBase' + ('_LOD1' if lod else '') + ' Mesh.Geometry'
    digest = hashlib.sha256((r / 'movable-skin' / name).read_bytes()).hexdigest()
    tables.append((ranges, digest))
    print(f'LOD{lod}: all {len(v)} vertices / {len(f)} faces, 70 parts, '
          f'{len(ranges)} immutable ranges; no subdivision.')

lines = ['// Generated by Lift01Footing.py from native collar/fender/post topology.',
         'using System;', 'using UnityEngine;', '', 'namespace BridgeBuilder.Bridges;', '',
         'internal static class Lift01Footing', '{',
         '    internal static MovableStructureModel.Plan CreateDetailed(int lod, Vector3[] source, int[] indices, float delta)',
         '    {', '        var data = lod switch', '        {',
         '            0 => (Count: 10836, Indices: 26880, Ranges: Near),',
         '            1 => (Count: 11530, Indices: 16128, Ranges: Middle),',
         '            _ => throw new ArgumentOutOfRangeException(nameof(lod))', '        };',
         '        if (!float.IsFinite(delta) ||',
         '            source.Length != data.Count || indices.Length != data.Indices)',
         '            throw new InvalidOperationException("Lift01 footing requires its measured layout.");',
         '        var positions = (Vector3[])source.Clone();',
         '        foreach (var range in data.Ranges)',
         '            for (var i = range.First; i <= range.Last; i++) positions[i].x += range.Direction * delta;',
         '        return new MovableStructureModel.Plan(source, positions, new[] { indices },',
         '            new[] { new bool[indices.Length / 3] });', '    }', '']
for field, (ranges, digest) in zip(('Near', 'Middle'), tables):
    lines += [f'    // Geometry SHA-256: {digest}',
              f'    private static readonly (int First, int Last, int Direction)[] {field} =', '    {']
    lines += [f'        ({a}, {b}, {w}),' for a, b, w in ranges]
    lines += ['    };', '']
lines += ['}']
output.write_text('\n'.join(lines) + '\n', encoding='utf-8')
