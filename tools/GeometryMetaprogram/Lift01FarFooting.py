"""Transfer measured detailed footing motion to the native simplified shell offline.
Usage: python Lift01FarFooting.py RESEARCH_DIRECTORY OUTPUT_CS
Native far geometry merges collars, fenders and posts into two continuous shells.
"""
from pathlib import Path
import hashlib
import json
import sys
import numpy as np

r, output = map(Path, sys.argv[1:])
near = np.load(r / 'lift01-footing-0.npz')
v, f = near['positions'].astype(float), near['indices']
far = np.load(r / 'lift01-footing-2.npz')
source, faces = far['positions'].astype(float), far['indices']
assert v.shape == (10836, 3) and f.shape == (8960, 3)
assert source.shape == (717, 3) and faces.shape == (500, 3)
parts = json.loads((r / 'lift01-footing-parts-0.json').read_text())
assert len(parts) == 70
roles = np.full(len(v), -1)
for k, part in enumerate(parts):
    roles[part['vertices']] = k
assert np.all(roles >= 0)
assert np.all(roles[f] == roles[f[:, :1]])
tri = v[f]
a = tri[:, 0]
e, h = tri[:, 1] - a, tri[:, 2] - a
aa, bb, cc = (e * e).sum(1), (e * h).sum(1), (h * h).sum(1)
det = aa * cc - bb * bb
weights, distances, owners = [], [], []
for p in source:
    ap = p - a
    d, q = (ap * e).sum(1), (ap * h).sum(1)
    u = np.divide(cc * d - bb * q, det, out=np.zeros_like(det), where=det > 1e-16)
    w = np.divide(aa * q - bb * d, det, out=np.zeros_like(det), where=det > 1e-16)
    bary = np.column_stack((1 - u - w, u, w))
    project = (bary[:, :, None] * tri).sum(1)
    dist = ((project - p) ** 2).sum(1)
    dist[(bary.min(1) < 0) | (det <= 1e-16)] = np.inf
    for i, j in ((0, 1), (1, 2), (2, 0)):
        edge = tri[:, j] - tri[:, i]
        length = (edge * edge).sum(1)
        t = np.divide(((p - tri[:, i]) * edge).sum(1), length,
                      out=np.zeros_like(length), where=length > 0)
        t = np.clip(t, 0, 1)
        cp = tri[:, i] + t[:, None] * edge
        ds = ((cp - p) ** 2).sum(1)
        m = ds < dist
        dist[m] = ds[m]
        bary[m] = 0
        bary[m, i], bary[m, j] = 1 - t[m], t[m]
    k = int(dist.argmin())
    weight = float(bary[k] @ np.sign(v[f[k], 0]))
    owner = int(roles[f[k, 0]])
    if owner >= 10:
        # Every post/bracket stays rigid, including simplified native vertices.
        assert abs(abs(weight) - 1) < 1e-10
        weight = float(np.sign(weight))
    weights.append(weight)
    owners.append(owner)
    distances.append(float(np.sqrt(dist[k])))
weights = np.array(weights, dtype=np.float32)
assert max(distances) < .685  # Recorded native simplification deviation, in metres.
assert set(owners) == {0, 1, 2, 3, 6, 7, 10, 15, 20, 25, 30, 35, 40, 45, 50, 55, 60, 65}
# Coincident native seam vertices must never separate after motion transfer.
coincident = {}
for p, w in zip(source, weights):
    key = tuple(p)
    if key in coincident:
        assert coincident[key] == w
    coincident[key] = w
p = source[faces]
normal = np.cross(p[:, 1] - p[:, 0], p[:, 2] - p[:, 0])
for delta in (-2.99, -2.75, -2, -.5, 0, 2, 8):
    moved = source.copy()
    moved[:, 0] += weights * delta
    assert np.array_equal(moved[:, 1:], source[:, 1:])
    q = moved[faces]
    after = np.cross(q[:, 1] - q[:, 0], q[:, 2] - q[:, 0])
    assert np.all((normal * after).sum(1) > 0)
digest = hashlib.sha256((r / 'movable-skin/LiftBridge01PillarBase_LOD2 Mesh.Geometry').read_bytes()).hexdigest()
lines = ['// Native LiftBridge01 far footing motion transferred offline from detailed parts.',
         '// Geometry SHA-256: ' + digest,
         '// Generated by Lift01FarFooting.py; no runtime proximity or geometry classifier.',
         'using System;', 'using UnityEngine;', '', 'namespace BridgeBuilder.Bridges;', '',
         'internal static class Lift01FarFooting', '{',
         '    internal static MovableStructureModel.Plan Create(Vector3[] source, int[] indices, float delta)',
         '    {',
         '        if (source.Length != 717 || indices.Length != 1500 || !float.IsFinite(delta))',
         '            throw new InvalidOperationException("Lift01 far footing requires its measured source.");',
         '        var positions = (Vector3[])source.Clone();',
         '        for (var i = 0; i < positions.Length; i++) positions[i].x += Weights[i] * delta;',
         '        return new MovableStructureModel.Plan(source, positions, new[] { indices },',
         '            new[] { new bool[500] });', '    }', '',
         '    private static readonly float[] Weights =', '    {']
for i in range(0, len(weights), 12):
    lines.append('        ' + ', '.join(format(float(w), '.9g') + 'f' for w in weights[i:i+12]) + ',')
lines += ['    };', '}']
output.write_text('\n'.join(lines) + '\n', encoding='utf-8')
print(f'Far footing: {len(weights)} vertices, 500 unchanged faces; max native correspondence distance {max(distances):.6f} m; seven widths and coincident seams passed.')
