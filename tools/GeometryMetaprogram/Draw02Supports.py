dll = c.CDLL(str(plugin))
for name, args, result in (
    ('decompress_calc_bound', [c.c_void_p,c.c_int64,c.c_int], c.c_int64),
    ('decompress_data', [c.c_void_p,c.c_int64,c.c_void_p,c.c_int64,c.c_int], c.c_int64),
    ('decompress_meshopt_index_buffer', [c.c_void_p,c.c_int64,c.c_int,c.c_int,c.c_void_p], c.c_int),
    ('decompress_meshopt_vertex_attribute', [c.c_void_p,c.c_int64,c.c_int,c.c_int,c.c_void_p], c.c_int)):
    f = getattr(dll,name); f.argtypes = args; f.restype = result

def decode(path):
    raw = path.read_bytes()
    version, meshes, flags = struct.unpack_from('<HII',raw)
    if meshes != 1: raise ValueError('Inspect multiple-mesh layout separately')
    h = struct.unpack_from('<QI14i5I',raw,10)
    offset = 98 + h[-1]*40
    def block(size, count, stride, indices=False):
        nonlocal offset
        data = raw[offset:offset+size]; offset += size
        if flags & 2:
            capacity = dll.decompress_calc_bound(data,len(data),0)
            buf = c.create_string_buffer(capacity)
            if dll.decompress_data(data,len(data),buf,capacity,0) != capacity: raise ValueError('ZSTD')
            data = buf.raw
        if flags & 1:
            buf = c.create_string_buffer(count*stride)
            method = dll.decompress_meshopt_index_buffer if indices else dll.decompress_meshopt_vertex_attribute
            if method(data,len(data),count,stride,buf): raise ValueError('Meshopt')
            data = buf.raw
        if len(data) != count*stride: raise ValueError('Decoded size')
        return data
    stride = 4 if h[17]&1 else 2
    indices = np.frombuffer(block(h[16],h[19],stride,True),dtype='<u4' if stride==4 else '<u2').reshape(-1,3)
    channels = {}
    for attribute in range(14):
        size=h[2+attribute]
        if not size: continue
        fmt=(h[0]>>(attribute*4))&15; dim=((h[1]>>(attribute*2))&3)+1
        width=(4,2,1,1,2,2,1,1,2,2,4,4)[fmt]*dim
        channels[attribute] = block(size,h[18],width)
    return np.frombuffer(channels[0],dtype='<f4').reshape(-1,3),indices


# Offline authored support regions: front transverse wall, rear ribbed wall,
# side returns and the control-room projection. These tests never enter runtime.
def weights(v, faces, column):
    span = np.where(abs(v[:,2]) > 85, .75, 14.75) if column else np.full(len(v),15.)
    result = np.clip(v[:,0] / span, -1., 1.)
    # Preserve native coarse side returns after simplification perturbs their X stations.
    # Side-facing wall triangles carry the corresponding high-detail side wall rigidly.
    rigid = {}
    for face in faces:
        points=v[face].astype(float)
        normal=np.cross(points[1]-points[0], points[2]-points[0])
        if abs(normal[0]) > abs(normal[2]) and abs(normal[0]) > abs(normal[1]):
            if points[:,0].min()>0:
                for vertex in face: rigid[tuple(v[vertex])] = 1
            elif points[:,0].max()<0:
                for vertex in face: rigid[tuple(v[vertex])] = -1
    for i, point in enumerate(v):
        if tuple(point) in rigid: result[i] = rigid[tuple(point)]
    return result.astype(np.float32)

def literal(x): return format(float(np.float32(x)),'.9g')+'f'
def emit_array(name, values):
    lines=[f'    private static readonly float[] {name} =', '    {']
    for i in range(0,len(values),12): lines.append('        '+', '.join(literal(x) for x in values[i:i+12])+',')
    return lines+['    };','']

out=['// Offline measured DrawBridge02 support displacement data, game 1.6.2f1.',
     '// Generated by tools/GeometryMetaprogram/Draw02Supports.py; no runtime part inference.',
     'using System;', 'using UnityEngine;', '', 'namespace BridgeBuilder.Bridges;', '',
     'internal static class Draw02SupportWideningData', '{',
     '    internal static MovableStructureModel.Plan CreatePlan(bool column, int lod,',
     '        Vector3[] source, int[] indices, float delta)', '    {',
     '        var data = (column, lod) switch', '        {']
records=[]
for column,stem in [(True,'DrawBridge02Pillar'),(False,'DrawBridge02PillarBase')]:
    for lod,suffix in enumerate(('','_LOD1','_LOD2')):
        path=r/'movable-skin'/f'{stem}{suffix} Mesh.Geometry'
        v,faces=decode(path)
        w=weights(v,faces,column)
        key=('Column' if column else 'Footing')+str(lod)
        records.append((key,v,faces,w,hashlib.sha256(path.read_bytes()).hexdigest()))
        out.append(f'            ({str(column).lower()}, {lod}) => ({key}, {len(faces)*3}),')
out+=['            _ => throw new ArgumentOutOfRangeException(nameof(lod))', '        };',
      '        var weights = data.Item1;',
      '        if (source.Length != weights.Length || indices.Length != data.Item2)',
      '            throw new InvalidOperationException("Draw02 support source does not match its recorded layout.");',
      '        var positions = (Vector3[])source.Clone();',
      '        for (var i = 0; i < positions.Length; i++) positions[i].x += weights[i] * delta;',
      '        return new MovableStructureModel.Plan(source, positions, new[] { indices },',
      '            new[] { new bool[indices.Length / 3] });', '    }', '']
for key,v,f,w,sha in records:
    out+=['    // Geometry SHA-256: '+sha]+emit_array(key,w)
    for delta in [-.5,0,2,8]:
        moved=v.copy(); moved[:,0]+=w*np.float32(delta)
        assert np.array_equal(moved[:,1:],v[:,1:])
        assert np.isfinite(moved).all()
        assert abs(float(np.ptp(moved[:,0])-np.ptp(v[:,0]))-2*delta)<1e-5
        if delta==0: assert np.array_equal(moved,v)
        # Coincident source corners must remain coincident after the same transformation.
        by_position={}
        for point,weight in zip(v,w):
            old=by_position.setdefault(tuple(point),weight)
            assert old==weight,(key,point,old,weight)
    np.savez(r/(key+'-widening-review.npz'),positions=v,indices=f,weights=w)
    print(key,len(v),len(f),'weight groups',len(np.unique(w)))
out+=['}','']
output.write_text('\n'.join(out),encoding='utf-8')
