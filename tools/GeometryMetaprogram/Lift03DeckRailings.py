"""Emit Lift03 measured road-edge railing translation maps.
Usage: python Lift03DeckRailings.py RESEARCH_DIRECTORY OUTPUT_CS
"""
from pathlib import Path
import sys,json,hashlib
import numpy as np
r,out=map(Path,sys.argv[1:]);rows=json.loads((r/'lift03-main-parts.json').read_text())
lines=['// Native Lift03 deck-edge railings; generated by Lift03DeckRailings.py.',
 'using System;','using UnityEngine;','','namespace BridgeBuilder.Bridges;','',
 'internal static class Lift03DeckRailings','{',
 '    internal static void Apply(int lod, Vector3[] source, Vector3[] positions, float upperDelta, float lowerDelta)','    {',
 '        var data = lod switch','        {',
 '            0 => (Count: 474534, Parts: Level0),','            1 => (Count: 349267, Parts: Level1),',
 '            _ => throw new ArgumentOutOfRangeException(nameof(lod))','        };',
 '        if (source.Length != data.Count || positions.Length != data.Count || !float.IsFinite(upperDelta) || !float.IsFinite(lowerDelta))',
 '            throw new InvalidOperationException("Lift03 deck railings require their recorded native layout.");',
 '        foreach (var part in data.Parts)','            for (var i = part.First; i <= part.Last; i++)',
 '                positions[i].x = source[i].x + part.Sign * (part.Upper ? upperDelta : lowerDelta);','    }','']
records=[]
for lod in (0,1):
 row=next(x for x in rows if x['lod']==lod and x['mesh']==0)
 assert hashlib.sha256((r/'movable-skin'/(row['source']+'.Geometry')).read_bytes()).hexdigest()==row['sha256']
 d=np.load(r/f'lift03-main-{lod}-0.npz');v,f,c=d['positions'],d['indices'],d['component']
 groups=[]
 for upper in (True,False):
  xmin,xmax,ymin,ymax=(10.29,10.41,20.38,21.18) if upper else (5.17,5.30,10.09,11.80)
  parts=[p['id'] for p in row['parts'] if p['minimum'][0]*p['maximum'][0]>0 and xmin<min(abs(p['minimum'][0]),abs(p['maximum'][0])) and max(abs(p['minimum'][0]),abs(p['maximum'][0]))<xmax and ymin<p['minimum'][1] and p['maximum'][1]<ymax]
  selected=np.isin(c,parts);assert np.array_equal(selected[f].any(1),selected[f].all(1))
  ids=np.flatnonzero(selected);assert len(ids)>0
  groups.append((upper,ids));records.append(dict(lod=lod,upper=upper,parts=parts))
  print(lod,'upper' if upper else 'lower',len(parts),'parts',len(ids),'vertices',int(selected[f].all(1).sum()),'triangles')
  for ud,ld in ((0,0),(2,8),(8,2),(-.25,2)):
   q=v.copy();q[ids,0]+=np.sign(v[ids,0])*(ud if upper else ld)
   for part in parts:
    ix=np.flatnonzero(c==part);assert np.allclose(q[ix]-v[ix],q[ix[0]]-v[ix[0]],atol=2e-6)
 ranges=[]
 for upper,ids in groups:
  for i in ids:
   sign=int(np.sign(v[i,0]))
   if ranges and ranges[-1][1]==i-1 and ranges[-1][2:]==[sign,upper]:ranges[-1][1]=int(i)
   else:ranges.append([int(i),int(i),sign,upper])
 lines += ['    // Geometry SHA-256: '+row['sha256'],f'    private static readonly (int First, int Last, int Sign, bool Upper)[] Level{lod} =','    {']
 lines += [f'        ({a}, {b}, {sgn}, {str(up).lower()}),' for a,b,sgn,up in ranges]
 lines += ['    };','']
lines+=['}',''];out.write_text('\n'.join(lines),encoding='utf-8');(r/'lift03-deck-railing-parts.json').write_text(json.dumps(records))
print('PASS independent deck deltas preserve every selected rigid part')

