"""Emit measured Draw03 ordinary-pillar detailed parts and all-LOD rigid feet.
Usage: python Draw03NetPillarParts.py RESEARCH_DIRECTORY OUTPUT_CS
Merged far top/column shells require separate plans, not component-wide scaling.
"""
from pathlib import Path
import hashlib
import json
import sys
import numpy as np

r, output = map(Path, sys.argv[1:])
audit = json.loads((r/'all-movable-audit.json').read_text())
tables = []
for part in range(3):
    for lod in range(3 if part == 2 else 2):
        stem = ('DrawBridge03NetPillarTop','DrawBridge03NetPillar','DrawBridge03NetPillarBase')[part]
        name = stem+(f'_LOD{lod}' if lod else '')+' Mesh.Geometry'
        digest = hashlib.sha256((r/'draw03-network-pillar'/name).read_bytes()).hexdigest()
        assert any(a.get('sha256') == digest for a in audit['assets'].values())
        d = np.load(r/f'draw03-netpillar-{part}-{lod}.npz')
        v, faces = d['positions'], d['indices'].reshape(-1,3)
        parts = json.loads((r/f'draw03-netpillar-parts-{part}-{lod}.json').read_text())
        assert [i for i,p in enumerate(parts) if not p['side']] == ([0] if part == 0 else [0,2,5] if part == 1 else [])
        weights = np.zeros(len(v))
        seen = np.zeros(len(v),dtype=int)
        minimum = float('inf')
        for p in parts:
            ids = p['vertices']; points = v[ids]; side = p['side']
            membership = np.isin(faces,ids)
            assert not np.any(membership.any(1) & ~membership.all(1))
            seen[ids] += 1
            if side:
                assert np.all(points[:,0]*side > 0)
                weights[ids] = side
                minimum = min(minimum,float(np.min(abs(points[:,0]))))
            else:
                lo,hi = float(points[:,0].min()),float(points[:,0].max())
                assert lo < 0 < hi
                weights[ids] = 2*(points[:,0].astype(float)-lo)/(hi-lo)-1
                minimum = min(minimum,(hi-lo)/2)
        assert np.all(seen == 1)
        for delta in (-16.,-8.,-min(.1,minimum*.5),0.,2.,8.):
            moved = v.astype(float).copy(); moved[:,0] += weights*delta
            assert np.array_equal(moved[:,1:],v[:,1:])
            p,q = v[faces].astype(float),moved[faces]
            before = np.cross(p[:,1]-p[:,0],p[:,2]-p[:,0])
            after = np.cross(q[:,1]-q[:,0],q[:,2]-q[:,0])
            valid = np.linalg.norm(before,axis=1)>1e-8
            if delta >= -.1: assert np.all(np.sum(before[valid]*after[valid],axis=1)>0)
            for component in parts:
                ids = component['vertices']
                if component['side']:
                    assert np.array_equal(moved[ids]-moved[ids[0]],v[ids].astype(float)-v[ids[0]])
        tables.append((part,lod,len(v),faces.size,digest,minimum,weights))
        np.savez(r/f'draw03-netpillar-plan-{part}-{lod}.npz',positions=v,indices=faces,weights=weights)
        print(f'Part {part} LOD{lod}: {len(parts)} measured parts, {len(v)} vertices, {len(faces)} unchanged triangles; rigid-side and positive-span winding checks passed; centre-crossing displacement {minimum:g} m')

def f(x): return format(float(np.float32(x)),'.9g')+'f'
lines = ['// Native DrawBridge03 ordinary-pillar parts, game 1.6.2f1.',
         '// Generated by Draw03NetPillarParts.py; merged far top/column use separate plans.',
         'using System;', 'using UnityEngine;', '', 'namespace BridgeBuilder.Bridges;', '',
         'internal static class Draw03NetPillarParts', '{',
         '    internal static MovableStructureModel.Plan Create(int part, int lod, Vector3[] source, int[] indices, float delta)',
         '    {', '        var data = (part, lod) switch', '        {']
for part,lod,count,size,digest,minimum,weights in tables:
    lines.append(f'            ({part}, {lod}) => (Count: {count}, Indices: {size}, Minimum: {f(minimum)}, Weights: Weights{part}{lod}),')
lines += ['            _ => throw new ArgumentOutOfRangeException(nameof(lod))', '        };',
          '        if (!float.IsFinite(delta) || source.Length != data.Count || indices.Length != data.Indices)',
          '            throw new InvalidOperationException("Draw03 ordinary pillar parts require their measured layout.");',
          '        var positions = (Vector3[])source.Clone();',
          '        for (var i = 0; i < positions.Length; i++) positions[i].x += data.Weights[i] * delta;',
          '        return new MovableStructureModel.Plan(source, positions, new[] { indices }, new[] { new bool[indices.Length / 3] });',
          '    }', '']
for part,lod,count,size,digest,minimum,weights in tables:
    lines += ['    // Geometry SHA-256: '+digest, f'    private static readonly float[] Weights{part}{lod} =', '    {']
    for start in range(0,len(weights),12): lines.append('        '+', '.join(map(f,weights[start:start+12]))+',')
    lines += ['    };','']
lines += ['}','']
output.write_text('\n'.join(lines),encoding='utf-8')
