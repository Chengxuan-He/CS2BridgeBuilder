"""Record deck-adjacent base and edge vertices, excluding upper machinery.

Offline ownership follows the reviewed detailed fixed/moving body profiles.
Runtime consumes only literal vertex ranges; it performs no height selection.
"""
from pathlib import Path
import hashlib,json,sys
import numpy as np

r,output=map(Path,sys.argv[1:])
audit=json.loads((r/'all-movable-audit.json').read_text())
groups=((0,20,22,204,224,226),(0,20,22,197,217,219),(10,19,20,21,39,48))
levels=[]
for lod,ids in enumerate(groups):
    name='PedestrianDrawBridge01'+(f'_LOD{lod}' if lod else '')+' Mesh'
    digest=hashlib.sha256((r/'movable-skin'/(name+'.Geometry')).read_bytes()).hexdigest()
    assert any(a.get('sha256')==digest for a in audit['assets'].values())
    d=np.load(r/f'pedestrian01-main-{lod}-0.npz')
    v,f,component=d['positions'],d['indices'],d['component']
    selected=np.isin(component,ids)&(v[:,1]<=10.100098)
    # The fixed central control enclosure starts at the walking surface. Its
    # bottom vertices belong to the enclosure, even though their Y equals 10.
    # Identify its triangles rather than taking all coplanar road vertices.
    if lod<2:
        fixed=np.isin(component,(0,204) if lod==0 else (0,197))
        enclosure=f[fixed[f].all(1)&(v[f,1]>=10).all(1)&
                    (np.abs(v[f,0])<=.25726318).all(1)]
        selected[np.unique(enclosure)]=False
    weights=np.zeros(len(v),dtype=np.int8)
    weights[selected]=np.sign(v[selected,0]).astype(np.int8)
    assert selected.any()
    for delta in (-.03,0,2,8):
        q=v.copy();q[:,0]+=weights*delta
        assert np.array_equal(q[~selected],v[~selected])
        assert np.array_equal(q[:,1:],v[:,1:])
        assert np.array_equal(q[selected & (v[:,0]==0)],v[selected & (v[:,0]==0)])
        # Verify fully covered retained triangles. Upper frame joins will be
        # verified after its separate mapping is composed with this one.
        faces=f[selected[f].all(1)]
        a,b=v[faces],q[faces]
        n=np.cross(a[:,1]-a[:,0],a[:,2]-a[:,0])
        m=np.cross(b[:,1]-b[:,0],b[:,2]-b[:,0])
        active=np.linalg.norm(n,axis=1)>1e-9
        assert np.all((n[active]*m[active]).sum(1)>0)
    ranges=[]
    for i in np.flatnonzero(selected):
        i=int(i);w=int(weights[i])
        if ranges and ranges[-1][1]==i-1 and ranges[-1][2]==w:ranges[-1][1]=i
        else:ranges.append([i,i,w])
    np.savez(r/f'pedestrian01-deck-base-{lod}.npz',positions=v,indices=f,
             selected=selected,weights=weights)
    levels.append((len(v),digest,ranges))
    print('PASS',lod,'base vertices',selected.sum(),'triangles',selected[f].all(1).sum())
lines=['// Generated by PedestrianDraw01DeckBases.py; deck-adjacent bases use sign-X translation.',
       'using System;','using UnityEngine;','','namespace BridgeBuilder.Bridges;','',
       'internal static class PedestrianDraw01DeckBases','{',
       '    internal static void Apply(int lod, Vector3[] source, Vector3[] positions, float delta)',
       '    {','        var data = lod switch','        {']
for lod,(count,_,_) in enumerate(levels):lines.append(f'            {lod} => (Count: {count}, Parts: Parts{lod}),')
lines+=['            _ => throw new ArgumentOutOfRangeException(nameof(lod))','        };',
        '        if (source.Length != data.Count || positions.Length != data.Count || !float.IsFinite(delta))',
        '            throw new InvalidOperationException("PedestrianDraw01 deck-base source layout changed.");',
        '        foreach (var part in data.Parts)',
        '            for (var i = part.First; i <= part.Last; i++)',
        '                positions[i].x = source[i].x + part.Side * delta;',
        '    }','']
for lod,(_,digest,ranges) in enumerate(levels):
    lines+=['    // Geometry SHA-256: '+digest,
            f'    private static readonly (int First, int Last, int Side)[] Parts{lod} =','    {']
    lines += [f'        ({a}, {b}, {s}),' for a,b,s in ranges]
    lines+=['    };','']
lines+=['}',''];output.write_text('\n'.join(lines),encoding='utf-8')
