"""Emit Lift04 support transforms from measured native column and footing meshes.
Usage: python Lift04Supports.py RESEARCH_DIRECTORY OUTPUT_CS
"""
from pathlib import Path
import hashlib,json,sys
import numpy as np
r,output=map(Path,sys.argv[1:])
records=json.loads((r/'lift04-support-parts.json').read_text())
hashes=(('11e10c8fb7a98ccc61538b57a1187d41ef13b200fd06e0fd6041c2336ae0ddb2','f2ee075ca9816054428b75ebdc477367b74293033f7c2ff45cbe93a2fea79201','9be4e2c95e1fc8772d7c391cb39787506c7086063946a8ef6f9232d2628a1a4a'),('01f43922248dc3621506886ef241b4ef862c8c5c67e7e8083f8e0bb00f233ca3','4e1c02181c9d98a9ce3d74cf0c32f700d4f1a93788b9d175a770362ab4ea8618','55a5a94d69e4cd2c661298c504cb0e6598c7cf96769fb7728b4c0231295b202d'))
lines=['// Native LiftBridge04 supports; generated by Lift04Supports.py.','// Side column lobes translate; their connecting faces extend. Separate footings stretch.','using System;','using UnityEngine;','','namespace BridgeBuilder.Bridges;','','internal static class Lift04SupportGeometry','{','    internal static MovableStructureModel.Plan Create(bool footing, int lod, Vector3[] source, int[] indices, float delta)','    {','        var data = (footing, lod) switch','        {']
tables=[]
for row in records:
 part,lod=row['part'],row['lod']
 digest=hashlib.sha256((r/'movable-skin'/row['source']).read_bytes()).hexdigest()
 assert digest==row['sha256']==hashes[part][lod]
 d=np.load(r/f'lift04-support-{part}-{lod}.npz');v,f,c=d['positions'],d['indices'],d['component']
 assert len(v)==((576,530,176),(1088,1022,136))[part][lod]
 assert len(f)==((512,460,128),(848,762,116))[part][lod]
 assert len(row['parts'])==2
 for p in row['parts']:
  ids=np.flatnonzero(c==p['id']);assert np.array_equal(v[ids].min(0),p['minimum']) and np.array_equal(v[ids].max(0),p['maximum'])
 if part:
  assert v[:,0].min()==-12.162353515625 and v[:,0].max()==12.162353515625
  weights=v[:,0].astype(float)/12.162353515625
 else:
  assert np.min(np.abs(v[:,0]))==2.60003662109375
  weights=np.sign(v[:,0]).astype(float)
  crossing=np.ptp(weights[f],axis=1)>0
  # Every cross-centre face joins only the recorded inner column boundaries.
  assert np.all(np.abs(v[f[crossing],0])==2.60003662109375)
 for delta in (-13,-4,-2.60003662109375,-1,0,2,8):
  q=v.astype(float).copy();q[:,0]+=weights*delta
  assert np.array_equal(q[:,1:],v[:,1:])
  a,b=v[f].astype(float),q[f];na=np.cross(a[:,1]-a[:,0],a[:,2]-a[:,0]);nb=np.cross(b[:,1]-b[:,0],b[:,2]-b[:,0]);active=np.linalg.norm(na,axis=1)>1e-9
  assert np.isfinite(q).all()
  if delta >= -1: assert np.all(np.sum(na[active]*nb[active],axis=1)>0)
  if not part:
   assert np.allclose((b[:,1:]-b[:,:1])[~crossing],(a[:,1:]-a[:,:1])[~crossing],atol=1e-12,rtol=0)
 ranges=[]
 for i,w in enumerate(weights if not part else np.zeros(len(v))):
  if ranges and ranges[-1][1]==i-1 and ranges[-1][2]==w:ranges[-1][1]=i
  else:ranges.append([i,i,float(w)])
 key=f'Parts{part}{lod}';tables.append((key,digest,ranges))
 lines.append(f'            ({str(bool(part)).lower()}, {lod}) => (Count: {len(v)}, IndexCount: {f.size}, Parts: {key}),')
 print(f'PASS part {part} LOD{lod}: {len(v)} vertices, {len(f)} faces, seven signed widths; YZ and side shape retained, positive-span winding checked')
lines+=['            _ => throw new ArgumentOutOfRangeException(nameof(lod))','        };','        if (source.Length != data.Count || indices.Length != data.IndexCount || !float.IsFinite(delta))','            throw new InvalidOperationException("Lift04 support requires its recorded topology.");','        var positions = (Vector3[])source.Clone();','        foreach (var part in data.Parts)','            for (var i = part.First; i <= part.Last; i++)','                positions[i].x += (footing ? source[i].x / 12.162353515625f : part.Sign) * delta;','        return new MovableStructureModel.Plan(source, positions, new[] { indices }, new[] { new bool[indices.Length / 3] });','    }','']
for key,digest,ranges in tables:
 lines+=['    // Geometry SHA-256: '+digest,f'    private static readonly (int First, int Last, float Sign)[] {key} =','    {']
 lines += [f'        ({a}, {b}, {w:g}f),' for a,b,w in ranges]
 lines+=['    };','']
lines+=['}',''];output.write_text('\n'.join(lines),encoding='utf-8')
