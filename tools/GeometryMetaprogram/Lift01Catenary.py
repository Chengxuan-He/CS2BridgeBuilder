"""Emit native Lift01 railway overhead removal membership for road replacement.
Usage: python Lift01Catenary.py RESEARCH_DIRECTORY OUTPUT_CS
The seven pole assemblies were reviewed in X/Y projection with their crossarms.
Only original complete triangles are removed, never receiving road triangles.
"""
from pathlib import Path
import hashlib
import json
import sys
import numpy as np

r, output = map(Path, sys.argv[1:])
# Four approach poles, two moving end poles and the moving centre pole.
starts = (2138, 2162, 2186, 2210, 7074, 9768, 9902)
side_ids = [i for a in starts for i in range(a, a + 24)]
# Six droppers and the two continuous longitudinal wires.
side_ids += [2234, 2235, 2236, 2237, 7072, 7073, 9766, 9767]
cross_ids = list(range(74, 90)) + list(range(488, 492))
cross_ids += list(range(635, 639)) + list(range(641, 645))
assert len(side_ids) == len(set(side_ids)) == 176
assert len(cross_ids) == len(set(cross_ids)) == 28
levels = []
for lod in (0, 1):
    side = json.loads((r / f'lift01-side-{lod}.json').read_text())
    cross = json.loads((r / f'lift01-crossing-{lod}.json').read_text())
    assert len(side) == 9926 and len(cross) == 645
    data = np.load(r / f'lift01-main-{lod}.npz')
    v, f = data['positions'], data['indices']
    selected = np.zeros(len(v), dtype=bool)
    for a in starts:
        foot, mast = side[a], side[a + 13]
        assert foot['minimum'][1] == 9.800048828125
        assert mast['minimum'][0] == 2.384765625
        assert mast['maximum'][0:2] == [2.60687255859375, 17.74267578125]
    for group in [side[i] for i in side_ids] + [cross[i] for i in cross_ids]:
        ids = group['vertices']
        assert not selected[ids].any()
        selected[ids] = True
        assert np.array_equal(v[ids].min(0), group['minimum'])
        assert np.array_equal(v[ids].max(0), group['maximum'])
        # Offline sanity check only: these are overhead assemblies, not trusswork.
        assert group['minimum'][1] >= 9.800048828125
        assert group['maximum'][1] <= 17.85
    if lod == 0:
        near = (side, cross)
    else:
        for groups, reference, ids in ((side, near[0], side_ids), (cross, near[1], cross_ids)):
            for i in ids:
                for key in ('minimum', 'maximum'):
                    assert np.max(abs(np.array(groups[i][key]) - reference[i][key])) <= .05078125
    membership = selected[f].sum(1)
    assert not np.any((membership != 0) & (membership != 3))
    faces = np.flatnonzero(membership == 3).tolist()
    # Rail/fastener membership is a distinct removal stage.
    rail_ids = [i for a, b in ((1814, 2138), (6270, 7072), (8966, 9766))
                for q in side[a:b] for i in q['vertices']]
    assert not selected[rail_ids].any()
    ranges = []
    for i in faces:
        if ranges and ranges[-1][1] + 1 == i:
            ranges[-1][1] = i
        else:
            ranges.append([i, i])
    assert [i for a, b in ranges for i in range(a, b + 1)] == faces
    name = 'LiftBridge01' + ('_LOD1' if lod else '') + ' Mesh.Geometry'
    digest = hashlib.sha256((r / 'movable-skin' / name).read_bytes()).hexdigest()
    audit = json.loads((r / 'lift-native-road-plane-candidates.json').read_text())
    record = next(x for x in audit if x['style'] == 1 and x['lod'] == lod)
    assert digest.lower() == record['sha256'].lower()
    road_faces = {i for c in record['candidates'] if c['bone'] in (0, 4)
                  and c['y'] == 9.800048828125 for i in c['faces']}
    assert road_faces.isdisjoint(faces)
    levels.append((len(f), ranges, digest))
    print(f'LOD{lod}: 7 poles, 28 crossarms, 2 wires, 6 droppers; '
          f'{selected.sum()} vertices / {len(faces)} whole faces.')

lines = ['// Generated by Lift01Catenary.py from reviewed native overhead assemblies.',
         '// Selected-road facilities replace these original railway-specific faces.',
         'using System;', '', 'namespace BridgeBuilder.Bridges;', '',
         'internal static class Lift01CatenaryRemoval', '{',
         '    internal static void Remove(int lod, bool[] removed)', '    {',
         '        var data = lod switch', '        {']
for lod, (count, _, _) in enumerate(levels):
    lines.append(f'            {lod} => (Count: {count}, Ranges: Lod{lod}),')
lines += ['            _ => throw new ArgumentOutOfRangeException(nameof(lod))', '        };',
          '        if (removed.Length != data.Count)',
          '            throw new InvalidOperationException("Lift01 overhead source layout changed.");',
          '        foreach (var range in data.Ranges)',
          '            for (var i = range.First; i <= range.Last; i++) removed[i] = true;',
          '    }', '']
for lod, (_, ranges, digest) in enumerate(levels):
    lines += [f'    // Geometry SHA-256: {digest}',
              f'    private static readonly (int First, int Last)[] Lod{lod} =', '    {']
    lines += [f'        ({a}, {b}),' for a, b in ranges]
    lines += ['    };', '']
lines += ['}']
output.write_text('\n'.join(lines) + '\n', encoding='utf-8')
