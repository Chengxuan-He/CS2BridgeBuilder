"""Align only the measured far roadbed boundary to detailed Lift02 stations."""
from pathlib import Path
import sys,hashlib,ctypes as c,json,struct
import numpy as np
r,out=map(Path,sys.argv[1:])
raw=(r/'movable-skin/LiftBridge02_LOD2 Mesh.Geometry').read_bytes()
assert hashlib.sha256(raw).hexdigest()=='1a41d4684ed32102dcd8400f5f9e2ce86fdf348a79da29f52245ec0abe56d258'
d=np.load(r/'lift02-main-2-0.npz');v,f,c=d['positions'].astype(np.float32),d['indices'],d['component']
# Re-decode the checked binary; OBJ-derived caches only provide component IDs.
components=d['component'].copy()
import ctypes as c
exec(Path(__file__).with_name('Lift02FarRoadTops.py').read_text().split('faces=(410')[0])
c=components
v=v.astype(np.float32)
assert v.shape==(4152,3) and f.shape==(2600,3)
# The detailed roadbed top and longitudinal ends have independently audited identities.
near=np.load(r/'lift02-main-0-0.npz');nv,nf=near['positions'].astype(np.float32),near['indices']
assert np.all(nv[nf[83248],1]==9.2666015625)
assert max(nv[nf[83248],2])==106
members=np.flatnonzero(np.isin(c,[12,50,78]));q=v.copy();rows=[]
for i in members:
 y,z=map(float,v[i,1:]);new_y=9.2666015625 if y==9.818359375 else y
 new_z=np.sign(z)*82 if abs(z)==81.96875 else np.sign(z)*106 if abs(z)==106.009765625 else z
 if (new_y,new_z)!=(y,z):
  q[i,1:]=[new_y,new_z];rows.append((int(i),y,z,new_y,float(new_z)))
assert rows
# Keep all unrelated coordinates and the complete native index array. Existing
# lower sidewall corners move longitudinally only where they share the end plane.
changed=np.flatnonzero(np.any(q!=v,axis=1));assert set(changed)<=set(members)
assert np.array_equal(q[:,0],v[:,0])
a=v[f].astype(float);b=q[f].astype(float)
na=np.cross(a[:,1]-a[:,0],a[:,2]-a[:,0]);nb=np.cross(b[:,1]-b[:,0],b[:,2]-b[:,0])
assert np.all(np.sum(na*nb,axis=1)>0)
lines=['// Generated by Lift02FarRoadBoundary.py from measured coarse/detailed roadbed planes.','using System;','using UnityEngine;','','namespace BridgeBuilder.Bridges;','','internal static class Lift02FarRoadBoundary','{','    internal static MovableStructureModel.Plan Apply(MovableStructureModel.Plan plan)','    {','        if (plan.SourcePositions.Length != 4152 || plan.SourceIndices.Length != 1 || plan.SourceIndices[0].Length != 7800)','            throw new InvalidOperationException("Lift02 far road boundary requires its recorded native layout.");','        var positions = (Vector3[])plan.Positions.Clone();','        foreach (var row in Vertices)','        {','            var source = plan.SourcePositions[row.Index];','            if (source.y != row.SourceY || source.z != row.SourceZ)','                throw new InvalidOperationException("Lift02 far road boundary source coordinates changed.");','            positions[row.Index].y = row.Y;','            positions[row.Index].z = row.Z;','        }','        return new MovableStructureModel.Plan(plan.SourcePositions, positions, plan.SourceIndices,','            plan.RemoveTriangles, reconstructsAuthoredPositions: true);','    }','','    private static readonly (int Index, float SourceY, float SourceZ, float Y, float Z)[] Vertices =','    {']
def fl(x):return format(x,'.17g')+'f'
lines += ['        ('+str(i)+', '+', '.join(fl(x) for x in values)+'),' for i,*values in rows]
lines += ['    };','}',''];out.write_text('\n'.join(lines))
np.savez(r/'lift02-far-road-boundary.npz',source=v,positions=q,indices=f,changed=changed)
print('PASS',len(rows),'recorded boundary vertices; all 2600 triangle windings preserved; other vertices and X unchanged.')


