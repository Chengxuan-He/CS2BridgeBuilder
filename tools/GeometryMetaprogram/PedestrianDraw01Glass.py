"""Verify and emit the immutable PedestrianDraw01 mesh-1 glass transform.
Usage: python PedestrianDraw01Glass.py RESEARCH_DIRECTORY OUTPUT_CS
"""
from pathlib import Path
import hashlib
import sys
import numpy as np

research, output = map(Path, sys.argv[1:])
levels = []
for lod in range(2):
    name = 'PedestrianDrawBridge01' + ('_LOD1' if lod else '') + ' Mesh'
    vertices, faces, bones = [], [], []
    bone = None
    for line in (research / 'movable-skin' / (name + '.mesh-1.obj')).read_text().splitlines():
        fields = line.split()
        if not fields:
            continue
        if fields[0] == 'v':
            vertices.append(list(map(float, fields[1:4])))
        elif fields[0] == 'g':
            bone = fields[1]
        elif fields[0] == 'f':
            faces.append([int(x.split('/')[0]) - 1 for x in fields[1:]])
            bones.append(bone)
    v, f = np.array(vertices), np.array(faces)
    assert v.shape == (12, 3) and f.shape == (6, 3)
    assert set(bones) == {'bone_0'}
    assert np.all(v[:, 0] < 0)
    # LOD1 reorders the first pane and its closing triangle. Compare geometry,
    # not vertex order; each native index buffer is retained at runtime.
    if levels:
        canonical = lambda points: sorted(tuple(sorted(tuple(p) for p in tri)) for tri in points)
        assert canonical(v[f]) == canonical(levels[0][0][levels[0][1]])
    for delta in (-.5, 0, 2, 8):
        moved = v.copy()
        moved[:, 0] -= delta

        assert np.array_equal(moved[:, 1:], v[:, 1:])
        # Translation preserves every triangle edge, including winding and shape.
        for a, b in ((0, 1), (0, 2)):
            assert np.allclose(moved[f[:, a]] - moved[f[:, b]],
                               v[f[:, a]] - v[f[:, b]], atol=1e-12, rtol=0)
    digest = hashlib.sha256((research / 'movable-skin' / (name + '.Geometry')).read_bytes()).hexdigest()
    levels.append((v, f, digest))
    print(f'LOD{lod}: 3 glass quads, 12 vertices, bone 0; rigid displacement verified')

code = """// Native PedestrianDrawBridge01 mesh-1 glass, game 1.6.2f1.
// Generated by PedestrianDraw01Glass.py; native LOD index ordering and fixed bone 0 remain unchanged.
using System;
using UnityEngine;

namespace BridgeBuilder.Bridges;

internal static class PedestrianDraw01Glass
{
    internal static MovableStructureModel.Plan Create(int lod, Vector3[] source,
        int[] indices, float delta)
    {
        if ((lod != 0 && lod != 1) || source.Length != 12 || indices.Length != 18 || !float.IsFinite(delta))
            throw new InvalidOperationException("PedestrianDraw01 glass requires its recorded mesh-1 layout.");
        var positions = (Vector3[])source.Clone();
        for (var i = 0; i < 12; i++) positions[i].x -= delta;

        return new MovableStructureModel.Plan(source, positions,
            new[] { indices }, new[] { new bool[6] });
    }
}
"""
header = ''.join(f'// LOD{lod} Geometry SHA-256: {level[2]}\n' for lod, level in enumerate(levels))
output.write_text(header + code, encoding='utf-8')



