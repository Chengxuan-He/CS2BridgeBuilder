"""Emit reviewed transverse members, excluding road/base and joined support shells.
Usage: python PedestrianDraw02TransverseParts.py RESEARCH_DIRECTORY OUTPUT_CS
Native detailed component identities correspond one-to-one across the two LODs.
"""
from pathlib import Path
import hashlib
import json
import sys
import numpy as np

r, output = map(Path, sys.argv[1:])
levels = [[p for p in json.loads((r / f'pedestrian02-main-{lod}-parts.json').read_text())
           if p['crossing']] for lod in range(2)]
assert len(levels[0]) == len(levels[1]) == 184
selected = []
for index, p in enumerate(levels[0]):
    lo, hi = p['minimum'], p['maximum']
    # Reviewed exceptions: joined pier caps, fixed/moving road bodies, hinge
    # supports, and the road-adjacent transverse/longitudinal bases. The two
    # reviewed 104-vertex hinge covers are complete transverse members.
    joined = len(p['vertices']) in (127, 455, 151, 678, 680)
    base = (lo[1] == 9.39990234375 and hi[1] == 9.699951171875) or (
        lo[1] == 9.49658203125 and hi[1] == 9.699951171875)
    if not joined and not base:
        selected.append(index)
assert len(selected) == 156
for near, middle in zip(*levels):
    a, b = np.array(near['minimum'] + near['maximum']), np.array(middle['minimum'] + middle['maximum'])
    assert np.max(abs(a - b)) <= .009521484375
    assert a[0] == b[0] and a[3] == b[3]

lines = ['// Native PedestrianDrawBridge02 transverse members, game 1.6.2f1.',
         '// Generated by PedestrianDraw02TransverseParts.py; excludes road/base/joined shells.',
         'using System;', 'using UnityEngine;', '', 'namespace BridgeBuilder.Bridges;', '',
         'internal static class PedestrianDraw02TransverseParts', '{',
         '    internal static void Apply(int lod, Vector3[] source, Vector3[] positions, float delta)',
         '    {', '        var data = lod switch', '        {',
         '            0 => (Count: 40168, Parts: Near),',
         '            1 => (Count: 32137, Parts: Middle),',
         '            _ => throw new ArgumentOutOfRangeException(nameof(lod))', '        };',
         '        if (!float.IsFinite(delta) || source.Length != data.Count || positions.Length != data.Count)',
         '            throw new InvalidOperationException("PedestrianDraw02 transverse parts require their recorded main mesh.");',
         '        foreach (var part in data.Parts)', '        {',
         '            var span = part.Max - part.Min;',
         '            foreach (var i in part.Vertices)',
         '                positions[i].x = source[i].x + (2f * source[i].x - part.Min - part.Max) / span * delta;',
         '        }', '    }', '']
def literal(x):
    return format(float(np.float32(x)), '.9g') + 'f'
for lod, field in enumerate(('Near', 'Middle')):
    d = np.load(r / f'pedestrian02-main-{lod}.npz')
    v = d['positions']
    name = 'PedestrianDrawBridge02' + ('_LOD1' if lod else '') + ' Mesh.Geometry'
    lines += ['    // Geometry SHA-256: ' + hashlib.sha256((r / 'movable-skin' / name).read_bytes()).hexdigest(),
              f'    private static readonly (float Min, float Max, int[] Vertices)[] {field} =', '    {']
    used = set()
    for index in selected:
        p = levels[lod][index]
        ids = p['vertices']
        assert not used.intersection(ids)
        used.update(ids)
        lo, hi = p['minimum'][0], p['maximum'][0]
        assert np.array_equal(v[ids].min(0), p['minimum'])
        assert np.array_equal(v[ids].max(0), p['maximum'])
        weights = (2 * v[ids, 0].astype(float) - lo - hi) / (hi - lo)
        for delta in (-6., -4., -.5, 0., 2., 8.):
            moved = v[ids].astype(float)
            moved[:, 0] += weights * delta
            assert np.array_equal(moved[:, 1:], v[ids, 1:])
            assert abs(np.ptp(moved[:, 0]) - abs(hi - lo + 2 * delta)) < 1e-10
            assert hi - lo > 0
        lines += [f'        ({literal(lo)}, {literal(hi)}, new[]', '        {']
        for start in range(0, len(ids), 20):
            lines.append('            ' + ', '.join(map(str, ids[start:start+20])) + ',')
        lines += ['        }),']
    lines += ['    };', '']
    print(f'LOD{lod}: {len(selected)} corresponding members / {len(used)} vertices; six signed own-span checks passed')
lines += ['}', '']
output.write_text('\n'.join(lines), encoding='utf-8')
