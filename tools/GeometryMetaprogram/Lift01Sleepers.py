"""Record whole native sleeper faces replaced by selected-network track visuals.
Usage: python Lift01Sleepers.py RESEARCH_DIRECTORY OUTPUT_CS
The 240 low-profile transverse trapezoids were reviewed in native near geometry.
This does not remove longitudinal rails or the road-bearing structural shell.
"""
from pathlib import Path
import hashlib
import json
import sys
import numpy as np

r, output = map(Path, sys.argv[1:])
groups = [json.loads((r / f'lift01-crossing-{lod}.json').read_text()) for lod in (0, 1)]
chosen = [i for i, p in enumerate(groups[0])
          if p['minimum'][0] == -1.350006103515625 and p['maximum'][0] == 1.350006103515625
          and p['minimum'][1] == 9.800048828125 and p['maximum'][1] == 9.86962890625]
assert len(chosen) == 240
audit = json.loads((r / 'lift-native-road-plane-candidates.json').read_text())
tables = []
for lod in (0, 1):
    data = np.load(r / f'lift01-main-{lod}.npz')
    v, f = data['positions'], data['indices']
    selected = np.zeros(len(v), dtype=bool)
    for i in chosen:
        group = groups[lod][i]
        assert group['minimum'] == groups[0][i]['minimum']
        assert group['maximum'] == groups[0][i]['maximum']
        ids = group['vertices']
        assert not selected[ids].any()
        selected[ids] = True
        assert np.array_equal(v[ids].min(0), group['minimum'])
        assert np.array_equal(v[ids].max(0), group['maximum'])
    membership = selected[f].sum(1)
    assert not np.any((membership != 0) & (membership != 3))
    faces = np.flatnonzero(membership == 3).tolist()
    record = next(x for x in audit if x['style'] == 1 and x['lod'] == lod)
    digest = hashlib.sha256((r / 'movable-skin' / record['geometry']).read_bytes()).hexdigest()
    assert digest.lower() == record['sha256'].lower()
    tops = {i for c in record['candidates'] if c['bone'] in (0, 4)
            and c['y'] == 9.800048828125 for i in c['faces']}
    assert tops.isdisjoint(faces)
    ranges = []
    for i in faces:
        if ranges and ranges[-1][1] + 1 == i:
            ranges[-1][1] = i
        else:
            ranges.append([i, i])
    assert [i for a, b in ranges for i in range(a, b+1)] == faces
    tables.append((len(f), ranges, digest))
    print(f'LOD{lod}: 240 complete sleepers, {len(faces)} faces, no shared structural/top faces.')

lines = ['// Generated by Lift01Sleepers.py from reviewed native sleeper groups.',
         '// Only whole original triangles are removed; no runtime spatial selection.',
         'using System;', '', 'namespace BridgeBuilder.Bridges;', '',
         'internal static class Lift01SleeperRemoval', '{',
         '    internal static void Remove(int lod, bool[] removed)', '    {',
         '        var data = lod switch', '        {']
for lod, (count, _, _) in enumerate(tables):
    lines.append(f'            {lod} => (Count: {count}, Ranges: Lod{lod}),')
lines += ['            _ => throw new ArgumentOutOfRangeException(nameof(lod))', '        };',
          '        if (removed.Length != data.Count)',
          '            throw new InvalidOperationException("Lift01 sleeper source layout changed.");',
          '        foreach (var range in data.Ranges)',
          '            for (var i = range.First; i <= range.Last; i++) removed[i] = true;',
          '    }', '']
for lod, (_, ranges, digest) in enumerate(tables):
    lines += [f'    // Geometry SHA-256: {digest}',
              f'    private static readonly (int First, int Last)[] Lod{lod} =', '    {']
    lines += [f'        ({a}, {b}),' for a, b in ranges]
    lines += ['    };', '']
lines += ['}']
output.write_text('\n'.join(lines)+'\n', encoding='utf-8')
