"""Emit measured side-part vertex ranges for both Lift01 main LODs.
Usage: python Lift01RigidParts.py RESEARCH_DIRECTORY OUTPUT_CS
Connected-part identification and LOD correspondence are offline only. Crossing
members, including joined road/base shells, require separate deformation plans.
"""
from pathlib import Path
import hashlib
import json
import sys
import numpy as np

r, output = map(Path, sys.argv[1:])
levels = []
for lod in range(2):
    data = np.load(r / f'lift01-main-{lod}.npz')
    v, faces = data['positions'], data['indices']
    assert (len(v), len(faces)) == ((472209, 380478), (351968, 228254))[lod]
    parent = list(range(len(v)))
    def root(i):
        while parent[i] != i:
            parent[i] = parent[parent[i]]
            i = parent[i]
        return i
    def join(a, b):
        parent[root(int(a))] = root(int(b))
    for a, b, c in faces:
        join(a, b)
        join(a, c)
    seen = {}
    for i, p in enumerate(v):
        key = tuple(p.round(4))
        if key in seen:
            join(i, seen[key])
        else:
            seen[key] = i
    groups = {}
    for i in range(len(v)):
        groups.setdefault(root(i), []).append(i)
    sides = []
    signs = np.zeros(len(v), dtype=np.int8)
    for ids in groups.values():
        p = v[ids]
        lo, hi = p.min(0), p.max(0)
        if lo[0] <= 0 <= hi[0]:
            continue
        sign = -1 if hi[0] < 0 else 1
        signs[ids] = sign
        sides.append((ids, lo, hi, sign))
    print('Identified', lod, len(sides), int(np.count_nonzero(signs)), flush=True)
    (r / f'lift01-side-{lod}.json').write_text(json.dumps([
        dict(vertices=p[0], minimum=p[1].tolist(), maximum=p[2].tolist(), side=p[3])
        for p in sides]), encoding='utf-8')
    crossing = []
    for ids in groups.values():
        points = v[ids]
        lo, hi = points.min(0), points.max(0)
        if lo[0] <= 0 <= hi[0]:
            crossing.append(dict(vertices=ids, minimum=lo.tolist(), maximum=hi.tolist()))
    (r / f'lift01-crossing-{lod}.json').write_text(json.dumps(crossing), encoding='utf-8')
    levels.append((v, sides, signs))

# Native authored order is preserved at both levels. Verify each same-order
# group is a nearest envelope match, stays on the same side, and retains the
# same bone-group signature. Simplified middle geometry is not necessarily contained by
# the detailed envelope; measured maximum coordinate difference is 0.05078125 m.
near, middle = levels[0][1], levels[1][1]
assert len(near) == len(middle) == 9926
assert [p[3] for p in near] == [p[3] for p in middle]
a = np.array([np.r_[p[1], p[2]] for p in near])
b = np.array([np.r_[p[1], p[2]] for p in middle])
assert np.max(abs(a-b)) == .05078125
for start in range(0, len(b), 64):
    distances = np.sum((b[start:start+64, None, :] - a[None, :, :])**2, axis=2)
    for row in range(len(distances)):
        assert distances[row, start+row] <= distances[row].min() + 1e-12
part_bones = []
for lod, (v, parts, signs) in enumerate(levels):
    name = 'LiftBridge01' + ('_LOD1' if lod else '') + ' Mesh.mesh-0.obj'
    vertex_bones = np.zeros(len(v), dtype=int)
    bone = -1
    for line in (r / 'movable-skin' / name).open():
        if line.startswith('g '):
            group = line.split()[1]
            bone = int(group[5:]) if group.startswith('bone_') else -1
        elif line.startswith('f '):
            for value in line.split()[1:]:
                i = int(value.split('/')[0])-1
                vertex_bones[i] |= 1 << (bone + 1)
    owned = []
    for ids, *_ in parts:
        assert np.all(vertex_bones[ids] != 0)
        owned.append(int(np.bitwise_or.reduce(vertex_bones[ids])))
    part_bones.append(owned)
assert part_bones[0] == part_bones[1]
assert [int(np.count_nonzero(level[2])) for level in levels] == [396744, 291054]

def ranges(ids):
    result = []
    for i in ids:
        i = int(i)
        if result and result[-1][1] + 1 == i:
            result[-1][1] = i
        else:
            result.append([i, i])
    return result

lines = ['// Native LiftBridge01 mesh-0 authored side parts, game 1.6.2f1.',
         '// Generated by Lift01RigidParts.py; no runtime spatial classification.',
         'using System;', 'using UnityEngine;', '', 'namespace BridgeBuilder.Bridges;', '',
         'internal static class Lift01RigidParts', '{',
         '    internal static void Apply(int lod, Vector3[] source, Vector3[] positions, float delta)',
         '    {', '        var data = lod switch', '        {',
         '            0 => (Count: 472209, Left: Left0, Right: Right0),',
         '            1 => (Count: 351968, Left: Left1, Right: Right1),',
         '            _ => throw new ArgumentOutOfRangeException(nameof(lod))', '        };',
         '        if (!float.IsFinite(delta) || source.Length != data.Count || positions.Length != data.Count)',
         '            throw new InvalidOperationException("Lift01 rigid parts require their recorded main mesh.");',
         '        foreach (var range in data.Left)',
         '            for (var i = range.First; i <= range.Last; i++) positions[i].x = source[i].x - delta;',
         '        foreach (var range in data.Right)',
         '            for (var i = range.First; i <= range.Last; i++) positions[i].x = source[i].x + delta;',
         '    }', '']
for lod, (v, parts, signs) in enumerate(levels):
    name = 'LiftBridge01' + ('_LOD1' if lod else '') + ' Mesh.Geometry'
    lines += ['    // Geometry SHA-256: ' + hashlib.sha256((r / 'movable-skin' / name).read_bytes()).hexdigest()]
    for side, label in ((-1, 'Left'), (1, 'Right')):
        ids = np.flatnonzero(signs == side)
        intervals = ranges(ids)
        assert [i for a, b in intervals for i in range(a, b + 1)] == ids.tolist()
        lines += [f'    private static readonly (int First, int Last)[] {label}{lod} =', '    {']
        lines += [f'        ({a}, {b}),' for a, b in intervals]
        lines += ['    };', '']
    for delta in (-.5, 0., 2., 8.):
        moved = v.copy()
        moved[:, 0] += signs * delta
        assert np.array_equal(moved[:, 1:], v[:, 1:])
        assert np.array_equal(moved[signs == 0], v[signs == 0])
        for ids, lo, hi, side in parts:
            assert np.allclose(moved[ids] - v[ids], [side * delta, 0, 0], atol=2e-6)
    print(f'LOD{lod}: {len(parts)} side parts / {np.count_nonzero(signs)} vertices; '
          'rigid displacement and untouched crossing vertices passed at four widths')
lines += ['}', '']
output.write_text('\n'.join(lines), encoding='utf-8')
print('All 9926 middle side parts retain nearest detailed envelope, side and bone correspondence.')
