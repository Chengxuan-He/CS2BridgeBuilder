"""Emit the measured Lift03 detailed upper/lower road-adjacent base maps.
Usage: python Lift03DeckBases.py RESEARCH_DIRECTORY OUTPUT_CS
Far merged structures are intentionally outside this detailed-only map.
"""
from pathlib import Path
import hashlib, json, sys
import numpy as np
r, output = map(Path, sys.argv[1:])
rows = json.loads((r/'lift03-main-parts.json').read_text())
hashes = ('f8bc2882fcba043d1d57a17fd27a43631b492ab4292f8fc6b9c3beeb00af53cd', '455d25f8ec83f91ea097551fb09a9f41abc79e9f15e836b19c0a527ad50ff9fa')
parts = (65, 66, 778, 779, 2826, 2827)
counts = ((320,612,320,612,1992,1812),(144,273,144,269,956,1176))
triangles = ((250,624,250,624,1520,1964),(80,159,80,157,492,900))
lines = ['// Measured native Lift03 road-adjacent bases; generated by Lift03DeckBases.py.', 'using System;', 'using UnityEngine;', '', 'namespace BridgeBuilder.Bridges;', '', 'internal static class Lift03DeckBases', '{', '    internal static void Apply(int lod, Vector3[] source, Vector3[] positions, float upperDelta, float lowerDelta)', '    {', '        var data = lod switch', '        {']
tables = []
for lod in range(2):
 row = next(x for x in rows if x['lod']==lod and x['mesh']==0)
 assert hashlib.sha256((r/'movable-skin'/(row['source']+'.Geometry')).read_bytes()).hexdigest()==hashes[lod]
 d = np.load(r/f'lift03-main-{lod}-0.npz'); v,f,c = d['positions'],d['indices'],d['component']
 bones=[]; bone=None
 for line in (r/'movable-skin'/(row['source']+'.mesh-0.obj')).read_text().splitlines():
  if line.startswith('g '): bone=line.split()[1]
  elif line.startswith('f '): bones.append(bone)
 bones=np.array(bones); selected=np.zeros(len(v),dtype=bool); upper=np.zeros(len(v),dtype=bool)
 for n,part in enumerate(parts):
  mask=c==part; ids=np.flatnonzero(mask); touched=mask[f].any(1)
  assert len(ids)==counts[lod][n] and touched.sum()==triangles[lod][n]
  assert np.all(mask[f[touched]])
  assert v[ids,0].min()<0<v[ids,0].max()
  assert len(set(bones[touched]))==1
  selected |= mask
  if n%2==0: upper |= mask
  print(f'LOD{lod} part {part}: {len(ids)} vertices, {touched.sum()} triangles, {set(bones[touched])}')
 signs=np.sign(v[:,0]); sf=f[selected[f].any(1)]
 for ud,ld in ((0,0),(2,2),(8,2),(2,8),(-.25,-.25)):
  q=v.copy(); q[selected,0]+=signs[selected]*np.where(upper[selected],ud,ld)
  assert np.array_equal(q[:,1:],v[:,1:]) and np.array_equal(q[~selected],v[~selected])
  a,b=v[sf],q[sf]; na=np.cross(a[:,1]-a[:,0],a[:,2]-a[:,0]); nb=np.cross(b[:,1]-b[:,0],b[:,2]-b[:,0]); valid=np.linalg.norm(na,axis=1)>1e-10
  assert np.all(np.sum(na[valid]*nb[valid],axis=1)>0)
 ranges=[]
 for i in np.flatnonzero(selected):
  sign=int(signs[i]); deck=bool(upper[i])
  if ranges and ranges[-1][1]==i-1 and ranges[-1][2:]==[sign,deck]: ranges[-1][1]=int(i)
  else: ranges.append([int(i),int(i),sign,deck])
 tables.append(ranges); lines.append(f'            {lod} => (Count: {len(v)}, Parts: Level{lod}),')
 np.savez(r/f'lift03-deck-bases-{lod}.npz',selected=selected,upper=upper,weights=signs*selected)
 print(f'PASS LOD{lod}: five independent deck-width pairs; original topology/YZ and winding')
lines += ['            _ => throw new ArgumentOutOfRangeException(nameof(lod))', '        };', '        if (source.Length != data.Count || positions.Length != data.Count || !float.IsFinite(upperDelta) || !float.IsFinite(lowerDelta))', '            throw new InvalidOperationException("Lift03 detailed bases require their recorded native topology.");', '        foreach (var part in data.Parts)', '            for (var i = part.First; i <= part.Last; i++)', '                positions[i].x = source[i].x + part.Sign * (part.Upper ? upperDelta : lowerDelta);', '    }', '']
for lod,ranges in enumerate(tables):
 lines += ['    // Geometry SHA-256: '+hashes[lod], f'    private static readonly (int First, int Last, int Sign, bool Upper)[] Level{lod} =', '    {']
 lines += [f'        ({a}, {b}, {s}, {str(u).lower()}),' for a,b,s,u in ranges]
 lines += ['    };','']
lines += ['}','']; output.write_text('\n'.join(lines),encoding='utf-8')
