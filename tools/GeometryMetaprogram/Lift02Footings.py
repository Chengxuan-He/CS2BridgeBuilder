"""Emit Lift02 continuous foundation own-span transforms at each native LOD.
Usage: python Lift02Footings.py RESEARCH_DIRECTORY OUTPUT_CS
The two chamfered foundations cross the centre; they are not side columns.
"""
from pathlib import Path
import hashlib,json,sys
import numpy as np
r,output=map(Path,sys.argv[1:])
audit=json.loads((r/'all-movable-audit.json').read_text())
levels=[]
for lod in range(3):
 name='LiftBridge02PillarBase'+(f'_LOD{lod}' if lod else '')+' Mesh.Geometry'
 digest=hashlib.sha256((r/'movable-skin'/name).read_bytes()).hexdigest()
 assert any(a.get('sha256')==digest for a in audit['assets'].values())
 data=np.load(r/f'lift02-support-1-{lod}.npz');v=data['positions'].astype(float);f=data['indices'];groups=data['component']
 assert v.shape==((724,692,132)[lod],3) and f.shape==((664,597,100)[lod],3)
 assert set(groups)=={0,1} and np.all(groups[f]==groups[f[:,:1]])
 weights=np.zeros(len(v));spans=[]
 for group in range(2):
  ids=np.flatnonzero(groups==group);x=v[ids,0];left=-x.min();right=x.max();assert left>20 and right>20
  spans.append((left,right));weights[ids]=np.where(x<0,x/left,x/right)
 weights=weights.astype(np.float32)
 p=v[f];n=np.cross(p[:,1]-p[:,0],p[:,2]-p[:,0]);active=np.linalg.norm(n,axis=1)>1e-9
 for delta in (-4.99,-4,-3,-1,0,2,8):
  moved=v.copy();moved[:,0]+=weights.astype(float)*delta
  assert np.array_equal(v[:,1:],moved[:,1:])
  q=moved[f];after=np.cross(q[:,1]-q[:,0],q[:,2]-q[:,0]);assert np.all(np.sum(n[active]*after[active],axis=1)>0)
  for group in range(2):
   ids=np.flatnonzero(groups==group)
   assert abs(moved[ids,0].min()-(v[ids,0].min()-delta))<1e-8
   assert abs(moved[ids,0].max()-(v[ids,0].max()+delta))<1e-8
  coincident={}
  for position,weight in zip(v,weights):
   key=tuple(position)
   if key in coincident:assert coincident[key]==weight
   coincident[key]=weight
 levels.append((digest,len(v),f.size,weights,spans))
 print(f'LOD{lod}: two foundations, {len(v)} vertices, {len(f)} unchanged triangles; own spans {spans}; seven-width signed mapping/bounds/seams passed')
lines=['// Native LiftBridge02 continuous chamfered foundations, game 1.6.2f1.', '// Generated by Lift02Footings.py; immutable own-span weights, no runtime classifier.', 'using System;', 'using UnityEngine;', '', 'namespace BridgeBuilder.Bridges;', '', 'internal static class Lift02FootingGeometry', '{', '    internal static MovableStructureModel.Plan Create(int lod, Vector3[] source, int[] indices, float delta)', '    {', '        var data = lod switch', '        {']
for lod,(_,count,indexcount,_,_) in enumerate(levels):lines.append(f'            {lod} => (Count: {count}, Indices: {indexcount}, Weights: Weights{lod}),')
minimum=min(min(pair) for level in levels for pair in level[4])
lines+=['            _ => throw new ArgumentOutOfRangeException(nameof(lod))', '        };', f'        if (!float.IsFinite(delta) || source.Length != data.Count || indices.Length != data.Indices)', '            throw new InvalidOperationException("Lift02 foundation requires its recorded layout.");', '        var positions = (Vector3[])source.Clone();', '        for (var i = 0; i < positions.Length; i++) positions[i].x += data.Weights[i] * delta;', '        return new MovableStructureModel.Plan(source, positions, new[] { indices }, new[] { new bool[indices.Length / 3] });', '    }', '']
for lod,(digest,count,indexcount,weights,spans) in enumerate(levels):
 lines+=['    // Geometry SHA-256: '+digest, f'    private static readonly float[] Weights{lod} =', '    {']
 for i in range(0,len(weights),8):lines.append('        '+', '.join(format(float(w),'.9g')+'f' for w in weights[i:i+8])+',')
 lines+=['    };','']
lines+=['}',''];output.write_text('\n'.join(lines),encoding='utf-8')
