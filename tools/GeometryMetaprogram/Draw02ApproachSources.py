"""Reconstruct measured Draw02 approach NetPiece/LOD inputs from the native audit.
Usage: python Draw02ApproachSources.py AUDIT_JSON OUTPUT_CS
"""
from pathlib import Path
import hashlib
import json
import struct
import sys

audit, output = map(Path, sys.argv[1:])
digest = hashlib.sha256(audit.read_bytes()).hexdigest()
assert digest == '47ef0f1723e8643e74a17751aa480f97260bf6e549aa60ec9f14f8e003b12070'
records = json.loads(audit.read_text(encoding='utf-8'))['selected']
roots = [79429, 79432, 79436, 79439, 79423, 79426, 79435, 79442, 79445]

def number(v): return format(float(v), '.17g') + 'f'
def vector(v):
    keys = 'xyzw' if 'w' in v else 'xyz'
    return f'new float{len(keys)}(' + ', '.join(number(v[k]) for k in keys) + ')'
def cid(v):
    raw = struct.pack('<4i', *(v[f'm_GuidPart{i}'] for i in range(1,5)))
    return json.dumps(''.join(f'{b&15:x}{b>>4:x}' for b in raw))
def resolve(ref): return records[str(ref['m_PathID'])]['data']
def components(d): return {c['name']: resolve(c) for c in d['components']}

lines = ['// Native DrawBridge02 approach pieces, game 1.6.2f1.',
         '// Audit SHA-256: ' + digest,
         '// Generated by tools/GeometryMetaprogram/Draw02ApproachSources.py.',
         'using Colossal.Mathematics;', 'using Game.Prefabs;', 'using Unity.Mathematics;',
         '', 'namespace BridgeBuilder.Bridges;', '',
         'internal sealed class Draw02ApproachSources : MovableSourceRenders', '{',
         '    internal Draw02ApproachSources(ContentPrefab content)', '    {', '        try', '        {']
total = 0
for part, identity in enumerate(roots):
    root = records[str(identity)]['data']
    cs = components(root)
    lods = cs.get('LodProperties')
    levels = [root] + ([resolve(r) for r in lods['m_LodMeshes']] if lods else [])
    assert len(levels) == (1 if part == 6 else 3)
    for lod, data in enumerate(levels):
        key = f'p{part}l{lod}'
        assert data['m_IsImpostor'] == 0 and data['m_ManualVTRequired'] == 0
        assert data['m_MeshCount'] == 1 and len(data['m_SurfaceAssets']) == 1
        typ = 'NetPiecePrefab' if lod == 0 else 'RenderPrefab'
        lines += [f'            var {key} = Create<{typ}>({json.dumps(data["m_Name"])}, {cid(data["m_GeometryAsset"])},',
                  f'                new[] {{ {cid(data["m_SurfaceAssets"][0])} }},',
                  f'                new Bounds3({vector(data["m_Bounds"]["min"])}, {vector(data["m_Bounds"]["max"])}),',
                  f'                {data["m_VertexCount"]}, {data["m_IndexCount"]}, 1, {number(data["m_SurfaceArea"])});']
        if lod == 0:
            lines += [f'            {key}.m_Layer = (NetPieceLayer){data["m_Layer"]};']
            for field in ('m_Width','m_Length','m_WidthOffset','m_NodeOffset','m_SideConnectionOffset'):
                lines += [f'            {key}.{field} = {number(data[field])};']
            h = data['m_HeightRange']
            lines += [f'            {key}.m_HeightRange = new Bounds1({number(h["min"])}, {number(h["max"])});',
                      f'            {key}.m_SurfaceHeights = {vector(data["m_SurfaceHeights"])};']
        for name, c in components(data).items():
            assert c['active'] == 1
            if name == 'LodProperties': continue
            if name == 'ContentPrerequisite':
                assert c['m_ContentPrerequisite']['name'] == 'BridgesAndPorts'
                lines += [f'            {key}.AddComponent<ContentPrerequisite>().m_ContentPrerequisite = content;']
            elif name == 'PlaceableNetPiece':
                lines += [f'            var cost{part} = {key}.AddComponent<PlaceableNetPiece>();']
                for field in ('m_ConstructionCost','m_ElevationCost','m_UpkeepCost'):
                    value = number(c[field]) if field == 'm_UpkeepCost' else str(c[field])
                    lines += [f'            cost{part}.{field} = {value};']
            elif name == 'AsymmetricPieceMesh':
                lines += [f'            var asym{part}l{lod} = {key}.AddComponent<AsymmetricPieceMesh>();']
                for field in ('m_Sideways','m_Lengthwise'):
                    lines += [f'            asym{part}l{lod}.{field} = {str(bool(c[field])).lower()};']
            else: raise AssertionError(name)
        total += 1
    if lods:
        lines += [f'            var lod{part} = p{part}l0.AddComponent<LodProperties>();',
                  f'            lod{part}.m_Bias = {number(lods["m_Bias"])};',
                  f'            lod{part}.m_ShadowBias = {number(lods["m_ShadowBias"])};',
                  f'            lod{part}.m_LodMeshes = new[] {{ p{part}l1, p{part}l2 }};']
lines += ['            Roots = new RenderPrefab[] { ' + ', '.join(f'p{i}l0' for i in range(len(roots))) + ' };',
          '        }', '        catch { Dispose(); throw; }', '    }', '}', '']
output.write_text('\n'.join(lines), encoding='utf-8')
print(f'Emitted {len(roots)} approach families / {total} native renders with complete recorded components.')

# Retain only prototype structural pieces. Selected-road traffic/sidewalk pieces
# are supplied separately by the road conversion, never copied from this prototype.
def requirements(values):
    return ('Array.Empty<NetPieceRequirements>()' if not values else
            'new[] { ' + ', '.join('NetPieceRequirements.' + value for value in values) + ' }')

section_ids = [118585,118586,118587,118588,118589]
layout = ['// Native DrawBridge02 structural approach layout, game 1.6.2f1.',
          '// Audit SHA-256: ' + digest,
          '// Generated by tools/GeometryMetaprogram/Draw02ApproachSources.py.',
          'using System;', 'using System.Linq;', 'using Game.Prefabs;', 'using Unity.Mathematics;',
          'using UnityEngine;', '', 'namespace BridgeBuilder.Bridges;', '',
          'internal static class Draw02ApproachLayout', '{',
          '    // The caller supplies widened, factory-owned pieces in recorded family order.',
          '    internal static void Apply(NetGeometryPrefab target, TowerFactory factory, NetPiecePrefab[] pieces, float layoutRemainder)',
          '    {',
          '        if (pieces.Length != 9 || pieces.Any(piece => piece == null || !factory.Created.Contains(piece)))',
          '            throw new InvalidOperationException("Draw02 approaches require nine owned structural pieces.");']
for i, identity in enumerate(section_ids):
    d = records[str(identity)]['data']
    structural = [p for p in d['m_Pieces'] if p['m_Piece']['m_PathID'] in roots]
    assert len(structural) == (1 if i == 2 else 2)
    layout += [f'        var section{i} = ScriptableObject.CreateInstance<NetSectionPrefab>();',
               f'        section{i}.name = target.name + " Fixed Approach Section {i}";',
               f'        factory.AdoptMovableSections(new PrefabBase[] {{ section{i} }});',
               f'        section{i}.m_SubSections = Array.Empty<NetSubSectionInfo>();',
               f'        section{i}.m_Pieces = new[]', '        {']
    for piece in structural:
        layout += ['            new NetPieceInfo', '            {',
                   f'                m_Piece = pieces[{roots.index(piece["m_Piece"]["m_PathID"])}],',
                   f'                m_Offset = {vector(piece["m_Offset"])},']
        for field in ('m_RequireAll','m_RequireAny','m_RequireNone'):
            layout += [f'                {field} = {requirements(piece[field])},']
        layout += ['            },']
    layout += ['        };']
layout += ['        var overhead = target.AddOrGetComponent<OverheadNetSections>();',
           '        overhead.m_Sections = new[]', '        {']
occurrences = records['118590']['data']['m_Sections']
assert len(occurrences) == 27
# Native overhead accumulation: compensate only the layout-width remainder.
for branch in range(3):
    active = occurrences[branch::3]
    widths = []
    for item in active:
        section = records[str(item['m_Section']['m_PathID'])]['data']
        structural = [p for p in section['m_Pieces'] if p['m_Piece']['m_PathID'] in roots]
        candidates = [resolve(p['m_Piece'])['m_Width'] for p in structural]
        assert len(set(candidates)) == 1
        widths.append(candidates[0])
    for delta in (-12., -8., -4., -3., -2., 0., 2., 8.):
        signed = [w+delta if x['m_Section']['m_PathID']==section_ids[0] else w for x,w in zip(active,widths)]
        physical = [max(0.,w) for w in signed]
        remainder = min(0.,3.+delta)
        def centres(values):
            cursor=-sum(values)/2
            result=[]
            for w in values:
                result.append(cursor+w/2)
                cursor+=w
            return result
        expected, actual = centres(signed), centres(physical)
        for i,x in enumerate(active):
            factor=0 if x['m_Median'] else .5 if x['m_Section']['m_PathID']==section_ids[0] else 1
            actual[i]+=(-1 if x['m_Invert'] else 1)*factor*remainder
        assert all(abs(a-b)<1e-10 for a,b in zip(actual,expected))
        assert min(physical)>=0
print('PASS 24 overhead-layout cases: signed origins retained with nonnegative sizes.')
for item in occurrences:
    layout += ['            new NetSectionInfo', '            {',
               f'                m_Section = section{section_ids.index(item["m_Section"]["m_PathID"])},',
               f'                m_HiddenLayers = (NetPieceLayerMask)({item["m_HiddenLayers"]}),',
               f'                m_Offset = {vector(item["m_Offset"])} + new float3({(-1 if item["m_Invert"] else 1) * (0 if item["m_Median"] else .5 if item["m_Section"]["m_PathID"] == section_ids[0] else 1):g}f * layoutRemainder, 0f, 0f),']
    for field in ('m_Invert','m_Flip','m_Median','m_HalfLength'):
        layout += [f'                {field} = {str(bool(item[field])).lower()},']
    for field in ('m_RequireAll','m_RequireAny','m_RequireNone'):
        values = item[field]
        if field == 'm_RequireAll': values = list(dict.fromkeys(values + ['Elevated']))
        layout += [f'                {field} = {requirements(values)},']
    layout += ['            },']
layout += ['        };', '        overhead.active = true;', '    }', '}', '']
output.with_name('Draw02ApproachLayout.g.cs').write_text('\n'.join(layout), encoding='utf-8')
print('Emitted five structural sections and all 27 native occurrence branches.')
