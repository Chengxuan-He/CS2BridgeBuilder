"""Retain six measured native road-end lips in the Lift01 far supplement.
Usage: python Lift01FarEndLips.py RESEARCH_DIRECTORY OUTPUT_CS
Run Lift01FarTowerCore.py first to check disjoint ownership against its output.
"""
from pathlib import Path
import hashlib
import json
import sys
import numpy as np

r, output = map(Path, sys.argv[1:])
digest = hashlib.sha256((r / 'movable-skin/LiftBridge01_LOD1 Mesh.Geometry').read_bytes()).hexdigest()
assert digest == 'c5694dce731ce05218de15761665cc1d234723049c48bd707c87587509ed8e4e'
d = np.load(r / 'lift01-main-1.npz')
v, faces = d['positions'], d['indices']
assert v.shape == (351968, 3) and faces.shape == (228254, 3)
parts = json.loads((r / 'lift01-crossing-1.json').read_text())
near = json.loads((r / 'lift01-crossing-0.json').read_text())
bones, bone = {}, None
for line in (r / 'movable-skin/LiftBridge01_LOD1 Mesh.mesh-0.obj').read_text().splitlines():
    fields = line.split()
    if fields and fields[0] == 'g':
        bone = fields[1]
    elif fields and fields[0] == 'f':
        for item in fields[1:]:
            bones.setdefault(int(item.split('/')[0])-1, set()).add(bone)
selected = (30, 31, 32, 33, 493, 640)
ids, kept = [], []
for ordinal, count in zip(selected, (82, 88, 80, 86, 84, 84)):
    part = parts[ordinal]
    assert len(part['vertices']) == count
    assert part['minimum'] == near[ordinal]['minimum'] and part['maximum'] == near[ordinal]['maximum']
    assert all(bones[i] == {f'bone_{4 if ordinal in (493, 640) else 0}'} for i in part['vertices'])
    member = np.isin(faces, part['vertices'])
    assert not np.any(member.any(1) & ~member.all(1))
    owned = np.flatnonzero(member.all(1))
    assert len(owned) == 48
    ids.extend(part['vertices'])
    kept.extend(map(int, owned))
assert len(ids) == len(set(ids)) == 504
assert len(kept) == len(set(kept)) == 288
core = np.load(r / 'lift01-far-tower-core-0.npz')
assert set(ids).isdisjoint(map(int, core['indices'].flat))
road = next(x for x in json.loads((r / 'lift-native-road-plane-candidates.json').read_text())
            if x['style'] == 1 and x['lod'] == 1)
for candidate in road['candidates']:
    if candidate['bone'] in (0, 4) and candidate['y'] == 9.800048828125:
        assert set(kept).isdisjoint(candidate['faces'])
ids = np.asarray(sorted(ids))
weights = np.sign(v[ids, 0])
weights[abs(v[ids, 0]) < .00001] = 0
minimum = float(abs(v[ids[weights != 0], 0]).min())
for delta in (-2.99, -2.75, -2, -.1, 0, 2, 8):
    moved = v.copy()
    moved[ids, 0] += weights * delta
    a, b = v[faces[kept]].astype(float), moved[faces[kept]].astype(float)
    n0 = np.cross(a[:, 1]-a[:, 0], a[:, 2]-a[:, 0])
    n1 = np.cross(b[:, 1]-b[:, 0], b[:, 2]-b[:, 0])
    valid = np.linalg.norm(n0, axis=1) > 1e-8
    assert np.isfinite(moved).all()
    if delta > -minimum: assert np.all(np.sum(n0[valid]*n1[valid], axis=1) > 0)
    assert np.array_equal(moved[:, 1:], v[:, 1:])
    if delta == 0:
        assert np.array_equal(moved, v)
    np.savez(r / f'lift01-far-end-lips-{delta}.npz', positions=moved, indices=faces[kept])

def ranges(values):
    result = []
    for i in sorted(map(int, values)):
        if result and result[-1][1] + 1 == i:
            result[-1][1] = i
        else:
            result.append([i, i])
    return result

lines = ['// Six native Lift01 road-end lips; original Surface and bones 0/4.',
         '// Generated by Lift01FarEndLips.py. Geometry SHA-256: ' + digest,
         'using System;', 'using System.Linq;', 'using UnityEngine;', '',
         'namespace BridgeBuilder.Bridges;', '', 'internal static class Lift01FarEndLips', '{',
         '    internal static MovableStructureModel.Plan Apply(MovableStructureModel.Plan plan, float delta)',
         '    {',
         '        if (plan.SourcePositions.Length != 351968 || plan.SourceIndices.Length != 1 ||',
         '            plan.SourceIndices[0].Length != 684762 || !float.IsFinite(delta))',
         '            throw new InvalidOperationException("Lift01 end lips require their recorded middle source.");',
         '        var positions = new Vector3[plan.SourcePositions.Length];',
         '        Array.Copy(plan.Positions, positions, positions.Length);',
         '        foreach (var item in Motion)',
         '            for (var i = item.First; i <= item.Last; i++)',
         '                positions[i].x = plan.SourcePositions[i].x + item.Weight * delta;',
         '        var remove = (bool[])plan.RemoveTriangles[0].Clone();',
         '        foreach (var range in Faces)',
         '            for (var i = range.First; i <= range.Last; i++) remove[i] = false;',
         '        return new MovableStructureModel.Plan(plan.SourcePositions, positions, plan.SourceIndices,',
         '            new[] { remove }, plan.AddedVertices, plan.Fragments, plan.InteriorVertices,',
         '            plan.Positions.Skip(positions.Length).Select(p => p.x).ToArray());',
         '    }', '', '    private static readonly (int First, int Last)[] Faces =', '    {']
lines += [f'        ({a}, {b}),' for a, b in ranges(kept)]
lines += ['    };', '', '    private static readonly (int First, int Last, int Weight)[] Motion =', '    {']
for weight in (-1, 0, 1):
    lines += [f'        ({a}, {b}, {weight}),' for a, b in ranges(ids[weights == weight])]
lines += ['    };', '}', '']
output.write_text('\n'.join(lines), encoding='utf-8')
print('Six end lips: 504 source vertices, 288 triangles; native bones, road/core exclusion and seven signed-width checks passed.')
