"""Record Draw03 native road/curb removal and retained exterior edge translation.
Usage: python Draw03RoadReplacement.py RESEARCH_DIR OUTPUT_CS
Only original near/middle road regions are covered; far requires its own plan.
"""
from pathlib import Path
import hashlib
import json
import sys
import numpy as np

r, output = map(Path, sys.argv[1:])
tables = []
for lod in range(2):
    name = 'DrawBridge03' + ('_LOD1' if lod else '') + ' Mesh.Geometry'
    digest = hashlib.sha256((r / 'movable-skin' / name).read_bytes()).hexdigest()
    assert digest == ('f7ecc824ad55745e791e40b18fd12f5def20657ed8ea56d373429d5a1337588f',
                      '15b8419da13d6e99e1dc0591f12f4019f0be09c3b220a481d24720daf7b57e12')[lod]
    d = np.load(r / f'draw03-main-{lod}.npz')
    v, faces = d['positions'].astype(float), d['indices']
    parts = [p for p in json.loads((r / f'draw03-parts-{lod}.json').read_text()) if not p['side']]
    removed, retained = [], []
    for part, bone in ((2, 0), (89, 0), (74, 1), (162, 2)):
        membership = np.isin(faces, parts[part]['vertices'])
        assert not np.any(membership.any(1) & ~membership.all(1))
        selected = np.flatnonzero(membership.all(1))
        assert set(d['bones'][selected]) == {bone}
        points = v[faces[selected]]
        interior = (np.abs(points[:, :, 0]).max(1) <= 12.5)
        road = interior & (points[:, :, 1].min(1) >= 10) & (points[:, :, 1].max(1) <= 10.199951171875)
        assert np.array_equal(interior, road)
        assert int(road.sum()) == (28 if bone == 0 else 128)
        if bone != 0:
            assert road.all()
        else:
            # No coarse triangle bridges road replacement and exterior structure.
            exterior = points[~road, :, 0]
            assert np.all((exterior.min(1) >= 12.5) | (exterior.max(1) <= -12.5))
        removed.extend(map(int, selected[road]))
        retained.extend(map(int, selected[~road]))
    assert len(removed) == len(set(removed)) == 312
    ids = sorted(set(map(int, faces[retained].ravel())))
    weights = {i: int(np.sign(v[i, 0])) for i in ids}
    assert set(weights.values()) == {-1, 1}
    for delta in (-.1, 0, 2, 8):
        moved = v.copy()
        for i, w in weights.items():
            moved[i, 0] += w * delta
        # Whole exterior faces move rigidly: edge vectors, normals and UV scale survive.
        before, after = v[faces[retained]], moved[faces[retained]]
        assert np.allclose(before[:, 1:] - before[:, :1], after[:, 1:] - after[:, :1], atol=1e-12)
        assert np.array_equal(moved[:, 1:], v[:, 1:])
    tables.append((sorted(removed), faces, weights, digest))
    np.savez(r / f'draw03-road-replacement-{lod}.npz', removed=np.array(sorted(removed)),
             exterior_faces=np.array(retained), exterior_vertices=np.array(ids))
    print(f'LOD{lod}: {len(removed)} road/curb faces removed; {len(retained)} exterior faces / {len(ids)} vertices retained rigidly.')

lines = ['// Native DrawBridge03 road/curb replacement and exterior edge preservation.',
         '// Generated by Draw03RoadReplacement.py; no runtime geometry classification.',
         'using System;', 'using UnityEngine;', '', 'namespace BridgeBuilder.Bridges;', '',
         'internal static class Draw03RoadReplacement', '{',
         '    internal static MovableStructureModel.Plan Apply(int lod, MovableStructureModel.Plan plan, float delta)',
         '    {', '        var data = lod switch', '        {',
         '            0 => (Count: 186078, Indices: 381444, Faces: Faces0, Sides: Sides0),',
         '            1 => (Count: 146988, Indices: 229152, Faces: Faces1, Sides: Sides1),',
         '            _ => throw new ArgumentOutOfRangeException(nameof(lod))', '        };',
         '        if (!float.IsFinite(delta) || plan.SourcePositions.Length != data.Count ||',
         '            plan.SourceIndices.Length != 1 || plan.SourceIndices[0].Length != data.Indices)',
         '            throw new InvalidOperationException("Draw03 road replacement requires its recorded main mesh.");',
         '        var mask = (bool[])plan.RemoveTriangles[0].Clone();',
         '        for (var i = 0; i < data.Faces.Length; i += 4)', '        {',
         '            var face = data.Faces[i];',
         '            for (var corner = 0; corner < 3; corner++)',
         '                if (plan.SourceIndices[0][face * 3 + corner] != data.Faces[i + corner + 1])',
         '                    throw new InvalidOperationException("Draw03 road replacement topology differs from its source.");',
         '            foreach (var fragment in plan.Fragments)',
         '                if (fragment.Slot == 0 && fragment.Triangle == face)',
         '                    throw new InvalidOperationException("Draw03 road removal overlaps a structural fragment.");',
         '            mask[face] = true;', '        }',
         '        var positions = new Vector3[data.Count];',
         '        Array.Copy(plan.Positions, positions, positions.Length);',
         '        foreach (var vertex in data.Sides)',
         '            positions[vertex.Index].x = plan.SourcePositions[vertex.Index].x + vertex.Side * delta;',
         '        var constructedX = new float[plan.ConstructedCount];',
         '        for (var i = 0; i < constructedX.Length; i++) constructedX[i] = plan.Positions[positions.Length + i].x;',
         '        return new MovableStructureModel.Plan(plan.SourcePositions, positions, plan.SourceIndices,',
         '            new[] { mask }, plan.AddedVertices, plan.Fragments, plan.InteriorVertices, constructedX);',
         '    }', '']
for lod, (removed, faces, weights, digest) in enumerate(tables):
    lines += ['    // Geometry SHA-256: ' + digest,
              f'    private static readonly int[] Faces{lod} =', '    {']
    lines += ['        ' + ', '.join(map(str, (i, *faces[i]))) + ',' for i in removed]
    lines += ['    };', f'    private static readonly (int Index, int Side)[] Sides{lod} =', '    {']
    lines += [f'        ({i}, {w}),' for i, w in weights.items()]
    lines += ['    };', '']
lines += ['}', '']
output.write_text('\n'.join(lines), encoding='utf-8')
