"""Emit Lift05 carriageway top faces, retaining shoulders and underside.
Usage: python Lift05RoadTops.py RESEARCH_DIRECTORY OUTPUT_CS
Far fixed ends are composite shells and require a separate reconstruction plan.
"""
from pathlib import Path
import ctypes as c
import hashlib, json, struct, sys
import numpy as np
r,output=map(Path,sys.argv[1:])
records=json.loads((r/'lift-native-road-plane-candidates.json').read_text())
dll=c.CDLL(r'D:\Program Files (x86)\Steam\steamapps\common\Cities Skylines II\Cities2_Data\Plugins\x86_64\PipelinePlugin.dll')
for name,args,result in (
 ('decompress_calc_bound',[c.c_void_p,c.c_int64,c.c_int],c.c_int64),
 ('decompress_data',[c.c_void_p,c.c_int64,c.c_void_p,c.c_int64,c.c_int],c.c_int64),
 ('decompress_meshopt_index_buffer',[c.c_void_p,c.c_int64,c.c_int,c.c_int,c.c_void_p],c.c_int),
 ('decompress_meshopt_vertex_attribute',[c.c_void_p,c.c_int64,c.c_int,c.c_int,c.c_void_p],c.c_int)):
 method=getattr(dll,name);method.argtypes=args;method.restype=result
levels=[]
for lod in range(3):
 record=next(x for x in records if x['style']==5 and x['lod']==lod)
 path=r/'movable-skin'/record['geometry'];raw=path.read_bytes()
 assert hashlib.sha256(raw).hexdigest()==record['sha256']
 version,meshes,flags=struct.unpack_from('<HII',raw)
 assert version==1 and meshes==(1 if lod==2 else 2)
 headers=[struct.unpack_from('<QI14i5I',raw,10+i*88) for i in range(meshes)];h=headers[0]
 def decode(block,count,stride,index=False):
  if flags&2:
   size=dll.decompress_calc_bound(block,len(block),0);assert size>0
   buf=c.create_string_buffer(size);assert dll.decompress_data(block,len(block),buf,size,0)==size;block=buf.raw
  if flags&1:
   buf=c.create_string_buffer(count*stride)
   method=dll.decompress_meshopt_index_buffer if index else dll.decompress_meshopt_vertex_attribute
   assert method(block,len(block),count,stride,buf)==0;block=buf.raw
  assert len(block)==count*stride
  return block
 offset=10+meshes*88+sum(x[-1]*40 for x in headers)
 stride=4 if h[17]&1 else 2
 f=np.frombuffer(decode(raw[offset:offset+h[16]],h[19],stride,True),dtype='<u4' if stride==4 else '<u2').reshape(-1,3)
 offset+=sum(x[16] for x in headers)
 assert h[0]&15==0 and h[1]&3==2
 v=np.frombuffer(decode(raw[offset:offset+h[2]],h[18],12),dtype='<f4').reshape(-1,3)
 faces=[];bones=[];bone=-1
 for line in path.with_suffix('.mesh-0.obj').read_text().splitlines():
  fields=line.split()
  if not fields:continue
  if fields[0]=='g':bone=int(fields[1][5:]) if fields[1].startswith('bone_') else -1
  elif fields[0]=='f':faces.append([int(x.split('/')[0])-1 for x in fields[1:]]);bones.append(bone)
 assert np.array_equal(f,faces)
 bones=np.array(bones);p=v[f].astype(float)
 normal=np.cross(p[:,1]-p[:,0],p[:,2]-p[:,0])
 candidate=next(x for x in record['candidates'] if x['bone']==2 and x['y']==9.800048828125)
 moving=[i for i in candidate['faces'] if p[i,:,0].min()>=-3 and p[i,:,0].max()<=3]
 if lod==1:
  # Seven reviewed native simplification slopes; not a runtime height tolerance.
  slopes=[14720,14721,14722,16639,16640,16657,16658]
  assert set(moving).isdisjoint(slopes)
  assert p[slopes,:,1].min()==9.7607421875 and p[slopes,:,1].max()==9.800048828125
  moving+=slopes
 moving=sorted(moving)
 assert len(moving)==(128,128,4)[lod] and np.all(bones[moving]==2)
 assert np.all(normal[moving,1]>0) and abs(normal[moving,1].sum()/2-749.53125)<1e-8
 assert np.max(abs(p[moving,:,0]))==3 and np.max(abs(p[moving,:,2]))==62.4609375
 fixed=[]
 if lod<2:
  fixed=sorted(next(x['faces'] for x in record['candidates'] if x['bone']==0 and x['y']==9.800048828125))
  assert len(fixed)==96 and np.all(bones[fixed]==0) and np.all(normal[fixed,1]>0)
  assert normal[fixed,1].sum()/2==342.71875
  assert np.max(abs(p[fixed,:,0]))==4 and np.max(abs(p[fixed,:,2]))==84
  assert np.min(abs(p[fixed,:,2]))==62.580078125
 assert set(fixed).isdisjoint(moving)
 assert all(normal[i,1]>0 for i in moving+fixed)
 levels.append((record,f,moving,fixed))
 print(f'LOD{lod}: {len(moving)} moving carriageway tops; {len(fixed)} detailed fixed tops; area, bones, topology verified')
lines=['// Generated by Lift05RoadTops.py from native game 1.6.2f1 Geometry.',
 '// Only carriageway tops; structural shoulders, sides and underside remain.',
 'using System;','','namespace BridgeBuilder.Bridges;','','internal static class Lift05RoadTops','{',
 '    internal static void RemoveMoving(int lod, int[] indices, bool[] removed) =>',
 '        Remove(lod, indices, removed, lod switch', '        {',
 '            0 => Moving0, 1 => Moving1, 2 => Moving2,',
 '            _ => throw new ArgumentOutOfRangeException(nameof(lod))','        });','',
 '    // LOD2 combines fixed road and side structure; it needs its own shell plan.',
 '    internal static void RemoveDetailedFixed(int lod, int[] indices, bool[] removed) =>',
 '        Remove(lod, indices, removed, lod switch','        {',
 '            0 => Fixed0, 1 => Fixed1,',
 '            _ => throw new ArgumentOutOfRangeException(nameof(lod))','        });','',
 '    private static void Remove(int lod, int[] indices, bool[] removed,',
 '        (int Triangle, int A, int B, int C)[] faces)','    {',
 '        var count = lod switch','        {']
for lod,(rec,f,moving,fixed) in enumerate(levels):lines.append(f'            {lod} => {len(f)},')
lines+=['            _ => throw new ArgumentOutOfRangeException(nameof(lod))','        };',
 '        if (indices.Length != count * 3 || removed.Length != count)',
 '            throw new InvalidOperationException("Lift05 road-top source layout changed.");',
 '        foreach (var face in faces)','        {','            var offset = face.Triangle * 3;',
 '            if (indices[offset] != face.A || indices[offset + 1] != face.B || indices[offset + 2] != face.C)',
 '                throw new InvalidOperationException("Lift05 road-top source topology changed.");',
 '            removed[face.Triangle] = true;','        }','    }','']
for lod,(rec,f,moving,fixed) in enumerate(levels):
 lines.append('// Geometry SHA-256: '+rec['sha256'])
 for name,ids in [('Moving',moving),('Fixed',fixed)]:
  if not ids:continue
  lines += [f'    private static readonly (int Triangle, int A, int B, int C)[] {name}{lod} =','    {']
  lines += [f'        ({i}, {f[i,0]}, {f[i,1]}, {f[i,2]}),' for i in ids]
  lines += ['    };','']
lines+=['}','']
output.write_text('\n'.join(lines),encoding='utf-8')
