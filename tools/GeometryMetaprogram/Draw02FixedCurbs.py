"""Record the fixed-platform prototype curb sides replaced by selected-road geometry.
Usage: python Draw02FixedCurbs.py RESEARCH_DIR OUTPUT_CS
"""
from pathlib import Path
import hashlib
import sys
import numpy as np

research, output = map(Path, sys.argv[1:])
tables=[]
for lod in range(2):
    d=np.load(research/f'draw02-main-lod{lod}-uv.npz')
    v,f=d['positions'],d['indices'].reshape(-1,3)
    p=v[f];lo,hi=p.min(1),p.max(1)
    # Reviewed curb risers/shoulder bevels between the original 9.800049 road
    # datum and 10 m sidewalk. Lower structural lips are deliberately excluded.
    selected=(lo[:,1]>=np.float32(9.800048828125))&(hi[:,1]<=10)&(lo[:,0]>=-9.5)&(hi[:,0]<=9.5)
    selected&=((lo[:,2]>=78.7)|(hi[:,2]<=-78.7))&(np.ptp(p[:,:,1],axis=1)>0)
    faces=np.flatnonzero(selected)
    assert len(faces)==(64,40)[lod]
    assert np.sum(p[faces,:,2].min(1)>0)==len(faces)//2
    assert np.sum(p[faces,:,2].max(1)<0)==len(faces)//2
    name='DrawBridge02'+(f'_LOD{lod}' if lod else '')+' Mesh.Geometry'
    digest=hashlib.sha256((research/'movable-skin'/name).read_bytes()).hexdigest()
    tables.append((faces,f,digest))
    print(f'LOD{lod}: {len(faces)} fixed curb side/bevel faces; symmetric ends; no top or lower support faces')

lines=['// Measured DrawBridge02 fixed-platform curb sides, game 1.6.2f1.',
       '// Generated by tools/GeometryMetaprogram/Draw02FixedCurbs.py.',
       'using System;', 'using UnityEngine;', '', 'namespace BridgeBuilder.Bridges;', '',
       'internal static class Draw02FixedCurbs', '{',
       '    internal static MovableStructureModel.Plan Remove(int lod, MovableStructureModel.Plan plan)',
       '    {', '        // The far proxy has no separate raised curb within this measured band.',
       '        if (lod == 2) return plan;',
       '        var records = lod switch { 0 => Near, 1 => Middle, _ => throw new ArgumentOutOfRangeException(nameof(lod)) };',
       '        var mask = (bool[])plan.RemoveTriangles[0].Clone();',
       '        for (var i = 0; i < records.Length; i += 4)', '        {',
       '            var face = records[i];', '            for (var corner = 0; corner < 3; corner++)',
       '                if (plan.SourceIndices[0][face * 3 + corner] != records[i + corner + 1])',
       '                    throw new InvalidOperationException("Draw02 fixed curb topology differs from the measured source.");',
       '            foreach (var fragment in plan.Fragments)',
       '                if (fragment.Slot == 0 && fragment.Triangle == face)',
       '                    throw new InvalidOperationException("Draw02 fixed curb removal overlaps a structural fragment.");',
       '            mask[face] = true;', '        }',
       '        var positions = new Vector3[plan.SourcePositions.Length];',
       '        Array.Copy(plan.Positions, positions, positions.Length);',
       '        var constructedX = new float[plan.ConstructedCount];',
       '        for (var i = 0; i < constructedX.Length; i++) constructedX[i] = plan.Positions[positions.Length + i].x;',
       '        return new MovableStructureModel.Plan(plan.SourcePositions, positions, plan.SourceIndices,',
       '            new[] { mask }, plan.AddedVertices, plan.Fragments, plan.InteriorVertices, constructedX);',
       '    }','']
for name,(faces,f,digest) in zip(('Near','Middle'),tables):
    lines+=['    // Geometry SHA-256: '+digest,f'    private static readonly int[] {name} =', '    {']
    for face in faces:lines+=['        '+', '.join(map(str,(face,*f[face])))+',']
    lines+=['    };','']
lines+=['}','']
output.write_text('\n'.join(lines),encoding='utf-8')
