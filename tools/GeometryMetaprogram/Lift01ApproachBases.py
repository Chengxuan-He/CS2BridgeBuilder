"""Emit the Lift01 road-adjacent base displacement, excluding support cradles.
Usage: python Lift01ApproachBases.py RESEARCH_DIRECTORY OUTPUT_CS
Original centre residues are recorded as stationary centre vertices offline.
"""
from pathlib import Path
import hashlib
import json
import sys
import numpy as np

r, output = map(Path, sys.argv[1:])
from Lift01ApproachBaseParts import partition

tables = []
for lod in range(2):
    v = np.load(r / f'lift01-approach-{lod}.npz')['positions']
    ids, frame_ids = partition(r, lod)
    weights = np.sign(v[ids, 0]).astype(np.int8)
    weights[abs(v[ids, 0]) < .00001] = 0
    groups = {side: [i for i, w in zip(ids, weights) if w == side] for side in (-1, 0, 1)}
    for delta in (-4., -2.75, -2., -.5, 0., 2., 8.):
        moved = v[ids].copy()
        moved[:, 0] += weights * delta
        assert np.array_equal(moved[:, 1:], v[ids, 1:])
        assert np.array_equal(moved[weights == 0], v[ids][weights == 0])
        data = np.load(r / f'lift01-approach-{lod}.npz')
        all_positions = v.copy()
        all_positions[ids] = moved
        faces = data['indices']
        member = np.isin(faces, ids)
        assert not np.any(member.any(1) & ~member.all(1))
        faces = faces[member.all(1)]
        before, after = v[faces].astype(float), all_positions[faces].astype(float)
        n0 = np.cross(before[:,1]-before[:,0], before[:,2]-before[:,0])
        n1 = np.cross(after[:,1]-after[:,0], after[:,2]-after[:,0])
        valid = np.linalg.norm(n0, axis=1) > 1e-8
        if delta >= -1: assert np.all(np.sum(n0[valid]*n1[valid], axis=1) > 0)
        for side in (-1, 1):
            assert np.allclose(moved[weights == side] - v[ids][weights == side], [side * delta, 0, 0], atol=2e-6)
    name = 'LiftBridge01Net' + ('_LOD1' if lod else '') + ' Mesh.Geometry'
    digest = hashlib.sha256((r / 'lift01-approaches' / name).read_bytes()).hexdigest()
    assert digest == ('13872e5563f59223f541d1d2146d9cec7bfe7fac937c9d829c4a7474313621f3',
                      '7d859975ab9190b8881d6b93b38ada4a70db112f9a6b9eecc4c11880e7047992')[lod]
    tables.append((groups, digest))
    print(f'LOD{lod}: fixed-span base, {len(ids)} vertices; centre and side displacement checks passed')

def ranges(ids):
    result = []
    for i in ids:
        if result and result[-1][1] + 1 == i:
            result[-1][1] = i
        else:
            result.append([i, i])
    return result

lines = ['// Native LiftBridge01Net road-adjacent base, excluding end U frames.',
         '// Generated by Lift01ApproachBases.py; centre residues are explicitly assigned.',
         'using System;', 'using UnityEngine;', '', 'namespace BridgeBuilder.Bridges;', '',
         'internal static class Lift01ApproachBases', '{',
         '    internal static void Apply(int lod, Vector3[] source, Vector3[] positions, float delta)',
         '    {', '        var data = lod switch', '        {',
         '            0 => (Count: 80210, Left: Left0, Centre: Centre0, Right: Right0),',
         '            1 => (Count: 38399, Left: Left1, Centre: Centre1, Right: Right1),',
         '            _ => throw new ArgumentOutOfRangeException(nameof(lod))', '        };',
         '        if (!float.IsFinite(delta) || source.Length != data.Count || positions.Length != data.Count)',
         '            throw new InvalidOperationException("Lift01 bases require their recorded fixed-span mesh.");',
         '        foreach (var range in data.Left)',
         '            for (var i = range.First; i <= range.Last; i++) positions[i].x = source[i].x - delta;',
         '        foreach (var range in data.Centre)',
         '            for (var i = range.First; i <= range.Last; i++) positions[i].x = source[i].x;',
         '        foreach (var range in data.Right)',
         '            for (var i = range.First; i <= range.Last; i++) positions[i].x = source[i].x + delta;',
         '    }', '']
for lod, (groups, digest) in enumerate(tables):
    lines.append('    // Geometry SHA-256: ' + digest)
    for side, name in ((-1, 'Left'), (0, 'Centre'), (1, 'Right')):
        lines += [f'    private static readonly (int First, int Last)[] {name}{lod} =', '    {']
        lines += [f'        ({a}, {b}),' for a, b in ranges(groups[side])]
        lines += ['    };', '']
lines += ['}', '']
output.write_text('\n'.join(lines), encoding='utf-8')
