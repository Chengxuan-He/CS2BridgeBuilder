"""Record Draw02's four fixed sidewalk nose slabs and their lateral allocation.
Usage: python Draw02FixedSidewalks.py RESEARCH_DIRECTORY OUTPUT_CS
The far proxy has no separate nose slabs; its shared structural envelope is retained.
"""
from pathlib import Path
import hashlib
import sys
import numpy as np

research, output = map(Path, sys.argv[1:])
tables = []
for lod in range(3):
    data = np.load(research / f'draw02-main-lod{lod}-uv.npz')
    v, f = data['positions'].astype(np.float32), data['indices'].reshape(-1, 3)
    p = v[f]
    lo, hi = p.min(1), p.max(1)
    # The reviewed wedge lies immediately behind each hinge opening. It has a
    # 10 m sidewalk top, 9.564453 m bottom, and an inner side at +/-6.699951 m.
    # These are offline identification bounds, not runtime geometry tests.
    ends = ((lo[:,2] >= 78.74) & (hi[:,2] <= 80.02)) | ((lo[:,2] >= -80.02) & (hi[:,2] <= -78.74))
    height = (lo[:,1] >= 9.56) & (hi[:,1] <= 10)
    groups = []
    for side in (-1, 1):
        lateral = ((lo[:,0] >= 6.69) & (hi[:,0] <= 9.5)) if side > 0 else ((lo[:,0] >= -9.5) & (hi[:,0] <= -6.69))
        faces = np.flatnonzero(ends & height & lateral)
        assert len(faces) == (22, 20, 0)[lod]
        vertices = np.unique(f[faces])
        # Every source vertex is owned by these slab faces alone: changing/removing
        # one sidewalk cannot distort the fixed foundation, curb or exterior platform.
        incident = np.flatnonzero(np.any(np.isin(f, vertices), axis=1))
        assert np.array_equal(incident, faces)
        if lod == 2:
            continue
        assert len(vertices) == (42, 40)[lod]
        assert np.sum(p[faces,:,2].min(1) > 0) == len(faces)//2
        assert set(v[vertices,0]) == ({np.float32(6.699951), np.float32(9.5)} if side > 0 else {np.float32(-9.5), np.float32(-6.699951)})
        # Native section allocation: [-9.5,-6] / [6,9.5]. Preserve the measured
        # inset of the slab within that allocation, rather than filling the curb.
        minimum = np.float32(-9.5 if side < 0 else 6)
        fractions = (v[vertices,0] - minimum) / np.float32(3.5)
        groups.append((side, faces, vertices, minimum, fractions))
    name = 'DrawBridge02' + (f'_LOD{lod}' if lod else '') + ' Mesh.Geometry'
    sha = hashlib.sha256((research/'movable-skin'/name).read_bytes()).hexdigest()
    tables.append((groups, sha))
    for side, faces, vertices, minimum, fractions in groups:
        for span in ((minimum, minimum+np.float32(3.5)), (-17.5,-14), (6,6.2), (-11,-6)):
            a, b = map(np.float32, span)
            moved = v.copy()
            moved[vertices,0] = v[vertices,0] + (a-minimum) + (b-a-np.float32(3.5))*fractions
            assert np.array_equal(moved[:,1:], v[:,1:])
            assert np.isfinite(moved).all()
            if a == minimum and b-a == np.float32(3.5):
                assert np.array_equal(moved, v)
            before, after = v[f[faces]].astype(float), moved[f[faces]].astype(float)
            n0 = np.cross(before[:,1]-before[:,0],before[:,2]-before[:,0])
            n1 = np.cross(after[:,1]-after[:,0],after[:,2]-after[:,0])
            assert np.all(np.sum(n0*n1,axis=1) > 0)
    print(f'LOD{lod}: {sum(len(g[1]) for g in groups)} fixed sidewalk slab faces; exclusive vertex ownership; native/unequal/narrow span checks passed')

lines = ['// DrawBridge02 fixed sidewalk nose slabs, game 1.6.2f1.',
         '// Generated by tools/GeometryMetaprogram/Draw02FixedSidewalks.py.',
         'using System;', 'using UnityEngine;', '', 'namespace BridgeBuilder.Bridges;', '',
         'internal static class Draw02FixedSidewalks', '{',
         '    internal static MovableStructureModel.Plan Apply(int lod, MovableStructureModel.Plan plan, MovableSelectedRoadLayout layout)',
         '    {',
         '        // The native far mesh has no independent nose slab. Its common foundation',
         '        // remains structural; do not add near-detail sidewalk wedges to that LOD.',
         '        if (lod == 2) return plan;',
         '        var groups = lod switch { 0 => Near, 1 => Middle, _ => throw new ArgumentOutOfRangeException(nameof(lod)) };',
         '        var positions = new Vector3[plan.SourcePositions.Length];',
         '        Array.Copy(plan.Positions, positions, positions.Length);',
         '        var removed = (bool[])plan.RemoveTriangles[0].Clone();',
         '        foreach (var group in groups)',
         '        {',
         '            var span = group.Left ? layout.LeftSidewalk : layout.RightSidewalk;',
         '            if (!(span.y > span.x))',
         '            {',
         '                foreach (var face in group.Faces) removed[face] = true;',
         '                continue;',
         '            }',
         '            foreach (var vertex in group.Vertices)',
         '                positions[vertex.Index].x = plan.SourcePositions[vertex.Index].x +',
         '                    (span.x - group.Minimum) + (span.y - span.x - 3.5f) * vertex.Fraction;',
         '        }',
         '        var constructedX = new float[plan.ConstructedCount];',
         '        for (var i = 0; i < constructedX.Length; i++) constructedX[i] = plan.Positions[positions.Length + i].x;',
         '        return new MovableStructureModel.Plan(plan.SourcePositions, positions, plan.SourceIndices,',
         '            new[] { removed }, plan.AddedVertices, plan.Fragments, plan.InteriorVertices, constructedX);',
         '    }', '',
         '    private readonly struct Group', '    {',
         '        internal readonly bool Left;', '        internal readonly float Minimum;',
         '        internal readonly int[] Faces;', '        internal readonly (int Index, float Fraction)[] Vertices;',
         '        internal Group(bool left, float minimum, int[] faces, (int, float)[] vertices)',
         '        { Left = left; Minimum = minimum; Faces = faces; Vertices = vertices; }', '    }', '']
for lod, name in enumerate(('Near', 'Middle')):
    groups, sha = tables[lod]
    lines += ['    // Geometry SHA-256: '+sha, f'    private static readonly Group[] {name} =', '    {']
    for side, faces, vertices, minimum, fractions in groups:
        lines += [f'        new({str(side < 0).lower()}, {minimum:g}f, new[] {{ '+', '.join(map(str,faces))+' },',
                  '            new (int, float)[] {']
        lines += [f'                ({i}, {fraction:.17g}f),' for i,fraction in zip(vertices,fractions)]
        lines += ['            }),']
    lines += ['    };','']
lines += ['}', '']
output.write_text('\n'.join(lines),encoding='utf-8')
