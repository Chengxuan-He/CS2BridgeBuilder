"""Emit Draw03's six structural sections and 33 native occurrence branches.
Usage: python Draw03ApproachLayout.py AUDIT_JSON OUTPUT_CS
"""
from pathlib import Path
import hashlib
import json
import sys

audit, output = map(Path, sys.argv[1:])
digest = hashlib.sha256(audit.read_bytes()).hexdigest()
assert digest == '47ef0f1723e8643e74a17751aa480f97260bf6e549aa60ec9f14f8e003b12070'
records = json.loads(audit.read_text(encoding='utf-8'))['selected']
roots = [79451, 79457, 79454, 79448, 79460]
sections = [118591, 118593, 118592, 118594, 118596, 118595]

def requirements(values):
    return ('Array.Empty<NetPieceRequirements>()' if not values else
            'new[] { '+', '.join('NetPieceRequirements.'+v for v in values)+' }')

def vector(v):
    return 'new float3('+', '.join(format(float(v[k]), '.17g')+'f' for k in 'xyz')+')'

lines = ['// Native DrawBridge03 structural approach layout, game 1.6.2f1.',
         '// Audit SHA-256: '+digest, '// Generated by Draw03ApproachLayout.py.',
         'using System;', 'using System.Linq;', 'using Game.Prefabs;',
         'using Unity.Mathematics;', 'using UnityEngine;', '',
         'namespace BridgeBuilder.Bridges;', '', 'internal static class Draw03ApproachLayout', '{',
         '    internal static void Apply(NetGeometryPrefab target, TowerFactory factory, NetPiecePrefab[] pieces, float layoutRemainder)',
         '    {',
         '        if (pieces.Length != 5 || pieces.Any(piece => piece == null || !factory.Created.Contains(piece)))',
         '            throw new InvalidOperationException("Draw03 approaches require five owned structural pieces.");',
         '        var median = factory.ResolveOriginal<NetPiecePrefab>("Elevated Bottom Piece 0 - Intersection Middle");']
for i, identity in enumerate(sections):
    d = records[str(identity)]['data']
    structural = [p for p in d['m_Pieces'] if p['m_Piece']['m_PathID'] in roots+[120704]]
    assert len(structural) == 1 and len(d['m_SubSections']) == 1
    # These are road/intersection lanes, supplied by the selected network itself;
    # the parallel structural sections must not add prototype road lanes again.
    sub = d['m_SubSections'][0]
    assert sub['m_Section']['m_PathID'] == [120877,120877,120877,120894,120900,120898][i]
    assert sub['m_RequireAll'] == ['Intersection'] and not sub['m_RequireAny'] and not sub['m_RequireNone']
    p = structural[0]; key = p['m_Piece']['m_PathID']
    lines += [f'        var section{i} = ScriptableObject.CreateInstance<NetSectionPrefab>();',
              f'        section{i}.name = target.name + " Fixed Approach Section {i}";',
              f'        factory.AdoptMovableSections(new PrefabBase[] {{ section{i} }});',
              f'        section{i}.m_SubSections = Array.Empty<NetSubSectionInfo>();',
              f'        section{i}.m_Pieces = new[]', '        {',
              '            new NetPieceInfo', '            {',
              '                m_Piece = '+('median' if key == 120704 else f'pieces[{roots.index(key)}]')+',',
              f'                m_Offset = {vector(p["m_Offset"])},']
    for field in ('m_RequireAll','m_RequireAny','m_RequireNone'):
        lines += [f'                {field} = {requirements(p[field])},']
    lines += ['            },', '        };']
lines += ['        var overhead = target.AddOrGetComponent<OverheadNetSections>();',
          '        overhead.m_Sections = new[]', '        {']
occurrences = records['118597']['data']['m_Sections']
assert len(occurrences) == 33
assert [p['m_Section']['m_PathID'] for p in occurrences[::3]] == [118595,118596,118592,118593,118591,118594,118591,118593,118592,118596,118595]
# Reproduce native overhead strip accumulation/centering for each occurrence branch.
# Offsets are in composition coordinates (not mirrored mesh coordinates).
for branch in range(3):
    active = occurrences[branch::3]
    widths = [(.5 if x['m_Section']['m_PathID'] == sections[5] else
               3.5 if x['m_Section']['m_PathID'] == sections[4] else
               0 if x['m_Median'] else 3.) for x in active]
    for delta in (-8., -4., -2., 0., 2., 8.):
        # Complete fixed structure shares the full 25 m deck span. The 0.5 m
        # outer railing strip remains rigid; the median is zero-width.
        scale = 1 + delta / 12.5
        structural = [x['m_Section']['m_PathID'] not in (sections[3], sections[5]) for x in active]
        physical = [w * scale if stretch else w for w, stretch in zip(widths, structural)]
        cursor = -sum(physical) / 2
        actual = []
        for w in physical:
            actual.append(cursor + w/2)
            cursor += w
        assert abs(sum(physical) - (sum(widths) + 2*delta)) < 1e-10
        assert min(physical) >= 0
print('PASS 18 native overhead-layout cases: distributed structural scale, rigid outer railing.')
# layoutRemainder is retained for source compatibility and is always zero in the
# current assembly. The historical signed-first-strip path is no longer called.
for p in occurrences:
    lines += ['            new NetSectionInfo', '            {',
              f'                m_Section = section{sections.index(p["m_Section"]["m_PathID"])},',
              f'                m_HiddenLayers = (NetPieceLayerMask)({p["m_HiddenLayers"]}),',
              f'                m_Offset = {vector(p["m_Offset"])} + new float3({(-1 if p["m_Invert"] else 1) * (0 if p["m_Median"] else .5 if p["m_Section"]["m_PathID"] == sections[0] else 1):g}f * layoutRemainder, 0f, 0f),']
    for field in ('m_Invert','m_Flip','m_Median','m_HalfLength'):
        lines += [f'                {field} = {str(bool(p[field])).lower()},']
    for field in ('m_RequireAll','m_RequireAny','m_RequireNone'):
        values = p[field]
        if field == 'm_RequireAll': values = list(dict.fromkeys(values+['Elevated']))
        lines += [f'                {field} = {requirements(values)},']
    lines += ['            },']
lines += ['        };', '        overhead.active = true;', '    }', '}', '']
output.write_text('\n'.join(lines), encoding='utf-8')
print('Emitted six Draw03 structural sections and all 33 native occurrence branches.')
