"""Emit measured Draw02 approach seam maps. Usage: RESEARCH_DIR OUTPUT_CS."""
from pathlib import Path
import hashlib
import sys
import numpy as np

research, output = map(Path, sys.argv[1:])
roots = [79429,79432,79436,79439,79423,79426,79435,79442,79445]
counts, maps = [], []
for family, root in enumerate(roots):
    family_counts = []
    for lod in range(1 if family == 6 else 3):
        data = np.load(research/'draw02-approaches'/f'{root+lod}.npz')
        v, f = data['positions'], data['indices']
        weights = np.zeros(len(v), dtype=np.float32)
        if family < 2:
            assert v[:,0].min() == -1.5 and v[:,0].max() == 1.5
            weights[:] = .5
            weights[v[:,0] == -1.5] = -.5
        elif family == 6:
            assert set(np.unique(v[:,0])) == {-1.,0.,1.}
            weights = np.sign(v[:,0])
        for delta in (-12,-8,-4,-3,-.1,0,2,8):
            moved=v.copy();moved[:,0]+=weights*delta
            assert np.array_equal(moved[:,1:],v[:,1:]) and np.isfinite(moved).all()
            if delta==0: assert np.array_equal(moved,v)
            if family<2:
                # Network section placement moves the positive inner strip's centre by delta/2.
                world_before=v[:,0]+1.5
                world_after=moved[:,0]+1.5+delta/2
                assert np.allclose(world_after,world_before+np.sign(world_before)*delta,atol=2e-6)
            elif family!=6: assert np.array_equal(moved,v)
            a,b=v[f].astype(float),moved[f].astype(float)
            n0=np.cross(a[:,1]-a[:,0],a[:,2]-a[:,0]);n1=np.cross(b[:,1]-b[:,0],b[:,2]-b[:,0])
            valid=np.linalg.norm(n0,axis=1)>1e-8
            if delta >= -.1: assert np.all(np.sum(n0[valid]*n1[valid],axis=1)>0)
        family_counts.append((len(v),len(f)))
        if family<2 or family==6:
            maps.append((family,lod,[(float(w),np.flatnonzero(weights==w).tolist()) for w in np.unique(weights)]))
        print(f'Family {family} LOD{lod}: {len(v)} vertices, {len(f)} triangles; eight signed widths, seam/rigidity and positive-span winding PASS')
    counts.append(family_counts)

lines=['// Native DrawBridge02 approach seam maps, game 1.6.2f1.',
       '// Generated by tools/GeometryMetaprogram/Draw02ApproachGeometry.py.',
       'using System;', 'using UnityEngine;', '', 'namespace BridgeBuilder.Bridges;', '',
       'internal static class Draw02ApproachGeometry', '{',
       '    internal static MovableStructureModel.Plan Create(int family, int lod, Vector3[] source, int[] indices, float delta)',
       '    {', '        var expected = Counts[family][lod];',
       '        if (source.Length != expected.Vertices || indices.Length != expected.Triangles * 3)',
       '            throw new InvalidOperationException("Draw02 approach geometry differs from the measured source.");',
       '        var positions = (Vector3[])source.Clone();',
       '        // Unchanged outer pieces move rigidly through the network section cursor.',
       '        var groups = (family, lod) switch', '        {']
for family,lod,_ in maps: lines += [f'            ({family}, {lod}) => Family{family}Lod{lod},']
lines += ['            _ => Array.Empty<(float Weight, int[] Vertices)>()', '        };',
          '        foreach (var group in groups)', '            foreach (var index in group.Vertices)',
          '                positions[index].x += group.Weight * delta;',
          '        return new MovableStructureModel.Plan(source, positions, new[] { indices },',
          '            new[] { new bool[expected.Triangles] });', '    }', '',
          '    private static readonly (int Vertices, int Triangles)[][] Counts =', '    {']
for row in counts: lines += ['        new[] { '+', '.join(f'({v}, {f})' for v,f in row)+' },']
lines += ['    };','']
for family,lod,groups in maps:
    lines += [f'    private static readonly (float Weight, int[] Vertices)[] Family{family}Lod{lod} =', '    {']
    for weight,ids in groups:
        lines += [f'        ({weight}f, new[]', '        {']
        for start in range(0,len(ids),20): lines += ['            '+', '.join(map(str,ids[start:start+20]))+',']
        lines += ['        }),']
    lines += ['    };','']
lines += ['}','']
output.write_text('\n'.join(lines),encoding='utf-8')
