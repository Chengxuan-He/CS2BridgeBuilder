"""Record middle support supplement and corresponding obstructing far shells.
Usage: python Lift03SupportFaces.py RESEARCH_DIRECTORY OUTPUT_CS
Uses original native faces, attributes and fixed bone 0; never copies road tops.
"""
from pathlib import Path
import ctypes as c, hashlib, struct, sys
import numpy as np
r, output = map(Path, sys.argv[1:3])
decoder = Path(__file__).with_name('Lift05Counterweights.py').read_text()
exec(decoder[decoder.index('dll = c.CDLL'):decoder.index('tables=[]')])
hashes = {1: '455d25f8ec83f91ea097551fb09a9f41abc79e9f15e836b19c0a527ad50ff9fa',
          2: '4dd846ac20f020fb45de94549d66e0bbafda4c575554a5b235a93e7d5a6008e4'}
levels = []
for lod in (1, 2):
    path = r / f'movable-skin/LiftBridge03_LOD{lod} Mesh.Geometry'
    raw = path.read_bytes()
    assert hashlib.sha256(raw).hexdigest() == hashes[lod]
    version, meshes, flags = struct.unpack_from('<HII', raw)
    assert version == 1 and meshes == (2 if lod == 1 else 1)
    headers = [struct.unpack_from('<QI14i5I', raw, 10 + i * 88) for i in range(meshes)]
    h = headers[0]
    section = decoder[decoder.index('    def decode('):decoder.index('    cached=np.load')]
    exec('\n'.join(line[4:] if line.startswith('    ') else line for line in section.splitlines()))
    cache = np.load(r / f'lift03-main-{lod}-0.npz')
    assert np.array_equal(f, cache['indices']) and np.allclose(v, cache['positions'], rtol=1e-7, atol=1e-6)
    parts = (102, 815, 658, 1371, 712, 1425) if lod == 1 else (6, 13)
    selected = np.flatnonzero(np.isin(cache['component'][f], parts).all(1))
    assert len(selected) == (2406 if lod == 1 else 32)
    faces, bones, bone = [], [], -1
    for line in path.with_suffix('.mesh-0.obj').read_text().splitlines():
        if line.startswith('g bone_'): bone = int(line[7:])
        elif line.startswith('f '):
            faces.append([int(x.split('/')[0])-1 for x in line.split()[1:]])
            bones.append(bone)
    assert np.array_equal(f, faces) and set(np.array(bones)[selected]) == {0}
    if lod == 1:
        tops = np.load(r/'lift03-road-top-faces-1.npz')['faces']
        assert not np.intersect1d(selected, tops).size
    levels.append((lod, len(f), f[selected], selected))
    print(f'PASS LOD{lod}: {len(selected)} original support faces, bone 0')
lines = ['// Measured support faces, generated by Lift03SupportFaces.py.',
         'using System;', '', 'namespace BridgeBuilder.Bridges;', '',
         'internal static class Lift03SupportFaces', '{']
for lod, count, faces, selected in levels:
    method = 'SelectMiddle' if lod == 1 else 'RemoveFar'
    lines += [f'    internal static void {method}(int[] indices, bool[] removed)', '    {',
              f'        if (indices.Length != {count} * 3 || removed.Length != {count})',
              '            throw new InvalidOperationException("Lift03 support source layout changed.");']
    if lod == 1: lines += ['        Array.Fill(removed, true);']
    lines += [f'        foreach (var face in Level{lod})', '        {',
              '            var offset = face.Triangle * 3;',
              '            if (indices[offset] != face.A || indices[offset + 1] != face.B || indices[offset + 2] != face.C)',
              '                throw new InvalidOperationException("Lift03 support source topology changed.");',
              '            removed[face.Triangle] = '+('false;' if lod == 1 else 'true;'), '        }', '    }',
              '    // Geometry SHA-256: ' + hashes[lod],
              f'    private static readonly (int Triangle, int A, int B, int C)[] Level{lod} =', '    {']
    lines += [f'        ({i}, {face[0]}, {face[1]}, {face[2]}),' for i, face in zip(selected, faces)]
    lines += ['    };']
lines += ['}', '']
output.write_text('\n'.join(lines), encoding='utf-8')
