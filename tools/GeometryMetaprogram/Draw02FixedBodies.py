"""Record the Draw02 fixed under-road bodies and their joined lateral structures.
Usage: python Draw02FixedBodies.py RESEARCH_DIRECTORY OUTPUT_CS
Source projections are reviewed offline; no runtime geometry classification is emitted.
"""
from pathlib import Path
import hashlib
import sys
import numpy as np

research, output = map(Path, sys.argv[1:])
tables = []
for lod in range(3):
    data = np.load(research / f'draw02-main-lod{lod}-uv.npz')
    v = data['positions'].astype(np.float32)
    faces = data['indices'].reshape(-1, 3)
    parent = list(range(len(v)))
    def root(a):
        while parent[a] != a:
            parent[a] = parent[parent[a]]
            a = parent[a]
        return a
    def join(a, b):
        parent[root(int(a))] = root(int(b))
    for a, b, c in faces:
        join(a, b)
        join(a, c)
    seen = {}
    for i, p in enumerate(v):
        key = tuple(p)
        if key in seen:
            join(i, seen[key])
        else:
            seen[key] = i
    groups = {}
    for i in range(len(v)):
        groups.setdefault(root(i), []).append(i)
    bodies = []
    for ids in groups.values():
        p = v[ids]
        lo, hi = p.min(0), p.max(0)
        if (lo[0] < -14 and hi[0] > 14 and
                (lo[2] > 69 or hi[2] < -69) and max(abs(lo[2]), abs(hi[2])) >= 90):
            bodies.append(ids)
    expected = ([1484, 1732], [1248, 1437], [104, 104, 122, 122])[lod]
    assert sorted(map(len, bodies)) == expected, (lod, list(map(len, bodies)))
    ids = sorted(i for body in bodies for i in body)
    # Near/middle contain authored centre stations encoded as +1e-6 as well as 0.
    # Record those explicitly rather than turning numerical residue into a side.
    weights = np.sign(v[ids, 0]).astype(np.int8)
    weights[np.abs(v[ids, 0]) < .00001] = 0
    sides = {side: [i for i, w in zip(ids, weights) if w == side] for side in (-1, 0, 1)}
    for delta in (-.5, 0, 2, 8):
        moved = v[ids].copy()
        moved[:, 0] += weights * np.float32(delta)
        assert np.array_equal(moved[:, 1:], v[ids, 1:])
        assert np.isfinite(moved).all()
        assert np.array_equal(moved[weights == 0], v[ids][weights == 0])
        for side in (-1, 1):
            mask = weights == side
            assert np.allclose(moved[mask, 0] - v[ids, 0][mask], side * delta, atol=2e-6)
        if delta == 0:
            assert np.array_equal(moved, v[ids])
    name = 'DrawBridge02' + (f'_LOD{lod}' if lod else '') + ' Mesh.Geometry'
    digest = hashlib.sha256((research / 'movable-skin' / name).read_bytes()).hexdigest()
    tables.append((len(v), sides, digest))
    print(f'LOD{lod}: {len(bodies)} fixed body groups, {len(ids)} vertices, {len(sides[0])} centre stations; displacement checks passed')

lines = ['// Native DrawBridge02 fixed under-road bodies, game 1.6.2f1.',
         '// Generated by tools/GeometryMetaprogram/Draw02FixedBodies.py.',
         '// Separate hinge axles, braces and moving members are not part of this map.',
         'using System;', 'using UnityEngine;', '', 'namespace BridgeBuilder.Bridges;', '',
         'internal static class Draw02FixedBodies', '{',
         '    internal static void Apply(int lod, Vector3[] source, Vector3[] positions, float delta)',
         '    {', '        var data = lod switch', '        {']
for lod, (count, _, _) in enumerate(tables):
    lines += [f'            {lod} => (Count: {count}, Left: Left{lod}, Centre: Centre{lod}, Right: Right{lod}),']
lines += ['            _ => throw new ArgumentOutOfRangeException(nameof(lod))', '        };',
          '        if (source.Length != data.Count || positions.Length != data.Count)',
          '            throw new InvalidOperationException("Draw02 fixed-body mapping requires its recorded main mesh.");',
          '        foreach (var i in data.Left) positions[i].x = source[i].x - delta;',
          '        foreach (var i in data.Centre) positions[i].x = source[i].x;',
          '        foreach (var i in data.Right) positions[i].x = source[i].x + delta;', '    }', '']
for lod, (_, sides, digest) in enumerate(tables):
    lines += ['    // Geometry SHA-256: ' + digest]
    for side, name in ((-1, 'Left'), (0, 'Centre'), (1, 'Right')):
        ids = sides[side]
        lines += [f'    private static readonly int[] {name}{lod} = new int[]', '    {']
        for i in range(0, len(ids), 20):
            lines += ['        ' + ', '.join(map(str, ids[i:i+20])) + ',']
        lines += ['    };', '']
lines += ['}', '']
output.write_text('\n'.join(lines), encoding='utf-8')
