import sys,json,hashlib
import numpy as np
r,out=map(Path,sys.argv[1:]);audit=json.loads((r/'all-movable-audit.json').read_text());tables=[]
for lod,parts in enumerate(((0,20,204,224),(0,20,197,217),(10,19,20,39))):
 name='PedestrianDrawBridge01'+(f'_LOD{lod}' if lod else '')+' Mesh'
 digest=hashlib.sha256((r/'movable-skin'/(name+'.Geometry')).read_bytes()).hexdigest()
