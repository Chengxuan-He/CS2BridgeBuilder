 mask=np.isin(c[f[:,0]],parts)&(p[:,:,1]==10).all(1)&(normal[:,1]>0)
 if lod==2:
  moving=np.isin(bones,['bone_1','bone_2']) & (np.abs(p[:,:,0]).max(1)<=3.686463) & (np.abs(p[:,:,1]-10.10009765625)<1e-6).all(1) & (normal[:,1]>0)
