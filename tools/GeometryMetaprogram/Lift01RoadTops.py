"""Emit verified Lift01 road-top membership; far-shell closure work is separate.

Usage: python Lift01RoadTops.py RESEARCH_DIRECTORY OUTPUT_CS
Reads the retained binary surface audit and corresponding native bone-group OBJ.
Runtime receives only face ordinals and original topology, never geometry classifiers.
"""
from pathlib import Path
import hashlib
import json
import sys
import numpy as np

research, output = map(Path, sys.argv[1:])
records = json.loads((research / 'lift-native-road-plane-candidates.json').read_text())
levels = []
for lod in (0, 1, 2):
    record = next(r for r in records if r['style'] == 1 and r['lod'] == lod)
    geometry = research / 'movable-skin' / record['geometry']
    assert hashlib.sha256(geometry.read_bytes()).hexdigest().lower() == record['sha256'].lower()
    vertices, faces, bones = [], [], []
    bone = -1
    for line in geometry.with_suffix('.mesh-0.obj').read_text().splitlines():
        fields = line.split()
        if not fields:
            continue
        if fields[0] == 'v':
            vertices.append(list(map(float, fields[1:4])))
        elif fields[0] == 'g':
            bone = int(fields[1][5:]) if fields[1].startswith('bone_') else -1
        elif fields[0] == 'f':
            faces.append([int(item.split('/')[0]) - 1 for item in fields[1:]])
            bones.append(bone)
    vertices, faces, bones = np.array(vertices), np.array(faces), np.array(bones)
    assert len(vertices) == record['vertices'] and len(faces) == record['triangles']
    if lod == 2:
        # Reviewed native inner road sheets, NOT the tall side-structure caps.
        # Moving sheets are slightly sloped; horizontal-plane selection misses them.
        chosen = [320, 321, 342, 343, 708, 709, 730, 731]
        assert len(vertices) == 1110 and len(faces) == 776
        for i in chosen:
            moving = i in (342, 343, 730, 731)
            points = vertices[faces[i]]
            assert bones[i] == (4 if moving else 0)
            assert abs(points[:, 0]).max() < 3.286
            assert points[:, 1].min() > 10.20 and points[:, 1].max() < 10.241
            assert np.cross(points[1] - points[0], points[2] - points[0])[1] > 0
            if moving:
                assert abs(points[:, 2]).max() < 80.18
            else:
                assert abs(points[:, 2]).min() > 79.8
        # All four underside faces remain untouched. The twelve inner-wall faces
        # still need closure adaptation to the detailed road datum before assembly.
        assert set(chosen).isdisjoint((338, 339, 726, 727))
        levels.append((record, faces, chosen))
        continue
    chosen = []
    for bone, count, area in ((0, 64 if lod == 0 else 32, 191.625),
                              (4, 320 if lod == 0 else 160, 959.90625)):
        source = next(c for c in record['candidates']
                      if c['bone'] == bone and c['y'] == 9.800048828125)
        ids = source['faces']
        assert len(ids) == count and source['area'] == area
        assert np.all(bones[ids] == bone)
        points = vertices[faces[ids]]
        assert np.max(abs(points[:, :, 1] - source['y'])) < 1e-5
        assert np.min(points[:, :, 0]) == -3 and np.max(points[:, :, 0]) == 3
        normals = np.cross(points[:, 1] - points[:, 0], points[:, 2] - points[:, 0])
        assert np.all(normals[:, 1] > 0)
        assert abs(normals[:, 1].sum() / 2 - area) < .001
        z = abs(points[:, :, 2])
        if bone == 0:
            assert abs(z.min() - 80.02734375) < 1e-5
            assert abs(z.max() - 95.99609375) < 1e-5
        else:
            assert abs(z.max() - 79.9921875) < 1e-5
        chosen.extend(ids)
    assert len(set(chosen)) == len(chosen)
    levels.append((record, faces, sorted(chosen)))

lines = ['// Generated by Lift01RoadTops.py from verified native mesh-0 road surfaces.',
         '// Top removal only; far-shell closure and structural widening are separate plans.',
         'using System;', '', 'namespace BridgeBuilder.Bridges;', '',
         'internal static class Lift01RoadTops', '{',
         '    internal static void Remove(int lod, int[] indices, bool[] removed)', '    {',
         '        var count = lod switch', '        {']
for lod, (record, _, _) in enumerate(levels):
    lines.append(f"            {lod} => {record['triangles']},")
lines += ['            _ => throw new ArgumentOutOfRangeException(nameof(lod))', '        };',
          '        if (indices.Length != count * 3 || removed.Length != count)',
          '            throw new InvalidOperationException("Lift01 road-top source layout changed.");',
          '        foreach (var face in Faces(lod))', '        {',
          '            var offset = face.Triangle * 3;',
          '            if (indices[offset] != face.A || indices[offset + 1] != face.B || indices[offset + 2] != face.C)',
          '                throw new InvalidOperationException("Lift01 road-top source topology changed.");',
          '            removed[face.Triangle] = true;', '        }', '    }', '',
          '    private static (int Triangle, int A, int B, int C)[] Faces(int lod) => lod switch', '    {']
for lod, (record, faces, chosen) in enumerate(levels):
    lines += [f"        // Geometry SHA-256: {record['sha256']}",
              f'        {lod} => new (int, int, int, int)[]', '        {']
    lines += [f'            ({i}, {faces[i, 0]}, {faces[i, 1]}, {faces[i, 2]}),' for i in chosen]
    lines.append('        },')
lines += ['        _ => throw new ArgumentOutOfRangeException(nameof(lod))', '    };', '}']
output.write_text('\n'.join(lines) + '\n', encoding='utf-8')
print('Lift01 road tops verified and emitted: 384 near / 192 middle / 8 far triangles; bone 0/4 only.')
