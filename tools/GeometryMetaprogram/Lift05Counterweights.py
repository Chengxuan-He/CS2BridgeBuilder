"""Emit the two measured centre-crossing Lift05 counterweights at all LODs.
Usage: python Lift05Counterweights.py RESEARCH_DIRECTORY OUTPUT_CS
"""
from pathlib import Path
import ctypes as c
import hashlib
import json
import struct
import sys
import numpy as np

r, output = map(Path, sys.argv[1:])
audit = json.loads((r/'all-movable-audit.json').read_text())
dll = c.CDLL(r'D:\Program Files (x86)\Steam\steamapps\common\Cities Skylines II\Cities2_Data\Plugins\x86_64\PipelinePlugin.dll')
for name, args, result in (
    ('decompress_calc_bound', [c.c_void_p,c.c_int64,c.c_int], c.c_int64),
    ('decompress_data', [c.c_void_p,c.c_int64,c.c_void_p,c.c_int64,c.c_int], c.c_int64),
    ('decompress_meshopt_index_buffer', [c.c_void_p,c.c_int64,c.c_int,c.c_int,c.c_void_p], c.c_int),
    ('decompress_meshopt_vertex_attribute', [c.c_void_p,c.c_int64,c.c_int,c.c_int,c.c_void_p], c.c_int)):
    method=getattr(dll,name);method.argtypes=args;method.restype=result

tables=[]
for lod, suffix in enumerate(('', '_LOD1', '_LOD2')):
    raw=(r/'movable-skin'/f'LiftBridge05{suffix} Mesh.Geometry').read_bytes()
    digest=hashlib.sha256(raw).hexdigest()
    assert any(a.get('sha256')==digest for a in audit['assets'].values())
    version, meshes, flags=struct.unpack_from('<HII',raw)
    assert version==1 and meshes==(1 if lod==2 else 2)
    headers=[struct.unpack_from('<QI14i5I',raw,10+i*88) for i in range(meshes)]
    h=headers[0]
    def decode(block,count,stride,index=False):
        if flags&2:
            size=dll.decompress_calc_bound(block,len(block),0)
            assert size>0
            buffer=c.create_string_buffer(size)
            assert dll.decompress_data(block,len(block),buffer,size,0)==size
            block=buffer.raw
        if flags&1:
            buffer=c.create_string_buffer(count*stride)
            method=dll.decompress_meshopt_index_buffer if index else dll.decompress_meshopt_vertex_attribute
            assert method(block,len(block),count,stride,buffer)==0
            block=buffer.raw
        assert len(block)==count*stride
        return block
    offset=10+meshes*88+sum(x[-1]*40 for x in headers)
    stride=4 if h[17]&1 else 2
    f=np.frombuffer(decode(raw[offset:offset+h[16]],h[19],stride,True),dtype='<u4' if stride==4 else '<u2').reshape(-1,3)
    offset+=sum(x[16] for x in headers)
    assert h[0]&15==0 and h[1]&3==2
    v=np.frombuffer(decode(raw[offset:offset+h[2]],h[18],12),dtype='<f4').reshape(-1,3)
    cached=np.load(r/f'lift05-main-{lod}-0.npz')
    assert np.array_equal(f,cached['indices'])
    assert np.allclose(v,cached['positions'],rtol=1e-7,atol=1e-6)
    components=((0,396),(0,239),(3,22))[lod]
    ids=np.flatnonzero(np.isin(cached['component'],components))
    assert len(ids)==(880,833,32)[lod]
    half=6.0191650390625
    for group in components:
        selected=cached['component']==group
        points=v[selected]
        assert points[:,0].min()==-half and points[:,0].max()==half
        # The reviewed pair is disconnected from all other authored parts.
        touched=selected[f].any(axis=1)
        assert np.all(selected[f[touched]])
        for delta in (-8,-6.0191650390625,-.5,0,2,8):
            moved=points.astype(float).copy()
            moved[:,0]+=points[:,0].astype(float)/half*delta
            assert np.array_equal(moved[:,1:],points[:,1:])
            assert np.allclose(moved[:,0],points[:,0]*(1+delta/half),atol=1e-6)
    ranges=[]
    for i in ids:
        if ranges and ranges[-1][1]==i-1:ranges[-1][1]=int(i)
        else:ranges.append([int(i),int(i)])
    tables.append((len(v),digest,ranges))
    print(f'LOD{lod}: {len(ids)} counterweight vertices; native topology and width checks passed')

lines=['// Native LiftBridge05 counterweights, game 1.6.2f1.',
       '// Generated by Lift05Counterweights.py from reviewed native components.',
       'using System;', 'using UnityEngine;', '', 'namespace BridgeBuilder.Bridges;', '',
       'internal static class Lift05CounterweightGeometry', '{',
       '    internal static void Apply(int lod, Vector3[] source, Vector3[] positions, float delta)',
       '    {', '        var data = lod switch', '        {']
for lod,(count,digest,ranges) in enumerate(tables):
    lines.append(f'            {lod} => (Count: {count}, Parts: Parts{lod}),')
lines+=['            _ => throw new ArgumentOutOfRangeException(nameof(lod))','        };',
        '        if (source.Length != data.Count || positions.Length != data.Count || !float.IsFinite(delta))',
        '            throw new InvalidOperationException("Lift05 counterweights require their native layout.");',
        '        foreach (var part in data.Parts)',
        '            for (var i = part.First; i <= part.Last; i++)',
        '                positions[i].x = source[i].x + source[i].x / 6.0191650390625f * delta;',
        '    }','']
for lod,(count,digest,ranges) in enumerate(tables):
    lines+=['    // Geometry SHA-256: '+digest,
            f'    private static readonly (int First, int Last)[] Parts{lod} =', '    {']
    lines += [f'        ({a}, {b}),' for a,b in ranges]
    lines += ['    };','']
lines+=['}','']
output.write_text('\n'.join(lines),encoding='utf-8')
