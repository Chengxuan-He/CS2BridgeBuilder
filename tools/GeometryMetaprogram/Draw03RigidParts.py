"""Extract exact-position-connected Draw03 parts and emit rigid side ranges.
Usage: python Draw03RigidParts.py RESEARCH_DIRECTORY OUTPUT_CS
All geometry classification is offline. Original bone domains remain separate.
"""
from pathlib import Path
import numpy as np,json,sys,hashlib
r, output = map(Path, sys.argv[1:])
levels=[]
for lod in range(3):
 name='DrawBridge03'+(f'_LOD{lod}' if lod else '')+' Mesh'
 digest=hashlib.sha256((r/'movable-skin'/(name+'.Geometry')).read_bytes()).hexdigest()
 assert digest == ('f7ecc824ad55745e791e40b18fd12f5def20657ed8ea56d373429d5a1337588f','15b8419da13d6e99e1dc0591f12f4019f0be09c3b220a481d24720daf7b57e12','3eb2b0a0489ef05c8bbac6c9ca9f536303802705d6f45ad8b4c4eb6d424621dc')[lod]
 verts=[];faces=[];bones=[];bone=None
 for line in (r/'movable-skin'/(name+'.mesh-0.obj')).read_text().splitlines():
  s=line.split()
  if not s:continue
  if s[0]=='v':verts.append(list(map(float,s[1:4])))
  elif s[0]=='g':bone=int(s[1].split('_')[1])
  elif s[0]=='f':faces.append([int(t.split('/')[0])-1 for t in s[1:]]);bones.append(bone)
 v=np.asarray(verts,dtype=np.float32);f=np.asarray(faces);b=np.asarray(bones);parent=list(range(len(v)));vb=np.full(len(v),-1)
 def root(i):
  while parent[i]!=i:parent[i]=parent[parent[i]];i=parent[i]
  return i
 def join(a,b):parent[root(int(a))]=root(int(b))
 for ids,bone in zip(f,b):
  assert np.all((vb[ids]==-1)|(vb[ids]==bone));vb[ids]=bone
  join(ids[0],ids[1]);join(ids[0],ids[2])
 seen={}
 for i,p in enumerate(v):
  key=(int(vb[i]),*p.tolist())
  if key in seen:join(i,seen[key])
  else:seen[key]=i
 groups={}
 for i in np.unique(f):groups.setdefault(root(int(i)),[]).append(int(i))
 parts=[]
 for ids in groups.values():
  p=v[ids];lo=p.min(0);hi=p.max(0);side=-1 if hi[0]<0 else 1 if lo[0]>0 else 0
  parts.append(dict(vertices=ids,minimum=lo.tolist(),maximum=hi.tolist(),side=side,bone=int(vb[ids[0]])))
 (r/f'draw03-parts-{lod}.json').write_text(json.dumps(parts))
 np.savez(r/f'draw03-main-{lod}.npz',positions=v,indices=f,bones=b)
 print(lod,'vertices',len(v),'triangles',len(f),'parts',len(parts),'sides',sum(p['side']!=0 for p in parts),'sidevertices',sum(len(p['vertices']) for p in parts if p['side']),'crossings',sum(p['side']==0 for p in parts))

 levels.append((v,f,parts,digest))

near=[p for p in levels[0][2] if p['side']]
lo=np.array([p['minimum'] for p in near]); hi=np.array([p['maximum'] for p in near])
sides=np.array([p['side'] for p in near]); bones=np.array([p['bone'] for p in near])
for part in levels[1][2]:
 if not part['side']:continue
 matches=(np.all(lo<=part['minimum'],axis=1)&np.all(hi>=part['maximum'],axis=1)
          &(sides==part['side'])&(bones==part['bone']))
 assert matches.any(), 'Middle side part has no detailed same-bone counterpart'

lines=['// Native DrawBridge03 independent side parts. Generated by Draw03RigidParts.py.',
       '// Crossing shells require their own mapping. No runtime spatial classification.',
       'using System;', 'using UnityEngine;', '', 'namespace BridgeBuilder.Bridges;', '',
       'internal static class Draw03RigidParts', '{',
       '    internal static void Apply(int lod, Vector3[] source, Vector3[] positions, float delta)',
       '    {', '        var data = lod switch', '        {']
for lod,(v,f,parts,digest) in enumerate(levels):
 lines.append(f'            {lod} => (Count: {len(v)}, Ranges: Level{lod}),')
lines += ['            _ => throw new ArgumentOutOfRangeException(nameof(lod))', '        };',
          '        if (source.Length != data.Count || positions.Length != data.Count || !float.IsFinite(delta))',
          '            throw new InvalidOperationException("Draw03 side parts require their recorded main mesh.");',
          '        foreach (var range in data.Ranges)',
          '            for (var i = range.First; i <= range.Last; i++)',
          '                positions[i].x = source[i].x + range.Side * delta;', '    }', '']
for lod,(v,f,parts,digest) in enumerate(levels):
 # Positive-leaf axle is split at X=-0.000022888.. / +0.000026702.. .
 # Its mirrored negative-leaf counterpart is connected. Both are full-span axles,
 # handled by Draw03Shafts rather than opening a gap between rigid halves.
 excluded=((268,270),(272,274),())[lod]
 if lod<2:
  assert sum(len(parts[i]['vertices']) for i in excluded)==(396,292)[lod]
  assert all(parts[i]['bone']==1 for i in excluded)
 selected=[p for i,p in enumerate(parts) if p['side'] and i not in excluded]
 assert (len(v),len(f),len(selected),sum(len(p['vertices']) for p in selected)) == (
     (186078,127148,2802,130422),(146988,76384,2890,98439),(684,448,2,78))[lod]
 signs=np.zeros(len(v),dtype=int)
 for part in selected:signs[part['vertices']]=part['side']
 assert np.all(signs[f]==signs[f[:,:1]])
 for delta in (-.5,0,2,8):
  moved=v.astype(float);moved[:,0]+=signs*delta
  assert np.array_equal(moved[signs==0],v[signs==0])
  for edge in (1,2):
   assert np.array_equal(moved[f[:,edge]]-moved[f[:,0]],v.astype(float)[f[:,edge]]-v.astype(float)[f[:,0]])
 ranges=[]
 for i in np.flatnonzero(signs):
  side=int(signs[i])
  if ranges and ranges[-1][1]+1==i and ranges[-1][2]==side:ranges[-1][1]=int(i)
  else:ranges.append([int(i),int(i),side])
 lines+=['    // Geometry SHA-256: '+digest,
         f'    private static readonly (int First, int Last, int Side)[] Level{lod} =', '    {']
 lines += [f'        ({a}, {b}, {side}),' for a,b,side in ranges]
 lines += ['    };','']
 print(f'LOD{lod}: {len(ranges)} ranges; four-width rigid-edge checks passed')
lines+=['}']
output.write_text('\n'.join(lines)+'\n',encoding='utf-8')
print('All middle side components have detailed same-side, same-bone envelope correspondence.')
