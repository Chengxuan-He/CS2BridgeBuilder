"""Emit single-network sampling adapters from the retained native movable audit.

Usage: python MovableSamplingAdapters.py AUDIT_JSON REPOSITORY
Lift03 deliberately requires a coordinated two-network implementation instead.
"""
import hashlib
import json
from pathlib import Path
import re
import sys

audit, repo = map(Path, sys.argv[1:])
digest = hashlib.sha256(audit.read_bytes()).hexdigest()
assert digest == '47ef0f1723e8643e74a17751aa480f97260bf6e549aa60ec9f14f8e003b12070'
records = json.loads(audit.read_text(encoding='utf-8'))['selected']
styles = [('Draw03', 'DrawBridge03')]
styles += [(f'Lift{i:02}', f'LiftBridge{i:02}') for i in (1, 2, 4, 5)]
styles += [(f'PedestrianDraw{i:02}', f'PedestrianDrawBridge{i:02}') for i in (1, 2)]


def component(data, name):
    ref = next(c for c in data['components'] if c['name'] == name)
    return records[str(ref['m_PathID'])]['data']


def number(value):
    return format(float(value), '.17g') + 'f'


def vector(data, axes):
    return ', '.join(number(data[k]) for k in axes)


for style, native in styles:
    network = [v['data'] for v in records.values()
               if v['data'].get('m_Name') == native and 'm_Sections' in v['data']]
    assert len(network) == 1
    bridge = component(network[0], 'Bridge')
    placements = component(network[0], 'NetSubObjects')['m_SubObjects']
    candidates = [p for p in placements if p['m_Object']['name'] == native]
    assert len(candidates) == 1
    p = candidates[0]
    mechanism = records[str(p['m_Object']['m_PathID'])]['data']
    names = [m['m_Mesh']['name'] for m in mechanism['m_Meshes']]
    assert len(names) == 3
    fields = [
        '            m_Object = mechanism,',
        f'            m_Position = new float3({vector(p["m_Position"], "xyz")}),',
        f'            m_Rotation = new quaternion({vector(p["m_Rotation"]["value"], "xyzw")}),',
        f'            m_Placement = (NetObjectPlacement){p["m_Placement"]},',
        f'            m_FixedIndex = {p["m_FixedIndex"]}, m_Spacing = {number(p["m_Spacing"])},',
    ]
    for key in ('m_AnchorTop', 'm_AnchorCenter', 'm_RequireElevated',
                'm_RequireOutsideConnection', 'm_RequireDeadEnd', 'm_RequireOrphan'):
        fields.append(f'            {key} = {str(bool(p[key])).lower()},')
    method = ('    internal static NetSubObjectInfo MechanismPlacement(ObjectPrefab mechanism) =>\n'
              '        new NetSubObjectInfo\n        {\n' + '\n'.join(fields) + '\n        };\n')
    folder = repo / 'src/BridgeBuilder/Bridges/Types' / style
    network_path = folder / f'{style}NetworkData.g.cs'
    source = network_path.read_text(encoding='utf-8')
    if 'internal static NetSubObjectInfo MechanismPlacement(' not in source:
        pattern = r'        new NetSubObjectInfo\n        \{\n            m_Object = mechanism,.*?\n        \},'
        matches = list(re.finditer(pattern, source, re.S))
        assert len(matches) == 1, style
        # Verify the retained placement's numeric and flag tokens before factoring it out.
        old = matches[0].group()
        def tokens(text):
            return re.findall(r'm_\w+|mechanism|true|false|(?<!\w)-?\d+(?:\.\d+)?(?:[eE][+-]?\d+)?f?', text)
        def normalize(text):
            return [float(t.rstrip('f')) if re.fullmatch(r'-?\d+(?:\.\d+)?(?:[eE][+-]?\d+)?f?', t) else t
                    for t in tokens(text)]
        assert normalize(old) == normalize('\n'.join(fields)), (style, old, fields)
        source = source[:matches[0].start()] + '        MechanismPlacement(mechanism),' + source[matches[0].end():]
        end = source.rfind('}')
        source = source[:end] + method + source[end:]
        network_path.write_text(source, encoding='utf-8')
    else:
        assert method in source, style

    code = f'''// Recorded {native} closed-pose sampling, game 1.6.2f1.
// Audit SHA-256: {digest}
// Generated by tools/GeometryMetaprogram/MovableSamplingAdapters.py.
using Game.Common;
using Game.Net;
using Game.Prefabs;
using Unity.Entities;

namespace BridgeBuilder.Bridges;

// Sampling input only; the style's all-LOD structure and road conversion follow separately.
internal static class {style}RoadSampling
{{
    internal static MovableStraightSample Create(string owner, Entity selectedRoad,
        RenderPrefab[] roots, ContentPrefab content, float halfWidthDelta,
        RandomSeed seed, NetPieceLayerMask replacedLayers, Upgraded? upgrade = null) =>
        MovableStraightSample.Create(owner, selectedRoad, roots, content, halfWidthDelta, seed,
            new[] {{ {', '.join(json.dumps(n) for n in names)} }},
            {style}MechanismData.Meshes, {style}MechanismData.ApplyComponents,
            {style}NetworkData.MechanismPlacement, {number(bridge['m_SegmentLength'])},
            {number(bridge['m_ElevationOnWater'])}, replacedLayers, upgrade);
}}
'''
    (folder / f'{style}RoadSampling.cs').write_text(code, encoding='utf-8')
    print(f'{style}: approach={bridge["m_SegmentLength"]}, water elevation={bridge["m_ElevationOnWater"]}, '
          f'mechanism position={p["m_Position"]}; placement preserved')
