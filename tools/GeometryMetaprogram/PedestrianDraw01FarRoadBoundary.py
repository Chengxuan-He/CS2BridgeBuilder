"""Align native far moving-road inner boundaries to the measured detailed sheet."""
from pathlib import Path
import hashlib,sys
import numpy as np
r,out=map(Path,sys.argv[1:])
# ControlHousing's audited binary decoder writes exact native positions/indices.
d=np.load(r/'pedestrian01-control-2.npz');v,f=d['positions'],d['indices']
c=np.load(r/'pedestrian01-main-2-0.npz')['component']
raw=(r/'movable-skin/PedestrianDrawBridge01_LOD2 Mesh.Geometry').read_bytes()
digest=hashlib.sha256(raw).hexdigest()
assert digest=='d514d88bf5fd4d8453a81578b36f099887cf562ad55255d4ca97267add15952b'
q=v.copy();inner=np.isin(c,(19,20))&(np.abs(v[:,0])==3.68646240234375)
top=inner&(v[:,1]==10.10009765625);assert top.sum()==40
q[top,1]=10
# The detailed road tip is distinct from the outer curb tip: move only inner
# upper boundary endpoints, leaving the original outer/underside tips intact.
tip=inner&(np.abs(v[:,2])==.06464385986328125)&(v[:,1]>=9.699951171875)
q[tip,2]=np.sign(v[tip,2])*.029998779296875
selected=np.any(q!=v,axis=1);assert np.array_equal(q[:,0],v[:,0])
a=v[f].astype(float);b=q[f].astype(float)
n=np.cross(a[:,1]-a[:,0],a[:,2]-a[:,0]);m=np.cross(b[:,1]-b[:,0],b[:,2]-b[:,0]);active=np.linalg.norm(n,axis=1)>1e-9
assert np.all((n[active]*m[active]).sum(1)>0)
lines=['// Generated by PedestrianDraw01FarRoadBoundary.py; native far Geometry SHA-256: '+digest,
       'using System;','using UnityEngine;','','namespace BridgeBuilder.Bridges;','',
       'internal static class PedestrianDraw01FarRoadBoundary','{',
       '    internal static MovableStructureModel.Plan Apply(MovableStructureModel.Plan plan)','    {',
       '        if (plan.SourcePositions.Length != 1702 || plan.SourceIndices.Length != 1 || plan.SourceIndices[0].Length != 3204)',
       '            throw new InvalidOperationException("PedestrianDraw01 far boundary source layout changed.");',
       '        var positions = new Vector3[plan.SourcePositions.Length];',
       '        Array.Copy(plan.Positions, positions, positions.Length);',
       '        foreach (var row in Vertices) {',
       '            var source = plan.SourcePositions[row.Index];',
       '            if (source.y != row.SourceY || source.z != row.SourceZ)',
       '                throw new InvalidOperationException("PedestrianDraw01 far boundary source coordinates changed.");',
       '            positions[row.Index].y = row.Y; positions[row.Index].z = row.Z;',
       '        }',
       '        var x = new float[plan.ConstructedCount];',
       '        for (var i = 0; i < x.Length; i++) x[i] = plan.Positions[positions.Length + i].x;',
       '        return new MovableStructureModel.Plan(plan.SourcePositions, positions, plan.SourceIndices, plan.RemoveTriangles,',
       '            addedVertices: plan.AddedVertices, interiorVertices: plan.InteriorVertices, fragments: plan.Fragments,',
       '            constructedX: x, reconstructsAuthoredPositions: true);','    }','',
       '    private static readonly (int Index, float SourceY, float SourceZ, float Y, float Z)[] Vertices =','    {']
for i in np.flatnonzero(selected):lines.append(f'        ({i}, '+', '.join(f'{float(x):.17g}f' for x in (v[i,1],v[i,2],q[i,1],q[i,2]))+'),')
lines+=['    };','}',''];out.write_text('\n'.join(lines),encoding='utf-8')
np.savez(r/'pedestrian01-far-boundary.npz',source=v,positions=q,indices=f,selected=selected)
print('PASS',selected.sum(),'boundary vertices;',top.sum(),'height corrections;',tip.sum(),'tip corrections; winding and X preserved')
