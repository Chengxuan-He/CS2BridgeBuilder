"""Record isolated, wholly lateral Draw02 parts without altering their shape.
Usage: python Draw02RigidParts.py RESEARCH_DIRECTORY OUTPUT_CS
Mixed/crossing components are deliberately left to their separate measured plans.
"""
from pathlib import Path
import hashlib
import json
import sys
import numpy as np

research, output = map(Path, sys.argv[1:])
tables = []
review = []
for lod in range(3):
    data = np.load(research / f'draw02-main-lod{lod}-uv.npz')
    v = data['positions'].astype(np.float32)
    faces = data['indices'].reshape(-1, 3)
    parent = list(range(len(v)))
    def root(a):
        while parent[a] != a:
            parent[a] = parent[parent[a]]
            a = parent[a]
        return a
    def join(a, b):
        parent[root(int(a))] = root(int(b))
    for a, b, c in faces:
        join(a, b)
        join(a, c)
    seen = {}
    for i, p in enumerate(v):
        key = tuple(p)
        if key in seen:
            join(i, seen[key])
        else:
            seen[key] = i
    groups = {}
    for i in np.unique(faces):
        groups.setdefault(root(int(i)), []).append(int(i))
    sides = {-1: [], 1: []}
    parts = []
    for ids in groups.values():
        p = v[ids]
        lo, hi = p.min(0), p.max(0)
        side = -1 if hi[0] < 0 else 1 if lo[0] > 0 else 0
        if side == 0:
            continue
        sides[side].extend(ids)
        parts.append(dict(side=side, vertices=ids, minimum=lo.tolist(), maximum=hi.tolist()))
        for delta in (-.5, 0, 2, 8):
            moved = p.copy()
            moved[:, 0] += np.float32(side * delta)
            assert np.array_equal(moved[:, 1:], p[:, 1:])
            assert np.allclose(moved[:, 0] - p[:, 0], side * delta, atol=2e-6)
            assert np.allclose(np.ptp(moved, axis=0), np.ptp(p, axis=0), atol=4e-6)
            if delta == 0:
                assert np.array_equal(moved, p)
    name = 'DrawBridge02' + (f'_LOD{lod}' if lod else '') + ' Mesh.Geometry'
    digest = hashlib.sha256((research / 'movable-skin' / name).read_bytes()).hexdigest()
    tables.append((len(v), sides, digest))
    review.append(dict(lod=lod, geometry_sha256=digest, parts=parts))
    print(f'LOD{lod}: {len(parts)} lateral parts, {sum(map(len, sides.values()))} vertices; rigid-shape checks passed')

# The glass is a separate fixed control-room mesh at negative X in both near LODs.
for lod in range(2):
    name = 'DrawBridge02' + ('_LOD1' if lod else '') + ' Mesh.mesh-1.obj'
    points = np.array([[float(x) for x in line.split()[1:4]]
                       for line in (research / 'movable-skin' / name).read_text().splitlines()
                       if line.startswith('v ')])
    assert points.shape == (68, 3) and points[:, 0].max() < 0

lines = ['// Native DrawBridge02 isolated lateral parts, game 1.6.2f1.',
         '// Generated by tools/GeometryMetaprogram/Draw02RigidParts.py.',
         '// No runtime connected-component or coordinate classification.',
         'using System;', 'using UnityEngine;', '', 'namespace BridgeBuilder.Bridges;', '',
         'internal static class Draw02RigidParts', '{',
         '    internal static void Apply(int lod, Vector3[] source, Vector3[] positions, float delta)',
         '    {', '        var data = lod switch', '        {']
for lod, (count, _, _) in enumerate(tables):
    lines += [f'            {lod} => (Count: {count}, Left: Left{lod}, Right: Right{lod}),']
lines += ['            _ => throw new ArgumentOutOfRangeException(nameof(lod))', '        };',
          '        if (source.Length != data.Count || positions.Length != data.Count)',
          '            throw new InvalidOperationException("Draw02 rigid mapping requires its recorded main mesh.");',
          '        foreach (var i in data.Left) positions[i].x = source[i].x - delta;',
          '        foreach (var i in data.Right) positions[i].x = source[i].x + delta;', '    }', '',
          '    internal static MovableStructureModel.Plan Glass(int lod, Vector3[] source, int[] indices, float delta)',
          '    {', '        if ((lod != 0 && lod != 1) || source.Length != 68 || indices.Length != 102)',
          '            throw new InvalidOperationException("Draw02 glass requires its recorded control-room mesh.");',
          '        var moved = (Vector3[])source.Clone();',
          '        for (var i = 0; i < moved.Length; i++) moved[i].x -= delta;',
          '        return new MovableStructureModel.Plan(source, moved, new[] { indices }, new[] { new bool[34] });',
          '    }', '']
for lod, (_, sides, digest) in enumerate(tables):
    lines += ['    // Geometry SHA-256: ' + digest]
    for side, name in ((-1, 'Left'), (1, 'Right')):
        ids = sorted(sides[side])
        lines += [f'    private static readonly int[] {name}{lod} = new int[]', '    {']
        for i in range(0, len(ids), 20):
            lines += ['        ' + ', '.join(map(str, ids[i:i+20])) + ',']
        lines += ['    };', '']
lines += ['}', '']
output.write_text('\n'.join(lines), encoding='utf-8')
(research / 'draw02-rigid-parts-review.json').write_text(json.dumps(review, indent=2), encoding='utf-8')
