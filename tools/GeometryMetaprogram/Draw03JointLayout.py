"""Emit selected-sidewalk adaptation for recorded Draw03 stepped joints.
Usage: python Draw03JointLayout.py RESEARCH_DIRECTORY OUTPUT_CS
Run Draw03SidewalkJoints.py first to produce draw03-sidewalk-joint-map.json.
"""
from pathlib import Path
import json
import sys
import numpy as np

r, output = map(Path, sys.argv[1:])
record = json.loads((r/'draw03-sidewalk-joint-map.json').read_text())
inner = record['innerStep']
tables = []
for level in record['levels']:
    lod = level['lod']
    d = np.load(r/f'draw03-main-{lod}.npz');v=d['positions'].astype(float);f=d['indices'].reshape(-1,3)
    ids = sorted(i for g in level['groups'] for i in g['vertices'])
    assert len(set(ids)) == len(ids)
    left = [i for g in level['groups'] for i in g['leftFaces']]
    right = [i for g in level['groups'] for i in g['rightFaces']]
    car = [i for g in level['groups'] for i in g['carriagewayFaces']]
    rows = []
    for i in ids:
        x=v[i,0];side=0 if abs(x)<.00001 else int(np.sign(x));walk=abs(x)>inner
        fraction=(abs(x)-9)/3.5 if walk else abs(x)/inner
        rows.append((i,side,walk,fraction))
    # Native, absent, left-only, right-only, unequal and widened sidewalks.
    cases=[((-12.5,-9),(9,12.5),0),((0,0),(0,0),0),((-12.5,-9),(0,0),0),
           ((0,0),(9,12.5),0),((-12.5,-11),(7.5,12.5),0),((-20.5,-17),(17,20.5),8)]
    for case,(lspan,rspan,delta) in enumerate(cases):
        moved=v.copy();removed=set()
        for span,faces in ((lspan,left),(rspan,right)):
            if span[1]<=span[0]:removed.update(faces)
        for i,side,walk,fraction in rows:
            if side==0:continue
            span=lspan if side<0 else rspan;present=span[1]>span[0]
            width=span[1]-span[0];start=-span[1] if side<0 else span[0]
            edge=start+(inner-9)/3.5*width if present else 12.5+delta
            shift=(start-9)+(width-3.5)*fraction if walk and present else (edge-inner)*(1 if walk else fraction)
            moved[i,0]=v[i,0]+side*shift
        if case==0:assert np.array_equal(v,moved)
        faces=np.array([i for i in left+car+right if i not in removed]);p=v[f[faces]];q=moved[f[faces]]
        before=np.cross(p[:,1]-p[:,0],p[:,2]-p[:,0]);after=np.cross(q[:,1]-q[:,0],q[:,2]-q[:,0])
        assert np.all(np.sum(before*after,axis=1)>0)
        assert not set(car)&removed and np.array_equal(v[:,1:],moved[:,1:])
        np.savez(r/f'draw03-joint-layout-{lod}-{case}.npz',positions=moved[ids],vertices=np.array(ids),faces=f[faces])
    tables.append((lod,level['sha256'],left,right,rows))
    print(f'LOD{lod}: {len(ids)} vertices; six sidewalk cases preserve carriageway faces, Y/Z and winding.')

def number(x):return format(float(np.float32(x)),'.9g')+'f'
lines=['// Draw03 stepped joint sidewalk adaptation. Generated by Draw03JointLayout.py.',
       'using System;','using UnityEngine;','','namespace BridgeBuilder.Bridges;','',
       'internal static class Draw03JointLayout','{',
       '    internal static MovableStructureModel.Plan Apply(int lod, MovableStructureModel.Plan plan,',
       '        MovableSelectedRoadLayout layout, float delta)','    {',
       '        var data = lod switch','        {',
       '            0 => (Left: Left0, Right: Right0, Vertices: Vertices0),',
       '            1 => (Left: Left1, Right: Right1, Vertices: Vertices1),',
       '            _ => throw new ArgumentOutOfRangeException(nameof(lod))','        };',
       '        var positions = new Vector3[plan.SourcePositions.Length];',
       '        Array.Copy(plan.Positions, positions, positions.Length);',
       '        var removed = (bool[])plan.RemoveTriangles[0].Clone();',
       '        if (!(layout.LeftSidewalk.y > layout.LeftSidewalk.x))',
       '            foreach (var face in data.Left) removed[face] = true;',
       '        if (!(layout.RightSidewalk.y > layout.RightSidewalk.x))',
       '            foreach (var face in data.Right) removed[face] = true;',
       '        foreach (var vertex in data.Vertices)','        {',
       '            var original = plan.SourcePositions[vertex.Index];',
       '            positions[vertex.Index].x = original.x;',
       '            if (vertex.Side == 0) continue;',
       '            var span = vertex.Side < 0 ? layout.LeftSidewalk : layout.RightSidewalk;',
       '            var present = span.y > span.x;',
       '            var width = span.y - span.x;',
       '            var start = vertex.Side < 0 ? -span.y : span.x;',
       '            const float inner = 9.389892578125f;',
       '            var edge = present ? start + (inner - 9f) / 3.5f * width : 12.5f + delta;',
       '            var shift = vertex.Walk && present',
       '                ? start - 9f + (width - 3.5f) * vertex.Fraction',
       '                : (edge - inner) * (vertex.Walk ? 1f : vertex.Fraction);',
       '            positions[vertex.Index].x += vertex.Side * shift;','        }',
       '        var constructedX = new float[plan.ConstructedCount];',
       '        for (var i = 0; i < constructedX.Length; i++) constructedX[i] = plan.Positions[positions.Length + i].x;',
       '        return new MovableStructureModel.Plan(plan.SourcePositions, positions, plan.SourceIndices,',
       '            new[] { removed }, plan.AddedVertices, plan.Fragments, plan.InteriorVertices, constructedX);','    }','']
for lod,sha,left,right,rows in tables:
    lines+=['    // Geometry SHA-256: '+sha]
    for name,faces in [('Left',left),('Right',right)]:
        lines += [f'    private static readonly int[] {name}{lod} = {{ '+', '.join(map(str,faces))+' };']
    lines += [f'    private static readonly (int Index, int Side, bool Walk, float Fraction)[] Vertices{lod} =','    {']
    lines += [f'        ({i}, {side}, {str(walk).lower()}, {number(frac)}),' for i,side,walk,frac in rows]
    lines += ['    };','']
lines+=['}',''];output.write_text('\n'.join(lines),encoding='utf-8')
