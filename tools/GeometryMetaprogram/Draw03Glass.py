"""Emit the independently measured Draw03 control-room glass displacement.
Usage: python Draw03Glass.py RESEARCH_DIRECTORY OUTPUT_CS
"""
from pathlib import Path
import hashlib
import sys
import numpy as np

research, output = map(Path, sys.argv[1:])
records = []
for lod, count, triangles, expected_hash in (
        (0, 704, 360, 'f7ecc824ad55745e791e40b18fd12f5def20657ed8ea56d373429d5a1337588f'),
        (1, 160, 88, '15b8419da13d6e99e1dc0591f12f4019f0be09c3b220a481d24720daf7b57e12')):
    name = 'DrawBridge03' + ('_LOD1' if lod else '') + ' Mesh'
    digest = hashlib.sha256((research / 'movable-skin' / (name + '.Geometry')).read_bytes()).hexdigest()
    assert digest == expected_hash
    vertices, faces, bones = [], [], []
    bone = None
    for line in (research / 'movable-skin' / (name + '.mesh-1.obj')).read_text().splitlines():
        fields = line.split()
        if not fields:
            continue
        if fields[0] == 'v':
            vertices.append(list(map(float, fields[1:4])))
        elif fields[0] == 'g':
            bone = fields[1]
        elif fields[0] == 'f':
            faces.append([int(item.split('/')[0]) - 1 for item in fields[1:]])
            bones.append(bone)
    v = np.asarray(vertices, dtype=np.float32).astype(float)
    f = np.asarray(faces)
    assert v.shape == (count, 3) and f.shape == (triangles, 3)
    assert set(bones) == {'bone_0'}
    assert len(np.unique(f)) == count
    direction = np.sign(v[:, 0]).astype(int)
    assert np.all(direction != 0)
    assert np.all(direction[f] == direction[f[:, :1]])
    # A complete pane cannot reach the centre: every edge and face stays on its
    # original side. Connected panes therefore undergo a single rigid translation.
    for delta in (-.5, 0, 2, 8):
        moved = v.copy()
        moved[:, 0] += direction * delta
        assert np.array_equal(moved[:, 1:], v[:, 1:])
        for edge in (1, 2):
            assert np.array_equal(moved[f[:, edge]] - moved[f[:, 0]],
                                  v[f[:, edge]] - v[f[:, 0]])
    ranges = []
    for i, side in enumerate(direction):
        if ranges and ranges[-1][1] + 1 == i and ranges[-1][2] == side:
            ranges[-1][1] = i
        else:
            ranges.append([i, i, int(side)])
    records.append((count, triangles, ranges, digest))
    np.savez(research / f'draw03-glass-{lod}.npz', positions=v, indices=f, direction=direction)
    print(f'LOD{lod}: {count} vertices, {triangles} triangles, {len(ranges)} ranges; bone 0 and rigid edges verified.')

lines = ['// Native DrawBridge03 mesh-1 glass. Generated by Draw03Glass.py.',
         '// Far LOD has no separate glass mesh; do not add detailed panes to it.',
         'using System;', 'using UnityEngine;', '', 'namespace BridgeBuilder.Bridges;', '',
         'internal static class Draw03Glass', '{',
         '    internal static MovableStructureModel.Plan Create(int lod, Vector3[] source, int[] indices, float delta)',
         '    {', '        var data = lod switch', '        {',
         '            0 => (Vertices: 704, Triangles: 360, Ranges: Near),',
         '            1 => (Vertices: 160, Triangles: 88, Ranges: Middle),',
         '            _ => throw new ArgumentOutOfRangeException(nameof(lod))', '        };',
         '        if (source.Length != data.Vertices || indices.Length != data.Triangles * 3 || !float.IsFinite(delta))',
         '            throw new InvalidOperationException("Draw03 glass requires its recorded mesh-1 layout.");',
         '        var positions = (Vector3[])source.Clone();',
         '        foreach (var range in data.Ranges)',
         '            for (var i = range.First; i <= range.Last; i++) positions[i].x += range.Side * delta;',
         '        return new MovableStructureModel.Plan(source, positions, new[] { indices },',
         '            new[] { new bool[data.Triangles] });', '    }', '']
for name, (_, _, ranges, digest) in zip(('Near', 'Middle'), records):
    lines += ['    // Geometry SHA-256: ' + digest,
              f'    private static readonly (int First, int Last, int Side)[] {name} =', '    {']
    lines += [f'        ({first}, {last}, {side}),' for first, last, side in ranges]
    lines += ['    };', '']
lines += ['}']
output.write_text('\n'.join(lines) + '\n', encoding='utf-8')
