"""Build Draw01 native source bindings from the verified source-sharing map."""
import json
from pathlib import Path

root=Path(__file__).resolve().parents[3]
folder=Path(__file__).resolve().parent/'NativeIntegration'
folder.mkdir(exist_ok=True)
data=json.loads((root/'artifacts/prepared-materials/Draw01/source-sharing/sampling-map.json').read_text())
sources=[]
for source in data['sources']:
    sources.append(dict(cid=source['cid'],sha256=source['sha256'],template=source['template'],
        builtin=source['builtin'],dependencies=source['channels'],
        binding='retain-original-surface',mipPolicy='retain-native-resource-graph-without-decoding',
        nativeSampling='original atlas UV; native material and texture sampling settings unchanged'))
samplers=[]
for sampler in data['samplers']:
    samplers.append(dict(key=sampler['key'],sourceMaterial=sampler['sourceMaterial'],sourceDigest=sampler['sourceDigest'],
        float32Bits=sampler['float32Bits'],textureResources=sampler['textureResources'],
        nativeOperation='Map local affine coordinates into the verified original atlas domain.',
        domainRequirement='Actual receiver is contained and Float32 UV gradients are preserved.',
        legacyDerivedOperation=sampler['mode'],
        unsupported='Outside authored domain or lost Float32 gradient: requires authored source-domain solution; do not infer native triangle folding.'))
(folder/'Sources.json').write_text(json.dumps(dict(schema='Draw01/NativeSources/1',sources=sources,
    textureResources=data['textureResources']),indent=2)+'\n')
(folder/'Sampling.json').write_text(json.dumps(dict(schema='Draw01/NativeSampling/1',samplers=samplers),separators=(',',':'))+'\n')
digests=sorted({s['sha256'] for s in sources})
source='''// Generated by tools/PreparedMaterials/Draw01/BuildNativeBindings.py.
using System;
using UnityEngine;

namespace BridgeBuilder.Bridges;

// Original atlas sampling only. Legacy derived triangle folding is not declared
// to be an authored prototype requirement. Never decode or replace source pixels.
internal static class Draw01NativeMaterialBinding
{
    internal static bool IsRecordedSource(string digest) => digest switch
    {
'''
source+=''.join('        "'+digest+'" => true,\n' for digest in digests)
source+='''        _ => false
    };

    internal static void RequireCompatible(string sourceDigest, MovableStructurePacking.Unit unit)
    {
        if (!IsRecordedSource(sourceDigest))
            throw new InvalidOperationException("Draw01 native material source differs from its recorded content.");
        if (!unit.CanUseSource)
            throw new InvalidOperationException("Draw01 native source mapping is not implemented for this receiver: the authored atlas domain or Float32 gradient cannot be preserved. A legacy folded texture is not an original-source fallback.");
    }

    // Caller binds the unchanged source Surface and retains its native texture/mip
    // graph. The original geometry path applies this map to the mesh UV stream.
    internal static Vector2 Map(MovableStructurePacking.Unit unit, Vector2 uv) => unit.SourceUv(uv);
}
'''
(folder/'Draw01NativeMaterialBinding.cs').write_text(source)
print(f'PASS Draw01 binding implementation: {len(sources)} source identities, {len(digests)} content identities, {len(samplers)} sampling records; no new native payload.')
