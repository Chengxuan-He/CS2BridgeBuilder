"""Verify the complete native fixed-base graph and emit its exact sampling gate."""
import hashlib
import json
from pathlib import Path
import re
import struct
import zipfile

ROOT = Path(__file__).resolve().parents[3]
RESEARCH = ROOT.parent / '2026-10-15/c-users-admin-documents-codex-cs2bridgebuilder/work/bridge-research'
OUT = ROOT / 'artifacts/material-resume/Draw01'


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def cid(value):
    raw = struct.pack('<4i', *(value['m_GuidPart' + str(i)] for i in range(1, 5)))
    return ''.join(f'{b & 15:x}{b >> 4:x}' for b in raw)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    audit_path = RESEARCH / 'all-movable-audit.json'
    audit = json.loads(audit_path.read_text())
    selected = audit['selected']
    names_source = ROOT / 'src/BridgeBuilder/Bridges/Types/Draw01/Draw01FixedBaseData.g.cs'
    roots = re.findall(r'"(DrawBridge01Bottom[^"\r\n]* Mesh)"', names_source.read_text())
    assert len(roots) == 5
    archive = Path('D:/Program Files (x86)/Steam/steamapps/common/Cities Skylines II/Cities2_Data/Content/BridgesAndPorts/Blob.cok')
    records = []
    with zipfile.ZipFile(archive) as z:
        for root in roots:
            matches = [(key, entry) for key, entry in selected.items() if entry['data'].get('m_Name') == root]
            assert len(matches) == 1
            root_id, entry = matches[0]
            assert entry['class'] == 'NetPiecePrefab'
            components = [selected[str(c['m_PathID'])] for c in entry['data']['components']]
            lods = [c['data']['m_LodMeshes'] for c in components if c['class'] == 'LodProperties']
            levels = [root_id] + [str(lod['m_PathID']) for group in lods for lod in group]
            assert len(levels) == (1 if 'Intersection' in root else 3)
            for level, key in enumerate(levels):
                render = selected[key]
                data = render['data']
                assert render['class'] == ('NetPiecePrefab' if level == 0 else 'RenderPrefab')
                assert data['m_MeshCount'] == 1 and len(data['m_SurfaceAssets']) == 1
                source_cid = cid(data['m_SurfaceAssets'][0])
                geometry_cid = cid(data['m_GeometryAsset'])
                source = audit['assets'][source_cid]
                geometry = audit['assets'][geometry_cid]
                raw = z.read(source['entry'])
                assert hashlib.sha256(raw).hexdigest() == source['sha256']
                assert z.read(source['entry'] + '.cid').decode().strip() == source_cid
                assert struct.unpack_from('<Hi?', raw) == (1, 17, False)
                assert hashlib.sha256(z.read(geometry['entry'])).hexdigest() == geometry['sha256']
                records.append(dict(root=root, render=data['m_Name'], mesh=0, lod=level,
                    sourceCid=source_cid, sourceSha256=source['sha256'], sourceEntry=source['entry'],
                    template=17, geometryCid=geometry_cid, geometrySha256=geometry['sha256'],
                    renderClass=render['class'], rootComponents=components))
    assert len(records) == 13
    target = ROOT / 'src/BridgeBuilder/Bridges/Types/Draw01/Draw01NativeMaterials.cs'
    cases = '\n'.join(f'            ("{r["render"]}", 0) => "{r["sourceCid"]}",' for r in records)
    method = '''    // BEGIN generated native network sampling gate
    // Generated by EmitNetworkSampling.py from the complete fixed-base LOD graph.
    // The caller must also prove native NetPiece graph context; a reduced LOD is
    // a RenderPrefab, and must inherit that context rather than use its own type.
    internal static bool IsNativeNetwork(string render, int mesh, string sourceCid)
    {
        string? expected = (render, mesh) switch
        {
CASES
            _ => null
        };
        return expected != null && sourceCid == expected;
    }
    // END generated native network sampling gate
'''.replace('CASES', cases)
    code = target.read_text()
    if '    // BEGIN generated native network sampling gate' in code:
        code = re.sub(r'    // BEGIN generated native network sampling gate.*?    // END generated native network sampling gate\n', lambda _: method, code, flags=re.S)
    else:
        code = code.replace('internal static class Draw01NativeMaterials\n{\n', 'internal static class Draw01NativeMaterials\n{\n' + method + '\n')
    target.write_text(code, newline='\n')
    report = dict(style='Draw01', sourceAuditSha256=sha(audit_path), archive=str(archive),
        sourceGraphSha256=sha(names_source), sources=records,
        capability='Root NetPiecePrefab; every level has no road and no skeleton; exact source identity and template 17.',
        semantics='Retain original native U, signed V, all non-position channels and Surface. The native network renderer supplies longitudinal distance/phase. Native composition and tiling components are retained.',
        acceptance='Offline graph/asset verification; native rendering and shared replay remain required.',
        localization='No user-visible string or localization behavior changed.')
    (OUT / 'native-network-sources.json').write_text(json.dumps(report, indent=2) + '\n')
    print(f'Verified {len(records)} fixed-base render/Surface slots across every native LOD.')


if __name__ == '__main__':
    main()
