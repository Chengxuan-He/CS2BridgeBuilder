"""Verify Draw02 fixed native network sources and emit their exact sampling gate."""
from pathlib import Path
import hashlib
import gzip
import json
import re
import runpy
import zipfile
import numpy as np

repo = Path(__file__).resolve().parents[3]
out = repo / 'artifacts/material-resume/Draw02'
out.mkdir(parents=True, exist_ok=True)
source_file = repo / 'src/BridgeBuilder/Bridges/Types/Draw02/Draw02ApproachSources.g.cs'
source_text = source_file.read_text()
source_map = json.loads((repo / 'artifacts/prepared-materials/Draw02/structure-units/retile-source-map.json').read_text())
parse = runpy.run_path(str(repo / 'tools/PreparedMaterials/Lift05/MapSharedSampling.py'))['surface']
archive = Path('D:/Program Files (x86)/Steam/steamapps/common/Cities Skylines II/Cities2_Data/Content/BridgesAndPorts/Blob.cok')
records = []
with zipfile.ZipFile(archive) as z:
    surfaces = {}
    for name in z.namelist():
        if name.startswith('DrawBridge02') and name.endswith('.Surface'):
            cid = z.read(name + '.cid')
            cid = ''.join(f'{b & 15:x}{b >> 4:x}' for b in cid) if len(cid) == 16 else cid.decode().strip()
            surfaces[cid] = (name, z.read(name))
    for entry in source_map:
        render, mesh, cid = entry['render'], entry['mesh'], entry['sourceCid']
        if not render.startswith('DrawBridge02Bottom'): continue
        assert mesh == 0
        # Exact serialized source pairing, not a prefix-based runtime classifier.
        assert re.search(r'Create<(?:NetPiecePrefab|RenderPrefab)>\("' + re.escape(render) + r'", "[a-f0-9]+", new\[\] \{ "' + cid + r'" \}', source_text)
        name, raw = surfaces[cid]
        digest = hashlib.sha256(raw).hexdigest()
        assert digest == entry['sourceDigest']
        descriptor = parse(raw)
        assert descriptor['template'] == 17
        assert descriptor['properties']['vectors'] == {}
        native_file = repo / 'artifacts/uv-density/native' / (render + '.npz')
        native = np.load(native_file)
        uv = native['mesh0_uv0']
        # This existing density export contains XY only; it is not evidence for ZW.
        assert uv.shape[1] == 2 and np.isfinite(uv).all()
        records.append(dict(**entry, archiveEntry=name, template=17,
            textures=descriptor['textures'],
            uv0Minimum=uv.min(0).tolist(), uv0Maximum=uv.max(0).tolist(),
            nonnegativeVVertices=int(np.count_nonzero(uv[:, 1] >= 0)),
            negativeVVertices=int(np.count_nonzero(uv[:, 1] < 0)),
            nativeSha256=hashlib.sha256(native_file.read_bytes()).hexdigest()))
assert len(records) == 19
cases = '\n'.join(f'            ("{r["render"]}", 0) => "{r["sourceCid"]}",' for r in records)
method = '''    // BEGIN generated native network sampling gate
    // Generated by EmitNetworkSampling.py. Only the shared fixed NetPiece graph
    // capability may call this gate; moving object renders keep their conversion.
    // Shader 581 preserves U and evaluates signed V using native network length.
    internal static bool IsNativeNetwork(string render, int mesh, string sourceCid)
    {
        string? expected = (render, mesh) switch
        {
CASES
            _ => null
        };
        return expected != null && sourceCid == expected;
    }
    // END generated native network sampling gate
'''.replace('CASES', cases)
target = repo / 'src/BridgeBuilder/Bridges/Types/Draw02/Draw02NativeMaterials.cs'
text = target.read_text()
if '    // BEGIN generated native network sampling gate' in text:
    text = re.sub(r'    // BEGIN generated native network sampling gate.*?    // END generated native network sampling gate\n', lambda _: method, text, flags=re.S)
else:
    text = text.replace('internal static class Draw02NativeMaterials\n{\n', 'internal static class Draw02NativeMaterials\n{\n' + method + '\n')
target.write_text(text, newline='\n')
evidence = dict(schema=1, style='Draw02', mode='native-network-signed-v',
    requiredGraphCapability='Root is NetPiecePrefab; every level has no road and no skeleton.',
    mapping=dict(u='Native shader581 forwards original U.',
                 v='V >= 0: original V times native network length mapping; V < 0: frac(V).',
                 otherChannels='Keep original UV0.zw, COLOR and every original non-position channel.'),
    sourceGraphSha256=hashlib.sha256(source_file.read_bytes()).hexdigest(),
    sources=records, nativeRenderingVerified=False,
    localization='No user-visible string or localization flow changed.')
classification = repo / 'artifacts/prepared-materials/shared-nontiling/actual-final/styles/Draw02.regions.json.classifications.ndjson.gz'
with gzip.open(classification, 'rt') as f:
    previous = [json.loads(line) for line in f]
identities = {(r['render'], r['mesh']) for r in records}
remaining = [r for r in previous if r['status'] == 'remaining']
assert len(remaining) == 582 and all((r['render'], r['mesh']) in identities for r in remaining)
repeats = [r for r in previous if r['status'] == 'repeat']
assert len(repeats) == 65 and all((r['render'], r['mesh']) not in identities for r in repeats)
evidence['previousObserverCoverage'] = dict(remainingCovered=len(remaining),
    uniqueRemainingDomains=len({(r['render'], r['mesh'], r['originalDomain']) for r in remaining}),
    genuineRepeatCasesOutsideNetworkGate=len(repeats),
    note='Source coverage only. A new shared observer run is needed to verify dispatch.')
(out / 'native-network-sources.json').write_text(json.dumps(evidence, indent=2) + '\n')
print(f'Verified {len(records)} exact native network slots; emitted Draw02NativeMaterials.IsNativeNetwork.')
