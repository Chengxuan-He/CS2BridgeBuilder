"""Emit Draw02 source-binding code and exact sampler call data; no texture conversion."""
import hashlib
import json
from pathlib import Path
import sys
import zipfile

def main(repo,game):
    root=repo/'artifacts/prepared-materials/Draw02/shared-source-migration'
    mapping=json.loads((root/'source-sampler-map.json').read_text())
    source={s['cid']:s['sha256'] for s in mapping['sources']}
    lines=['// Generated by tools/PreparedMaterials/Draw02/EmitNativeBindingData.py.',
           '// Native content identity only; sampler coordinates never enter this table.',
           'using System.Collections.Generic;','', 'namespace BridgeBuilder.Bridges;',
           'internal static class Draw02NativeSourceCatalog', '{',
           '    internal static readonly IReadOnlyDictionary<string, string> Sources = new Dictionary<string, string>', '    {']
    lines += [f'        ["{cid}"] = "{sha}",' for cid,sha in sorted(source.items())]
    lines += ['    };','}','']
    code=repo/'src/BridgeBuilder/Bridges/Types/Draw02/Draw02NativeSourceCatalog.g.cs'
    code.write_text('\n'.join(lines),encoding='utf-8')
    cases=dict(style='Draw02',schema='BridgeBuilder/Draw02NativeBindingCalls/1',
               sourceBindings=mapping['sources'],samplers=mapping['samplers'],
               execution='Draw02NativeSourceBindings.TryBind(source, actualReceiverUnit, out slot, out requirement)',
               unsupported='Derive and validate original native mapping; never use a per-sampler texture bake')
    out=root/'native-binding-calls.json';out.write_text(json.dumps(cases,indent=2)+'\n',encoding='utf-8')
    fixtures=root/'source-descriptor-fixtures';fixtures.mkdir(exist_ok=True)
    remaining=set(source)
    for family in ('Game','BridgesAndPorts'):
        for path in (game/'Content'/family).glob('Blob*.cok'):
            with zipfile.ZipFile(path) as archive:
                for name in archive.namelist():
                    if not name.endswith('.cid'):continue
                    cid=archive.read(name).decode().strip()
                    if cid not in remaining:continue
                    data=archive.read(name[:-4]);assert hashlib.sha256(data).hexdigest()==source[cid]
                    (fixtures/(cid+'.Surface')).write_bytes(data);remaining.remove(cid)
    assert not remaining,remaining
    print(json.dumps(dict(sourceBindings=len(source),samplerCalls=len(mapping['samplers']),
                          generatedSource=str(code),callData=str(out),newTextures=0)))

if __name__=='__main__':main(Path(sys.argv[1]).resolve(),Path(sys.argv[2]).resolve())
